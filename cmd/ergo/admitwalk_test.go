// admitNames are the folder names the generated trees use: two package
// names and every name DIR/... leaves out (build.md, Workspace).
var admitNames = []string{"a", "b", "testdata", "vendor", "node_modules", "ergo.bind", "_u", ".h"}

// admitRefused is the model of build.md's Workspace rule, written apart
// from sketchfront.AdmitFolder: hidden and underscored folders, testdata,
// node_modules, vendor and ergo.bind hold no package.
func admitRefused(name string) bool {
	return strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_") ||
		name == "testdata" || name == "node_modules" || name == "vendor" || name == "ergo.bind"
}

// admitTree is a generated module tree: every folder below the root,
// relative and slash-separated, each holding one .ergo file, and the
// folders that hold an ergo.mod of their own (nested members).
type admitTree struct {
	dirs    []string
	members map[string]bool
}

// genAdmitTree draws a tree up to three folders deep. Every tree has an
// ergo.bind at the root and one below a package folder, so each walk meets
// the binding folder at two depths.
func genAdmitTree(r *rand.Rand) admitTree {
	t := admitTree{members: map[string]bool{}}
	var grow func(parent string, depth int)
	grow = func(parent string, depth int) {
		if depth == 3 {
			return
		}
		for _, name := range admitNames {
			forced := (parent == "" && (name == "a" || name == "ergo.bind")) || (parent == "a" && name == "ergo.bind")
			if !forced && r.IntN(3) != 0 {
				continue
			}
			rel := name
			if parent != "" {
				rel = parent + "/" + name
			}
			t.dirs = append(t.dirs, rel)
			if (name == "a" || name == "b") && parent != "" && r.IntN(4) == 0 {
				t.members[rel] = true
			}
			grow(rel, depth+1)
		}
	}
	grow("", 0)
	return t
}

// admitted is whether DIR/... from the root reaches rel by the model.
func admitted(rel string) bool {
	for part := range strings.SplitSeq(rel, "/") {
		if admitRefused(part) {
			return false
		}
	}
	return true
}

// inMember is whether rel is a nested member or lies below one.
func (t admitTree) inMember(rel string) bool {
	for m := range t.members {
		if rel == m || strings.HasPrefix(rel, m+"/") {
			return true
		}
	}
	return false
}

func (t admitTree) write(tb *testing.T, root string) {
	tb.Helper()
	files := map[string]string{
		"ergo.mod":  "module admit\n",
		"ergo.work": "version 1\n",
		"p.ergo":    "// Code generated by ergo gen api; DO NOT EDIT.\n// Contract nowhere.X, digest 0\npackage p\n",
	}
	for _, d := range t.dirs {
		files[d+"/p.ergo"] = files["p.ergo"]
		if t.members[d] {
			files[d+"/ergo.mod"] = "module admit/" + d + "\n"
		}
	}
	writeFiles(tb, root, files)
}

// TestDirWalksAgreeOnAdmittedFolders is DIR/...'s one rule (build.md,
// Workspace): for seeded trees holding ergo.bind, testdata, vendor and the
// other refused names at several depths, ergo check's package discovery,
// its member discovery, ergo fmt's folder walk, the task runner's member
// walk and ergo gate's key each reach exactly the folders the model
// admits, the last two stopping at a nested member. The gate still hashes
// the root's ergo.bind files, which import go reads. A failing seed
// prints the tree and its replay command.
func TestDirWalksAgreeOnAdmittedFolders(t *testing.T) {
	seeds, first := 60, uint64(1)
	if s := os.Getenv("ADMITWALK_SEED"); s != "" {
		n, err := strconv.ParseUint(s, 10, 64)
		if err != nil {
			t.Fatalf("ADMITWALK_SEED=%q is not a seed", s)
		}
		first, seeds = n, 1
	}
	refusedDepths := map[string]map[int]bool{}
	for seed := first; seed < first+uint64(seeds); seed++ {
		tree := genAdmitTree(rand.New(rand.NewPCG(seed, 0xb1d)))
		root := t.TempDir()
		tree.write(t, root)
		fail := func(walk string, got, want []string) {
			t.Helper()
			slices.Sort(got)
			slices.Sort(want)
			if !slices.Equal(got, want) {
				t.Fatalf("seed %d: %s reached %q, want %q\ntree: %q, members %v\nreplay: ADMITWALK_SEED=%d go test -count=1 -run '^TestDirWalksAgreeOnAdmittedFolders$' ./cmd/ergo",
					seed, walk, got, want, tree.dirs, tree.members, seed)
			}
		}
		var all, own, members []string
		all = append(all, ".")
		own = append(own, ".")
		for _, d := range tree.dirs {
			part := d[strings.LastIndex(d, "/")+1:]
			if admitRefused(part) {
				depth := strings.Count(d, "/")
				if refusedDepths[part] == nil {
					refusedDepths[part] = map[int]bool{}
				}
				refusedDepths[part][depth] = true
			}
			if !admitted(d) {
				continue
			}
			all = append(all, d)
			if tree.members[d] {
				members = append(members, d)
			}
			if !tree.inMember(d) {
				own = append(own, d)
			}
		}

		pkgs, err := sketchfront.DiscoverPackages(root)
		if err != nil {
			t.Fatalf("seed %d: check's discovery: %v", seed, err)
		}
		var got []string
		for _, p := range pkgs {
			got = append(got, admitRel(t, root, p.Dir))
		}
		fail("check's package discovery", got, all)

		ws, err := sketchfront.DiscoverWorkspace(nil, root)
		if err != nil {
			t.Fatalf("seed %d: member discovery: %v", seed, err)
		}
		got = nil
		for _, m := range ws.Members {
			if m.Rel != "." {
				got = append(got, m.Rel)
			}
		}
		fail("member discovery", got, members)

		opts := fmtOptions{files: []string{root}}
		if err := expandFormatFolders(&opts); err != nil {
			t.Fatalf("seed %d: fmt's walk: %v", seed, err)
		}
		got = nil
		for _, f := range opts.files {
			got = append(got, admitRel(t, root, filepath.Dir(f)))
		}
		fail("fmt's folder walk", got, all)

		var elsewhere []Elsewhere
		if _, err := memberGens(root, ".", tree.members, &elsewhere); err != nil {
			t.Fatalf("seed %d: task member walk: %v", seed, err)
		}
		got = nil
		for _, e := range elsewhere {
			got = append(got, e.Pkg)
		}
		fail("task runner's member walk", got, own)

		parts, err := gateTreeParts(root, "", map[string]bool{})
		if err != nil {
			t.Fatalf("seed %d: gate's key: %v", seed, err)
		}
		got = []string{"."}
		var bindFiles, wantBind []string
		for _, p := range parts {
			if d, ok := strings.CutPrefix(p, "dir "); ok {
				got = append(got, d)
			} else if f, ok := strings.CutPrefix(p, "file ergo.bind/"); ok && strings.HasSuffix(strings.Fields(f)[0], ".ergo") {
				bindFiles = append(bindFiles, strings.Fields(f)[0])
			}
		}
		fail("gate's key", got, own)
		for _, d := range tree.dirs {
			if b, ok := strings.CutPrefix(d, "ergo.bind/"); ok {
				wantBind = append(wantBind, b+"/p.ergo")
			}
		}
		wantBind = append(wantBind, "p.ergo")
		fail("gate's key over the root's bindings", bindFiles, wantBind)
	}
	if seeds > 1 {
		for _, name := range []string{"ergo.bind", "testdata", "vendor"} {
			if !refusedDepths[name][0] || !refusedDepths[name][1] {
				t.Errorf("the seeds put %s at depths %v; want the root and below a folder", name, refusedDepths[name])
			}
		}
	}
}

// admitRel is dir relative to root, slash-separated.
func admitRel(t *testing.T, root, dir string) string {
	t.Helper()
	r, err := filepath.Rel(root, dir)
	if err != nil {
		t.Fatal(err)
	}
	return filepath.ToSlash(r)
}
