var updateBodies = flag.Bool("update-bodies", false, "rewrite files_gen.go from runtime/v1's Go sources")

// bodyTablePath is the generated table BodyOf reads.
const bodyTablePath = "files_gen.go"

// TestBodyTableIsCurrent is the staleness check of the generated body
// facts (CHK1): files_gen.go must be what the reviewed rules (goDecls.body:
// the hidden-argument convention, pureRefusal, hostReach) read from this
// package's Go sources, so a runtime edit that changes a body's shape, its
// marks or its host reach fails here until the table is rewritten, and
// never makes a check or a lowering differ silently. It catches the mutant
// bodies-table-stale of the ledger. Rewrite the table with:
// go test ./runtime/v1 -run TestBodyTableIsCurrent -update-bodies
func TestBodyTableIsCurrent(t *testing.T) {
	decls, err := parseSources()
	if err != nil {
		t.Fatal(err)
	}
	want := renderBodyTable(decls)
	if *updateBodies {
		if err := os.WriteFile(bodyTablePath, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(bodyTablePath)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != want {
		t.Fatalf("%s is not the table runtime/v1's sources give; rewrite it with go test ./runtime/v1 -run TestBodyTableIsCurrent -update-bodies", bodyTablePath)
	}
	// The table read back is the parse: BodyOf answers every name as the
	// reviewed rules do, a name with no exported body included.
	names := []string{"NoSuchBody", "Closed"}
	for name := range decls {
		names = append(names, name)
	}
	for _, name := range names {
		want, wantErr := decls.body(name)
		got, gotErr := BodyOf(name)
		if fmt.Sprint(wantErr) != fmt.Sprint(gotErr) || !reflect.DeepEqual(want, got) {
			t.Errorf("BodyOf(%q) = %+v, %v; the sources give %+v, %v", name, got, gotErr, want, wantErr)
		}
	}
	for name := range decls {
		want, wantOK := decls.goType(name)
		got, gotOK := TypeOf(name)
		if wantOK != gotOK || !reflect.DeepEqual(want, got) {
			t.Errorf("TypeOf(%q) = %+v, %v; the sources give %+v, %v", name, got, gotOK, want, wantOK)
		}
	}
}

// renderBodyTable is the Go source of files_gen.go: for every exported
// function and method of decls, its Body or the text of its refusal.
func renderBodyTable(decls goDecls) string {
	var names []string
	for name, g := range decls {
		if g.fn != nil {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString("// Code generated by TestBodyTableIsCurrent (runtime/v1); DO NOT EDIT.\n")
	b.WriteString("// Rewrite it with: go test ./runtime/v1 -run TestBodyTableIsCurrent -update-bodies\n\n")
	b.WriteString("package v1\n\n")
	b.WriteString("// bodyTable is goDecls.body of every exported function and method of\n")
	b.WriteString("// Source, by BodyOf name: its Body, or the text of the error the reviewed\n")
	b.WriteString("// rules refuse it with. BodyOf reads it, so no process parses Source to\n")
	b.WriteString("// learn a body's shape (CHK1). Its rows are sorted by name, and it is a\n")
	b.WriteString("// slice, which Go lays out at build time: a process pays nothing for it at\n")
	b.WriteString("// start, as it would to build a map.\n")
	b.WriteString("var bodyTable = []bodyRow{\n")
	for _, name := range names {
		body, err := decls.body(name)
		if err != nil {
			fmt.Fprintf(&b, "\t{%q, bodyFact{refusal: %q}},\n", name, err.Error())
			continue
		}
		fmt.Fprintf(&b, "\t{%q, bodyFact{body: %s}},\n", name, bodyLiteral(body))
	}
	b.WriteString("}\n\n")
	b.WriteString("// typeTable is goDecls.goType of every exported type of Source, by name.\n")
	b.WriteString("// TypeOf reads it (CHK1). Sorted by name, a slice, as bodyTable is.\n")
	b.WriteString("var typeTable = []typeRow{\n")
	var types []string
	for name, g := range decls {
		if g.typ != nil {
			types = append(types, name)
		}
	}
	sort.Strings(types)
	for _, name := range types {
		t, _ := decls.goType(name)
		var fields []string
		if t.Arity > 0 {
			fields = append(fields, fmt.Sprintf("Arity: %d", t.Arity))
		}
		if t.Struct {
			fields = append(fields, "Struct: true")
		}
		if len(t.Fields) > 0 {
			fields = append(fields, fmt.Sprintf("Fields: %#v", t.Fields))
		}
		if t.Basic != "" {
			fields = append(fields, fmt.Sprintf("Basic: %q", t.Basic))
		}
		fields = append(fields, packageField(t.Package))
		fmt.Fprintf(&b, "\t{%q, GoType{%s}},\n", name, strings.Join(fields, ", "))
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(err)
	}
	return string(src)
}

// bodyLiteral is the Go expression of b, with its zero fields left out.
func bodyLiteral(b Body) string {
	var fields []string
	if len(b.TypeParams) > 0 {
		var tps []string
		for _, tp := range b.TypeParams {
			tps = append(tps, fmt.Sprintf("{Name: %q, Constraint: %q}", tp.Name, tp.Constraint))
		}
		fields = append(fields, "TypeParams: []TypeParam{"+strings.Join(tps, ", ")+"}")
	}
	if len(b.Hidden) > 0 {
		var hs []string
		for _, h := range b.Hidden {
			hs = append(hs, fmt.Sprintf("%q", string(h)))
		}
		fields = append(fields, "Hidden: []Hidden{"+strings.Join(hs, ", ")+"}")
	}
	if len(b.Params) > 0 {
		var ps []string
		for _, p := range b.Params {
			pf := []string{fmt.Sprintf("Type: %q", p.Type)}
			if p.Func != nil {
				pf = append(pf, "Func: &"+bodyLiteral(*p.Func))
			}
			if p.Funcs != nil {
				pf = append(pf, "Funcs: &"+bodyLiteral(*p.Funcs))
			}
			ps = append(ps, "{"+strings.Join(pf, ", ")+"}")
		}
		fields = append(fields, "Params: []Param{"+strings.Join(ps, ", ")+"}")
	}
	if len(b.Results) > 0 {
		var rs []string
		for _, r := range b.Results {
			rs = append(rs, fmt.Sprintf("%q", r))
		}
		fields = append(fields, "Results: []string{"+strings.Join(rs, ", ")+"}")
	}
	if b.Pure {
		fields = append(fields, "Pure: true")
	}
	if b.Host {
		fields = append(fields, "Host: true")
	}
	if b.Owned != "" {
		fields = append(fields, fmt.Sprintf("Owned: %q", b.Owned))
	}
	if b.Wait != "" {
		fields = append(fields, fmt.Sprintf("Wait: %q", b.Wait))
	}
	if b.Release != "" {
		fields = append(fields, fmt.Sprintf("Release: %q", b.Release))
	}
	if b.BridgeTarget != "" {
		fields = append(fields, fmt.Sprintf("BridgeTarget: %q, BridgeProvider: %q", b.BridgeTarget, b.BridgeProvider))
	}
	if b.Check != "" {
		fields = append(fields, fmt.Sprintf("Check: %q", b.Check))
	}
	if b.View != "" {
		fields = append(fields, fmt.Sprintf("View: %q", b.View))
	}
	if b.AppendsSlice {
		fields = append(fields, "AppendsSlice: true")
	}
	if b.ReadsMap {
		fields = append(fields, "ReadsMap: true")
	}
	if b.WritesMap {
		fields = append(fields, "WritesMap: true")
	}
	if b.TakesMap {
		fields = append(fields, "TakesMap: true")
	}
	if b.Package != "" {
		fields = append(fields, packageField(b.Package))
	}
	return "Body{" + strings.Join(fields, ", ") + "}"
}

// packageField is the Package field of a generated row: Path, or Path
// and the leaf's name (binsize BS1).
func packageField(pkg string) string {
	if leaf, ok := strings.CutPrefix(pkg, Path+"/"); ok {
		return fmt.Sprintf("Package: Path + %q", "/"+leaf)
	}
	return "Package: Path"
}
