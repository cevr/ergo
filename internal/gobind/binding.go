// Header is the first line of every binding file.
const Header = "// Code generated by ergo bind go; DO NOT EDIT."

// Decls maps every exported declaration of pkg, in name order, each type
// followed by its methods. Other packages are spelled by a placeholder that
// Render replaces with the import's name.
func Decls(pkg *types.Package) []Decl {
	var out []Decl
	q := func(p *types.Package) string { return "⟦" + p.Path() + " " + p.Name() + "⟧" }
	scope := pkg.Scope()
	for _, name := range scope.Names() {
		obj := scope.Lookup(name)
		if !obj.Exported() {
			continue
		}
		d := Map(obj, nil, q)
		out = append(out, d)
		tn, ok := obj.(*types.TypeName)
		if !ok || d.Refused != "" {
			continue
		}
		n, ok := tn.Type().(*types.Named)
		if !ok {
			continue
		}
		if _, iface := n.Underlying().(*types.Interface); iface {
			continue // an interface's methods are members of its type
		}
		ms := types.NewMethodSet(types.NewPointer(n))
		var methods []*types.Func
		for i := 0; i < ms.Len(); i++ {
			if f, ok := ms.At(i).Obj().(*types.Func); ok && f.Exported() {
				methods = append(methods, f)
			}
		}
		sort.Slice(methods, func(i, j int) bool { return methods[i].Name() < methods[j].Name() })
		for _, f := range methods {
			out = append(out, Map(f, n, q))
		}
	}
	return out
}

// Platform is one GOOS/GOARCH pair.
type Platform struct{ GOOS, GOARCH string }

func (p Platform) String() string { return p.GOOS + "/" + p.GOARCH }

// Merge keeps the declarations that map to the same text on every
// platform; any other is refused as platform-specific, so no declaration is
// typed by one platform's Go (interop.md, Go's standard library).
func Merge(platforms []Platform, decls [][]Decl) []Decl {
	byName := make([]map[string]Decl, len(decls))
	var names []string
	seen := map[string]bool{}
	for i, ds := range decls {
		byName[i] = map[string]Decl{}
		for _, d := range ds {
			byName[i][d.Name] = d
			if !seen[d.Name] {
				seen[d.Name] = true
				names = append(names, d.Name)
			}
		}
	}
	var out []Decl
	for _, name := range names {
		first, ok := byName[0][name]
		var missing, differ []string
		for i := range decls {
			d, ok := byName[i][name]
			switch {
			case !ok:
				missing = append(missing, platforms[i].String())
			case !same(d, first):
				differ = append(differ, platforms[i].String())
			}
		}
		if !ok {
			for i := range decls {
				if d, ok := byName[i][name]; ok {
					first = d
					break
				}
			}
		}
		switch {
		case len(missing) > 0:
			first = Decl{Kind: first.Kind, Name: name, Go: first.Go, Refused: "platform-specific: Go does not declare it on " + strings.Join(missing, ", ")}
		case len(differ) > 0:
			first = Decl{Kind: first.Kind, Name: name, Go: first.Go, Refused: "platform-specific: its Go declaration differs on " + strings.Join(differ, ", ")}
		}
		out = append(out, first)
	}
	return out
}

func same(a, b Decl) bool {
	return a.Kind == b.Kind && a.Go == b.Go && a.Ergo == b.Ergo && a.Variadic == b.Variadic && a.Context == b.Context && a.Refused == b.Refused && slices.Equal(a.Members, b.Members)
}

var placeholder = regexp.MustCompile(`⟦([^⟧]*)⟧`)

// Render writes the binding file of the Go package path, whose package
// name is name, from its declarations; stamp is the rest of the
// `// ergo:bind` line (toolchain and platforms). module, for a package
// outside Go's standard library, is its module's stamp (ModuleLine), the
// third line. It returns the file formatted as ergo fmt formats it.
func Render(path, name, stamp, module string, decls []Decl) (string, error) {
	var body strings.Builder
	for _, d := range decls {
		body.WriteString("\n// ergo:go " + d.Go + "\n")
		if d.Refused != "" {
			body.WriteString("// ergo:refused " + d.Name + ": " + d.Refused + "\n")
			continue
		}
		if d.Context {
			body.WriteString("// ergo:context\n")
		}
		if d.Variadic {
			body.WriteString("// ergo:variadic\n")
		}
		body.WriteString("extern go " + d.Target(path) + " " + d.Ergo + "\n")
		for _, m := range d.Members {
			body.WriteString("\n// ergo:go " + m.Go + "\n")
			body.WriteString("// ergo:refused " + d.Name + "." + m.Name + ": " + m.Refused + "\n")
		}
	}
	text := body.String()
	// Each referenced package gets an import; the name an import binds is
	// the Go package's name, aliased when it is a keyword or taken.
	var keys []string
	for _, m := range placeholder.FindAllStringSubmatch(text, -1) {
		if !slices.Contains(keys, m[1]) {
			keys = append(keys, m[1])
		}
	}
	sort.Strings(keys)
	local := map[string]string{}
	taken := map[string]bool{name: true}
	var imports strings.Builder
	for _, k := range keys {
		p, n, _ := strings.Cut(k, " ")
		if syntax.IsKeyword(n) {
			n = "go" + n
		}
		for i := 2; taken[n]; i++ {
			n = fmt.Sprintf("%s%d", strings.TrimRight(n, "0123456789"), i)
		}
		taken[n] = true
		local[k] = n
		if n == lastElem(p) {
			imports.WriteString("import go " + p + "\n")
		} else {
			imports.WriteString("import go " + n + " " + p + "\n")
		}
	}
	text = placeholder.ReplaceAllStringFunc(text, func(s string) string { return local[s[len("⟦"):len(s)-len("⟧")]] })
	src := Header + "\n// ergo:bind " + path + " " + stamp + "\n"
	if module != "" {
		src += ModuleLine + module + "\n"
	}
	if imports.Len() > 0 {
		src += "\n" + imports.String()
	}
	src += text
	out, err := format.Source(src)
	if err != nil {
		return "", fmt.Errorf("binding of %s does not parse: %w", path, err)
	}
	return out, nil
}

func lastElem(p string) string { return p[strings.LastIndex(p, "/")+1:] }

// File is the binding file of one Go package, from its type-checked
// package on each platform (pkgs[i] on platforms[i]).
func File(pkgs []*types.Package, platforms []Platform, goVersion string) (string, error) {
	c := newCloser(platforms)
	for i, p := range pkgs {
		c.add(i, p)
	}
	return c.file(pkgs[0].Path(), pkgs[0].Name(), goVersion)
}

// closer merges each package's declarations across the platforms and
// closes them (Close), reading the closed declarations of every package a
// declaration names, once each.
type closer struct {
	platforms []Platform
	pkgs      map[string][]*types.Package // by path, one per platform
	done      map[string][]Decl
	// modules is the module stamp of each package outside Go's standard
	// library, by import path (ModuleLine).
	modules map[string]string
}

func newCloser(platforms []Platform) *closer {
	return &closer{platforms: platforms, pkgs: map[string][]*types.Package{}, done: map[string][]Decl{}}
}

// name is the Go package name of path, from the first platform that has it.
func (c *closer) name(path string) string {
	for _, p := range c.pkgs[path] {
		if p != nil {
			return p.Name()
		}
	}
	return lastElem(path)
}

func (c *closer) add(i int, p *types.Package) {
	ps := c.pkgs[p.Path()]
	if ps == nil {
		ps = make([]*types.Package, len(c.platforms))
		c.pkgs[p.Path()] = ps
	}
	if ps[i] == nil {
		ps[i] = p
	}
}

func (c *closer) file(path, name, goVersion string) (string, error) {
	var ps []string
	for _, p := range c.platforms {
		ps = append(ps, p.String())
	}
	return Render(path, name, goVersion+" "+strings.Join(ps, " "), c.modules[path], c.decls(path))
}

// decls is the merged and closed declarations of the package path. Go
// imports are acyclic, and a declaration names only types of its package
// and its imports, so the recursion ends.
func (c *closer) decls(path string) []Decl {
	if ds, ok := c.done[path]; ok {
		return ds
	}
	c.done[path] = nil // a cycle, impossible in Go, would read nothing
	var all [][]Decl
	var platforms []Platform
	for i, p := range c.pkgs[path] {
		if p == nil {
			continue
		}
		ds := Decls(p)
		for _, d := range ds {
			for _, rp := range d.refPkgs {
				c.add(i, rp)
			}
		}
		all = append(all, ds)
		platforms = append(platforms, c.platforms[i])
	}
	merged := Close(path, Merge(platforms, all), func(ref string) bool {
		p, name := splitRef(ref)
		for _, d := range c.decls(p) {
			if d.Name == name {
				return d.Refused != ""
			}
		}
		return true
	})
	c.done[path] = merged
	return merged
}

func splitRef(ref string) (path, name string) {
	i := strings.LastIndex(ref, ".")
	return ref[:i], ref[i+1:]
}

// Close refuses each declaration of the package path that names a refused
// type, of its package or another (refusedElsewhere), until none is left:
// a struct field or an interface method that names one becomes a refused
// member, and any other declaration is refused whole. A use of a prelude
// type (Map, Seq, Option) is refused when the package declares a type of
// that name, which would hide it in the binding. So every binding checks
// clean: it names only types that map (docs/spec/interop.md).
func Close(path string, decls []Decl, refusedElsewhere func(ref string) bool) []Decl {
	local, refused := map[string]bool{}, map[string]bool{}
	for _, d := range decls {
		if d.Kind == Type {
			local[d.Name] = true
			refused[d.Name] = d.Refused != ""
		}
	}
	bad := func(refs []string) string {
		for _, ref := range refs {
			p, name := splitRef(ref)
			switch {
			case p == "" && local[name]:
				return fmt.Sprintf("the package declares its own %s, which hides Ergo's %s in the binding", name, name)
			case p == path && refused[name]:
				return "it names the refused type " + name
			case p != "" && p != path && refusedElsewhere(ref):
				return "it names the refused type " + ref
			}
		}
		return ""
	}
	for changed := true; changed; {
		changed = false
		for i := range decls {
			d := &decls[i]
			if d.Refused != "" {
				continue
			}
			if why := bad(d.Refs); why != "" {
				*d = Decl{Kind: d.Kind, Name: d.Name, Go: d.Go, Refused: why}
				if d.Kind == Type {
					refused[d.Name] = true
				}
				changed = true
				continue
			}
			var kept []Line
			for _, l := range d.Lines {
				if why := bad(l.Refs); why != "" {
					d.Members = append(d.Members, Member{l.Name, l.Go, why})
					continue
				}
				kept = append(kept, l)
			}
			if len(kept) == len(d.Lines) {
				continue
			}
			changed = true
			if len(kept) == 0 && strings.HasSuffix(d.Go, " interface") {
				*d = Decl{Kind: d.Kind, Name: d.Name, Go: d.Go, Refused: "no method of the interface maps"}
				refused[d.Name] = true
				continue
			}
			d.Lines, d.Ergo = kept, typeText(d.Name, kept)
		}
	}
	return decls
}
