// ratchetPath is the check agreement's ratchet: the name of each case it
// was measured on ("case NAME") and each disagreement, named by its case
// and its diagnostic ("site CODE missing|extra in CASE: DIAG"), sorted.
// The counts per code are derived from the sites. It is generated
// (ratchetCommand writes it); a conflict in it is a regeneration.
var ratchetPath = filepath.Join("testdata", "check_agree.sites")

// sitesVariable names the file each run writes its own sites to, in the
// ratchet's form (default: check-agree-sites.txt in the temp directory),
// so a moved count is explained by a diff of names.
const sitesVariable = "ERGO_AGREE_SITES"

// ratchetCommand writes ratchetPath from a run of TestCompilerCheckAgrees.
const ratchetCommand = "ERGO_WRITE_RATCHET=1 go test -count=1 -run '^TestCompilerCheckAgrees$' ./internal/selfhostcheck"

// Match the run queue's width for the parallel side of the comparison.
const checkdumpParallelThreads = 4

// ratchetCount is a code's disagreements: Go lines the Ergo side lacks
// and Ergo lines the Go side lacks.
type ratchetCount struct {
	Missing, Extra int
}

// siteLines is the ratchet's form of a run: a comment, the cases, then
// the sites, each part sorted.
func siteLines(names, sites []string) []string {
	out := []string{"# generated by " + ratchetCommand + "; do not edit"}
	cs := make([]string, 0, len(names))
	for _, n := range names {
		cs = append(cs, "case "+n)
	}
	sort.Strings(cs)
	ss := make([]string, 0, len(sites))
	for _, x := range sites {
		ss = append(ss, "site "+x)
	}
	sort.Strings(ss)
	return append(append(out, cs...), ss...)
}

// readSites reads a ratchet file's case names and sites (a multiset).
func readSites(text string) (map[string]bool, map[string]int) {
	cases, sites := map[string]bool{}, map[string]int{}
	for _, l := range strings.Split(text, "\n") {
		if n, ok := strings.CutPrefix(l, "case "); ok {
			cases[n] = true
		} else if x, ok := strings.CutPrefix(l, "site "); ok {
			sites[x]++
		}
	}
	return cases, sites
}

// countSites is the per-code count of sites, each "CODE missing|extra …".
func countSites(sites map[string]int) map[string]ratchetCount {
	out := map[string]ratchetCount{}
	for x, k := range sites {
		f := strings.Fields(x)
		if len(f) < 2 {
			continue
		}
		n := out[f[0]]
		if f[1] == "missing" {
			n.Missing += k
		} else {
			n.Extra += k
		}
		out[f[0]] = n
	}
	return out
}

// checkLine is one diagnostic as checkdump prints it.
type checkLine struct {
	File    string `json:"file"`
	Line    int    `json:"line"`
	Col     int    `json:"col"`
	Code    string `json:"code"`
	Message string `json:"message"`
}

func (l checkLine) String() string {
	return fmt.Sprintf("%s %d:%d: %s %s", l.File, l.Line, l.Col, l.Code, l.Message)
}

// agreeCase is one package of the agreement: its files, the tables the Go
// side writes for the Ergo side, and the Go checker's diagnostics.
type agreeCase struct {
	name         string
	path         string
	files        []string
	ext, foreign []string
	want         []checkLine
	src          string // a generated case's source
}

// goCheckLines is ds as checkdump's lines, each in the file names gives.
func goCheckLines(ds []check.Diagnostic, names []string) []checkLine {
	var out []checkLine
	for _, d := range ds {
		name := ""
		if d.File >= 0 && d.File < len(names) {
			name = names[d.File]
		}
		out = append(out, checkLine{File: name, Line: d.Line, Col: d.Column, Code: d.Code, Message: d.Message})
	}
	return out
}

// TestCompilerCheckAgrees is S3-AGREE's one driver: the self-hosted
// checker's diagnostics (cmd/checkdump: code, position and text, as JSON)
// against the Go checker's, over
//   - every corpus folder the Go checker accepts (it reports none there:
//     an Ergo line is a false diagnostic),
//   - the Go checker's negative fixtures, each a package of one file, and
//   - seeded programs: the unused perturbations of corpus files and the
//     ownership-flow programs.
//
// checkdump runs once serially and once in parallel; the two outputs
// must be the same bytes (a hard failure, never ratcheted). The disagreements are
// counted per code, a Go line the Ergo side lacks (missing) and an Ergo
// line the Go side lacks (extra), and held against the ratchet file: a
// site the file lacks fails, printed in full, and so does a case the file
// names that this run no longer draws (never a silent drop); a site the
// run lacks is logged (the file only shrinks, by regeneration:
// ratchetCommand). Each run writes its own sites to a file
// (sitesVariable). The Ergo side types with the tables the Go side writes
// (prelude, universe, Go imports), as the expression agreement does.
//
// It builds Go because checkdump is the Ergo program under test: only its
// lowered, built form runs over the corpus.
func TestCompilerCheckAgrees(t *testing.T) {
	needsBuild(t)
	ctx, cancel := testwait.Context(t, context.Background())
	defer cancel()
	base := uint32(1)
	if v := os.Getenv(seedVariable); v != "" {
		n, err := strconv.ParseUint(v, 10, 32)
		if err != nil {
			t.Fatalf("%s=%q: %v", seedVariable, v, err)
		}
		base = uint32(n)
	}
	var cases []agreeCase
	// The corpus, one folder at a time (eachGoPackage), and the folders of
	// testdata/agree: the smallest programs of gaps found elsewhere, each
	// a package the Go checker accepts.
	dirs := corpusDirs(t)
	err := filepath.WalkDir(filepath.Join(repoRoot(), "internal", "selfhostcheck", "testdata", "agree"), func(p string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() && strings.HasSuffix(p, ".ergo") && dirs[len(dirs)-1] != filepath.Dir(p) {
			dirs = append(dirs, filepath.Dir(p))
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	corpus := make([]*agreeCase, len(dirs))
	eachGoPackage(dirs, func(i int, pkg *check.Package) {
		_, ext := goKinds(pkg)
		_, foreign := goTypes(pkg)
		corpus[i] = &agreeCase{name: rel(dirs[i]), path: importPath(dirs[i], pkg), ext: ext, foreign: foreign}
	})
	for i, c := range corpus {
		if c != nil {
			c.files = ergoFiles(t, dirs[i])
			cases = append(cases, *c)
		}
	}
	folders := len(cases)
	// One source as a package of one file: the Go checker's diagnostics
	// and its tables.
	tmp := t.TempDir()
	single := func(name, file, src string, checkSource func(string) (*check.Package, []check.Diagnostic)) bool {
		pkg, ds := checkSource(src)
		if pkg == nil || (len(ds) > 0 && ds[0].Code == check.CodeSyntax) {
			return false // the parser's, not the checker's
		}
		dir := filepath.Join(tmp, "case", strconv.Itoa(len(cases)))
		if err := os.MkdirAll(dir, 0o755); err != nil {
			t.Fatal(err)
		}
		f := filepath.Join(dir, file)
		writeLines(t, f, []string{strings.TrimSuffix(src, "\n")})
		_, ext := goKinds(pkg)
		_, foreign := goTypes(pkg)
		cases = append(cases, agreeCase{name: name, path: "main", files: []string{f}, ext: ext, foreign: foreign, want: goCheckLines(ds, []string{file}), src: src})
		return true
	}
	fixtures := 0
	for _, glob := range []string{"internal/sketch/check/testdata/fixtures/negative/*.ergo", "internal/sketch/check/testdata/v1/*.neg.ergo"} {
		paths, err := filepath.Glob(filepath.Join(repoRoot(), glob))
		if err != nil {
			t.Fatal(err)
		}
		for _, p := range paths {
			src, err := os.ReadFile(p)
			if err != nil {
				t.Fatal(err)
			}
			if single(rel(p), filepath.Base(p), string(src), check.CheckSource) {
				fixtures++
			}
		}
	}
	seeds := 0
	pool := unusedPool(t)
	for _, d := range unusedDraws(pool) {
		if single(d.name, "p.ergo", d.src, d.check) {
			seeds++
		}
	}
	for seed := base; seed < base+300; seed++ {
		if single(fmt.Sprintf("flow seed %d", seed), "p.ergo", flowProgram(seed), check.CheckSource) {
			seeds++
		}
	}
	var manifest []string
	goLines := 0
	for i, c := range cases {
		e, f := filepath.Join(tmp, fmt.Sprintf("ext%d", i)), filepath.Join(tmp, fmt.Sprintf("foreign%d", i))
		writeLines(t, e, c.ext)
		writeLines(t, f, c.foreign)
		manifest = append(manifest, strings.Join(append([]string{c.path, e, f}, c.files...), " "))
		goLines += len(c.want)
	}
	m := filepath.Join(tmp, "manifest")
	writeLines(t, m, manifest)
	bin := filepath.Join(t.TempDir(), "checkdump")
	if o, err := runCompiler(t, ctx, ergoCLI(t, ctx), "build", "-o", bin, "./cmd/checkdump"); err != nil {
		t.Fatalf("ergo build ./cmd/checkdump: %v\n%s", err, o)
	}
	one := runDump(t, ctx, bin, "-std", stdDir(), "-threads", "1", "-corpus", m)
	parallel := runDump(t, ctx, bin, "-std", stdDir(), "-threads", strconv.Itoa(checkdumpParallelThreads), "-corpus", m)
	if a, b := strings.Join(one, "\n"), strings.Join(parallel, "\n"); a != b {
		t.Fatalf("checkdump -threads 1 and -threads %d differ:\n%s", checkdumpParallelThreads, firstDifference(one, parallel))
	}
	got := make([][]checkLine, len(cases))
	at := -1
	for _, l := range one {
		if strings.HasPrefix(l, "@pkg ") {
			at++
			continue
		}
		var c checkLine
		if err := json.Unmarshal([]byte(l), &c); err != nil {
			t.Fatalf("checkdump wrote a line that is no diagnostic object: %v\n%s", err, l)
		}
		if at >= 0 && at < len(cases) {
			got[at] = append(got[at], c)
		}
	}
	if at != len(cases)-1 {
		t.Fatalf("checkdump -corpus wrote %d packages, want %d", at+1, len(cases))
	}
	// The disagreements, each named by its case and its diagnostic.
	var sites, names []string
	for i, c := range cases {
		names = append(names, c.name)
		have := map[string]int{}
		for _, l := range got[i] {
			have[l.String()]++
		}
		for _, w := range c.want {
			if have[w.String()] > 0 {
				have[w.String()]--
				continue
			}
			sites = append(sites, fmt.Sprintf("%s missing in %s: %s", w.Code, c.name, w))
		}
		for _, l := range got[i] {
			if have[l.String()] > 0 {
				have[l.String()]--
				sites = append(sites, fmt.Sprintf("%s extra in %s: %s", l.Code, c.name, l))
			}
		}
	}
	lines := siteLines(names, sites)
	text := strings.Join(lines, "\n") + "\n"
	out := os.Getenv(sitesVariable)
	if out == "" {
		out = filepath.Join(os.TempDir(), "check-agree-sites.txt")
	}
	if err := os.WriteFile(out, []byte(text), 0o644); err != nil {
		t.Fatal(err)
	}
	nowCases, nowSites := readSites(text)
	counts := countSites(nowSites)
	codes := make([]string, 0, len(counts))
	missing, extra := 0, 0
	for code, n := range counts {
		codes = append(codes, code)
		missing += n.Missing
		extra += n.Extra
	}
	sort.Strings(codes)
	var table []string
	for _, code := range codes {
		table = append(table, fmt.Sprintf("%s missing %d extra %d", code, counts[code].Missing, counts[code].Extra))
	}
	t.Logf("%d corpus folders, %d fixtures, %d seeds (%d cases); %d Go diagnostics; %d missing, %d extra (sites: %s):\n%s", folders, fixtures, seeds, len(cases), goLines, missing, extra, out, strings.Join(table, "\n"))
	write := os.Getenv("ERGO_WRITE_RATCHET") != ""
	b, err := os.ReadFile(ratchetPath)
	if write && os.IsNotExist(err) {
		b, err = nil, nil // first generation has no previous cases
	}
	if err != nil {
		t.Fatalf("no ratchet: %v (write it: %s)", err, ratchetCommand)
	}
	wasCases, wasSites := readSites(string(b))
	var gone, added, fewer []string
	for n := range wasCases {
		if !nowCases[n] {
			gone = append(gone, n)
		}
	}
	for x, k := range nowSites {
		if k > wasSites[x] {
			added = append(added, x)
		}
	}
	for x, k := range wasSites {
		if k > nowSites[x] {
			fewer = append(fewer, x)
		}
	}
	sort.Strings(gone)
	sort.Strings(added)
	sort.Strings(fewer)
	if len(gone) > 0 {
		t.Fatalf("%d cases of the ratchet are no longer drawn (resolve each, then regenerate: %s):\n%s", len(gone), ratchetCommand, strings.Join(gone, "\n"))
	}
	if write {
		if err := os.WriteFile(ratchetPath, []byte(text), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("wrote %s", ratchetPath)
		return
	}
	if len(added) > 0 {
		t.Errorf("%d sites the ratchet does not hold (diff %s against %s):\n%s", len(added), out, ratchetPath, strings.Join(added, "\n"))
	}
	if len(fewer) > 0 {
		t.Logf("%d sites of the ratchet are gone; regenerate: %s", len(fewer), ratchetCommand)
	}
}

// firstDifference is the first line where a and b differ, with its index.
func firstDifference(a, b []string) string {
	for i := 0; i < len(a) || i < len(b); i++ {
		var x, y string
		if i < len(a) {
			x = a[i]
		}
		if i < len(b) {
			y = b[i]
		}
		if x != y {
			return fmt.Sprintf("line %d:\n-threads 1: %s\n-threads %d: %s", i+1, x, checkdumpParallelThreads, y)
		}
	}
	return "(same lines)"
}
