package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateFailLocal is a program whose fallible bodies fail with a local
// or a parameter (INLINE-FAIL-LOCAL, lower/ir_forms_inline.go): the IR
// inliner copies them into a site that binds a value and an error, the
// failure set as the site's error by its Go type.
//   - a try in a let (tryLet), in a return under an if (tryRet), and in a
//     match arm (tryMatch): each passes on a callee's error, a local of
//     type error;
//   - a failure held in a let and returned from a match arm or an if
//     (held): a local of a failure type, converted to error;
//   - a failure passed as a parameter (failWith, a record; orFail, a
//     generic one over an Option, the shape of a prelude OrFail written
//     by a user): a parameter, converted to error, or standing for the
//     caller's local it reads;
//   - main catches each in its loop (a variant binding read in the arm),
//     run catches in a loop and passes its last failure on through a
//     try, and main catches that in even seeds and fails with it in odd
//     ones (uncaught: the program exits 1 with the cause).
//
// main prints the totals; a copy whose failure is the wrong value, of the
// wrong type, or lost changes them or the exit status.
func GenerateFailLocal(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x6661696c6c6f6361))
	n := func(k int) int { return r.IntN(k) }
	row := "Gone | Bad"
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateFailLocal\n\n")
	b.WriteString("type Gone { At int }\n\ntype Bad { Why int }\n\n")
	fmt.Fprintf(&b, "func c0(x int) int fails %s {\n\tif x < -500 {\n\t\treturn Gone{At: x}\n\t}\n\tif x %% %d == 0 {\n\t\treturn Gone{At: x}\n\t}\n\tif x %% %d == 1 {\n\t\treturn Bad{Why: x}\n\t}\n\tx * %d\n}\n\n", row, 3+n(5), 4+n(5), 2+n(4))
	fmt.Fprintf(&b, "func tryLet(x int) int fails %s {\n\tlet v = try c0(x + %d)\n\tv + %d\n}\n\n", row, n(5), 1+n(9))
	fmt.Fprintf(&b, "func tryRet(x int) int fails %s {\n\tif x %% 2 == %d {\n\t\treturn try c0(x - %d)\n\t}\n\tx + %d\n}\n\n", row, n(2), n(5), n(9))
	fmt.Fprintf(&b, "func tryMatch(x int) int fails %s {\n\tmatch x %% 3 {\n\tcase 0:\n\t\tlet a = try c0(x)\n\t\ta + 1\n\tcase 1:\n\t\tlet c = try tryLet(x + %d)\n\t\tc * 2\n\tcase _:\n\t\tx\n\t}\n}\n\n", row, n(7))
	fmt.Fprintf(&b, "func held(x int) int fails %s {\n\tlet g = Gone{At: x + %d}\n\tlet e = Bad{Why: x - %d}\n\tif x < -500 {\n\t\treturn g\n\t}\n\tmatch x %% %d {\n\tcase 0:\n\t\treturn g\n\tcase 1:\n\t\treturn e\n\tcase _:\n\t\tx * 3\n\t}\n}\n\n", row, n(9), n(9), 4+n(4))
	fmt.Fprintf(&b, "func failWith(x int, g Gone) int fails Gone {\n\tif x %% %d == 0 {\n\t\treturn g\n\t}\n\tx - 1\n}\n\n", 3+n(4))
	b.WriteString("func orFail[T, F](o Option[T], f F) T fails F {\n\tmatch o {\n\tcase Some[T] as s:\n\t\ts.Value\n\tcase None:\n\t\treturn f\n\t}\n}\n\n")
	b.WriteString("func look(m Map[int, int], k int) int fails Gone {\n\tlet v = try orFail(m.Get(k), Gone{At: k})\n\tv + 1\n}\n\n")
	b.WriteString("func viaFailWith(x int) int fails Gone {\n\tlet g = Gone{At: x * 2}\n\tlet v = try failWith(x, g)\n\tv\n}\n\n")
	fmt.Fprintf(&b, "func run(n int, last int) int fails %s {\n\tlet mut t = 0\n\tfor i in 0..n {\n\t\tt = t + (tryLet(i) catch {\n\t\tcase Gone as g:\n\t\t\tg.At\n\t\tcase Bad:\n\t\t\t1\n\t\t})\n\t}\n\tlet w = try held(last)\n\tt + w\n}\n\n", row)
	fmt.Fprintf(&b, "func main() fails %s needs Console {\n", row)
	keys := make([]string, 3+n(5))
	for i := range keys {
		keys[i] = fmt.Sprintf("%d: %d", 2*i+n(2), n(50))
	}
	fmt.Fprintf(&b, "\tlet m = Map[int, int]{%s}\n", strings.Join(keys, ", "))
	b.WriteString("\tlet mut total = 0\n")
	fmt.Fprintf(&b, "\tfor i in 0..%d {\n", 40+n(120))
	for _, f := range []string{"tryLet", "tryRet", "tryMatch", "held"} {
		fmt.Fprintf(&b, "\t\tlet r%s = %s(i - %d) catch {\n\t\tcase Gone as g:\n\t\t\tg.At %% 7\n\t\tcase Bad as e:\n\t\t\te.Why * 2\n\t\t}\n", f, f, n(10))
		fmt.Fprintf(&b, "\t\ttotal = total + r%s\n", f)
	}
	b.WriteString("\t\tlet w = failWith(i, Gone{At: i + 1}) catch {\n\t\tcase Gone as g:\n\t\t\t0 - g.At\n\t\t}\n")
	b.WriteString("\t\tlet v = viaFailWith(i) catch {\n\t\tcase Gone as g:\n\t\t\tg.At + 5\n\t\t}\n")
	fmt.Fprintf(&b, "\t\tlet k = look(m, i %% %d) catch {\n\t\tcase Gone as g:\n\t\t\tg.At * 3\n\t\t}\n", 8+n(8))
	b.WriteString("\t\ttotal = total + w + v + k\n\t}\n")
	b.WriteString("\tConsole.Println(\"total \\(total)\")\n")
	last := -1000 - n(50) // held fails with g below -500
	if seed%2 == 1 {
		fmt.Fprintf(&b, "\tlet z = try run(%d, %d)\n", 5+n(20), last)
	} else {
		fmt.Fprintf(&b, "\tlet z = run(%d, %d) catch {\n\tcase Gone as g:\n\t\tg.At\n\tcase Bad as e:\n\t\te.Why + 1\n\t}\n", 5+n(20), last)
	}
	b.WriteString("\tConsole.Println(\"z \\(z)\")\n}\n")
	return b.String()
}
