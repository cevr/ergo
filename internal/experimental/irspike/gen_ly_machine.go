package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateMachine is a program whose IR bodies take machine values (F7,
// "machine value"): a machine with an initial value (A) and one with an
// input (B) share a seeded step over a counter state and number signals
// that emits, ignores, finishes, rejects or enters by the signal and the
// state. The IR bodies convert a machine literal to the prelude Machine
// (planA), to an InputMachine started with an input (planB), and read the
// plan's initial state (firstA, through std machines.Initial); main folds
// each plan over seeded signals with std machines.Run, so the step, the
// initial value and the start function of the generated Machine all run.
func GenerateMachine(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x6c796d6163680a02))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateMachine\n\nimport machines\n\n")
	b.WriteString("type St { n int }\n\ntype Sig { v int }\n\n")
	emit, ignore, done, reject := 2+g.n(3), 30+g.n(20), 200+g.n(300), 7+g.n(5)
	fmt.Fprintf(&b, "func stepA(s St, e Sig) Decision[St, int] {\n\tif e.v == %d {\n\t\treturn Reject\n\t}\n\tif e.v %% %d == 0 {\n\t\treturn Emit[St, int]{Next: St{n: s.n + e.v}, Output: s.n}\n\t}\n\tif e.v > %d {\n\t\treturn Ignore\n\t}\n\tif s.n > %d {\n\t\treturn Done[int]{Output: s.n - e.v}\n\t}\n\tEnter[St]{Next: St{n: s.n*2 + e.v}}\n}\n\n", reject, emit, ignore, done)
	fmt.Fprintf(&b, "type A machine[St, Sig] {\n\tinitial: St{n: %d},\n\tstep:    stepA,\n}\n\n", 1+g.n(9))
	fmt.Fprintf(&b, "func startB(i int) St { St{n: i*%d + 1} }\n\n", 2+g.n(4))
	b.WriteString("type B machine[St, Sig] {\n\tinitial: startB,\n\tstep:    stepA,\n}\n\n")
	b.WriteString("func planA() Machine[St, Sig, int] { A{} }\n\n")
	b.WriteString("func planB(i int) Machine[St, Sig, int] { machines.Start(B{}, i) }\n\n")
	b.WriteString("func firstA() int { machines.Initial(A{}).n }\n\n")
	b.WriteString("func show(m Machine[St, Sig, int], signals []Sig) string {\n\tlet o = machines.Run(m, signals) catch {\n\tcase machines.Rejected as r:\n\t\treturn \"rejected at \\(r.At)\"\n\t}\n\tmatch o {\n\tcase machines.Finished[St, int] as f:\n\t\t\"finished \\(f.State.n) \\(f.Output) \\(len(f.Emitted))\"\n\tcase machines.Running[St, int] as r:\n\t\t\"running \\(r.State.n) \\(len(r.Emitted))\"\n\t}\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	for i := 0; i < 3; i++ {
		var sig []string
		for j := 0; j < 3+g.n(6); j++ {
			sig = append(sig, fmt.Sprintf("Sig{v: %d}", g.n(50)))
		}
		fmt.Fprintf(&b, "\tlet s%d = []Sig{%s}\n", i, strings.Join(sig, ", "))
		fmt.Fprintf(&b, "\tConsole.Println(\"%d: \\(firstA()) \\(show(planA(), s%d)) \\(show(planB(%d), s%d))\")\n", i, i, g.n(20), i)
	}
	b.WriteString("}\n")
	return b.String()
}
