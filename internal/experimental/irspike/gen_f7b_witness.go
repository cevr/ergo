package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateWitness is a program of calls that pass witnesses (F7 lane B):
// json.Encode of drawn records (a codec witness) and a generic
// function over a method set, at two record types whose Score bodies are
// drawn, called from functions w0..w(n-1) on drawn values. A witness of
// the wrong instance, one dropped or one passed in the wrong place
// changes the output or fails the IR build. It returns the names of the
// functions that call through a witness.
func GenerateWitness(seed uint64) (string, []string) {
	r := rand.New(rand.NewPCG(seed, seed^0x2545f4914f6cdd1d))
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateWitness\n\nimport json\n\n")
	b.WriteString("type Scored {\n\tScore() int,\n}\n\n")
	fmt.Fprintf(&b, "type A { N int, Tag string } implements Scored\n\ntype B { Xs []int, Ok bool } implements Scored\n\n")
	fmt.Fprintf(&b, "func Score(a A) int {\n\ta.N * %d + len(a.Tag)\n}\n\n", 1+r.IntN(4))
	fmt.Fprintf(&b, "func Score(b B) int {\n\tlet mut t = %d\n\tfor x in b.Xs {\n\t\tt = t + x\n\t}\n\tif b.Ok {\n\t\tt * 2\n\t} else {\n\t\tt\n\t}\n}\n\n", r.IntN(5))
	b.WriteString("func total[T Scored](xs []T) int {\n\tlet mut t = 0\n\tfor x in xs {\n\t\tt = t + x.Score()\n\t}\n\tt\n}\n\n")
	b.WriteString("func pair[P Scored, Q Scored](p P, q Q) int {\n\tp.Score() * 100 + q.Score()\n}\n\n")
	tags := []string{`""`, `"a"`, `"bc"`, `"x\"y"`}
	aLit := func() string { return fmt.Sprintf("A{N: %d, Tag: %s}", r.IntN(9)-2, tags[r.IntN(len(tags))]) }
	bLit := func() string {
		var xs []string
		for i, n := 0, r.IntN(4); i < n; i++ {
			xs = append(xs, fmt.Sprint(r.IntN(7)))
		}
		return fmt.Sprintf("B{Xs: []int{%s}, Ok: %v}", strings.Join(xs, ", "), r.IntN(2) == 0)
	}
	var names []string
	n := 4 + r.IntN(4)
	for i := 0; i < n; i++ {
		name := fmt.Sprintf("w%d", i)
		names = append(names, name)
		switch r.IntN(5) {
		case 0:
			fmt.Fprintf(&b, "func %s() string {\n\tjson.Encode(json.Codec[A]{MaxBytes: 0, MaxDepth: 0}, %s)\n}\n\n", name, aLit())
		case 1:
			fmt.Fprintf(&b, "func %s() string {\n\tjson.Encode(json.Codec[B]{MaxBytes: 0, MaxDepth: 0}, %s)\n}\n\n", name, bLit())
		case 2:
			fmt.Fprintf(&b, "func %s() string {\n\tlet t = total([]A{%s, %s})\n\t\"\\(t)\"\n}\n\n", name, aLit(), aLit())
		case 3:
			fmt.Fprintf(&b, "func %s() string {\n\tlet t = total([]B{%s})\n\t\"\\(t)\"\n}\n\n", name, bLit())
		default:
			p, q := aLit(), bLit()
			if r.IntN(2) == 0 {
				p, q = q, p
			}
			fmt.Fprintf(&b, "func %s() string {\n\tlet t = pair(%s, %s)\n\t\"\\(t)\"\n}\n\n", name, p, q)
		}
	}
	b.WriteString("func main() needs Console {\n")
	for _, name := range names {
		fmt.Fprintf(&b, "\tlet r%s = %s()\n\tConsole.Println(\"%s: \\(r%s)\")\n", name, name, name, name)
	}
	b.WriteString("}\n")
	return b.String(), names
}
