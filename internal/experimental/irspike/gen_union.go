package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateUnion writes the union program of seed (IRG3): a small union
// (Small) that the lowering keeps flat unless the seed makes a variant too
// large for a register-sized struct, a recursive union (Tree) that is
// always a Go interface, a named scalar (Meters), and functions that build
// variants into unions (returned, assigned, as record fields, as call
// arguments, as an if's and a match's arms), match them (statements,
// results, values; type tests, `T as x`, wildcards, arms in any order) and
// match literal subjects of int and string. main prints every function's
// results over fixed inputs.
func GenerateUnion(seed uint64) string {
	g := &ugen{r: rand.New(rand.NewPCG(seed, seed^0x2545f4914f6cdd1d))}
	return g.program()
}

type ugen struct {
	r *rand.Rand
	b strings.Builder
}

func (g *ugen) n(k int) int { return g.r.IntN(k) }

// arms writes the arms in a shuffled order, one per line at indent in.
func (g *ugen) arms(in string, arms []string) string {
	g.r.Shuffle(len(arms), func(i, j int) { arms[i], arms[j] = arms[j], arms[i] })
	// A wildcard covers every later case: it comes last.
	var rest, wild []string
	for _, a := range arms {
		if strings.HasPrefix(a, "case _") {
			wild = append(wild, a)
		} else {
			rest = append(rest, a)
		}
	}
	arms = append(rest, wild...)
	var b strings.Builder
	for _, a := range arms {
		b.WriteString(in + strings.ReplaceAll(a, "\n", "\n"+in) + "\n")
	}
	return b.String()
}

func (g *ugen) program() string {
	g.b.WriteString("// generated by irspike.GenerateUnion\n\n")
	g.b.WriteString("type A {}\n\ntype B { N int }\n\n")
	if g.n(3) == 0 {
		// Too large for the flat form: Small is a Go interface.
		g.b.WriteString("type C { S string, T string }\n\n")
	} else {
		g.b.WriteString("type C { S string }\n\n")
	}
	g.b.WriteString("type Small = A | B | C\n\n")
	g.b.WriteString("type Leaf { N int }\n\ntype Node { L Tree, R Tree, K int }\n\ntype Tree = Leaf | Node\n\n")
	g.b.WriteString("type Meters int\n\n")
	k := 2 + g.n(5)

	// Variants into a union: an if's arms, returned.
	fmt.Fprintf(&g.b, "func mk(i int) Small {\n\tif i %% 3 == 0 {\n\t\tA\n\t} else if i %% 3 == 1 {\n\t\tB{N: i * %d}\n\t} else {\n\t\t%s\n\t}\n}\n\n", k, g.cLit("i"))
	// A match's arms, returned, each a variant.
	fmt.Fprintf(&g.b, "func flip(s Small) Small {\n\tmatch s {\n%s\t}\n}\n\n", g.arms("\t", []string{
		"case A:\n\tB{N: 1}",
		"case B as b:\n\t" + g.cLit("b.N"),
		"case C:\n\tA",
	}))
	// A match in result position: type tests, as, a wildcard.
	weightArms := []string{"case B as b:\n\tb.N * " + fmt.Sprint(k), "case C as c:\n\tlen(c.S) + 100"}
	if g.n(2) == 0 {
		weightArms = append(weightArms, "case A:\n\t-1")
	} else {
		weightArms = append(weightArms, "case _:\n\t-1")
	}
	fmt.Fprintf(&g.b, "func weight(s Small) int {\n\tmatch s {\n%s\t}\n}\n\n", g.arms("\t", weightArms))
	// A match in value position, then used.
	fmt.Fprintf(&g.b, "func name(s Small) string {\n\tlet w = match s {\n%s\t}\n\tw + \"!\"\n}\n\n", g.arms("\t", []string{
		"case A:\n\t\"a\"",
		"case B, C:\n\t\"bc\"",
	}))
	// A match and an if in value position whose arms are variants: they
	// join their union.
	fmt.Fprintf(&g.b, "func pick(s Small, i int) int {\n\tlet u = match s {\n%s\t}\n\tlet v = if i > %d { A } else { u }\n\tweight(u) * 10 + weight(v)\n}\n\n", g.arms("\t", []string{
		"case A:\n\tB{N: i}",
		"case B:\n\t" + g.cLit("i"),
		"case C:\n\ts",
	}), g.n(5))
	// A statement match in a loop: op-assignments, an empty arm, a
	// continue, a wildcard.
	cArm := "case C:\n\tn += 100"
	if g.n(2) == 0 {
		cArm = "case C:\n\tcontinue"
	}
	aArm := "case A:"
	if g.n(2) == 0 {
		aArm = "case _:\n\tn -= 1"
	}
	fmt.Fprintf(&g.b, "func count(xs []Small) int {\n\tlet mut n = 0\n\tfor x in xs {\n\t\tmatch x {\n%s\t\t}\n\t\tn += 1\n\t}\n\tn\n}\n\n", g.arms("\t\t", []string{"case B as b:\n\tn += b.N", cArm, aArm}))
	// A break inside a match leaves the loop, not Go's switch: the loop
	// takes a label the break names.
	fmt.Fprintf(&g.b, "func firstB(xs []Small) int {\n\tlet mut r = -1\n\tfor x in xs {\n\t\tmatch x {\n%s\t\t}\n\t}\n\tr\n}\n\n", g.arms("\t\t", []string{"case B as b:\n\tr = b.N\n\tbreak", "case _:\n\tr += 0"}))
	// Variants as call arguments and in a slice of the union.
	fmt.Fprintf(&g.b, "func all(i int) int {\n\tlet xs = []Small{mk(i), B{N: %d}, A, mk(i + 1), B{N: 5}}\n\tcount(xs) + weight(%s) + firstB(xs) * 1000\n}\n\n", g.n(9), g.cLit("i * 2"))
	// A recursive union: variants as record fields.
	fmt.Fprintf(&g.b, "func build(d int) Tree {\n\tif d <= 0 {\n\t\tLeaf{N: d + %d}\n\t} else {\n\t\tNode{L: build(d - 1), R: Leaf{N: d}, K: d}\n\t}\n}\n\n", g.n(5))
	fmt.Fprintf(&g.b, "func sum(t Tree) int {\n\tmatch t {\n%s\t}\n}\n\n", g.arms("\t", []string{
		"case Leaf as l:\n\tl.N",
		"case Node as n:\n\tn.K + sum(n.L) * " + fmt.Sprint(1+g.n(3)) + " + sum(n.R)",
	}))
	fmt.Fprintf(&g.b, "func depth(t Tree) int {\n\tlet mut d = 0\n\tmatch t {\n%s\t}\n\td\n}\n\n", g.arms("\t", []string{
		"case Leaf:\n\td = 1",
		"case Node as n:\n\tlet l = depth(n.L)\n\tlet r = depth(n.R)\n\td = 1 + l\n\tif r > l {\n\t\td = 1 + r\n\t}",
	}))
	// Literal subjects.
	fmt.Fprintf(&g.b, "func classify(x int) string {\n\tmatch x {\n%s\t}\n}\n\n", g.arms("\t", []string{
		"case 0:\n\t\"zero\"",
		fmt.Sprintf("case 1, %d:\n\t\"few\"", 2+g.n(3)),
		"case -1:\n\t\"minus\"",
		"case _:\n\t\"many\"",
	}))
	fmt.Fprintf(&g.b, "func code(s string) int {\n\tlet c = match s {\n%s\t}\n\tc * %d\n}\n\n", g.arms("\t", []string{
		"case \"a\":\n\t1",
		"case \"b\", \"c\":\n\t2",
		"case _:\n\t0",
	}), k)
	// A named scalar.
	fmt.Fprintf(&g.b, "func stretch(m Meters, by Meters) Meters {\n\tlet mut r = m\n\tif r < %d {\n\t\tr += by * %d\n\t}\n\tr - 1\n}\n\n", g.n(20), 1+g.n(3))
	g.b.WriteString("func meters(m Meters) int {\n\tlet mut n = 0\n\tlet mut x = m\n\tfor x > 0 {\n\t\tx = x - 7\n\t\tn += 1\n\t}\n\tn\n}\n\n")
	g.trees() // gen_tree.go
	g.main()
	return g.b.String()
}

// cLit is a C literal whose text holds the int expression x.
func (g *ugen) cLit(x string) string {
	if strings.Contains(g.b.String(), "type C { S string, T string }") {
		return "C{S: \"c\\(" + x + ")\", T: \"t\"}"
	}
	return "C{S: \"c\\(" + x + ")\"}"
}

func (g *ugen) main() {
	g.b.WriteString("func main() needs Console {\n")
	for i := 0; i < 6; i++ {
		x := g.n(9) - 2
		fmt.Fprintf(&g.b, "\tConsole.Println(\"mk %d \\(weight(mk(%d))) \\(name(mk(%d))) \\(weight(flip(mk(%d)))) \\(all(%d)) \\(pick(mk(%d), %d))\")\n", x, x, x, x, x, x, x)
		fmt.Fprintf(&g.b, "\tConsole.Println(\"classify %d \\(classify(%d)) \\(code(\"%s\"))\")\n", x, x, []string{"a", "b", "c", "d", ""}[g.n(5)])
	}
	for d := 0; d < 4; d++ {
		fmt.Fprintf(&g.b, "\tConsole.Println(\"tree %d \\(sum(build(%d))) \\(depth(build(%d)))\")\n", d, d, d)
	}
	fmt.Fprintf(&g.b, "\tConsole.Println(\"meters \\(meters(stretch(%d, %d)))\")\n", g.n(30), g.n(5))
	g.treeMain() // gen_tree.go
	g.b.WriteString("}\n")
}
