package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// wireWriterSites are GenerateWireWriters's functions with an IR body in
// every seed. The putK take a record first in most seeds, which makes
// them its methods (R1.put0), so the encoders they reach are checked by
// the test's report instead.
var wireWriterSites = []string{"show"}

// wireWriterDecls are what every GenerateWireWriters program holds: the
// union U (a variant of no field, one field and three), put, which
// encodes on the Writer interface, and show, which prints each event
// codec's Events recorded, so an event out of place, missing or with
// another value changes the output.
const wireWriterDecls = `type U = Ua{} | Ub{X int} | Uc{S string, Y []int, Z bool}

func show(evs []codec.Event) string {
	let mut s = ""
	for ev in evs {
		let t = match ev {
		case codec.BoolEvent as x:
			"b\(x.V)"
		case codec.IntEvent as x:
			"i\(x.V)"
		case codec.UintEvent as x:
			"u\(x.V)"
		case codec.FloatEvent as x:
			"f\(x.V)"
		case codec.StringEvent as x:
			"s\(x.V)"
		case codec.BeginListEvent as x:
			"[\(x.N)"
		case codec.EndListEvent:
			"]"
		case codec.BeginObjectEvent as x:
			"{\(x.N)"
		case codec.TagEvent as x:
			"#\(x.Name)"
		case codec.KeyEvent as x:
			"k\(x.K)"
		case codec.EndObjectEvent:
			"}"
		case codec.NullEvent:
			"null"
		case codec.NumberEvent as x:
			"n\(x.Text)"
		}
		s = s + " " + t
	}
	s
}

`

// GenerateWireWriters is a program of encoders on the prelude's Writer
// interface (W1; lower's ir_wire.go, wireWrite): seeded records R0..Rn
// whose fields are drawn from basic values (narrow integers too), slices
// of them, a Map of ints, the union U, an omittable field
// (json.Optional, absent or present), a nullable one (json.Nullable),
// an earlier record, a slice or a Map of earlier records, so the
// encoders call one another, loop, and switch on a variant. Each value
// is written through put(v, w Writer) on codec's Events, and its events
// printed (show).
func GenerateWireWriters(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x510e527fade682d1))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateWireWriters\n\nimport codec\nimport json\n\n")
	b.WriteString(wireWriterDecls)
	kinds := []string{"int", "string", "bool", "float64", "int8", "uint16", "[]int", "[]string", "U", "Map[string, int]", "json.Optional[int]", "json.Nullable[string]"}
	records := 2 + g.n(3)
	fields := make([][]string, records)
	for i := range records {
		var fs []string
		for k := range 1 + g.n(5) {
			opts := append([]string(nil), kinds...)
			if i > 0 {
				opts = append(opts, fmt.Sprintf("R%d", g.n(i)), fmt.Sprintf("[]R%d", g.n(i)), fmt.Sprintf("Map[string, R%d]", g.n(i)))
			}
			ft := opts[g.n(len(opts))]
			fields[i] = append(fields[i], ft)
			fs = append(fs, fmt.Sprintf("F%d %s", k, ft))
		}
		fmt.Fprintf(&b, "type R%d { %s }\n\n", i, strings.Join(fs, ", "))
	}
	var value func(t string, depth int) string
	value = func(t string, depth int) string {
		switch {
		case t == "int":
			return fmt.Sprint(g.n(2000) - 1000)
		case t == "int8":
			return fmt.Sprint(g.n(256) - 128)
		case t == "uint16":
			return fmt.Sprint(g.n(65536))
		case t == "string":
			return []string{`""`, `"a"`, `"q\"x"`, `"é世"`, `"line\nbreak"`}[g.n(5)]
		case t == "bool":
			return []string{"true", "false"}[g.n(2)]
		case t == "float64":
			return []string{"0.5", "-2.25", "1e21", "3.0"}[g.n(4)]
		case t == "json.Optional[int]":
			if g.n(2) == 0 {
				return "json.Absent"
			}
			return fmt.Sprintf("json.Present[int]{Value: %d}", g.n(50))
		case t == "json.Nullable[string]":
			if g.n(2) == 0 {
				return "json.Null"
			}
			return fmt.Sprintf("json.NonNull[string]{Value: %s}", value("string", depth))
		case t == "U":
			switch g.n(3) {
			case 0:
				return "Ua"
			case 1:
				return fmt.Sprintf("Ub{X: %d}", g.n(50))
			}
			return fmt.Sprintf("Uc{S: %s, Y: %s, Z: %s}", value("string", depth), value("[]int", depth), value("bool", depth))
		case strings.HasPrefix(t, "Map[string, "):
			// Keys drawn out of order, so the encoding's order is WireKeys'.
			elem := strings.TrimSuffix(strings.TrimPrefix(t, "Map[string, "), "]")
			var xs []string
			for _, k := range []string{`"z"`, `"b"`, `"m"`, `"a"`}[:g.n(5)] {
				if depth > 2 && strings.HasPrefix(elem, "R") {
					break
				}
				xs = append(xs, k+": "+value(elem, depth+1))
			}
			return t + "{" + strings.Join(xs, ", ") + "}"
		case strings.HasPrefix(t, "[]"):
			elem := t[2:]
			var xs []string
			for range g.n(4) {
				if depth > 2 && strings.HasPrefix(elem, "R") {
					break
				}
				xs = append(xs, value(elem, depth+1))
			}
			return t + "{" + strings.Join(xs, ", ") + "}"
		case strings.HasPrefix(t, "R"):
			var i int
			fmt.Sscan(t[1:], &i)
			var fs []string
			for k, ft := range fields[i] {
				fs = append(fs, fmt.Sprintf("F%d: %s", k, value(ft, depth+1)))
			}
			return t + "{" + strings.Join(fs, ", ") + "}"
		}
		panic("GenerateWireWriters: kind " + t)
	}
	// putK encodes the K-th value on the Writer interface: its type's
	// encoder is the one on the reference Writer.
	var main strings.Builder
	for k := range 6 {
		t := fmt.Sprintf("R%d", g.n(records))
		switch g.n(4) {
		case 0:
			t = "U"
		case 1:
			t = "[]" + t
		}
		fmt.Fprintf(&b, "func put%d(v %s, w Writer) {\n\tencode(v, w)\n}\n\n", k, t)
		fmt.Fprintf(&main, "\tlet e%d = codec.NewEvents()\n\tput%d(%s, e%d)\n\tConsole.Println(show(codec.Recorded(e%d)))\n", k, k, value(t, 0), k, k)
	}
	b.WriteString("func main() needs Console {\n" + main.String() + "}\n")
	return b.String()
}
