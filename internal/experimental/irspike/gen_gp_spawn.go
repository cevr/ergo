package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// spawnFuncs are GenerateSpawn's functions: each starts a task with
// task.Go on its frame scope and owns the Task in the scope's list form,
// and each has an IR body (GP-SPAWN, PARK2's "body that needs a frame").
var spawnFuncs = []string{"join", "spawns", "leave", "scoped", "later", "gather", "sorts"}

// GenerateSpawn is a program of bodies that start tasks (GP-SPAWN): a
// task.Go call takes the body's frame scope, and the Task it returns is an
// owned local, registered on the scope (v1.Owning), handed off when Wait
// takes it (v1.Hand), released where the plan says (Owned.Release) or by
// the scope's End, and kept until the frame's exit is known when the body
// returns it (v1.Returned):
//   - join starts one task and waits for it;
//   - spawns starts and joins a seeded number of tasks in a loop (the shape
//     of benchmarks/park's spawn);
//   - leave starts a task it never waits for: the scope's End joins it, so
//     a defect its block raises at a seeded k ends the program at the
//     frame's exit, after the body's own line;
//   - scoped starts one inside an if block, released at the block's end:
//     its defect at a seeded k ends the program before the line after the
//     block;
//   - later returns its task, which main waits for;
//   - gather's block reads two parameters, a let and the environment
//     (Console), each a field of the captures GoWith keeps in the Task
//     (GP-SPAWN2);
//   - sorts' block matches a union with `T as x` binds, on a subject it
//     computes and on one it captures: the copy of the block GoWith runs
//     holds the match forms, whose binds must be the copy's statements
//     (MATCH-BIND-ICE).
//
// main calls each at seeded arguments and prints what they return. A
// release that does not run, runs at another place or loses its defect
// changes the output.
func GenerateSpawn(seed uint64) string { return generateSpawn(seed, true) }

// generateSpawn is GenerateSpawn, without sorts and its union when
// matches is false: TestIRSpawnsTypeCheck's irGo prints the kinds the
// other bodies use, not a match form's.
func generateSpawn(seed uint64, matches bool) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x6a09e667f3bcc909))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateSpawn\n\nimport task\n\n")
	fmt.Fprintf(&b, "func join(k int) int {\n\tlet t = task.Go() { k * %d }\n\tt.Wait()\n}\n\n", 2+g.n(5))
	b.WriteString("func spawns(n int) int {\n\tlet mut acc = 0\n\tfor i in 0..n {\n\t\tlet t = task.Go() { i & 3 }\n\t\tacc += t.Wait()\n\t}\n\tacc\n}\n\n")
	b.WriteString("func leave(k int) int needs Console {\n\tlet t = task.Go() {\n\t\tlet ys = []int{1, 2}\n\t\tys[k]\n\t}\n\tConsole.Println(\"leave body \\(k)\")\n\tk\n}\n\n")
	fmt.Fprintf(&b, "func scoped(k int) int needs Console {\n\tif k > %d {\n\t\tlet t = task.Go() {\n\t\t\tlet ys = []int{1, 2, 3}\n\t\t\tys[k]\n\t\t}\n\t\tConsole.Println(\"scoped block \\(k)\")\n\t}\n\tConsole.Println(\"scoped after \\(k)\")\n\tk\n}\n\n", g.n(2))
	fmt.Fprintf(&b, "func later(k int) Task[int] {\n\tlet t = task.Go() { k + %d }\n\tt\n}\n\n", 1+g.n(9))
	fmt.Fprintf(&b, "func gather(a int, s string) int needs Console {\n\tlet w = a * %d\n\tlet t = task.Go() {\n\t\tConsole.Println(\"gather \\(s) \\(w)\")\n\t\tw + len(s) - a\n\t}\n\tt.Wait()\n}\n\n", 2+g.n(4))
	askAt, sorts := 1+g.n(4), g.n(8) // drawn either way, so the other draws stay the same
	if matches {
		b.WriteString("type Ask = Big{N int} | Small{N int}\n\n")
		fmt.Fprintf(&b, "func ask(k int) Ask {\n\tif k > %d {\n\t\tBig{N: k * 2}\n\t} else {\n\t\tSmall{N: k}\n\t}\n}\n\n", askAt)
		b.WriteString("func sorts(k int) int {\n\tlet a = ask(k + 1)\n\tlet t = task.Go() {\n\t\tlet mut r = 0\n\t\tmatch ask(k) {\n\t\tcase Big as b:\n\t\t\tr = b.N + 1\n\t\tcase Small as s:\n\t\t\tr = s.N * 3\n\t\t}\n\t\tmatch a {\n\t\tcase Big as b:\n\t\t\tr = r + b.N * 5\n\t\tcase Small as s:\n\t\t\tr = r - s.N\n\t\t}\n\t\tr\n\t}\n\tt.Wait()\n}\n\n")
	}
	b.WriteString("func main() needs Console {\n")
	for i, k := 0, 2+g.n(3); i < k; i++ {
		fmt.Fprintf(&b, "\tConsole.Println(\"join \\(join(%d))\")\n", g.n(9))
		fmt.Fprintf(&b, "\tConsole.Println(\"spawns \\(spawns(%d))\")\n", g.n(6))
		fmt.Fprintf(&b, "\tConsole.Println(\"leave \\(leave(%d))\")\n", g.n(2))
		fmt.Fprintf(&b, "\tConsole.Println(\"scoped \\(scoped(%d))\")\n", g.n(3))
		fmt.Fprintf(&b, "\tlet l%d = later(%d)\n\tConsole.Println(\"later \\(l%d.Wait())\")\n", i, g.n(9), i)
		fmt.Fprintf(&b, "\tConsole.Println(\"gather \\(gather(%d, %q))\")\n", g.n(9), []string{"", "ab", "xyz"}[g.n(3)])
		if matches {
			fmt.Fprintf(&b, "\tConsole.Println(\"sorts \\(sorts(%d))\")\n", (sorts+i)%8)
		}
	}
	// The last call raises a defect at a task's release, which ends the
	// program: the seed's residue mod 2 picks the frame's End (leave) or
	// the block's end (scoped), so two seeds in a row reach each.
	if seed%2 == 0 {
		b.WriteString("\tConsole.Println(\"leave \\(leave(5))\")\n")
	} else {
		b.WriteString("\tConsole.Println(\"scoped \\(scoped(7))\")\n")
	}
	b.WriteString("}\n")
	return b.String()
}
