package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateAdaptTask is a program of a std call whose Go parameter is a
// block that runs on a task of its own (FLIP OPC-adapt): tasks.Go of a
// literal (one that fails with a seeded Bad, one that does not) or of a
// trailing block, in functions the IR lowers. main starts the members on a
// FailFast Set in a seeded order, the failing one last, waits, and prints
// what the Wait failed with and which later Go calls the closed Set
// refused; a block's failure its adapter loses changes the output.
func GenerateAdaptTask(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x9b05688c2b3e6c1f))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateAdaptTask\n\nimport tasks\n\ntype Bad { N int }\n\n")
	n := 1 + g.n(90)
	b.WriteString("func quiet(set tasks.Set[Bad]) bool {\n\ttasks.Go(set, func() fails Bad {}) catch {\n\tcase tasks.Closed:\n\t\treturn false\n\t}\n\ttrue\n}\n\n")
	fmt.Fprintf(&b, "func loud(set tasks.Set[Bad]) bool {\n\ttasks.Go(set, func() fails Bad { return Bad{N: %d} }) catch {\n\tcase tasks.Closed:\n\t\treturn false\n\t}\n\ttrue\n}\n\n", n)
	// A trailing block that fails at a call's failure is a function
	// literal the IR keeps as source (closureLit's unitReturns): this one
	// runs a call that cannot fail.
	fmt.Fprintf(&b, "func calm(k int) int {\n\tk * %d\n}\n\n", 2+g.n(5))
	b.WriteString("func block(set tasks.Set[Bad]) bool {\n\ttasks.Go(set) {\n\t\tlet _ = calm(3)\n\t} catch {\n\tcase tasks.Closed:\n\t\treturn false\n\t}\n\ttrue\n}\n\n")
	starts := []string{"quiet", "loud", "block"}
	// Each function is called (an unused one is not lowered): quiet and
	// block in a seeded order with seeded extras, then loud last, so no
	// Go before the Wait races the failure that closes the Set.
	var later []string
	first := []string{"quiet", "block"}
	g.r.Shuffle(2, func(i, j int) { first[i], first[j] = first[j], first[i] })
	for i, k := 0, g.n(3); i < k; i++ {
		first = append(first, []string{"quiet", "block"}[g.n(2)])
	}
	first = append(first, "loud")
	for i, k := 0, 1+g.n(3); i < k; i++ {
		later = append(later, starts[g.n(3)])
	}
	b.WriteString("func main() needs Console {\n\tlet set = tasks.NewSet[Bad](tasks.FailFast)\n")
	for i, f := range first {
		fmt.Fprintf(&b, "\tlet a%d = %s(set)\n", i, f)
	}
	b.WriteString("\tlet mut failed = 0\n\tset.Wait() catch {\n\tcase Bad as x:\n\t\tfailed = x.N\n\t}\n")
	for i, f := range later {
		fmt.Fprintf(&b, "\tlet b%d = %s(set)\n", i, f)
	}
	b.WriteString("\tset.Stop()\n")
	for i := range first {
		fmt.Fprintf(&b, "\tConsole.Println(\"a%d \\(a%d)\")\n", i, i)
	}
	b.WriteString("\tConsole.Println(\"failed \\(failed)\")\n")
	for i := range later {
		fmt.Fprintf(&b, "\tConsole.Println(\"b%d \\(b%d)\")\n", i, i)
	}
	b.WriteString("}\n")
	return b.String()
}
