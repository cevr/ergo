package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateSeed is a program whose functions start let mut slices from
// one-element literals and grow them in place (MAPCOPY RU11, the seeded
// capacity; lower/seedcap.go), among the statements that would see a
// slice's room past its length if the value rule forgot it: a copy of
// the slice into another let mut that both then grow, a slice stored in
// a slice of slices before its own next Append, a let bound to it before
// an Append, a call that appends to its parameter, re-seeding inside a
// loop (hosts/mygo's flatten). main prints every slice's elements, so an
// Append that writes into another value's array changes what it prints.
func GenerateSeed(seed uint64) string {
	g := &seedGen{r: rand.New(rand.NewPCG(seed, seed^0x5eedca9))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateSeed\n\n")
	b.WriteString("func show(xs []int) string {\n\tlet mut s = \"[\"\n\tfor x in xs {\n\t\ts = s + \" \\(x)\"\n\t}\n\ts + \" ]\"\n}\n\n")
	b.WriteString("func shows(xss [][]int) string {\n\tlet mut s = \"\"\n\tfor xs in xss {\n\t\ts = s + show(xs)\n\t}\n\ts\n}\n\n")
	b.WriteString("func grow(xs []int, v int) []int {\n\tlet mut ys = xs\n\tys = ys.Append(v)\n\tys\n}\n\n")
	// A generic body's seeded literal: its slice type names T.
	b.WriteString("func pair[T](a T, c T) []T {\n\tlet mut xs = []T{a}\n\txs = xs.Append(c)\n\txs\n}\n\n")
	nf := 3 + g.r.IntN(3)
	for i := 0; i < nf; i++ {
		fmt.Fprintf(&b, "func f%d(n int, k int) needs Console {\n", i)
		b.WriteString("\tlet mut xs = []int{k}\n\tlet mut ys = []int{}\n\tlet mut out = [][]int{}\n")
		for s, ns := 0, 4+g.r.IntN(8); s < ns; s++ {
			b.WriteString(g.stmt("\t", s, 0))
		}
		// Each let mut is written at least once (the checker refuses one
		// that is not), and the stored xs is grown after.
		b.WriteString("\tout = out.Append(xs)\n\tys = ys.Append(k)\n\txs = xs.Append(n)\n")
		b.WriteString("\tConsole.Println(\"xs \\(show(xs)) ys \\(show(ys)) out \\(shows(out))\")\n}\n\n")
	}
	b.WriteString("func main() needs Console {\n\tConsole.Println(show(pair(7, 8)))\n")
	for i := 0; i < nf; i++ {
		for _, in := range []string{"0, 1", "1, 2", "3, 5"} {
			fmt.Fprintf(&b, "\tf%d(%s)\n", i, in)
		}
	}
	b.WriteString("}\n")
	return b.String()
}

type seedGen struct{ r *rand.Rand }

// stmt is the s-th statement at indent ind, d loops deep.
func (g *seedGen) stmt(ind string, s, d int) string {
	v := []string{"xs", "ys"}[g.r.IntN(2)]
	w := map[string]string{"xs": "ys", "ys": "xs"}[v]
	val := []string{"k", "n", fmt.Sprint(s), "len(xs)"}[g.r.IntN(4)]
	switch g.r.IntN(10) {
	case 0, 1, 2:
		return fmt.Sprintf("%s%s = %s.Append(%s)\n", ind, v, v, val)
	case 3:
		return fmt.Sprintf("%s%s = []int{%s}\n", ind, v, val)
	case 4:
		return fmt.Sprintf("%s%s = %s\n", ind, w, v)
	case 5:
		return fmt.Sprintf("%sout = out.Append(%s)\n", ind, v)
	case 6:
		return fmt.Sprintf("%slet z%d = %s\n%s%s = %s.Append(%d)\n%sConsole.Println(\"z%d \\(show(z%d))\")\n", ind, s, v, ind, v, v, 100+s, ind, s, s)
	case 7:
		return fmt.Sprintf("%s%s = grow(%s, %d)\n", ind, w, v, 200+s)
	case 8:
		return fmt.Sprintf("%sConsole.Println(\"%s \\(show(%s))\")\n", ind, v, v)
	}
	if d > 0 {
		return fmt.Sprintf("%s%s = %s.Append(%s)\n", ind, v, v, val)
	}
	// A loop that re-seeds and stores, as flatten does.
	var b strings.Builder
	fmt.Fprintf(&b, "%sfor i%d in 0..n {\n", ind, s)
	for j, nj := 0, 1+g.r.IntN(4); j < nj; j++ {
		b.WriteString(g.stmt(ind+"\t", 1000+s*10+j, d+1))
	}
	fmt.Fprintf(&b, "%s\t%s = %s.Append(i%d)\n%s}\n", ind, v, v, s, ind)
	return b.String()
}
