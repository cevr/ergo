package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateTupleArg is a program whose types hold a tuple wherever a type
// is spelled (PORT-TUPLE-ARG): a type argument of the prelude Option, of a
// generic record of the program (Box[T]) and of a generic function (keep),
// a slice's element, a Map's value, a tuple's own element, at any depth
// (Option[Box[((int, string), int)]]). Each shape k is a type T<k> built
// by mk<k>(a, b) and read back to an int by rd<k>(v), each from its inner
// shape's; every element of a tuple is read, weighted by its place, so a
// field read from the wrong place, an element lost or a wrapper that is
// not the value's changes what main prints at its inputs. A shape with a
// tuple in it is drawn first, so each program spells one at depth two or
// more.
func GenerateTupleArg(seed uint64) string {
	g := &tagen{r: rand.New(rand.NewPCG(seed, seed^0x5e1d7a3c90b4f62d))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateTupleArg\n\n")
	b.WriteString("type Box[T] { V T }\n\n")
	b.WriteString("func keep[T](x T) T {\n\tx\n}\n\n")
	n := 3 + g.r.IntN(3)
	var roots []tashape
	for i := 0; i < n; i++ {
		roots = append(roots, g.shape(&b, 3, true))
	}
	b.WriteString("func main() needs Console {\n")
	for _, s := range roots {
		for _, in := range [][2]int{{0, 0}, {1, 2}, {5, 3}, {-4, 9}} {
			fmt.Fprintf(&b, "\tConsole.Println(\"%s %d %d \\(rd%d(keep(mk%d(%d, %d))))\")\n", s.name, in[0], in[1], s.k, s.k, in[0], in[1])
		}
	}
	b.WriteString("}\n")
	return b.String()
}

type tagen struct {
	r    *rand.Rand
	next int
}

// tashape is a generated type: its Ergo spelling, the index k of its mk
// and rd functions, a name for main's lines.
type tashape struct {
	typ  string
	k    int
	name string
}

// shape writes the functions of a fresh shape of at most depth levels and
// returns it; tuple asks for a tuple at this level or below.
func (g *tagen) shape(b *strings.Builder, depth int, tuple bool) tashape {
	k := g.next
	g.next++
	wrappers := []string{"option", "box", "slice", "map"}
	var forms []string
	switch {
	case depth <= 0:
		forms = []string{"leaf"}
	case tuple && depth >= 3:
		forms = wrappers // a wrapper on top: the tuple is its argument or below
	case tuple && depth == 1:
		forms = []string{"tuple", "tuple2"}
	case tuple:
		forms = append([]string{"tuple", "tuple2"}, wrappers...)
	default:
		forms = append([]string{"tuple", "tuple2", "leaf"}, wrappers...)
	}
	form := forms[g.r.IntN(len(forms))]
	sub := func(tuple bool) tashape { return g.shape(b, depth-1, tuple) }
	var s tashape
	switch form {
	case "leaf":
		if g.r.IntN(2) == 0 {
			s = tashape{typ: "int", k: k, name: "int"}
			fmt.Fprintf(b, "func mk%d(a int, b int) int {\n\ta * 3 - b\n}\n\n", k)
			fmt.Fprintf(b, "func rd%d(v int) int {\n\tv\n}\n\n", k)
		} else {
			s = tashape{typ: "string", k: k, name: "string"}
			fmt.Fprintf(b, "func mk%d(a int, b int) string {\n\t\"s\\(a)_\\(b)\"\n}\n\n", k)
			fmt.Fprintf(b, "func rd%d(v string) int {\n\tlen(v)\n}\n\n", k)
		}
	case "tuple", "tuple2":
		x := sub(false)
		y := tashape{typ: "int", k: -1}
		if form == "tuple2" {
			y = sub(false)
		}
		if g.r.IntN(2) == 0 && form == "tuple" { // a tuple of a tuple
			x = g.wrapTuple(b, x)
		}
		s = tashape{typ: "(" + x.typ + ", " + y.typ + ")", k: k, name: "(" + x.name + ", " + y.name + ")"}
		ymk, yrd := "b - a", "y"
		if y.k >= 0 {
			ymk, yrd = fmt.Sprintf("mk%d(b, a)", y.k), fmt.Sprintf("rd%d(y)", y.k)
		}
		fmt.Fprintf(b, "func mk%d(a int, b int) %s {\n\t(mk%d(a, b), %s)\n}\n\n", k, s.typ, x.k, ymk)
		fmt.Fprintf(b, "func rd%d(v %s) int {\n\tlet (x, y) = v\n\trd%d(x) * 31 + %s\n}\n\n", k, s.typ, x.k, yrd)
	case "option":
		x := sub(tuple)
		s = tashape{typ: "Option[" + x.typ + "]", k: k, name: "Option[" + x.name + "]"}
		fmt.Fprintf(b, "func mk%d(a int, b int) %s {\n\tif a <= b {\n\t\treturn Some{Value: mk%d(a, b)}\n\t}\n\tNone\n}\n\n", k, s.typ, x.k)
		fmt.Fprintf(b, "func rd%d(v %s) int {\n\tmatch v {\n\tcase Some[%s] as s:\n\t\trd%d(s.Value) + 1\n\tcase None:\n\t\t-7\n\t}\n}\n\n", k, s.typ, x.typ, x.k)
	case "box":
		x := sub(tuple)
		s = tashape{typ: "Box[" + x.typ + "]", k: k, name: "Box[" + x.name + "]"}
		fmt.Fprintf(b, "func mk%d(a int, b int) %s {\n\tBox[%s]{V: mk%d(a, b)}\n}\n\n", k, s.typ, x.typ, x.k)
		fmt.Fprintf(b, "func rd%d(v %s) int {\n\trd%d(v.V) * 3\n}\n\n", k, s.typ, x.k)
	case "slice":
		x := sub(tuple)
		s = tashape{typ: "[]" + x.typ, k: k, name: "[]" + x.name}
		fmt.Fprintf(b, "func mk%d(a int, b int) %s {\n\t[]%s{mk%d(a, b), mk%d(b, a + 1)}\n}\n\n", k, s.typ, x.typ, x.k, x.k)
		fmt.Fprintf(b, "func rd%d(v %s) int {\n\tlet mut t = len(v)\n\tfor e in v {\n\t\tt = t * 5 + rd%d(e)\n\t}\n\tt\n}\n\n", k, s.typ, x.k)
	case "map":
		x := sub(tuple)
		s = tashape{typ: "Map[string, " + x.typ + "]", k: k, name: "Map[string, " + x.name + "]"}
		fmt.Fprintf(b, "func mk%d(a int, b int) %s {\n\tMap[string, %s]{\"a\": mk%d(a, b), \"b\": mk%d(b, a)}\n}\n\n", k, s.typ, x.typ, x.k, x.k)
		fmt.Fprintf(b, "func rd%d(v %s) int {\n\tmatch v.Get(\"b\") {\n\tcase Some[%s] as e:\n\t\trd%d(e.Value) + len(v)\n\tcase None:\n\t\t-9\n\t}\n}\n\n", k, s.typ, x.typ, x.k)
	}
	return s
}

// wrapTuple is a tuple shape (x, int) over x: the element of a tuple of a
// tuple.
func (g *tagen) wrapTuple(b *strings.Builder, x tashape) tashape {
	k := g.next
	g.next++
	s := tashape{typ: "(" + x.typ + ", int)", k: k, name: "(" + x.name + ", int)"}
	fmt.Fprintf(b, "func mk%d(a int, b int) %s {\n\t(mk%d(a, b), a + b)\n}\n\n", k, s.typ, x.k)
	fmt.Fprintf(b, "func rd%d(v %s) int {\n\tlet (x, y) = v\n\trd%d(x) * 17 + y\n}\n\n", k, s.typ, x.k)
	return s
}
