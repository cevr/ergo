// EqualFuncs are the functions of GenerateEqual whose bodies compare with
// == or != on a type that is not basic (FLIP F7, equality on IR): each
// must have an IR body.
var EqualFuncs = []string{"eqP", "neRow", "eqInts", "neInts", "eqGrid", "eqMap", "eqRows", "isNum", "notCells"}

// GenerateEqual is a program of == and != on types that are not basic: a
// record Go compares (P), a record that holds a slice (Row), slices of
// int, of slices and of records, a Map, and a union compared with one of
// its variants on either side (Cell). main calls each comparison on
// seeded pairs: equal copies, one element changed, and one value a strict
// prefix of the other (the length decides). want is the output the
// reference model (Go's slices.Equal and maps.Equal on the same values)
// expects, one line per call.
func GenerateEqual(seed uint64) (text, want string) {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x9e3779b97f4a7c15))}
	var b, w strings.Builder
	b.WriteString("// generated by irspike.GenerateEqual\n\n")
	b.WriteString("type P { x int, s string }\n\n")
	b.WriteString("type Row { name string, cells []int }\n\n")
	b.WriteString("func eqP(a P, b P) bool {\n\ta == b\n}\n\n")
	b.WriteString("func neRow(a Row, b Row) bool {\n\ta != b\n}\n\n")
	b.WriteString("func eqInts(a []int, b []int) bool {\n\ta == b\n}\n\n")
	b.WriteString("func neInts(a []int, b []int) bool {\n\ta != b\n}\n\n")
	b.WriteString("func eqGrid(a [][]string, b [][]string) bool {\n\ta == b\n}\n\n")
	b.WriteString("func eqMap(a Map[string, int], b Map[string, int]) bool {\n\ta == b\n}\n\n")
	b.WriteString("func eqRows(a []Row, b []Row) bool {\n\ta == b\n}\n\n")
	// A union with a variant Go cannot compare, against one of its
	// variants on either side: the variant goes into the union first.
	b.WriteString("type Cell = Num{n int} | Cells{xs []int}\n\n")
	b.WriteString("func isNum(c Cell, n int) bool {\n\tc == Num{n: n}\n}\n\n")
	b.WriteString("func notCells(c Cell, xs []int) bool {\n\tCells{xs: xs} != c\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	n := 0
	emit := func(call string, got bool) {
		fmt.Fprintf(&b, "\tlet r%d = %s\n\tConsole.Println(\"%d \\(r%d)\")\n", n, call, n, n)
		fmt.Fprintf(&w, "%d %t\n", n, got)
		n++
	}
	for k := 0; k < 4; k++ {
		x, y := g.intPair()
		emit("eqInts("+intsLit(x)+", "+intsLit(y)+")", slices.Equal(x, y))
		x, y = g.intPair()
		emit("neInts("+intsLit(x)+", "+intsLit(y)+")", !slices.Equal(x, y))
		px, py := g.n(3), g.n(3)
		ps := []string{`"a"`, `"b"`}
		sx, sy := g.n(2), g.n(2)
		emit(fmt.Sprintf("eqP(P{x: %d, s: %s}, P{x: %d, s: %s})", px, ps[sx], py, ps[sy]), px == py && sx == sy)
		x, y = g.intPair()
		nx, ny := g.n(2), g.n(2)
		emit(fmt.Sprintf("neRow(Row{name: %s, cells: %s}, Row{name: %s, cells: %s})", ps[nx], intsLit(x), ps[ny], intsLit(y)), !(nx == ny && slices.Equal(x, y)))
		gx, gy := g.gridPair()
		emit("eqGrid("+gridLit(gx)+", "+gridLit(gy)+")", slices.EqualFunc(gx, gy, slices.Equal))
		mx, my := g.mapPair()
		emit("eqMap("+mapLit(mx)+", "+mapLit(my)+")", maps.Equal(mx, my))
		rx, ry := g.intPair()
		rows := func(cells []int) string {
			var rs []string
			for i := range cells {
				rs = append(rs, fmt.Sprintf("Row{name: \"r\", cells: %s}", intsLit(cells[:i+1])))
			}
			return "[]Row{" + strings.Join(rs, ", ") + "}"
		}
		// Row i holds the first i+1 cells: two lists of rows are equal
		// exactly when the cells are.
		emit("eqRows("+rows(rx)+", "+rows(ry)+")", slices.Equal(rx, ry))
		cx, cy := g.intPair()
		cn, dn := g.n(3), g.n(3)
		if g.n(2) == 0 {
			emit(fmt.Sprintf("isNum(Num{n: %d}, %d)", cn, dn), cn == dn)
			emit(fmt.Sprintf("notCells(Cells{xs: %s}, %s)", intsLit(cx), intsLit(cy)), !slices.Equal(cx, cy))
		} else {
			emit(fmt.Sprintf("isNum(Cells{xs: %s}, %d)", intsLit(cx), dn), false)
			emit(fmt.Sprintf("notCells(Num{n: %d}, %s)", cn, intsLit(cy)), true)
		}
	}
	b.WriteString("}\n")
	return b.String(), w.String()
}

// intPair is two int slices: equal, one element changed, or one a strict
// prefix of the other, in either order.
func (g *ggen) intPair() (x, y []int) {
	for i, n := 0, g.n(4); i < n; i++ {
		x = append(x, g.n(4))
	}
	y = slices.Clone(x)
	switch g.n(4) {
	case 0: // equal
	case 1:
		if len(y) > 0 {
			y[g.n(len(y))] += 1 + g.n(3)
		} else {
			y = append(y, g.n(4))
		}
	case 2:
		y = append(y, g.n(4))
	case 3:
		if len(y) > 0 {
			y = y[:len(y)-1]
		} else {
			y = append(y, g.n(4))
		}
	}
	if g.n(2) == 0 {
		x, y = y, x
	}
	return x, y
}

func (g *ggen) gridPair() (x, y [][]string) {
	words := []string{"a", "b", ""}
	for i, n := 0, g.n(3); i < n; i++ {
		var row []string
		for j, m := 0, g.n(3); j < m; j++ {
			row = append(row, words[g.n(3)])
		}
		x = append(x, row)
	}
	for _, row := range x {
		y = append(y, slices.Clone(row))
	}
	switch g.n(3) {
	case 0: // equal
	case 1:
		if len(y) > 0 {
			i := g.n(len(y))
			y[i] = append(y[i], "z") // the inner lengths differ
		} else {
			y = append(y, nil)
		}
	case 2:
		y = append(y, []string{"a"}) // the outer lengths differ
	}
	if g.n(2) == 0 {
		x, y = y, x
	}
	return x, y
}

func (g *ggen) mapPair() (x, y map[string]int) {
	keys := []string{"a", "b", "c"}
	x, y = map[string]int{}, map[string]int{}
	for _, k := range keys[:g.n(3)] {
		x[k] = g.n(3)
		y[k] = x[k]
	}
	switch g.n(3) {
	case 0: // equal
	case 1:
		y["c"] = 9 // a key x lacks
	case 2:
		for k := range y {
			y[k]++ // a value differs
			break
		}
	}
	if g.n(2) == 0 {
		x, y = y, x
	}
	return x, y
}

func intsLit(xs []int) string {
	var s []string
	for _, x := range xs {
		s = append(s, fmt.Sprint(x))
	}
	return "[]int{" + strings.Join(s, ", ") + "}"
}

func gridLit(xs [][]string) string {
	var rows []string
	for _, row := range xs {
		var s []string
		for _, w := range row {
			s = append(s, fmt.Sprintf("%q", w))
		}
		rows = append(rows, "[]string{"+strings.Join(s, ", ")+"}")
	}
	return "[][]string{" + strings.Join(rows, ", ") + "}"
}

func mapLit(m map[string]int) string {
	var s []string
	for _, k := range slices.Sorted(maps.Keys(m)) {
		s = append(s, fmt.Sprintf("%q: %d", k, m[k]))
	}
	return "Map[string, int]{" + strings.Join(s, ", ") + "}"
}
