package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateGoCalls is a program of calls of Go package functions (FLIP F7
// FORK-GOCALL): each goN calls an import go function, some with an Ergo
// function value for Go's function parameter (sort.Search, strings.Map,
// strings.IndexFunc: goCallback's adapter), the value capturing a
// parameter of goN or calling Go itself (unicode). hold owns a Go
// resource (*os.File, a taken parameter) that its frame releases with
// Go's Close. main runs each goN on several inputs and prints the
// results, so a callback that runs with the wrong value, the wrong
// capture, or not at all changes the output. (I-FLIP: FORK's
// gen_gocall.go, beside SP4's GenerateGoCall in the file of that name.)
func GenerateGoCalls(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x9b05688c2b3e6c1f))
	var b strings.Builder
	nf := 3 + r.IntN(3)
	for i := 0; i < nf; i++ {
		k := 1 + r.IntN(5)
		switch r.IntN(5) {
		case 0:
			// A callback with a parameter, capturing t.
			ops := []string{"i * i >= t", fmt.Sprintf("i * %d >= t", k), fmt.Sprintf("i + %d >= t", k)}
			fmt.Fprintf(&b, "func go%d(t int, s string) int {\n\tsort.Search(%d + t, func(i int) bool { %s })\n}\n\n", i, 10*k, ops[r.IntN(len(ops))])
		case 1:
			// A callback that calls Go (unicode) on each rune.
			calls := []string{"unicode.ToUpper(r)", "unicode.SimpleFold(r)", fmt.Sprintf("r + %d", k)}
			fmt.Fprintf(&b, "func go%d(t int, s string) int {\n\tlet m = strings.Map(func(r rune) rune { %s }, s)\n\tstrings.Count(m, \"A\") + len(m) * t\n}\n\n", i, calls[r.IntN(len(calls))])
		case 2:
			// A callback with a bool result.
			preds := []string{"unicode.IsDigit(r)", "unicode.IsUpper(r)", "r == 'a'"}
			fmt.Fprintf(&b, "func go%d(t int, s string) int {\n\tstrings.IndexFunc(s, func(r rune) bool { %s }) + t\n}\n\n", i, preds[r.IntN(len(preds))])
		case 3:
			// Plain operands and results.
			fmt.Fprintf(&b, "func go%d(t int, s string) int {\n\tlet x = strings.Repeat(s, %d)\n\tstrings.Count(x, \"b\") + t\n}\n\n", i, k)
		default:
			// A callback that captures a local of the caller.
			fmt.Fprintf(&b, "func go%d(t int, s string) int {\n\tlet lim = len(s) + %d\n\tsort.Search(100, func(i int) bool { i >= lim * t })\n}\n\n", i, k)
		}
	}
	// A Go value that is a resource (*os.File), owned by a taken
	// parameter: hold's frame releases it with Go's Close on each exit.
	hk := 1 + r.IntN(3)
	fmt.Fprintf(&b, "func hold(f own go.Ref[os.File], k int) int needs Console | Ambient {\n\tConsole.Println(\"held \\(k)\")\n\tif k > %d {\n\t\treturn k\n\t}\n\tk + %d\n}\n\n", hk, hk)
	b.WriteString("func opened(k int) int fails go.Error needs Console | Ambient {\n\tlet f = try os.Open(\"/dev/null\")\n\thold(f, k)\n}\n\n")
	b.WriteString("func main() needs Console | Ambient {\n")
	for k := 0; k < 4; k += 1 + r.IntN(2) {
		fmt.Fprintf(&b, "\tlet h%d = opened(%d) catch {\n\tcase go.Error:\n\t\t0\n\t}\n\tConsole.Println(\"hold \\(h%d)\")\n", k, k, k)
	}
	inputs := []string{`"ab9Cb"`, `""`, `"zZ1a"`, `"bbAb"`}
	for i := 0; i < nf; i++ {
		for t := 0; t < 3; t++ {
			s := inputs[r.IntN(len(inputs))]
			fmt.Fprintf(&b, "\tlet v%d_%d = go%d(%d, %s)\n\tConsole.Println(\"go%d %d \\(v%d_%d)\")\n", i, t, i, t, s, i, t, i, t)
		}
	}
	b.WriteString("}\n")
	var head strings.Builder
	head.WriteString("// generated by irspike.GenerateGoCalls\n\n")
	for _, pkg := range []string{"os", "sort", "strings", "unicode"} {
		if strings.Contains(b.String(), pkg+".") {
			head.WriteString("import go " + pkg + "\n")
		}
	}
	return head.String() + "\n" + b.String()
}
