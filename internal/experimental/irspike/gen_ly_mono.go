package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateMonoCopies is a program whose generic functions run at known
// types (FLIP F7 PORT-COPY): describe calls label (a witness call), count
// at string and at int (a comparable type parameter), pairs (two type
// parameters, an appended slice of a generic record) and Box's pick at
// string and int (a generic record's Go method that prints). Since
// B-WITNESS, describe takes the IR, and the IR calls the generic bodies
// themselves: the monomorphic copies (mono.go) are the emitter's, made
// only for a caller whose body it writes.
func GenerateMonoCopies(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x6c796d6f6e6f0a01))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateMonoCopies\n\n")
	b.WriteString("type Named { Name() string }\n\ntype Dog { Tag string } implements Named\n\nfunc Name(d Dog) string { d.Tag }\n\n")
	b.WriteString("func label[T Named](x T) string { \"<\" + x.Name() + \">\" }\n\n")
	b.WriteString("type Pair[A, B] { Left A, Right B }\n\n")
	b.WriteString("func count[T comparable](xs []T, y T) int {\n\tlet mut n = 0\n\tfor x in xs {\n\t\tif x == y {\n\t\t\tn = n + 1\n\t\t}\n\t}\n\tn\n}\n\n")
	b.WriteString("func pairs[A, B](xs []A, ys []B) []Pair[A, B] {\n\tlet mut out = []Pair[A, B]{}\n\tfor i in 0..len(xs) {\n\t\tif i < len(ys) {\n\t\t\tout = out.Append(Pair[A, B]{Left: xs[i], Right: ys[i]})\n\t\t}\n\t}\n\tout\n}\n\n")
	b.WriteString("type Box[T] { Items []T, Spare T }\n\n")
	b.WriteString("func pick[T](b Box[T], i int) T needs Console {\n\tConsole.Println(\"pick \\(i)\")\n\tlet mut out = b.Spare\n\tfor j in 0..len(b.Items) {\n\t\tif j == i {\n\t\t\tout = b.Items[j]\n\t\t}\n\t}\n\tout\n}\n\n")
	words := []string{"ab", "cd", "ef", "gh"}
	b.WriteString("func describe(d Dog, xs []string, ns []int) string needs Console {\n")
	b.WriteString("\tlet ps = pairs(xs, ns)\n\tlet mut last = \"-\"\n\tfor p in ps {\n\t\tlast = \"\\(p.Left)\\(p.Right)\"\n\t}\n")
	fmt.Fprintf(&b, "\tlet b = Box[string]{Items: xs, Spare: %q}\n", words[g.n(len(words))])
	fmt.Fprintf(&b, "\t\"\\(label(d)) \\(count(xs, %q)) \\(count(ns, %d)) \\(len(ps)) \\(last) \\(pick(b, %d)) \\(pick(Box[int]{Items: ns, Spare: %d}, %d))\"\n}\n\n",
		words[g.n(len(words))], g.n(4), g.n(5), g.n(9), g.n(5))
	b.WriteString("func main() needs Console {\n")
	for i := 0; i < 3; i++ {
		var xs, ns []string
		for j := 0; j < g.n(6); j++ {
			xs = append(xs, fmt.Sprintf("%q", words[g.n(len(words))]))
		}
		for j := 0; j < g.n(6); j++ {
			ns = append(ns, fmt.Sprint(g.n(4)))
		}
		fmt.Fprintf(&b, "\tConsole.Println(describe(Dog{Tag: \"d%d\"}, []string{%s}, []int{%s}))\n", i, strings.Join(xs, ", "), strings.Join(ns, ", "))
	}
	b.WriteString("}\n")
	return b.String()
}
