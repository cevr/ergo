package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// actorSeqFuncs are GenerateActorSeq's functions with IR bodies; std's
// actor.Changes, whose body calls the runtime's ActorChanges (a std
// function returning Go's iter.Seq[T], ADAPTED-RESULTS shape 2), is
// checked apart (TestIRActorChangesMatchSource).
var actorSeqFuncs = []string{"step", "lastState", "counted"}

// GenerateActorSeq is a program over actor.Changes, the Seq of a stopped
// actor's states (ADAPTED-RESULTS: a std function's iter.Seq made a Seq):
//   - lastState starts a machine at a seeded initial state, stops it, and
//     reads Changes: one Changed, its last state, made by the changed
//     function the call adapts;
//   - counted makes the Seq before it stops the actor, then counts the
//     values at a seeded room, breaking at the first when asked: the
//     function runs when the Seq is iterated, and a break stops it.
//
// main calls each at seeded arguments and prints what they return.
func GenerateActorSeq(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x5e0a3c1d27f4b869))
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateActorSeq\n\nimport actor\nimport time\n\n")
	fmt.Fprintf(&b, "func step(s int, e int) Decision[int, int] {\n\tmatch ((e %% 3) + 3) %% 3 {\n\tcase 0:\n\t\tEnter[int]{Next: s + e}\n\tcase 1:\n\t\tStay[int]{Next: s + %d}\n\tcase _:\n\t\tIgnore\n\t}\n}\n\n", 1+r.IntN(4))
	b.WriteString("func untimed(s int) Option[Timeout[int]] { None }\n\n")
	b.WriteString("func unworked(s int) Option[func(send func(e int))] { None }\n\n")
	b.WriteString("func unexited(s int) Option[func()] { None }\n\n")
	b.WriteString("func machineAt(k int) Machine[int, int, int] { Machine[int, int, int]{Initial: k, Step: step, After: untimed, Work: unworked, Exit: unexited} }\n\n")
	b.WriteString("func lastState(k int) int {\n\twith context { Scheduler: time.NewManual(0) } {\n\t\tlet a = actor.StartMachine(machineAt(k), 1, func(o int) {})\n\t\ta.Stop()\n\t\tlet mut out = 0 - 1\n\t\tfor c in actor.Changes(a, 2) {\n\t\t\tmatch c {\n\t\t\tcase actor.Changed[int] as x:\n\t\t\t\tout = x.State\n\t\t\tcase actor.Overflowed as o:\n\t\t\t\tout = 0 - 100 - o.Missed\n\t\t\t}\n\t\t}\n\t\tout\n\t}\n}\n\n")
	b.WriteString("func counted(k int, room int, stop bool) int {\n\twith context { Scheduler: time.NewManual(0) } {\n\t\tlet a = actor.StartMachine(machineAt(k), 1, func(o int) {})\n\t\tlet cs = actor.Changes(a, room)\n\t\ta.Stop()\n\t\tlet mut n = 0\n\t\tfor _ in cs {\n\t\t\tn = n + 1\n\t\t\tif stop {\n\t\t\t\tbreak\n\t\t\t}\n\t\t}\n\t\tn * 10 + k\n\t}\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	for i, n := 0, 2+r.IntN(3); i < n; i++ {
		fmt.Fprintf(&b, "\tConsole.Println(\"last \\(lastState(%d))\")\n", r.IntN(20)-5)
		fmt.Fprintf(&b, "\tConsole.Println(\"counted \\(counted(%d, %d, %v))\")\n", r.IntN(9), 1+r.IntN(4), r.IntN(2) == 0)
	}
	b.WriteString("}\n")
	return b.String()
}
