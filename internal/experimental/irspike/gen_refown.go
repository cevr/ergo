package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateRefOwned is a program of the Ref's owned sites (V6, IR-OWN): a
// function literal written at Update or sync.Modify takes the held Map
// over and writes it in place. tally updates in a loop; snap reads the
// held Map with Get, so the next owned site must copy it first; a Modify
// that returns the Map it stores is not fresh, so the site after it must
// copy too; keep stores a Map the program still reads (the value rule
// copies it there). Each prints the sizes of the Maps outside the cell beside
// the cell's, with seeded keys, so an in-place write that reaches a Map
// outside the cell changes the output.
func GenerateRefOwned(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x3c6ef372fe94f82b))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateRefOwned\n\nimport sync\n\n")
	fmt.Fprintf(&b, "func tally(n int) int {\n\tlet r = sync.NewRef[Map[int, int]](Map[int, int]{})\n\tfor i in 0..n {\n\t\tr.Update(func(m Map[int, int]) Map[int, int] {\n\t\t\tm.Put(i * %d, i)\n\t\t})\n\t}\n", 1+g.n(3))
	fmt.Fprintf(&b, "\tlet snap = r.Get()\n\tr.Update(func(m Map[int, int]) Map[int, int] {\n\t\tm.Put(%d, 1)\n\t})\n", 100+g.n(9))
	fmt.Fprintf(&b, "\tlet size = sync.Modify(r, func(m Map[int, int]) (int, Map[int, int]) {\n\t\tlet c = m.Put(%d, 2)\n\t\t(len(c), c)\n\t})\n", 200+g.n(9))
	// out and the cell share one Map (the site is not fresh), so the
	// Update after it copies before it writes.
	fmt.Fprintf(&b, "\tlet out = sync.Modify(r, func(m Map[int, int]) (Map[int, int], Map[int, int]) {\n\t\tlet c = m.Put(%d, 4)\n\t\t(c, c)\n\t})\n\tr.Update(func(m Map[int, int]) Map[int, int] {\n\t\tm.Put(%d, 5)\n\t})\n", 400+g.n(9), 500+g.n(9))
	b.WriteString("\tlet held = r.Get()\n\tlen(snap) * 1000 + len(held) * 10 + size + len(out) * 100000\n}\n\n")
	fmt.Fprintf(&b, "func keep(n int) int {\n\tlet r = sync.NewRef[Map[int, int]](Map[int, int]{})\n\tlet mut kept = Map[int, int]{}\n\tfor i in 0..n {\n\t\tkept = kept.Put(i, i)\n\t}\n\tr.Update(func(m Map[int, int]) Map[int, int] {\n\t\tkept\n\t})\n\tr.Update(func(m Map[int, int]) Map[int, int] {\n\t\tm.Put(%d, 3)\n\t})\n\tlet held = r.Get()\n\tlen(kept) * 100 + len(held)\n}\n\n", 300+g.n(9))
	// A generic site (LWR-REF-GENERIC, std cache's table[K, V]): fill's
	// literal takes tab[V] over and hands it to put2, which writes it in
	// place; the second fill copies it once, as snap shares it.
	b.WriteString("type tab[V] { m Map[int, V], n int }\n\n")
	b.WriteString("func put2[V](t tab[V], k int, v V) tab[V] {\n\tlet mut u = t\n\tu.m = u.m.Put(k, v)\n\tu.n += 1\n\tu\n}\n\n")
	b.WriteString("func fill[V](r sync.Ref[tab[V]], n int, v V) {\n\tfor i in 0..n {\n\t\tr.Update(func(t tab[V]) tab[V] {\n\t\t\tput2(t, i, v)\n\t\t})\n\t}\n}\n\n")
	fmt.Fprintf(&b, "func generic(n int) int {\n\tlet r = sync.NewRef[tab[int]](tab[int]{m: Map[int, int]{}, n: 0})\n\tfill(r, n, %d)\n\tlet snap = r.Get()\n\tfill(r, n + %d, 9)\n\tlet held = r.Get()\n\tlen(snap.m) * 100 + len(held.m) + held.n * 1000\n}\n\n", g.n(9), 1+g.n(3))
	// The in-place form (IR-OWN-MODIFY, json's Stream): each literal binds
	// the held scan to one let mut s first and returns s or (x, s) last,
	// so s is the cell's value, written through a pointer; snap reads it
	// with Get, so the Update after it must copy the slice and the Map
	// before it writes, and the Update's whole store of s keeps snap's.
	b.WriteString("type scan { buf []int, pos int, seen Map[int, int] }\n\n")
	fmt.Fprintf(&b, "func stream(n int) int {\n\tlet r = sync.NewRef[scan](scan{buf: []int{}, pos: 0, seen: Map[int, int]{}})\n\tlet mut total = 0\n\tfor i in 0..n {\n\t\tlet got = sync.Modify(r, func(v scan) (int, scan) {\n\t\t\tlet mut s = v\n\t\t\ts.buf = s.buf.Append(i * %d)\n\t\t\tif i %% 2 == 0 {\n\t\t\t\ts.pos += 1\n\t\t\t} else {\n\t\t\t\ts.seen = s.seen.Put(i, s.pos)\n\t\t\t}\n\t\t\t(s.pos + len(s.buf), s)\n\t\t})\n\t\ttotal += got\n\t}\n", 1+g.n(5))
	fmt.Fprintf(&b, "\tlet snap = r.Get()\n\tr.Update(func(v scan) scan {\n\t\tlet mut s = v\n\t\ts.buf = s.buf.Append(%d)\n\t\ts.seen = s.seen.Put(%d, 1)\n\t\tif len(s.buf) > %d {\n\t\t\ts = scan{buf: []int{}, pos: s.pos + 1, seen: s.seen}\n\t\t}\n\t\ts\n\t})\n", 10+g.n(9), 100+g.n(9), 2+g.n(4))
	b.WriteString("\tlet held = r.Get()\n\ttotal + len(snap.buf) * 1000 + len(held.buf) * 10 + len(snap.seen) * 100000 + len(held.seen) * 10000000 + held.pos * 7\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	for k := 0; k < 4; k++ {
		fmt.Fprintf(&b, "\tConsole.Println(\"%d: \\(tally(%d)) \\(keep(%d)) \\(generic(%d)) \\(stream(%d))\")\n", k, 1+g.n(6), 1+g.n(6), 1+g.n(6), g.n(7))
	}
	b.WriteString("}\n")
	return b.String()
}
