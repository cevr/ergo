package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateUnary is a program whose conditions and values are unary
// operators over binary operands (MISCOMPILE-1): !(p && false),
// !(q || true), -(a - b), ^(a | b), +(a * b), nested, with constants on
// either side. Go's writer reads a condition's shape (staticBool folds
// &&, || and ! with a constant side), so the IR must keep a binary operand
// of a unary operator as the parser would, in parentheses; each function
// sums the branches its conditions take and the values, and main prints
// every function at several inputs, so a branch dropped or a value folded
// wrong changes the output.
func GenerateUnary(seed uint64) string {
	g := &ungen{r: rand.New(rand.NewPCG(seed, seed^0x51ed270b1d3a6f45))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateUnary\n\n")
	nf := 3 + g.r.IntN(3)
	for i := 0; i < nf; i++ {
		fmt.Fprintf(&b, "func u%d(p bool, q bool, a int, c int) int {\n\tlet mut acc = 0\n", i)
		for j, n := 0, 4+g.r.IntN(5); j < n; j++ {
			fmt.Fprintf(&b, "\tif %s {\n\t\tacc = acc + %d\n\t}\n", g.cond(3), 1<<j)
		}
		for j, n := 0, 1+g.r.IntN(3); j < n; j++ {
			fmt.Fprintf(&b, "\tacc = acc * 3 + (%s)\n", g.num(3))
		}
		b.WriteString("\tacc\n}\n\n")
	}
	b.WriteString("func main() needs Console {\n")
	for i := 0; i < nf; i++ {
		for _, in := range []string{"true, true, 3, 5", "true, false, -2, 7", "false, true, 0, -4", "false, false, 9, 9"} {
			fmt.Fprintf(&b, "\tConsole.Println(\"u%d(%s) \\(u%d(%s))\")\n", i, in, i, in)
		}
	}
	b.WriteString("}\n")
	return b.String()
}

type ungen struct{ r *rand.Rand }

// cond is a bool expression at most d deep, mostly a ! over a binary
// operand with a constant side.
func (g *ungen) cond(d int) string {
	leaf := func() string { return []string{"p", "q", "true", "false", "(a < c)", "(a == 3)"}[g.r.IntN(6)] }
	if d <= 0 {
		return leaf()
	}
	op := []string{"&&", "||", "==", "!="}[g.r.IntN(4)]
	switch g.r.IntN(4) {
	case 0:
		return "(" + g.cond(d-1) + " " + op + " " + g.cond(d-1) + ")"
	case 1:
		return "!(" + leaf() + " " + op + " " + leaf() + ")"
	default:
		return "!(" + g.cond(d-1) + " " + op + " " + g.cond(d-1) + ")"
	}
}

// num is an int expression at most d deep, mostly a unary operator over
// a binary operand.
func (g *ungen) num(d int) string {
	leaf := func() string { return []string{"a", "c", "3", "0", "7", "-2"}[g.r.IntN(6)] }
	if d <= 0 {
		return leaf()
	}
	un := []string{"-", "^", "+"}[g.r.IntN(3)]
	op := []string{"-", "|", "+", "*", "&", "^"}[g.r.IntN(6)]
	if g.r.IntN(3) == 0 {
		return "(" + g.num(d-1) + " " + op + " " + g.num(d-1) + ")"
	}
	return un + "(" + g.num(d-1) + " " + op + " " + g.num(d-1) + ")"
}
