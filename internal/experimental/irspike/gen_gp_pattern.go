package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// refinePatternFuncs are GenerateRefinePattern's functions that have IR bodies: the
// Parse each refinement derives, whose where calls matches(it, `…`) (a
// pattern call, CallPattern), and the functions that call it.
var refinePatternFuncs = []string{"ParseT0", "ParseT1", "p0", "p1"}

// refinePatternPool are the patterns GenerateRefinePattern draws from: classes,
// alternation, repetition with bounds, an optional group, and one whose
// automaton is past PatternTableStates, so its matcher is the table form.
var refinePatternPool = []string{
	`[a-z0-9](?:[a-z0-9-]{0,6}[a-z0-9])?`,
	`[^@ ]+@[^@ ]+`,
	`a(b|c)*d`,
	`[0-9]{2,4}`,
	`x?y+z*`,
	`(ab)+`,
	`[a-d]{1,3}-[0-9]{1,30}`,
}

// GenerateRefinePattern is a program of two refinements of string by a pattern
// (types.md, Refinements 11) and of seeded strings that each derived Parse
// takes or refuses (GP-PATTERN): main prints, per string, 1 when Parse
// takes it whole, 0 when it refuses it. A matcher that takes a string its
// pattern does not match, or refuses one it does, changes the output.
func GenerateRefinePattern(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x2545f4914f6cdd1d))
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateRefinePattern\n\n")
	for i := range 2 {
		fmt.Fprintf(&b, "type T%d string where matches(it, `%s`)\n\n", i, refinePatternPool[r.IntN(len(refinePatternPool))])
		fmt.Fprintf(&b, "func p%d(s string) string {\n\tlet v = ParseT%d(s) catch {\n\tcase Unsatisfied:\n\t\treturn \"0\"\n\t}\n\tif string(v) == s { \"1\" } else { \"?\" }\n}\n\n", i, i)
	}
	const runes = "abcdxyz0129@-. "
	var inputs []string
	for range 12 {
		n := r.IntN(9)
		var s strings.Builder
		for range n {
			s.WriteByte(runes[r.IntN(len(runes))])
		}
		inputs = append(inputs, fmt.Sprintf("%q", s.String()))
	}
	// Strings that the pool's patterns take, so each seed shows both answers.
	inputs = append(inputs, `"ab"`, `"abcd"`, `"a1-b2"`, `"xyyz"`, `"b-123"`, `"me@here"`, `"12"`)
	fmt.Fprintf(&b, "func main() needs Console {\n\tfor s in []string{%s} {\n\t\tConsole.Println(\"\\(p0(s)) \\(p1(s))\")\n\t}\n}\n", strings.Join(inputs, ", "))
	return b.String()
}
