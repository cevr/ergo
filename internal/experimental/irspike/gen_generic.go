package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateGeneric writes the generic-union program of seed (MSB1 through
// the IR path): a generic union G[A, B] of the program at instances of an
// enum, int and string, which the lowering makes one generic Go struct of
// a tag and shared slots (lower/genericunion.go); an enum E3, a byte; and
// a machine step over enum states that returns the prelude's Decision[S,
// O], with a transition table drawn from the seed, run by a loop that
// matches each Decision. Every function but main is one the IR builder
// lowers, so the IR's generic unions are the ones the shared lowerer
// decided. main prints every function's results over drawn inputs.
func GenerateGeneric(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x6d73623166750001))
	var b strings.Builder
	b.WriteString(`// generated by irspike.GenerateGeneric

type GA[A] { x A }

type GB[A, B] { x A, y B }

type GC {}

type GD[B] { y B }

type G[A, B] = GA[A] | GB[A, B] | GC | GD[B]

type EA {}

type EB {}

type EC {}

type E3 = EA | EB | EC

func e3(k int) E3 {
	if k % 3 == 0 {
		return EA
	}
	if k % 3 == 1 {
		return EB
	}
	EC
}

func e3name(e E3) string {
	match e {
	case EA:
		"a"
	case EB:
		"b"
	case EC:
		"c"
	}
}

`)
	t1, t2 := 1+r.IntN(3), 3+r.IntN(4)
	fmt.Fprintf(&b, `func mkG(k int) G[E3, int] {
	if k < %d {
		return GA[E3]{x: e3(k)}
	}
	if k == %d {
		return GC
	}
	if k %% 2 == 0 {
		return GB[E3, int]{x: e3(k + 1), y: k * 3}
	}
	GD[int]{y: k}
}

func showG(g G[E3, int]) string {
	match g {
	case GA[E3] as a:
		"A" + e3name(a.x)
	case GB[E3, int] as v:
		"B" + e3name(v.x) + "\(v.y)"
	case GC:
		"C"
	case GD[int] as d:
		"D\(d.y)"
	}
}

func mkS(k int) G[int, string] {
	if k %% 3 == 0 {
		return GB[int, string]{x: k, y: "s\(k)"}
	}
	if k %% 3 == 1 {
		return GD[string]{y: "d\(k)"}
	}
	GA[int]{x: k * 2}
}

func swapS(g G[int, string]) G[string, int] {
	match g {
	case GA[int] as a:
		GD[int]{y: a.x}
	case GB[int, string] as v:
		GB[string, int]{x: v.y, y: v.x}
	case GC:
		GC
	case GD[string] as d:
		GA[string]{x: d.y}
	}
}

func showT(g G[string, int]) string {
	match g {
	case GA[string] as a:
		"A" + a.x
	case GB[string, int] as v:
		"B" + v.x + "\(v.y)"
	case GC:
		"C"
	case GD[int] as d:
		"D\(d.y)"
	}
}

func sameS(a G[int, string], b G[int, string]) bool { a == b }

func countB(n int) int {
	let mut c = 0
	let mut k = 0
	for k < n {
		match mkG(k) {
		case GB[E3, int]:
			c += 1
		case _:
			c += 0
		}
		k += 1
	}
	c
}

`, t1, t2)
	states, signals := []string{"M0", "M1", "M2", "M3"}, []string{"I0", "I1", "I2"}
	for _, s := range append(append([]string{}, states...), signals...) {
		fmt.Fprintf(&b, "type %s {}\n\n", s)
	}
	b.WriteString("type MS = M0 | M1 | M2 | M3\n\ntype MI = I0 | I1 | I2\n\n")
	b.WriteString("func msName(s MS) string {\n\tmatch s {\n")
	for _, s := range states {
		fmt.Fprintf(&b, "\tcase %s:\n\t\t%q\n", s, s)
	}
	b.WriteString("\t}\n}\n\n")
	b.WriteString("func mi(k int) MI {\n\tif k % 3 == 0 {\n\t\treturn I0\n\t}\n\tif k % 3 == 1 {\n\t\treturn I1\n\t}\n\tI2\n}\n\n")
	b.WriteString("func mstep(s MS, e MI) Decision[MS, E3] {\n\tmatch (s, e) {\n")
	outs := []string{"EA", "EB", "EC"}
	vs := decisionVariants() // gen_decision.go
	moves := -1              // the first variant that moves and outputs nothing
	for i, v := range vs {
		if moves < 0 && v.has("Next") && !v.has("Output") {
			moves = i
		}
	}
	for _, s := range states {
		for _, e := range signals {
			v := vs[r.IntN(len(vs))]
			next := states[r.IntN(len(states))]
			if s == "M0" && e == "I0" {
				v, next = vs[moves], "M1" // a run moves at least once
			}
			fmt.Fprintf(&b, "\tcase (%s, %s):\n\t\t%s\n", s, e, decisionLit(v, next, outs[r.IntN(3)]))
		}
	}
	b.WriteString("\t}\n}\n\n")
	// scan matches every variant of Decision, each arm marking its
	// variant's index in the output: a variant read as another changes it.
	b.WriteString("func scan(seed int, n int) string {\n\tlet mut s MS = M0\n\tlet mut out = \"\"\n\tlet mut k = 0\n\tfor k < n {\n\t\tk += 1\n\t\tmatch mstep(s, mi(k * seed + k / 2)) {\n")
	for i, v := range vs {
		bind := ""
		if len(v.fields) > 0 {
			bind = " as v"
		}
		fmt.Fprintf(&b, "\t\tcase %s%s:\n\t\t\tout = out + \"%d\"\n", v.at("MS", "E3"), bind, i)
		switch {
		case v.has("Next") && v.has("Output"):
			b.WriteString("\t\t\ts = v.Next\n\t\t\tout = out + e3name(v.Output)\n")
		case v.has("Next"):
			b.WriteString("\t\t\ts = v.Next\n")
		case v.has("Output"):
			// An output with no next state ends the run (Done).
			fmt.Fprintf(&b, "\t\t\treturn out + \" %s \" + e3name(v.Output)\n", strings.ToLower(v.name))
		}
	}
	b.WriteString("\t\t}\n\t}\n\tout + \" at \" + msName(s)\n}\n\n")
	b.WriteString(`func main() needs Console {
`)
	for range 6 {
		k := r.IntN(14)
		fmt.Fprintf(&b, "\tConsole.Println(showG(mkG(%d)) + \" \" + showT(swapS(mkS(%d))))\n", k, k+r.IntN(3))
	}
	a := r.IntN(9)
	fmt.Fprintf(&b, "\tConsole.Println(\"\\(sameS(mkS(%d), mkS(%d))) \\(sameS(mkS(%d), mkS(%d))) \\(countB(%d))\")\n", a, a, a, a+1, 5+r.IntN(20))
	for range 3 {
		fmt.Fprintf(&b, "\tConsole.Println(scan(%d, %d))\n", 1+r.IntN(7), 1+r.IntN(12))
	}
	b.WriteString("}\n")
	return b.String()
}
