package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// queueTupleFuncs are GenerateQueueTuple's functions: each pops a queue
// of pairs, whose runtime method returns Go's (T, error) at T the pair's
// struct (ADAPTED-RESULTS: Queue.Pop of a tuple), and each has an IR body.
var queueTupleFuncs = []string{"drained", "front", "pairOf"}

// GenerateQueueTuple is a program of bodies over a queue.Queue[(int,
// string)]:
//   - drained pushes seeded pairs, ends the queue, then pops each into
//     two names until Closed breaks the loop, as examples/chat's serveAll
//     does;
//   - front returns the popped pair itself, its failure passed on;
//   - pairOf reads front's pair, or a seeded pair when the queue is closed
//     and empty.
//
// main calls each at seeded arguments and prints what they return.
func GenerateQueueTuple(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x2f6b1c93d70a4e85))
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateQueueTuple\n\nimport queue\n\n")
	fmt.Fprintf(&b, "func filled(n int) queue.Queue[(int, string)] fails queue.Closed {\n\tlet q = queue.New[(int, string)](n + 1)\n\tfor i in 0..n {\n\t\ttry q.Push((i * %d + 1, \"w\\(i)\"))\n\t}\n\tq.End()\n\tq\n}\n\n", 1+r.IntN(5))
	b.WriteString("func drained(n int) int fails queue.Closed {\n\tlet q = try filled(n)\n\tlet mut s = 0\n\tfor {\n\t\tlet a, w = q.Pop() catch {\n\t\tcase queue.Closed:\n\t\t\tbreak\n\t\t}\n\t\ts = s * 7 + a + len(w)\n\t}\n\ts\n}\n\n")
	b.WriteString("func front(q queue.Queue[(int, string)]) (int, string) fails queue.Closed {\n\ttry q.Pop()\n}\n\n")
	fmt.Fprintf(&b, "func pairOf(n int) string fails queue.Closed {\n\tlet q = try filled(n)\n\tlet a, w = front(q) catch {\n\tcase queue.Closed:\n\t\t(0 - %d, \"none\")\n\t}\n\t\"\\(a):\\(w)\"\n}\n\n", r.IntN(9))
	b.WriteString("func main() needs Console {\n")
	for i, n := 0, 2+r.IntN(3); i < n; i++ {
		fmt.Fprintf(&b, "\tlet d%d = drained(%d) catch {\n\tcase queue.Closed:\n\t\t0 - 9\n\t}\n\tConsole.Println(\"drained \\(d%d)\")\n", i, r.IntN(6), i)
		fmt.Fprintf(&b, "\tlet p%d = pairOf(%d) catch {\n\tcase queue.Closed:\n\t\t\"closed\"\n\t}\n\tConsole.Println(\"pair \\(p%d)\")\n", i, r.IntN(3), i)
	}
	b.WriteString("}\n")
	return b.String()
}
