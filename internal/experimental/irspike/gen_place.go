package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// placeFuncs are the functions GeneratePlace writes besides the plN: each
// takes a *T first, so each is a method of T (digest, whose loops copy,
// may keep its source body).
var placeFuncs = []string{"Inner.grow", "Inner.reset", "Rec.bump"}

// GeneratePlace is a program of places (FLIP F2): functions plN(r *Rec,
// k int) that write fields and elements through r (r.inr.xs[1] = …,
// r.items[0].n += …, (*r).a = …), fields and elements of a local record
// (loc.n, loc.xs[2]), pass a place's address to a *T function (grow(&r.inr,
// k), reset(&loc, k), which stores through *i) and call one on a T place
// (loc.grow(k), r.items[1].reset(k): the place's address, not a copy's),
// and on a *T (r.bump(k)). Some stores to a field through r take a value
// whose statements write first (r.a = if k > 1 { r.inr.n = …; … } else
// { … }): r is a parameter, so no statement moves the place (STOREMOVE).
// moved stores through a let mut p that the value's statements reassign,
// which only the place fixed first gets right. main runs each at several
// k and prints what it returns and a digest of r, so a write lost, made
// to a copy, made twice or made to the moved place changes the output.
func GeneratePlace(seed uint64) string {
	g := &plgen{r: rand.New(rand.NewPCG(seed, seed^0x9c4f1d2b7a3e5c61))}
	var b strings.Builder
	b.WriteString(`// generated by irspike.GeneratePlace

type Inner { n int, xs []int }

type Rec { a int, inr Inner, items []Inner }

func grow(i mut Inner, k int) {
	i.n = i.n + k
	i.xs[0] = i.xs[0] * 2 + k
}

func reset(i mut Inner, k int) {
	*i = Inner{n: k + i.n % 7, xs: []int{i.xs[2], i.xs[0], k}}
}

func bump(r mut Rec, k int) {
	r.a = r.a * 3 + k
	r.items[1].xs[2] += r.inr.n
}

func digest(r mut Rec) int {
	let mut d = r.a
	d = d * 31 + r.inr.n
	for x in r.inr.xs {
		d = d * 31 + x
	}
	for it in r.items {
		d = d * 31 + it.n
		for x in it.xs {
			d = d * 31 + x
		}
	}
	d
}

func mk(k int) Rec {
	Rec{a: k, inr: Inner{n: k, xs: []int{k, 1, 2}}, items: []Inner{Inner{n: 1, xs: []int{0, k, 4}}, Inner{n: 2, xs: []int{5, 6, k}}}}
}

// moved stores through p, a let mut, a value whose statements move p:
// the store goes to the record p held before them (r).
func moved(r mut Rec, k int) int {
	let mut other = mk(k + 7)
	let mut p = r
	p.a = if k > 1 {
		p = &other
		p.a + 1
	} else {
		k
	}
	r.a * 100 + other.a
}

// movedAll is moved's store to *q itself.
func movedAll(r mut Rec, k int) int {
	let mut other = mk(k + 7)
	let mut q = r
	*q = if k > 2 {
		q = &other
		mk(q.a + 1)
	} else {
		*q
	}
	r.a * 100 + other.a
}

`)
	nf := 3 + g.r.IntN(3)
	for i := 0; i < nf; i++ {
		fmt.Fprintf(&b, "func pl%d(r *Rec, k int) int {\n\tlet mut loc = Inner{n: k, xs: []int{k, 1, 2}}\n\tif k > 2 {\n\t\tloc = Inner{n: 1, xs: []int{3, k, 5}}\n\t}\n", i)
		for j, n := 0, 5+g.r.IntN(6); j < n; j++ {
			b.WriteString("\t" + g.stmt() + "\n")
		}
		b.WriteString("\tloc.n + loc.xs[0] + loc.xs[1] + loc.xs[2]\n}\n\n")
	}
	b.WriteString("func main() needs Console {\n\tlet mut r = mk(1)\n\tfor k in 0..4 {\n")
	for i := 0; i < nf; i++ {
		fmt.Fprintf(&b, "\t\tlet v%d = pl%d(&r, k)\n\t\tConsole.Println(\"pl%d \\(k) \\(v%d) \\(r.digest())\")\n", i, i, i, i)
	}
	b.WriteString("\t\tlet w = moved(&r, k)\n\t\tConsole.Println(\"moved \\(k) \\(w) \\(r.digest())\")\n\t\tlet wa = movedAll(&r, k)\n\t\tConsole.Println(\"movedAll \\(k) \\(wa) \\(r.digest())\")\n")
	b.WriteString("\t}\n}\n")
	return b.String()
}

type plgen struct{ r *rand.Rand }

func (g *plgen) pick(xs ...string) string { return xs[g.r.IntN(len(xs))] }

// inner is a place of an Inner: through r or a local.
func (g *plgen) inner() string {
	return g.pick("r.inr", "r.items[0]", "r.items[1]", "loc", "(*r).inr")
}

// intPlace is a place of an int.
func (g *plgen) intPlace() string {
	switch g.r.IntN(4) {
	case 0:
		return g.pick("r.a", "(*r).a")
	case 1:
		return g.inner() + ".n"
	default:
		return g.inner() + fmt.Sprintf(".xs[%d]", g.r.IntN(3))
	}
}

// num is an int value.
func (g *plgen) num() string {
	switch g.r.IntN(3) {
	case 0:
		return "k"
	case 1:
		return fmt.Sprintf("%s %% 97 + %d", g.intPlace(), g.r.IntN(9))
	}
	return fmt.Sprintf("k * %d + 1", 2+g.r.IntN(5))
}

// fieldPlace is a place of an int reached from r by fields alone (r.a,
// (*r).inr.n): r is a parameter, so no statement moves it.
func (g *plgen) fieldPlace() string {
	return g.pick("r", "(*r)") + g.pick(".a", ".inr.n")
}

// stmtValue is an int value whose IR writes statements: an if whose arm
// first writes a place, which may be the stored one.
func (g *plgen) stmtValue() string {
	return fmt.Sprintf("if k > %d {\n\t\t%s = %s\n\t\t%s\n\t} else {\n\t\t%s\n\t}", g.r.IntN(4), g.intPlace(), g.num(), g.num(), g.num())
}

func (g *plgen) stmt() string {
	switch g.r.IntN(9) {
	case 7, 8:
		return g.fieldPlace() + " = " + g.stmtValue()
	case 0, 1:
		return g.intPlace() + " = " + g.num()
	case 2:
		return g.intPlace() + " " + g.pick("+", "-", "^", "|") + "= " + g.num()
	case 3:
		return g.pick("grow", "reset") + "(&" + g.inner() + ", " + g.num() + ")"
	case 4:
		return g.inner() + "." + g.pick("grow", "reset") + "(" + g.num() + ")"
	case 5:
		return "r.bump(" + g.num() + ")"
	}
	return g.intPlace() + " = " + g.intPlace() + " + 1"
}
