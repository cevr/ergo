package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateCellWire is a program of cell writers (CW-IR; lower's
// ir_wire.go): seeded records, slices, Maps and a union, each value
// encoded on std json's Text, whose provider's proved laws rewrite each
// codec function's runs of events, and printed. Record i's fields are
// drawn from basic values, slices of them, a Map of ints, an earlier
// record, a slice or a Map of earlier records and the union, so the
// codec functions call one another
// in the states a run ends in (an entry variant), in a loop and in a
// switch's arms.
//
// Each value is encoded twice: on json's Text and on Tape, a cell writer
// whose laws are true by construction (lower's tapeSource, the text
// form's property): RawJoins, MarkLast (mark is idempotent) and EchoMark
// (a mark then echo writes the mark). Its event bodies are drawn: an
// event ends in an idempotent mark or a constant raw, and echo writes
// the last mark, so a state carried wrong (into a run, past a loop, into
// an arm, into a callee's entry variant) changes what Tape writes.
func GenerateCellWire(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x6a09e667f3bcc909))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateCellWire\n\nimport json\n\n")
	b.WriteString(cellTape)
	for _, e := range cellTapeEvents {
		body := strings.ReplaceAll(e.bodies[g.n(len(e.bodies))], "$", []string{"", `; t.mark("")`}[g.n(2)])
		params := "t mut tape"
		if e.param != "" {
			params += ", " + e.param
		}
		fmt.Fprintf(&b, "func %s(%s) { %s }\n", e.name, params, body)
	}
	b.WriteString("\n")
	// The union: variants with no field, one field and three.
	b.WriteString("type U = Ua{} | Ub{X int} | Uc{S string, Y []int, Z bool}\n\n")
	kinds := []string{"int", "string", "bool", "float64", "int64", "[]int", "[]string", "U", "Map[string, int]"}
	records := 2 + g.n(3)
	fields := make([][]string, records)
	for i := range records {
		n := 1 + g.n(4)
		var fs []string
		for k := range n {
			opts := append([]string(nil), kinds...)
			if i > 0 {
				opts = append(opts, fmt.Sprintf("R%d", g.n(i)), fmt.Sprintf("[]R%d", g.n(i)), fmt.Sprintf("Map[string, R%d]", g.n(i)))
			}
			ft := opts[g.n(len(opts))]
			fields[i] = append(fields[i], ft)
			fs = append(fs, fmt.Sprintf("F%d %s", k, ft))
		}
		fmt.Fprintf(&b, "type R%d { %s }\n\n", i, strings.Join(fs, ", "))
	}
	var value func(t string, depth int) string
	value = func(t string, depth int) string {
		switch {
		case t == "int" || t == "int64":
			return fmt.Sprint(g.n(2000) - 1000)
		case t == "string":
			return []string{`""`, `"a"`, `"q\"x"`, `"é世"`, `"line\nbreak"`, `"<&>"`}[g.n(6)]
		case t == "bool":
			return []string{"true", "false"}[g.n(2)]
		case t == "float64":
			return []string{"0.5", "-2.25", "1e21", "3.0"}[g.n(4)]
		case t == "U":
			switch g.n(3) {
			case 0:
				return "Ua"
			case 1:
				return fmt.Sprintf("Ub{X: %d}", g.n(50))
			}
			return fmt.Sprintf("Uc{S: %s, Y: %s, Z: %s}", value("string", depth), value("[]int", depth), value("bool", depth))
		case strings.HasPrefix(t, "Map[string, "):
			// Keys drawn out of order, so the encoding's order is WireKeys'.
			elem := strings.TrimSuffix(strings.TrimPrefix(t, "Map[string, "), "]")
			var xs []string
			for _, k := range []string{`"z"`, `"b"`, `"m"`, `"a"`}[:g.n(5)] {
				if depth > 2 && strings.HasPrefix(elem, "R") {
					break
				}
				xs = append(xs, k+": "+value(elem, depth+1))
			}
			return t + "{" + strings.Join(xs, ", ") + "}"
		case strings.HasPrefix(t, "[]"):
			elem := t[2:]
			var xs []string
			for range g.n(4) {
				if depth > 2 && strings.HasPrefix(elem, "R") {
					break
				}
				xs = append(xs, value(elem, depth+1))
			}
			return t + "{" + strings.Join(xs, ", ") + "}"
		case strings.HasPrefix(t, "R"):
			var i int
			fmt.Sscan(t[1:], &i)
			var fs []string
			for k, ft := range fields[i] {
				fs = append(fs, fmt.Sprintf("F%d: %s", k, value(ft, depth+1)))
			}
			return t + "{" + strings.Join(fs, ", ") + "}"
		}
		panic("GenerateCellWire: kind " + t)
	}
	// E's lists are empty: a loop that runs no time leaves the state the
	// loop began in (a key's mark), not the state its body ends in.
	b.WriteString("type E { A []int, B []string, C []U, D Map[string, int] }\n\n")
	b.WriteString("func main() needs Console {\n")
	b.WriteString("\tlet e = E{A: []int{}, B: []string{}, C: []U{}, D: Map[string, int]{}}\n")
	b.WriteString("\tlet te = json.NewText()\n\tencode(e, te)\n\tConsole.Println(te.Written())\n")
	b.WriteString("\tlet pe = NewTape()\n\tencode(e, pe)\n\tConsole.Println(pe.Written())\n")
	for k := range 6 {
		t := fmt.Sprintf("R%d", g.n(records))
		switch g.n(4) {
		case 0:
			t = "U"
		case 1:
			t = "[]" + t
		}
		x := value(t, 0)
		fmt.Fprintf(&b, "\tlet t%d = json.NewText()\n\tencode(%s, t%d)\n\tConsole.Println(t%d.Written())\n", k, x, k, k)
		fmt.Fprintf(&b, "\tlet p%d = NewTape()\n\tencode(%s, p%d)\n\tConsole.Println(p%d.Written())\n", k, x, k, k)
	}
	b.WriteString("}\n")
	return b.String()
}
