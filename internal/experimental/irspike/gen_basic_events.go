package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// basicEventSites are GenerateBasicEvents's bodies, whose encodes and
// decodes of basic values each have an IR body in every seed.
var basicEventSites = []string{"viaEvents", "viaText"}

// GenerateBasicEvents is a program that encodes and decodes basic values,
// one event each, which the emitter writes inline (wireEvents.basic;
// PORT-ENCODE-DIRECT):
//   - viaEvents encodes an int, a string, a bool, a float64, a uint8 and
//     Level, a defined type over int, on a codec.Events (the reference
//     Writer), and decodes them back from a Replay in that order;
//   - viaText encodes the same kinds on an HTML json Text, a direct
//     writer whose provider is a cell, between the Text's own list events.
//
// The values are drawn, with strings the HTML Text escapes, so an event of
// another kind, a conversion lost, a write that misses the cell or a
// decode of the other type changes the output.
func GenerateBasicEvents(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x510e527fade682d1))
	n := func(k int) int { return r.IntN(k) }
	word := func() string { return []string{"s", "<b>", "a&b", "", "q\\\"t", "é"}[n(6)] }
	flt := func() string { return []string{"1.5", "-0.25", "3.0", "100.125"}[n(4)] }
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateBasicEvents\n\nimport codec\nimport json\n\ntype Level int\n\n")
	b.WriteString("func viaEvents(i int, s string, t bool, f float64, u uint8, l Level) string fails wired[int] {\n")
	b.WriteString("\tlet e = codec.NewEvents()\n\tencode(i, e)\n\tencode(s, e)\n\tencode(t, e)\n\tencode(f, e)\n\tencode(u, e)\n\tencode(l, e)\n")
	b.WriteString("\tlet r = codec.NewReplay(codec.Recorded(e))\n\tlet a = try decode[int](r)\n\tlet b = try decode[string](r)\n\tlet c = try decode[bool](r)\n\tlet d = try decode[float64](r)\n\tlet g = try decode[uint8](r)\n\tlet h = try decode[Level](r)\n")
	b.WriteString("\t\"\\(a) \\(b) \\(c) \\(d) \\(g) \\(int(h))\"\n}\n\n")
	b.WriteString("func viaText(i int, s string, t bool, f float64, u uint16, l Level) string {\n")
	b.WriteString("\tlet w = json.NewHTMLText()\n\tw.BeginList(6)\n\tencode(i, w)\n\tencode(s, w)\n\tencode(t, w)\n\tencode(f, w)\n\tencode(u, w)\n\tencode(l, w)\n\tw.EndList()\n\tw.Written()\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	for i := 0; i < 3; i++ {
		args := fmt.Sprintf("%d, \"%s\", %t, %s, %d, Level(%d)", n(2000)-1000, word(), n(2) == 0, flt(), n(256), n(20)-10)
		fmt.Fprintf(&b, "\tlet a%d = viaEvents(%s) catch {\n\tcase _:\n\t\t\"failed\"\n\t}\n\tConsole.Println(a%d)\n\tConsole.Println(viaText(%s))\n", i, args, i, args)
	}
	b.WriteString("}\n")
	return b.String()
}
