package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// pairSites are GenerateWirePairs's callers, with an IR body in every
// seed, by their Go names (their first parameter is an E); the codec
// functions are checked by their CodecText (TestIRWirePairsMatchSource).
var pairSites = []string{"E.viaText", "E.viaCounter"}

// GenerateWirePairs is a program that encodes by-name pairs and refined
// types on two cell writers, json's Text and Counter (GenerateOmittable),
// PORT-WIRE:
//   - Level, a union written by name (a plain pair: Wire gives the string
//     its base writes);
//   - Tags, a record written as the list Wire gives (a pair whose base is
//     not basic: its base's codec function);
//   - time.Time, std's append-form pair (Wire appends its text to the
//     frame's buffer, StringBytes writes it);
//   - Small and Wide, refined ints, written as their base.
//
// main calls no ParseX: json.Encode's witness carries E's decoder, which
// alone names each pair's parser, and the build must still declare it
// (NIH-67: the decoder's parser is a reachability edge, reach.go
// decoded).
func GenerateWirePairs(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x1f83d9abfb41bd6b))
	n := func(k int) int { return r.IntN(k) }
	level := func() string { return []string{"Debug", "Info", "Warn"}[n(3)] }
	tag := func() string { return []string{"\"a\"", "\"c&d\"", "\"<b>\"", "\"\""}[n(4)] }
	list := func(f func() string) string {
		var xs []string
		for i := n(3); i > 0; i-- {
			xs = append(xs, f())
		}
		return strings.Join(xs, ", ")
	}
	at := func() string {
		ns := 0
		if n(2) == 0 {
			ns = n(2_000_000_000)
		}
		return fmt.Sprintf("time.Unix(%d, %d)", n(1_700_000_000), ns)
	}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateWirePairs\n\nimport json\nimport time\n\n")
	b.WriteString(counterDecls)
	b.WriteString(pairDecls)
	b.WriteString("func viaText(e E, l Level) string {\n\tlet w = json.NewText()\n\tw.BeginList(2)\n\tencode(e, w)\n\tencode(l, w)\n\tw.EndList()\n\tw.Written()\n}\n\n")
	b.WriteString("func viaCounter(e E, l Level) string {\n\tlet w = newCounter()\n\tencode(e, w)\n\tencode(l, w)\n\tw.Written()\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	for i := 0; i < 3; i++ {
		e := fmt.Sprintf("E{L: %s, T: Tags{xs: []string{%s}}, At: %s, S: %d, W: %d, Ls: []Level{%s}, Ts: []time.Time{%s}}",
			level(), list(tag), at(), n(100), n(2001)-1000, list(level), list(at))
		l := level()
		fmt.Fprintf(&b, "\tConsole.Println(viaText(%s, %s))\n\tConsole.Println(viaCounter(%s, %s))\n", e, l, e, l)
		if i == 0 {
			fmt.Fprintf(&b, "\tConsole.Println(json.Encode(json.Codec[E]{MaxBytes: 0, MaxDepth: 0}, %s))\n", e)
		}
	}
	b.WriteString("}\n")
	return b.String()
}

// pairDecls are GenerateWirePairs's types: two by-name pairs, Level and
// Tags, two refined ints, and E, which holds them, std's time.Time and
// lists of both pairs.
const pairDecls = pairTypes + `type E { L Level, T Tags, At time.Time, S Small, W Wide, Ls []Level, Ts []time.Time }

`

const pairTypes = `type Level = Debug | Info | Warn

type Debug {}

type Info {}

type Warn {}

type UnknownLevel { Name string }

func ParseLevel(name string) Level fails UnknownLevel {
	match name {
	case "debug":
		Debug
	case "info":
		Info
	case "warn":
		Warn
	case _:
		UnknownLevel{Name: name}
	}
}

func Wire(l Level) string {
	match l {
	case Debug:
		"debug"
	case Info:
		"info"
	case Warn:
		"warn"
	}
}

type Tags { xs []string }

func ParseTags(xs []string) Tags { Tags{xs: xs} }

func Wire(t Tags) []string { t.xs }

type Small int where 0 <= it && it <= 99

type Wide int64 where -1000 <= it && it <= 1000

`
