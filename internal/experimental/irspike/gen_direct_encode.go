package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// directEncodeSites are GenerateDirectEncode's bodies whose encodes write
// on a direct writer, a json Text (PORT-ENCODE-DIRECT): each has an IR
// body in every seed. P.concrete is concrete's Go name (its first
// parameter is a P).
var directEncodeSites = []string{"Encode", "viaText", "html", "list", "P.concrete"}

// GenerateDirectEncode is a program whose encodes write on json's Text,
// a direct writer whose provider is a cell (PORT-ENCODE-DIRECT; the
// emitter's direct path, wiredirect.go and wiretext.go):
//   - json.Encode itself, at Q;
//   - viaText, html and list, generic over T, encode a T (the witness's
//     Direct field) and []T and Option[T] (generic direct codec functions
//     that take the witness) between the Text's own list events, so a
//     comma lost or doubled between the cell's writes changes the text;
//   - concrete encodes a P, a Q and a []P (direct codec functions of
//     concrete types).
//
// html writes on an HTML Text, whose escapes differ, and the strings are
// drawn with characters it escapes, so a writer of the other kind, a
// write lost from the cell or a value of the other type changes the
// output.
func GenerateDirectEncode(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x1f83d9abfb41bd6b))
	n := func(k int) int { return r.IntN(k) }
	word := func() string { return []string{"x", "<b>", "a&b", "", "q\\\"t", "é"}[n(6)] }
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateDirectEncode\n\nimport json\n\n")
	b.WriteString("type P { A int, B string }\n\ntype Q { Xs []int, N bool, In P }\n\n")
	b.WriteString("func viaText[T wire](v T) string needs wired[T] {\n\tlet w = json.NewText()\n\tw.BeginList(2)\n\tencode(v, w)\n\tencode(v, w)\n\tw.EndList()\n\tw.Written()\n}\n\n")
	b.WriteString("func html[T wire](v T) string needs wired[T] {\n\tlet w = json.NewHTMLText()\n\tencode(v, w)\n\tw.Written()\n}\n\n")
	b.WriteString("func list[T wire](xs []T, o Option[T]) string needs wired[T] {\n\tlet w = json.NewText()\n\tw.BeginList(2)\n\tencode(xs, w)\n\tencode(o, w)\n\tw.EndList()\n\tw.Written()\n}\n\n")
	b.WriteString("func concrete(p P, q Q, xs []P) string {\n\tlet w = json.NewText()\n\tw.BeginList(3)\n\tencode(p, w)\n\tencode(q, w)\n\tencode(xs, w)\n\tw.EndList()\n\tw.Written()\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	ps := make([]string, 3)
	for i := range ps {
		ps[i] = fmt.Sprintf("P{A: %d, B: \"%s\"}", n(200)-100, word())
	}
	xs := make([]string, n(4))
	for i := range xs {
		xs[i] = fmt.Sprint(n(50) - 10)
	}
	fmt.Fprintf(&b, "\tlet q = Q{Xs: []int{%s}, N: %t, In: %s}\n", strings.Join(xs, ", "), n(2) == 0, ps[0])
	b.WriteString("\tConsole.Println(json.Encode(json.Codec[Q]{MaxBytes: 0, MaxDepth: 0}, q))\n")
	fmt.Fprintf(&b, "\tConsole.Println(viaText(%s))\n\tConsole.Println(viaText(q))\n", ps[1])
	fmt.Fprintf(&b, "\tConsole.Println(html(q))\n\tConsole.Println(html(%s))\n", ps[2])
	opt := "None"
	if n(2) == 0 {
		opt = "Some{Value: " + ps[1] + "}"
	}
	fmt.Fprintf(&b, "\tConsole.Println(list([]P{%s}, %s))\n", strings.Join(ps[:n(4)], ", "), opt)
	fmt.Fprintf(&b, "\tConsole.Println(concrete(%s, q, []P{%s}))\n", ps[2], strings.Join(ps[:n(4)], ", "))
	b.WriteString("}\n")
	return b.String()
}
