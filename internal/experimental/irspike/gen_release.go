package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// releaseFuncs are GenerateRelease's functions that must have IR bodies:
// each calls a std body that takes the hidden release of its result
// (v1.ResultRelease).
var releaseFuncs = []string{"raced", "summed", "timed"}

// GenerateRelease is a program of std calls whose body takes the hidden
// release of its result (hidden arguments, the release: v1.ResultRelease,
// a v1.Releaser of the call's value type). raced runs tasks.Race over
// blocks with no interruption point that return a resource Res, whose
// Close prints its id: the first block wins and Race releases the losers'
// values, in block order, through the release the call passes (Gap 47).
// summed runs tasks.Transform at limit 1 over ints, failing at a seeded
// element (a value that holds no resource: a nil release). timed runs
// timeout.After with a deadline no run reaches, so it gives its Res (the
// release is passed and not run). Each release prints, so a release not
// passed, passed for the wrong value or run on the wrong value changes the
// output.
func GenerateRelease(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x72656c65617365a1))}
	var b strings.Builder
	b.WriteString(`// generated by irspike.GenerateRelease

import tasks
import timeout

type Res { id int } implements Closer

func Close(r Res) needs Console {
	Console.Println("close \(r.id)")
}

type Fault { at int }

`)
	m := 2 + g.n(4)
	var blocks []string
	for i := 0; i < m; i++ {
		blocks = append(blocks, fmt.Sprintf("\t\tfunc() Res needs Console { Res{id: %d} },\n", 400+10*i+g.n(10)))
	}
	fmt.Fprintf(&b, "func raced() int needs Console {\n\tlet won = tasks.Race([]func() Res needs Console{\n%s\t})\n\tConsole.Println(\"won \\(won.id)\")\n\twon.id\n}\n\n", strings.Join(blocks, ""))
	fmt.Fprintf(&b, "func summed(xs []int, bad int) int fails Fault {\n\tlet ys = try tasks.Transform(xs, 1, func(x int) int fails Fault {\n\t\tif x == bad {\n\t\t\treturn Fault{at: x}\n\t\t}\n\t\tx * %d\n\t})\n\tlet mut s = 0\n\tfor y in ys {\n\t\ts = s + y\n\t}\n\ts\n}\n\n", 2+g.n(5))
	b.WriteString("func timed(k int) int fails timeout.Expired needs Console | Scheduler {\n\tlet r = try timeout.After(1h) {\n\t\tRes{id: 500 + k}\n\t}\n\tConsole.Println(\"timed \\(r.id)\")\n\tr.id + 1\n}\n\n")
	b.WriteString("func main() needs Console | Ambient {\n\twith context { Scheduler: NewLiveScheduler() } {\n")
	b.WriteString("\t\tConsole.Println(\"raced \\(raced())\")\n")
	for i := 0; i < 3; i++ {
		var xs []string
		for j := 0; j < 2+g.n(6); j++ {
			xs = append(xs, fmt.Sprintf("%d", g.n(9)))
		}
		fmt.Fprintf(&b, "\t\tlet s%d = summed([]int{%s}, %d) catch {\n\t\tcase Fault as f:\n\t\t\t-100 - f.at\n\t\t}\n\t\tConsole.Println(\"summed \\(s%d)\")\n", i, strings.Join(xs, ", "), g.n(9), i)
		fmt.Fprintf(&b, "\t\tlet t%d = timed(%d) catch {\n\t\tcase timeout.Expired:\n\t\t\t-1\n\t\t}\n\t\tConsole.Println(\"timed \\(t%d)\")\n", i, g.n(50), i)
	}
	b.WriteString("\t}\n}\n")
	return b.String()
}
