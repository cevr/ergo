package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// wireReadSites are GenerateWireReads's functions that decode on a
// direct reader, with an IR body in every seed (PORT-WIRE-READ).
var wireReadSites = []string{"viaJSON", "viaRd", "load", "settle", "viaDecode"}

// readerDecls is rd, a direct reader (wirereader.go: a named record that
// provides the prelude's Reader by functions on its value) over json's
// Reader, whose String reads the text and gives a fixed one while
// StringBytes gives the text's own bytes. An append-form pair (std's
// time.Time) reads through StringBytes and a string field through String,
// so a reader of one in place of the other shows in the output.
const readerDecls = `type rd { inner json.Reader } implements Reader

func TakeNull(r rd) bool { r.inner.TakeNull() }
func Peek(r rd) WireKind { r.inner.Peek() }
func Number(r rd) string fails WireWrongKind { try r.inner.Number() }
func Path(r rd) string { r.inner.Path() }
func Bool(r rd) bool fails WireWrongKind { try r.inner.Bool() }
func Int(r rd) int64 fails WireWrongKind { try r.inner.Int() }
func Uint(r rd) uint64 fails WireWrongKind { try r.inner.Uint() }
func Float(r rd) float64 fails WireWrongKind { try r.inner.Float() }
func String(r rd) string fails WireWrongKind {
	let _ = try r.inner.String()
	"2001-02-03T04:05:06Z"
}
func StringBytes(r rd, into []byte) []byte fails WireWrongKind { try r.inner.StringBytes(into) }
func BeginList(r rd) fails WireWrongKind { try r.inner.BeginList() }
func BeginObject(r rd) fails WireWrongKind { try r.inner.BeginObject() }
func Tag(r rd) string fails WireMissingField { try r.inner.Tag() }
func More(r rd) bool { r.inner.More() }
func Key(r rd) string { r.inner.Key() }
func Skip(r rd) { r.inner.Skip() }
func End(r rd) { r.inner.End() }

type Ev { At time.Time, N int, Name string, Ts []time.Time }

func show(e Ev) string {
	let mut s = "\(e.At.UnixSeconds()) \(e.N) \(e.Name) ["
	for t in e.Ts {
		s = s + " \(t.UnixSeconds())"
	}
	s + " ]"
}

func viaJSON(text string) string {
	let r = json.Open(text, 0, 0) catch {
	case _:
		return "malformed"
	}
	let e = decode[Ev](r) catch {
	case _:
		return "wrong"
	}
	show(e)
}

func viaRd(text string) string {
	let r = json.Open(text, 0, 0) catch {
	case _:
		return "malformed"
	}
	let e = decode[Ev](rd{inner: r}) catch {
	case _:
		return "wrong"
	}
	show(e)
}

func load[T wire](text string) T fails json.Malformed | wired[T] needs wired[T] {
	let r = try json.Open(text, 0, 0)
	try decode[T](rd{inner: r})
}

// settle reads a decode's failure back as json's Decode does: a catch
// that binds the whole row, wired[T] in it.
func settle[T wire](text string) T fails json.Malformed | wired[T] needs wired[T] {
	let r = try json.Open(text, 0, 0)
	let v = decode[T](rd{inner: r}) catch {
	case err:
		r.Skip()
		return err
	}
	v
}

func viaDecode(text string) string {
	let e = json.Decode[Ev](json.Codec[Ev]{MaxBytes: 0, MaxDepth: 0}, text) catch {
	case json.Malformed:
		return "malformed"
	case _:
		return "wrong"
	}
	show(e)
}

`

// GenerateWireReads is a program that decodes records holding std's
// time.Time (an append-form pair), an int, a string and a list of times on
// direct readers (PORT-WIRE-READ): json's Reader (viaJSON), rd (viaRd) and
// rd through a generic with a codec witness (load), each on texts that
// read, texts of the wrong shape and broken texts. main calls each with a
// constant, so the build-time fold (CF1) computes those calls by the
// evaluator, and both() holds the folded program to the unfolded one.
func GenerateWireReads(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x3c6ef372fe94f82b))
	n := func(k int) int { return r.IntN(k) }
	at := func() string {
		return fmt.Sprintf("%04d-%02d-%02dT%02d:%02d:%02dZ", 1970+n(80), 1+n(12), 1+n(28), n(24), n(60), n(60))
	}
	text := func() string {
		var ts []string
		for i := n(3); i > 0; i-- {
			ts = append(ts, `\"`+at()+`\"`)
		}
		name := []string{"x", "", "a b", "2020-01-01T00:00:00Z"}[n(4)]
		switch n(6) {
		case 0: // the wrong shape: a string where the int is
			return fmt.Sprintf(`{\"at\": \"%s\", \"n\": \"%d\", \"name\": \"%s\", \"ts\": []}`, at(), n(9), name)
		case 1: // a broken text
			return fmt.Sprintf(`{\"at\": \"%s\", \"n\": %d`, at(), n(9))
		}
		return fmt.Sprintf(`{\"at\": \"%s\", \"n\": %d, \"name\": \"%s\", \"ts\": [%s]}`, at(), n(100), name, strings.Join(ts, ", "))
	}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateWireReads\n\nimport json\nimport time\n\n")
	b.WriteString(readerDecls)
	b.WriteString("func main() needs Console {\n")
	for i := 0; i < 3; i++ {
		t := text()
		fmt.Fprintf(&b, "\tConsole.Println(viaJSON(\"%s\"))\n\tConsole.Println(viaRd(\"%s\"))\n", t, t)
		fmt.Fprintf(&b, "\tlet e%d = load[Ev](\"%s\") catch {\n\tcase _:\n\t\tEv{At: time.Unix(0, 0), N: -1, Name: \"failed\", Ts: []time.Time{}}\n\t}\n\tConsole.Println(show(e%d))\n", i, t, i)
		fmt.Fprintf(&b, "\tlet s%d = settle[Ev](\"%s\") catch {\n\tcase json.Malformed:\n\t\tEv{At: time.Unix(0, 0), N: -2, Name: \"malformed\", Ts: []time.Time{}}\n\tcase _:\n\t\tEv{At: time.Unix(0, 0), N: -1, Name: \"failed\", Ts: []time.Time{}}\n\t}\n\tConsole.Println(show(s%d))\n\tConsole.Println(viaDecode(\"%s\"))\n", i, t, i, t)
	}
	b.WriteString("}\n")
	return b.String()
}
