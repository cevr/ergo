package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// fillFuncs are GenerateFill's functions whose slice the IR presizes
// (B-FILL): each gets an IR body whose Go holds v1.SliceOfLen in every
// seed. sameFuncs are its look-alikes that must keep their appends, each
// an IR body too.
var (
	fillFuncs = []string{"counted", "offset", "words", "shared"}
	sameFuncs = []string{"growing", "between", "lastLoop", "loud", "collected"}
)

// GenerateFill is a program of slices built by a count loop that appends
// one value per iteration to an empty slice (B-FILL), which the IR makes
// at their final length and fills by index:
//   - counted: constant bounds from 0, read back at an index Go can then
//     prove in range;
//   - offset: bounds from parameters, so the Range starts past 0 or ends
//     before it starts (an empty slice);
//   - words: string elements;
//   - shared: the slice extended afterward from two places, which must
//     not share an array.
//
// and their look-alikes that keep the appends: an element that reads the
// slice's growing length (growing), a statement that reads the empty
// slice between the let and the loop (between), and a body with no value
// whose last statement is the loop, after a read of the empty slice
// (lastLoop), a bound that prints when it is computed (loud), and a
// collect from a parameter's elements (collected, stackvm's held), a
// loop idiom whose guarded call appends the part at once (IRF-2). main
// prints a digest of each, so a value out of place, a
// length, or a shared array changes the output.
func GenerateFill(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x2545f4914f6cdd1d))
	n := func(k int) int { return r.IntN(k) }
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateFill\n\n")
	b.WriteString("func digest(xs []int) int {\n\tlet mut s = len(xs)\n\tfor x in xs {\n\t\ts = s * 31 + x\n\t}\n\ts\n}\n\n")
	k, m := 1+n(40), 1+n(7)
	fmt.Fprintf(&b, "func counted(q int) int {\n\tlet mut keys = []int{}\n\tfor i in 0..%d {\n\t\tkeys = keys.Append(if i %% %d == 0 { 0 - 1 } else { i * %d })\n\t}\n\tlet mut sum = digest(keys)\n\tfor j in 0..q {\n\t\tsum = sum + keys[j %% %d]\n\t}\n\tsum\n}\n\n", k, 2+n(4), m, k)
	b.WriteString("func offset(a int, z int) int {\n\tlet mut xs = []int{}\n\tfor i in a..z {\n\t\txs = xs.Append(i * i - a)\n\t}\n\tdigest(xs)\n}\n\n")
	b.WriteString("func words(n int) string {\n\tlet mut ws = []string{}\n\tfor i in 0..n {\n\t\tws = ws.Append(\"w\\(i)\")\n\t}\n\tlet mut s = \"\"\n\tfor w in ws {\n\t\ts = s + w + \",\"\n\t}\n\ts\n}\n\n")
	b.WriteString("func shared(n int) int {\n\tlet mut xs = []int{}\n\tfor i in 0..n {\n\t\txs = xs.Append(i + 1)\n\t}\n\tlet ys = xs.Append(100)\n\tlet zs = xs.Append(200)\n\tdigest(ys) * 7 + digest(zs) + digest(xs)\n}\n\n")
	b.WriteString("func growing(n int) int {\n\tlet mut xs = []int{}\n\tfor i in 0..n {\n\t\txs = xs.Append(len(xs) * 2 + i)\n\t}\n\tdigest(xs)\n}\n\n")
	b.WriteString("func between(n int) int {\n\tlet mut xs = []int{}\n\tlet before = len(xs)\n\tfor i in 0..n {\n\t\txs = xs.Append(i)\n\t}\n\tdigest(xs) + before * 1000\n}\n\n")
	b.WriteString("func lastLoop(n int) needs Console {\n\tlet mut xs = []int{}\n\tConsole.Println(\"last \\(len(xs))\")\n\tfor i in 0..n {\n\t\txs = xs.Append(i)\n\t}\n}\n\n")
	b.WriteString("func bound(n int) int needs Console {\n\tConsole.Println(\"bound \\(n)\")\n\tn\n}\n\n")
	b.WriteString("func loud(n int) int needs Console {\n\tlet mut xs = []int{}\n\tfor i in 0..bound(n) {\n\t\txs = xs.Append(i * 3)\n\t}\n\tdigest(xs)\n}\n\n")
	b.WriteString("func collected(q []int, n int) int {\n\tlet mut xs = []int{}\n\tfor i in 0..n {\n\t\txs = xs.Append(q[i])\n\t}\n\tdigest(xs)\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	fmt.Fprintf(&b, "\tConsole.Println(\"collected \\(collected([]int{%d, 6, 7, 8}, %d))\")\n", 1+n(9), 1+n(4))
	for i := 0; i < 3; i++ {
		a := n(10) - 2
		fmt.Fprintf(&b, "\tConsole.Println(\"%d: \\(counted(%d)) \\(offset(%d, %d)) \\(words(%d)) \\(shared(%d)) \\(growing(%d)) \\(between(%d))\")\n", i, n(200), a, a+n(12)-3, n(6), n(9), n(8), n(8))
		fmt.Fprintf(&b, "\tlastLoop(%d)\n", n(5))
		fmt.Fprintf(&b, "\tConsole.Println(\"loud \\(loud(%d))\")\n", n(6))
	}
	b.WriteString("}\n")
	return b.String()
}
