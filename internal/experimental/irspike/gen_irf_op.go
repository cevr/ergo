package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// opFuncs are GenerateOps' functions whose IR body calls Meter's
// operation through the known adapter (IRF-5): every with that reaches
// them binds a Plain. opDynamic are the ones that keep the interface call:
// two provider types reach twice, a literal's call reaches esc, and
// inner's with rebinds Meter for the call inside it (its entry read is
// for the call before the with).
var (
	opFuncs   = []string{"leaf", "mid", "rec", "inner"}
	opDynamic = []string{"twice", "esc"}
)

// GenerateOps is a program of capability calls (IR-FORMS IRF-5): a
// capability Meter with two providers of the program, Plain and Shift,
// each a record whose function provides the operation (an operations
// conversion); functions that call Meter.Add in a loop, through a chain
// of callers that inherit their binding, and recursively; withs that
// bind Meter to Plains of different fields (inline and a named context),
// a function reached by a Plain and by a Shift, a with inside a function
// that rebinds Meter for the calls in its block, and a function called
// from a function literal under a Shift's with. main prints every
// result, so a call that reads the wrong provider, or a provider's
// fields from another with, changes the output, and a wrong adapter
// panics in its entry's assertion.
func GenerateOps(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x2545f4914f6cdd1d))
	var b strings.Builder
	k := func(n int) int { return 1 + r.IntN(n) }
	b.WriteString("// generated by irspike.GenerateOps\n\nimport slices\n\n")
	b.WriteString("type Meter {\n\tAdd(x int) int,\n}\n\n")
	b.WriteString("type Plain { Scale int, Base int } implements Meter\n\nfunc Add(p Plain, x int) int { x * p.Scale + p.Base }\n\n")
	b.WriteString("type Shift { By int } implements Meter\n\nfunc Add(s Shift, x int) int { x - s.By }\n\n")
	fmt.Fprintf(&b, "let Fast = context {\n\tMeter: Plain{Scale: %d, Base: %d},\n}\n\n", k(5), r.IntN(9))
	// leaf: the loop; mid: a caller that inherits; rec: recursion.
	fmt.Fprintf(&b, "func leaf(n int) int needs Meter {\n\tlet mut s = 0\n\tfor i in 0..n {\n\t\ts = s + Meter.Add(i & %d)\n\t}\n\ts\n}\n\n", []int{7, 15, 1023}[r.IntN(3)])
	b.WriteString("func mid(n int) int needs Meter {\n\tleaf(n) + Meter.Add(n)\n}\n\n")
	b.WriteString("func rec(n int) int needs Meter {\n\tif n <= 0 {\n\t\t0\n\t} else {\n\t\tMeter.Add(n) + rec(n - 1)\n\t}\n}\n\n")
	// twice: a Plain's with and a Shift's reach it.
	b.WriteString("func twice(n int) int needs Meter {\n\tMeter.Add(n) * 2\n}\n\n")
	// inner: its own with rebinds Meter for the calls in the block.
	fmt.Fprintf(&b, "func inner(n int) int needs Meter {\n\tlet a = Meter.Add(n)\n\twith context { Meter: Shift{By: %d} } {\n\t\ta * 100 + Meter.Add(n) + twice(n)\n\t}\n}\n\n", k(9))
	// esc: called directly under Plains, and from a literal under a Shift.
	b.WriteString("func esc(x int) int needs Meter {\n\tMeter.Add(x) + 1\n}\n\n")
	// The literal is made outside the Shift's with and called inside it.
	fmt.Fprintf(&b, "func lits(xs []int) int needs Meter {\n\tlet f = func(x int) int needs Meter { esc(x) }\n\tlet ys = with context { Meter: Shift{By: %d} } {\n\t\tslices.Transform(xs, f)\n\t}\n\tlet mut s = esc(len(xs))\n\tfor y in ys {\n\t\ts = s * 3 + y\n\t}\n\ts\n}\n\n", k(9))
	// Withs: inline Plains of seeded fields, and the named context.
	b.WriteString("func run(n int, scale int, base int) int {\n")
	fmt.Fprintf(&b, "\tlet a = with context { Meter: Plain{Scale: scale, Base: base} } {\n\t\tmid(n) + rec(%d) + inner(n) + twice(n) + esc(n)\n\t}\n", k(6))
	b.WriteString("\tlet c = with Fast { leaf(n * 2) + lits([]int{n, n + 1, n + 2}) }\n")
	fmt.Fprintf(&b, "\tlet d = with context { Meter: Shift{By: %d} } { twice(n) }\n", k(9))
	b.WriteString("\ta * 7 + c * 3 + d\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	for i := 0; i < 3; i++ {
		fmt.Fprintf(&b, "\tConsole.Println(\"\\(run(%d, %d, %d))\")\n", r.IntN(40), k(7), r.IntN(20)-5)
	}
	b.WriteString("}\n")
	return b.String()
}
