package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// wcalleeSites are GenerateWitnessCallee's generic functions whose IR
// bodies call operations through their witness parameters (B-WITNESS);
// each has an IR body that calls a witness field ("vcall") in every
// seed.
var wcalleeSites = []string{"scaled", "both", "areaOf"}

// GenerateWitnessCallee is a program of generic functions over an
// operation type, Shape, whose bodies call its operations on their type
// parameter's values (B-WITNESS, the callee side):
//   - scaled calls an operation with no result (Note), a fallible one
//     under try (Scale) and one with a value (Area);
//   - both has two type parameters, so no call of it goes to a copy for a
//     known witness (witspec.go): its body runs, and it passes each of its
//     witnesses on to scaled and areaOf, whose bodies run too; it catches
//     scaled's failure and Scale's, called on its own witness;
//   - areaOf reads Area of each element of a slice of its type parameter;
//   - single has one type parameter, so main's call of it at Sq goes to
//     the copy for that known witness (witspec.go), on both paths.
//
// Rect and Sq keep Shape with drawn bodies. main prints both at drawn
// operands in both orders, so a witness passed in the wrong place, an
// operation of the other type, a failure lost or a value misread changes
// the output.
func GenerateWitnessCallee(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x3c6ef372fe94f82b))
	n := func(k int) int { return r.IntN(k) }
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateWitnessCallee\n\n")
	b.WriteString("type Neg { At int }\n\n")
	b.WriteString("type Shape {\n\tArea() int,\n\tScale(k int) int fails Neg,\n\tNote(k int),\n}\n\n")
	b.WriteString("type Rect { W int, H int } implements Shape\n\ntype Sq { S int } implements Shape\n\n")
	fmt.Fprintf(&b, "func Area(r Rect) int {\n\tr.W * r.H + %d\n}\n\n", n(5))
	fmt.Fprintf(&b, "func Scale(r Rect, k int) int fails Neg {\n\tif k < %d {\n\t\tNeg{At: k}\n\t} else {\n\t\tr.W * k + r.H\n\t}\n}\n\n", n(3)-1)
	b.WriteString("func Note(r Rect, k int) {\n\tlet _ = r.W + k\n}\n\n")
	fmt.Fprintf(&b, "func Area(s Sq) int {\n\ts.S * s.S - %d\n}\n\n", n(4))
	fmt.Fprintf(&b, "func Scale(s Sq, k int) int fails Neg {\n\tif k %% %d == 0 {\n\t\tNeg{At: k + 1}\n\t} else {\n\t\ts.S * %d + k\n\t}\n}\n\n", 2+n(3), 1+n(6))
	b.WriteString("func Note(s Sq, k int) {\n\tlet _ = s.S - k\n}\n\n")
	b.WriteString("func scaled[T Shape](t T, k int) int fails Neg {\n\tt.Note(k)\n\tlet a = try t.Scale(k)\n\ta * 7 + t.Area()\n}\n\n")
	b.WriteString("func areaOf[T Shape](xs []T) int {\n\tlet mut s = 0\n\tfor x in xs {\n\t\ts = s * 3 + x.Area()\n\t}\n\ts\n}\n\n")
	b.WriteString("func both[P Shape, Q Shape](p P, q Q, k int) int {\n\tlet x = scaled(p, k) catch {\n\tcase Neg as e:\n\t\te.At * 10\n\t}\n\tlet y = scaled(q, k - 3) catch {\n\tcase Neg as e:\n\t\te.At * 100\n\t}\n\tlet z = p.Scale(k + 1) catch {\n\tcase Neg as e:\n\t\te.At - 50\n\t}\n\tx * 1000 + y + areaOf([]P{p, p}) - areaOf([]Q{q}) + q.Area() * z\n}\n\n")
	fmt.Fprintf(&b, "func single[T Shape](t T, k int) int {\n\tt.Area() * %d + k\n}\n\n", 2+n(5))
	b.WriteString("func main() needs Console {\n")
	for i := 0; i < 4; i++ {
		rect := fmt.Sprintf("Rect{W: %d, H: %d}", n(7), n(7)-2)
		sq := fmt.Sprintf("Sq{S: %d}", n(9)-3)
		k := n(10) - 3
		fmt.Fprintf(&b, "\tConsole.Println(\"%d: \\(both(%s, %s, %d)) \\(both(%s, %s, %d)) \\(single(%s, %d))\")\n", i, rect, sq, k, sq, rect, k+1, sq, k)
	}
	b.WriteString("}\n")
	return b.String()
}
