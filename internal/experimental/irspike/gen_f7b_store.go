package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// storeFuncs are GenerateStore's functions: each gets an IR body in every
// seed (B-STOREPLACE, "store of a call that updates its place"; Delete,
// Go's builtin delete, since B-BUILTINS).
var storeFuncs = []string{"Tally.add", "Tally.drop", "fresh"}

// GenerateStore is a program of stores of calls that update their place:
// a Map field written by Put and Delete and stored back into itself (p.m =
// p.m.Put(k, v), which the value rule writes in place and the store
// drops), and a slice field grown by Append and stored back, through a
// pointer (add, drop) and in a local record (fresh). main reads the
// records back, so an update lost, applied to a copy or applied twice
// changes the output.
func GenerateStore(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x510e527fade682d1))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateStore\n\n")
	b.WriteString("type Tally { counts Map[string, int], seen []string, total int }\n\n")
	b.WriteString("func add(t mut Tally, k string, n int) {\n\tt.counts = t.counts.Put(k, n)\n\tt.seen = t.seen.Append(k)\n\tt.total += n\n}\n\n")
	b.WriteString("func drop(t mut Tally, k string) {\n\tt.counts = t.counts.Delete(k)\n}\n\n")
	fmt.Fprintf(&b, "func fresh(n int) int {\n\tlet keys = []string{\"a\", \"b\", \"c\", \"d\"}\n\tlet mut r = Tally{counts: Map[string, int]{}, seen: []string{}, total: 0}\n\tfor i in 0..n {\n\t\tr.counts = r.counts.Put(keys[i %% %d], i * %d)\n\t\tr.seen = r.seen.Append(keys[i %% 4])\n\t\tr.total += i\n\t\tif i %% %d == 0 {\n\t\t\tr.counts = r.counts.Delete(keys[0])\n\t\t}\n\t}\n\tr.total * 1000 + len(r.counts) * 100 + len(r.seen)\n}\n\n", 2+g.n(3), 1+g.n(5), 2+g.n(3))
	b.WriteString("func count(t Tally, k string) int {\n\tmatch t.counts.Get(k) {\n\tcase Some as v:\n\t\tv.Value\n\tcase None:\n\t\t-1\n\t}\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	b.WriteString("\tlet mut t = Tally{counts: Map[string, int]{}, seen: []string{}, total: 0}\n")
	keys := []string{`"a"`, `"b"`, `"c"`, `"d"`}
	for k := 0; k < 8; k++ {
		if g.n(3) == 0 {
			fmt.Fprintf(&b, "\tdrop(&t, %s)\n", keys[g.n(4)])
		} else {
			fmt.Fprintf(&b, "\tadd(&t, %s, %d)\n", keys[g.n(4)], g.n(40))
		}
	}
	b.WriteString("\tConsole.Println(\"\\(t.total) \\(len(t.counts)) \\(len(t.seen)) \\(count(t, \"a\")) \\(count(t, \"b\")) \\(count(t, \"c\")) \\(count(t, \"d\"))\")\n")
	fmt.Fprintf(&b, "\tConsole.Println(\"\\(fresh(%d)) \\(fresh(%d))\")\n", g.n(9), 3+g.n(12))
	b.WriteString("}\n")
	return b.String()
}
