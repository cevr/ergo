package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// ownListFuncs are the functions GenerateOwnList writes besides the olN:
// taker owns its taken parameter beside a local it writes in place, so
// its frame takes the list form too.
var ownListFuncs = []string{"Res.taker", "Res.failing"}

// ownListMark is the line GenerateOwnList's main prints before its last
// call (whose Close fails): every value opened before it is closed
// before it, once.
const ownListMark = "-- every value opened so far is closed"

// GenerateOwnList is a program of frames that open a scope only for their
// owned values and keep them in the list form (OWNED-LOCAL: a plain frame
// not in the static form, v1.NewOwnerScope): each olN(k int, bad bool)
// int writes a field of one of its owned locals in place, so its release
// reads the written value (v1.OwningAt), and around it opens more, lends
// them, hands some to a taking function, returns early on some k, and
// opens values in an inner scope or a loop. taker owns its taken
// parameter in such a frame, and failing does too with an error row (a
// failure releases both values). Each Close prints the id and the written
// field, so a value released twice, never, out of order, with its old
// fields, or after a hand-off changes the output; at the last call a
// Close that fails shows a defect's release order.
func GenerateOwnList(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x3c6ef372fe94f82b))
	var b strings.Builder
	b.WriteString(`// generated by irspike.GenerateOwnList

type Res { id int, n int, bad bool } implements Closer

func Close(r Res) needs Console {
	Console.Println("close \(r.id) n=\(r.n)")
	if r.bad {
		// A defect in a checked Close (an index out of range).
		let none = []int{}
		let v = none[r.id]
		Console.Println("never \(v)")
	}
}

func open(id int, bad bool) Res needs Console {
	Console.Println("open \(id)")
	Res{id: id, n: 0, bad: bad}
}

func use(r Res) int needs Console {
	Console.Println("use \(r.id) n=\(r.n)")
	r.id + r.n
}

func keep(r own Res) needs Console {
	Console.Println("keep \(r.id) n=\(r.n)")
}

// taker owns its taken parameter r in a list frame (w is written in
// place): r is released at the frame's exit unless handed to keep.
func taker(r own Res, k int) int needs Console {
	let mut w = open(900 + k, false)
	w.n = k + 1
	if k > 1 {
		keep(r)
		return use(w)
	}
	use(r) + use(w)
}

type Oops { code int }

// failing owns r and w in a list frame with an error row: a failure
// releases both, and r is taken only on success.
func failing(r own Res, k int) int fails Oops needs Console {
	let mut w = open(800 + k, false)
	w.n = k + 2
	if k > 1 {
		return Oops{code: use(w)}
	}
	keep(r)
	use(w)
}

func failingAt(k int) int needs Console {
	failing(open(600 + k, false), k) catch {
	case Oops as o:
		o.code
	}
}

`)
	nf := 3 + r.IntN(3)
	for i := 0; i < nf; i++ {
		fmt.Fprintf(&b, "func ol%d(k int, bad bool) int needs Console {\n\tlet mut s = k\n\ts = s * 2\n", i)
		n := 2 + r.IntN(4)
		w := r.IntN(n) // the local written in place
		var live []string
		for j := 0; j < n; j++ {
			name := fmt.Sprintf("r%d", j)
			id := 10*(i+1) + j
			badArg := "false"
			if j == 0 {
				badArg = "bad" // released last: the defect comes after the others' releases
			}
			if j == w {
				fmt.Fprintf(&b, "\tlet mut %s = open(%d, %s)\n\t%s.n = k * %d + 1\n", name, id, badArg, name, j+2)
			} else {
				fmt.Fprintf(&b, "\tlet %s = open(%d, %s)\n", name, id, badArg)
			}
			live = append(live, name)
			switch r.IntN(5) {
			case 0:
				fmt.Fprintf(&b, "\tlet u%d = use(%s)\n\ts = s + u%d\n", j, name, j)
			case 1:
				if j != 0 {
					fmt.Fprintf(&b, "\tif k == %d {\n\t\tkeep(%s)\n\t\treturn s\n\t}\n", r.IntN(4), name)
				}
			case 2:
				fmt.Fprintf(&b, "\tif k == %d {\n\t\treturn s + %d\n\t}\n", r.IntN(4), j)
			case 3:
				id := 100*(i+1) + j
				if r.IntN(2) == 0 {
					fmt.Fprintf(&b, "\tif k > %d {\n\t\tlet mut t%d = open(%d, false)\n\t\tt%d.n = k\n\t\tlet v%d = use(t%d)\n\t\ts = s + v%d\n\t}\n", r.IntN(3), j, id, j, j, j, j)
				} else {
					fmt.Fprintf(&b, "\tfor q in 0..3 {\n\t\tlet t%d = open(%d + q, false)\n\t\tlet v%d = use(t%d)\n\t\ts = s + v%d\n\t\tif q == k {\n\t\t\tbreak\n\t\t}\n\t}\n", j, id, j, j, j)
				}
			case 4:
				fmt.Fprintf(&b, "\tlet g%d = taker(open(%d, false), k)\n\ts = s + g%d\n", j, 500+id, j)
			}
			if j == w && r.IntN(2) == 0 {
				// A second write after other code ran: the release reads it.
				fmt.Fprintf(&b, "\t%s.n = %s.n + 7\n", name, name)
			}
		}
		if r.IntN(2) == 0 {
			fmt.Fprintf(&b, "\tlet un = use(%s)\n\ts = s + un\n", live[r.IntN(len(live))])
		}
		b.WriteString("\ts\n}\n\n")
	}
	b.WriteString("func main() needs Console {\n\tfor k in 0..4 {\n")
	for i := 0; i < nf; i++ {
		fmt.Fprintf(&b, "\t\tConsole.Println(\"ol%d \\(k) \\(ol%d(k, false))\")\n", i, i)
	}
	b.WriteString("\t\tConsole.Println(\"taker \\(k) \\(taker(open(700 + k, false), k))\")\n")
	b.WriteString("\t\tConsole.Println(\"failing \\(k) \\(failingAt(k))\")\n\t}\n")
	// The opens and closes before this line pair up (TestIROwnedListMatchSource).
	b.WriteString("\tConsole.Println(\"" + ownListMark + "\")\n")
	fmt.Fprintf(&b, "\tConsole.Println(\"bad \\(ol%d(1, true))\")\n}\n", r.IntN(nf))
	return b.String()
}
