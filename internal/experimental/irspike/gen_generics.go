package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateGenerics is a program of generic functions (F1): bodies with
// type parameters of their own, a generic record's functions (Go methods,
// whose type parameters are the receiver's) and calls of generic std
// bodies (slices.Contains, slices.Index, maps.Clone), at int, string and bool and at
// a type parameter of the caller. Each function is drawn from a few shapes
// with seeded constants and is called from main at several type
// arguments and inputs, so a type argument, a parameter or an element
// read wrong changes the output.
func GenerateGenerics(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x2545f4914f6cdd1d))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateGeneric\n\nimport maps\nimport slices\n\n")
	b.WriteString("type Box[T] { v T, n int }\n\n")
	fmt.Fprintf(&b, "func Size[T](b Box[T]) int {\n\tb.n * %d + %d\n}\n\n", 1+g.n(3), g.n(5))
	b.WriteString("func Value[T](b Box[T]) T {\n\tb.v\n}\n\n")
	// Or names the receiver's type parameter in its body (a local of T).
	fmt.Fprintf(&b, "func Or[T](b Box[T], d T) T {\n\tlet mut out = d\n\tif b.n > %d {\n\t\tout = b.v\n\t}\n\tout\n}\n\n", g.n(5))
	fmt.Fprintf(&b, "func boxed[T](v T, n int) Box[T] {\n\tBox[T]{v: v, n: n + %d}\n}\n\n", g.n(4))
	// pick: the element at i, or d.
	cmp := []string{"j == i", "j + %d == i", "i == j * %d"}[g.n(3)]
	if strings.Contains(cmp, "%d") {
		cmp = fmt.Sprintf(cmp, 1+g.n(2))
	}
	fmt.Fprintf(&b, "func pick[T](xs []T, i int, d T) T {\n\tlet mut out = d\n\tfor j, x in xs {\n\t\tif %s {\n\t\t\tout = x\n\t\t}\n\t}\n\tout\n}\n\n", cmp)
	// grow: xs with a appended k times, then b's count.
	fmt.Fprintf(&b, "func grow[A, B](xs []A, a A, b B, k int) []A {\n\tlet mut out = []A{}\n\tfor x in xs {\n\t\tout = out.Append(x)\n\t}\n\tfor _ in 0..k {\n\t\tout = out.Append(a)\n\t}\n\tlet bx = boxed(b, %d)\n\tif bx.Size() > %d {\n\t\tout = out.Append(a)\n\t}\n\tout\n}\n\n", g.n(3), g.n(6))
	// has and where: generic std bodies, at the caller's type parameter.
	b.WriteString("func has[T comparable](xs []T, x T) bool {\n\tslices.Contains(xs, x)\n}\n\n")
	// cloned: a std body with two type parameters of different types.
	b.WriteString("func cloned[K comparable, V](m Map[K, V]) Map[K, V] {\n\tmaps.Clone(m)\n}\n\n")
	fmt.Fprintf(&b, "func where[T comparable](xs []T, x T) int {\n\tslices.Index(xs, x) + %d\n}\n\n", g.n(3))
	// twice: a generic body that calls generic bodies at its own types.
	b.WriteString("func twice[T comparable](xs []T, x T, d T) int {\n\tlet ys = grow(xs, x, d, 1)\n\tlet mut n = 0\n\tif has(ys, d) {\n\t\tn = n + 10\n\t}\n\tn + where(ys, x) + len(ys)\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	ints := g.ints()
	strs := []string{`"a"`, `"bb"`, `""`, `"z"`}
	g.r.Shuffle(len(strs), func(i, j int) { strs[i], strs[j] = strs[j], strs[i] })
	slist := "[]string{" + strings.Join(strs[:1+g.n(4)], ", ") + "}"
	for k := 0; k < 3; k++ {
		i := g.n(5) - 1
		// Each value is a let first: a string literal stays out of the
		// interpolation.
		fmt.Fprintf(&b, "\tlet pi%d = pick(%s, %d, %d)\n", k, ints, i, g.n(9))
		fmt.Fprintf(&b, "\tlet ps%d = pick(%s, %d, \"d\")\n", k, slist, i)
		fmt.Fprintf(&b, "\tlet gr%d = len(grow(%s, %d, true, %d))\n", k, ints, g.n(9), g.n(3))
		fmt.Fprintf(&b, "\tlet ti%d = twice(%s, %d, %d)\n", k, ints, g.n(9), g.n(9))
		fmt.Fprintf(&b, "\tlet ts%d = twice(%s, %s, %s)\n", k, slist, strs[g.n(4)], strs[g.n(4)])
		fmt.Fprintf(&b, "\tlet bs%d = boxed(%s, %d).Size()\n", k, strs[g.n(4)], g.n(7))
		fmt.Fprintf(&b, "\tlet bv%d = boxed(%d, %d).Or(%d)\n", k, g.n(9), g.n(5), g.n(9))
		fmt.Fprintf(&b, "\tlet cl%d = len(cloned(Map[string, int]{\"a\": %d, \"b%d\": %d}))\n", k, g.n(9), g.n(3), g.n(9))
		fmt.Fprintf(&b, "\tConsole.Println(\"%d: \\(pi%d) [\\(ps%d)] \\(gr%d) \\(ti%d) \\(ts%d) \\(bs%d) \\(bv%d) \\(cl%d)\")\n", k, k, k, k, k, k, k, k, k)
	}
	b.WriteString("}\n")
	return b.String()
}

type ggen struct{ r *rand.Rand }

func (g *ggen) n(k int) int { return g.r.IntN(k) }

// ints is an int slice literal of up to five elements.
func (g *ggen) ints() string {
	var xs []string
	for i, n := 0, g.n(6); i < n; i++ {
		xs = append(xs, fmt.Sprint(g.n(9)))
	}
	return "[]int{" + strings.Join(xs, ", ") + "}"
}
