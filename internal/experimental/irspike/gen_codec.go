package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateCodec is a program of the codec built-ins (FLIP OPC-codec):
// put encodes a record on the prelude's Writer and back decodes one from
// its Reader, each a body the IR lowers; main writes seeded records on
// std codec's Events and reads them back from a Replay of the events, then
// reads once more past the end, which fails, so both the value and the
// failure path show in the output.
func GenerateCodec(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x3c6ef372fe94f82b))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateCodec\n\nimport codec\n\ntype P { A int, B string, C []int, D bool }\n\n")
	b.WriteString("func put(p P, w Writer) {\n\tencode(p, w)\n}\n\n")
	b.WriteString("func back(r Reader) P fails wired[P] {\n\tdecode[P](r)\n}\n\n")
	none := fmt.Sprintf("P{A: %d, B: \"none\", C: []int{}, D: false}", -1-g.n(9))
	b.WriteString("func main() needs Console {\n\tlet e = codec.NewEvents()\n")
	n := 1 + g.n(3)
	for i := 0; i < n; i++ {
		fmt.Fprintf(&b, "\tput(P{A: %d, B: \"s%d\", C: %s, D: %v}, e)\n", g.n(100)-50, g.n(9), g.ints(), g.n(2) == 0)
	}
	b.WriteString("\tlet r = codec.NewReplay(codec.Recorded(e))\n")
	for i := 0; i <= n; i++ {
		fmt.Fprintf(&b, "\tlet q%d = back(r) catch {\n\tcase _:\n\t\t%s\n\t}\n", i, none)
		fmt.Fprintf(&b, "\tConsole.Println(\"%d: \\(q%d.A) \\(q%d.B) \\(len(q%d.C)) \\(q%d.D)\")\n", i, i, i, i, i)
	}
	b.WriteString("}\n")
	return b.String()
}
