package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// omittableSites are GenerateOmittable's bodies with an IR body in every
// seed, by their Go names (their first parameter is an R); the codec
// functions of R, Inner and Shape are checked by their CodecText instead
// (TestIROmittableMatchSource).
var omittableSites = []string{"R.viaText", "R.viaCounter"}

// GenerateOmittable is a program that encodes records with omittable
// fields (json.Optional, WireOmittable) on two cell writers (PORT-WIRE):
//   - json's Text (NewText), whose BeginObject takes no count;
//   - Counter, a sealed Writer of this package whose one provider is a
//     cell (as json's Text is: std has no privilege), whose BeginObject
//     writes the count it is given, so a count that keeps an absent field
//     shows.
//
// R draws its fields from omittable and plain ones (an Optional of an
// int, a string and a record, Inner, which has one of its own); Shape is
// a union whose variants hold omittable fields. Each value draws each
// omittable field present or absent, so a key written for an absent
// field, a count not lowered, or a field read twice changes the output.
func GenerateOmittable(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x9b05688c2b3e6c1f))
	n := func(k int) int { return r.IntN(k) }
	word := func() string { return []string{"", "<b>", "a&b", "q\\\"t", "é"}[n(5)] }
	kinds := []string{"json.Optional[int]", "json.Optional[Inner]", "json.Optional[string]", "int", "string"}
	fields := 3 + n(3)
	types := make([]string, fields)
	omittable := false
	for i := range types {
		types[i] = kinds[n(len(kinds))]
		omittable = omittable || strings.HasPrefix(types[i], "json.")
	}
	if !omittable {
		types[0] = kinds[n(3)]
	}
	inner := func() string {
		y := "json.Absent"
		if n(2) == 0 {
			y = fmt.Sprintf("json.Present{Value: \"%s\"}", word())
		}
		return fmt.Sprintf("Inner{X: %d, Y: %s}", n(10), y)
	}
	opt := func(v string) string {
		if n(3) == 0 {
			return "json.Absent"
		}
		return "json.Present{Value: " + v + "}"
	}
	value := func(t string) string {
		switch t {
		case "json.Optional[int]":
			return opt(fmt.Sprint(n(100)))
		case "json.Optional[Inner]":
			return opt(inner())
		case "json.Optional[string]":
			return opt("\"" + word() + "\"")
		case "int":
			return fmt.Sprint(n(200) - 100)
		}
		return "\"" + word() + "\""
	}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateOmittable\n\nimport json\n\n")
	b.WriteString(counterDecls)
	b.WriteString("type Inner { X int, Y json.Optional[string] }\n\n")
	b.WriteString("type Shape = Dot | Box\n\ntype Dot { At json.Optional[int] }\n\ntype Box { W int, H json.Optional[int], L json.Optional[string] }\n\n")
	b.WriteString("type R { ")
	for i, t := range types {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "F%d %s", i, t)
	}
	b.WriteString(" }\n\n")
	b.WriteString("func viaText(r R, s Shape) string {\n\tlet w = json.NewText()\n\tw.BeginList(2)\n\tencode(r, w)\n\tencode(s, w)\n\tw.EndList()\n\tw.Written()\n}\n\n")
	b.WriteString("func viaCounter(r R, s Shape) string {\n\tlet w = newCounter()\n\tencode(r, w)\n\tencode(s, w)\n\tw.Written()\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	for i := 0; i < 3; i++ {
		var rv strings.Builder
		rv.WriteString("R{")
		for j, t := range types {
			if j > 0 {
				rv.WriteString(", ")
			}
			fmt.Fprintf(&rv, "F%d: %s", j, value(t))
		}
		rv.WriteString("}")
		sv := fmt.Sprintf("Dot{At: %s}", opt(fmt.Sprint(n(10))))
		if n(2) == 0 {
			sv = fmt.Sprintf("Box{W: %d, H: %s, L: %s}", n(10), opt(fmt.Sprint(n(10))), opt("\""+word()+"\""))
		}
		fmt.Fprintf(&b, "\tConsole.Println(viaText(%s, %s))\n", rv.String(), sv)
		fmt.Fprintf(&b, "\tConsole.Println(viaCounter(%s, %s))\n", rv.String(), sv)
		if i == 0 {
			fmt.Fprintf(&b, "\tConsole.Println(json.Encode(json.Codec[R]{MaxBytes: 0, MaxDepth: 0}, %s))\n", rv.String())
		}
	}
	b.WriteString("}\n")
	return b.String()
}

// counterDecls is Counter, a sealed Writer whose one provider, the record
// counter, is a cell: each event appends its name and arguments, and
// BeginObject and BeginList the count they are given.
const counterDecls = `type Counter {
	..Writer,
	mut Written() string,
	// note seals Counter in this package, so its provider is a cell.
	mut note(s string),
}

type counter { out string } implements Counter

func note(t mut counter, s string) { t.out = t.out + s }

func Null(t mut counter) { t.note("null ") }
func Number(t mut counter, s string) { t.out = t.out + "num " + s + " " }
func Bool(t mut counter, b bool) { t.out = t.out + "\(b) " }
func Int(t mut counter, n int64) { t.out = t.out + "\(n) " }
func Uint(t mut counter, n uint64) { t.out = t.out + "u\(n) " }
func Float(t mut counter, f float64) { t.out = t.out + "f\(f) " }
func String(t mut counter, s string) { t.out = t.out + "'" + s + "' " }
func StringBytes(t mut counter, b []byte) { t.out = t.out + "bytes " }
func BeginList(t mut counter, n int) { t.out = t.out + "[\(n) " }
func EndList(t mut counter) { t.out = t.out + "] " }
func BeginObject(t mut counter, n int) { t.out = t.out + "{\(n) " }
func Tag(t mut counter, s string) { t.out = t.out + "#" + s + " " }
func Key(t mut counter, k string) { t.out = t.out + k + ": " }
func EndObject(t mut counter) { t.out = t.out + "} " }
func Written(t mut counter) string { t.out }

func newCounter() Counter { counter{out: ""} }

`
