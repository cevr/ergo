package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateKnownCallback is a program whose IR bodies call known-callback
// variants (F7, "known-callback variant"; known.go): apply calls its
// callback in a loop; twice forwards its callback to apply (its variant
// calls apply's variant); pick calls a callback with a bool result and
// one with no result; mapG is generic. Each is called with pure literals
// that read the caller's locals (known sites, so the IR passes plain
// literals to the variant), and apply is also called with a literal read
// from a binding (not known: the uniform function), so both bodies run
// on the same values.
func GenerateKnownCallback(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x6c796b63620a0405))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateKnownCallback\n\n")
	b.WriteString("func apply(xs []int, f func(x int) int) int {\n\tlet mut s = 0\n\tfor x in xs {\n\t\ts = s + f(x)\n\t}\n\ts\n}\n\n")
	fmt.Fprintf(&b, "func twice(xs []int, f func(x int) int) int {\n\tlet a = apply(xs, f)\n\tlet c = apply(xs, f)\n\ta*%d + c\n}\n\n", 2+g.n(5))
	b.WriteString("func pick(a int, c int, keep func(x int) bool, see func(x int)) int {\n\tsee(a)\n\tif keep(a) {\n\t\treturn a\n\t}\n\tc\n}\n\n")
	b.WriteString("func mapG[T](xs []T, f func(x T) T) []T {\n\tlet mut out = []T{}\n\tfor x in xs {\n\t\tout = out.Append(f(x))\n\t}\n\tout\n}\n\n")
	k, m, lim := 1+g.n(9), 2+g.n(7), g.n(60)
	fmt.Fprintf(&b, "func useApply(xs []int, k int) int {\n\tapply(xs, func(x int) int { x*k + %d })\n}\n\n", m)
	fmt.Fprintf(&b, "func useTwice(xs []int, k int) int {\n\ttwice(xs, func(x int) int {\n\t\tif x > k {\n\t\t\treturn x - k\n\t\t}\n\t\tx + %d\n\t})\n}\n\n", m)
	fmt.Fprintf(&b, "func usePick(a int, c int) int {\n\tpick(a, c, func(x int) bool { x %% %d == 0 }, func(x int) {\n\t\tif x > %d {\n\t\t\treturn\n\t\t}\n\t})\n}\n\n", m, lim)
	fmt.Fprintf(&b, "func useMap(xs []int, k int) int {\n\tlet ys = mapG[int](xs, func(x int) int { x + k })\n\tlet mut s = 0\n\tfor y in ys {\n\t\ts = s*%d + y\n\t}\n\ts\n}\n\n", m)
	b.WriteString("func useBound(xs []int, k int) int {\n\tlet f = func(x int) int { x - k }\n\tapply(xs, f)\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	for i := 0; i < 3; i++ {
		var xs []string
		for j := 0; j < 2+g.n(7); j++ {
			xs = append(xs, fmt.Sprint(g.n(80)))
		}
		fmt.Fprintf(&b, "\tlet xs%d = []int{%s}\n", i, strings.Join(xs, ", "))
		fmt.Fprintf(&b, "\tConsole.Println(\"%d: \\(useApply(xs%d, %d)) \\(useTwice(xs%d, %d)) \\(usePick(%d, %d)) \\(useMap(xs%d, %d)) \\(useBound(xs%d, %d))\")\n",
			i, i, k+i, i, 20+g.n(40), g.n(100), g.n(100), i, k, i, k)
	}
	b.WriteString("}\n")
	return b.String()
}
