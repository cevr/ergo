package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateOwnLit is a program of owned Ref sites (FLIP F7 FORK-OWNLIT;
// refown.go, V6): a Ref's Update and sync.Modify given a function literal
// written at the call, whose parameter takes the held value over and
// writes it in place. A seeded sequence of operations runs on two cells,
// a Map and a record that holds a slice, and keeps what Get and an
// aliasing Modify give back:
//
//   - put, grow: Update writing the held value in place (Map's Put, the
//     slice's Append);
//   - take: Modify returning a scalar and the Map with an entry deleted;
//   - alias: Modify returning the held Map as both elements, so its
//     result is not fresh and the cell marks what it stores shared;
//   - a Get, which marks the held value shared.
//
// Every kept value is printed at the end, so a write in place that
// reaches a value given back earlier (a copy function that copies
// nothing, a fresh flag that is wrong) changes the output.
func GenerateOwnLit(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x3c6ef372fe94f82b))}
	keys := []string{"a", "b", "c"}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateOwnLit\n\nimport sync\n\n")
	b.WriteString("type S { Items []int, N int }\n\n")
	b.WriteString("func put(r sync.Ref[Map[string, int]], k string, v int) {\n\tr.Update() func(m Map[string, int]) Map[string, int] { m.Put(k, v) }\n}\n\n")
	b.WriteString("func take(r sync.Ref[Map[string, int]], k string) int {\n\tsync.Modify(r) func(m Map[string, int]) (int, Map[string, int]) {\n\t\t(at(m, k), m.Delete(k))\n\t}\n}\n\n")
	b.WriteString("func alias(r sync.Ref[Map[string, int]]) Map[string, int] {\n\tsync.Modify(r) func(m Map[string, int]) (Map[string, int], Map[string, int]) { (m, m) }\n}\n\n")
	fmt.Fprintf(&b, "func grow(r sync.Ref[S], k int) {\n\tr.Update() func(s S) S { S{..s, Items: s.Items.Append(k), N: s.N + %d} }\n}\n\n", 1+g.n(3))
	// The in-place form (FORK-INPLACE): a literal that binds the held
	// value to one let mut first and returns it last writes the cell's
	// value through a pointer.
	fmt.Fprintf(&b, "func push(r sync.Ref[S], k int) {\n\tr.Update() func(v S) S {\n\t\tlet mut s = v\n\t\ts.Items = s.Items.Append(k)\n\t\ts.N = s.N + %d\n\t\ts\n\t}\n}\n\n", 1+g.n(4))
	b.WriteString("func bump(s mut S, k int) int {\n\ts.N = s.N * 2 + k\n\ts.N\n}\n\n")
	b.WriteString("func bumpn(r sync.Ref[S], k int) int {\n\tsync.Modify(r, func(v S) (int, S) {\n\t\tlet mut s = v\n\t\tlet x = bump(&s, k)\n\t\t(x + len(s.Items), s)\n\t})\n}\n\n")
	b.WriteString("func at(m Map[string, int], k string) int {\n\tmatch m.Get(k) {\n\tcase Some[int] as v:\n\t\tv.Value\n\tcase None:\n\t\t-1\n\t}\n}\n\n")
	b.WriteString("func mtext(m Map[string, int]) string {\n\t\"a=\\(at(m, \"a\")) b=\\(at(m, \"b\")) c=\\(at(m, \"c\"))\"\n}\n\n")
	b.WriteString("func stext(s S) string {\n\tlet mut out = \"\\(s.N):\"\n\tfor x in s.Items {\n\t\tout = out + \" \\(x)\"\n\t}\n\tout\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	fmt.Fprintf(&b, "\tlet m = sync.NewRef[Map[string, int]](Map[string, int]{\"a\": %d})\n", g.n(9))
	fmt.Fprintf(&b, "\tlet s = sync.NewRef[S](S{Items: []int{%d}, N: 0})\n", g.n(9))
	// Each site runs at least once, so each function is lowered.
	fmt.Fprintf(&b, "\tput(m, \"b\", %d)\n\tgrow(s, %d)\n", 10+g.n(90), g.n(99))
	fmt.Fprintf(&b, "\tlet k0s = s.Get()\n\tpush(s, %d)\n\tConsole.Println(\"bump \\(bumpn(s, %d))\")\n", g.n(99), g.n(9))
	fmt.Fprintf(&b, "\tlet k = alias(m)\n\tConsole.Println(\"take \\(take(m, %q))\")\n", keys[g.n(3)])
	kept := []string{"mtext(k)", "stext(k0s)"}
	for i := 0; i < 8+g.n(5); i++ {
		switch g.n(6) {
		case 0, 1:
			fmt.Fprintf(&b, "\tput(m, %q, %d)\n", keys[g.n(3)], 10+g.n(90))
		case 2:
			fmt.Fprintf(&b, "\tConsole.Println(\"take \\(take(m, %q))\")\n", keys[g.n(3)])
		case 3:
			fmt.Fprintf(&b, "\tlet k%d = alias(m)\n", i)
			kept = append(kept, fmt.Sprintf("mtext(k%d)", i))
		case 4:
			fmt.Fprintf(&b, "\tlet k%d = m.Get()\n", i)
			kept = append(kept, fmt.Sprintf("mtext(k%d)", i))
		default:
			if g.n(2) == 0 {
				fmt.Fprintf(&b, "\tlet k%d = s.Get()\n", i)
				kept = append(kept, fmt.Sprintf("stext(k%d)", i))
			}
			switch g.n(3) {
			case 0:
				fmt.Fprintf(&b, "\tgrow(s, %d)\n", g.n(99))
			case 1:
				fmt.Fprintf(&b, "\tpush(s, %d)\n", g.n(99))
			default:
				fmt.Fprintf(&b, "\tConsole.Println(\"bump \\(bumpn(s, %d))\")\n", g.n(9))
			}
		}
	}
	for i, k := range kept {
		fmt.Fprintf(&b, "\tConsole.Println(\"kept %d: \\(%s)\")\n", i, k)
	}
	b.WriteString("\tConsole.Println(\"m: \\(mtext(m.Get())) s: \\(stext(s.Get()))\")\n")
	b.WriteString("}\n")
	return b.String()
}
