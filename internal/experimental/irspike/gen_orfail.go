package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateOrFail is a program that reads a Map through the prelude's
// OrFail and through a user's own OrFail over a user Option, whose failure
// parameter F is a value parameter's type (a slot row: PRELUDE-ORFAIL):
//   - look and myLook fail with a miss built in place, held in a local,
//     or passed in by the caller, inside functions whose row names it;
//   - main catches each read in a loop (caught), through one function
//     that passes the failure on with try (propagated), and in odd seeds
//     fails with a miss (uncaught: exit 1);
//   - two miss types share one row, so a catch arm of the wrong type
//     changes the totals.
//
// main prints the totals; a value parameter boxed into the wrong Go type,
// or a failure taken by the wrong arm, changes them, the exit status or
// the build.
func GenerateOrFail(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x6f726661696c))
	n := func(k int) int { return r.IntN(k) }
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateOrFail\n\n")
	b.WriteString("type Miss { Key int }\n\ntype Gone { At int }\n\n")
	b.WriteString("type MyOpt[T] = MySome{Value T} | MyNone{}\n\n")
	b.WriteString("func myOrFail[T, F](o MyOpt[T], f F) T fails F {\n\tmatch o {\n\tcase MySome as s:\n\t\ts.Value\n\tcase MyNone:\n\t\tf\n\t}\n}\n\n")
	b.WriteString("func myGet(m Map[int, int], k int) MyOpt[int] {\n\tmatch m.Get(k) {\n\tcase Some[int] as s:\n\t\tMySome[int]{Value: s.Value}\n\tcase None:\n\t\tMyNone\n\t}\n}\n\n")
	fmt.Fprintf(&b, "func look(m Map[int, int], k int) int fails Miss | Gone {\n\tif k %% %d == 0 {\n\t\tlet g = Gone{At: k}\n\t\treturn m.Get(k + 1).OrFail(g)\n\t}\n\tm.Get(k).OrFail(Miss{Key: k})\n}\n\n", 5+n(4))
	fmt.Fprintf(&b, "func myLook(m Map[int, int], k int, f Gone) int fails Miss | Gone {\n\tif k %% %d == 1 {\n\t\treturn myOrFail(myGet(m, k + 2), f)\n\t}\n\tmyOrFail(myGet(m, k), Miss{Key: k + %d})\n}\n\n", 4+n(4), n(5))
	b.WriteString("func through(m Map[int, int], k int) int fails Miss | Gone {\n\tlet v = try m.Get(k).OrFail(Miss{Key: k * 2})\n\tv + 1\n}\n\n")
	fmt.Fprintf(&b, "func main() fails Miss | Gone needs Console {\n\tlet mut m = Map[int, int]{}\n\tfor i in 0..%d {\n\t\tif i %% %d != 0 {\n\t\t\tm = m.Put(i, i * %d)\n\t\t}\n\t}\n\tlet mut total = 0\n\tfor k in 0..%d {\n", 40+n(40), 2+n(3), 2+n(5), 30+n(40))
	b.WriteString("\t\tlet a = look(m, k) catch {\n\t\tcase Miss as e:\n\t\t\te.Key * 3\n\t\tcase Gone as g:\n\t\t\tg.At + 7\n\t\t}\n")
	b.WriteString("\t\tlet c = myLook(m, k, Gone{At: k * 5}) catch {\n\t\tcase Miss as e:\n\t\t\te.Key + 11\n\t\tcase Gone as g:\n\t\t\tg.At * 13\n\t\t}\n")
	b.WriteString("\t\tlet d = through(m, k) catch {\n\t\tcase Miss as e:\n\t\t\te.Key + 17\n\t\tcase Gone:\n\t\t\t19\n\t\t}\n")
	b.WriteString("\t\ttotal = total + a + c + d\n\t}\n")
	b.WriteString("\tConsole.Println(\"total \\(total)\")\n")
	if seed%2 == 1 {
		// Uncaught: key -1 is never set.
		b.WriteString("\tlet z = try look(m, -1)\n")
	} else {
		b.WriteString("\tlet z = look(m, -1) catch {\n\tcase Miss as e:\n\t\te.Key\n\tcase Gone:\n\t\t0\n\t}\n")
	}
	b.WriteString("\tConsole.Println(\"z \\(z)\")\n}\n")
	return b.String()
}
