package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateKnownRecord is a program whose IR bodies call copies for a known
// record (F7, "copy for a known record"; record.go): functions that take a
// Machine and call its Step, called with a machine literal (whose record
// the lowering knows), so each call goes to the function's copy for the
// machine, where m.Step is a direct call of the step function. fold is a
// plain function, foldG a generic one (its copy is one instance), and
// outer passes its record on to fold (its copy calls fold's copy). main
// also calls fold with a Machine the lowering does not know (planA's
// result), which takes fold itself, so both bodies run on the same
// signals. The state is a union, so the step stays a function (a record
// state makes it a method, which a copy calls through the field).
func GenerateKnownRecord(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x6c796b6e6f776e03))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateKnownRecord\n\nimport machines\n\n")
	b.WriteString("type St = Lo{n int} | Hi{n int}\n\ntype Sig { v int }\n\n")
	b.WriteString("func num(s St) int {\n\tmatch s {\n\tcase Lo as l:\n\t\tl.n\n\tcase Hi as h:\n\t\th.n\n\t}\n}\n\n")
	emit, ignore, done, reject := 2+g.n(3), 30+g.n(20), 200+g.n(300), 7+g.n(5)
	fmt.Fprintf(&b, "func stepA(s St, e Sig) Decision[St, int] {\n\tlet n = num(s)\n\tif e.v == %d {\n\t\treturn Reject\n\t}\n\tif e.v %% %d == 0 {\n\t\treturn Emit[St, int]{Next: Hi{n: n + e.v}, Output: n}\n\t}\n\tif e.v > %d {\n\t\treturn Ignore\n\t}\n\tif n > %d {\n\t\treturn Done[int]{Output: n - e.v}\n\t}\n\tEnter[St]{Next: Lo{n: n*2 + e.v}}\n}\n\n", reject, emit, ignore, done)
	fmt.Fprintf(&b, "type A machine[St, Sig] {\n\tinitial: Lo{n: %d},\n\tstep:    stepA,\n}\n\n", 1+g.n(9))
	b.WriteString("func planA() Machine[St, Sig, int] { A{} }\n\n")
	b.WriteString("func fold(m Machine[St, Sig, int], xs []Sig, i int, s St) int {\n\tif i == len(xs) {\n\t\treturn num(s)\n\t}\n\tlet d = m.Step(s, xs[i])\n\tfold(m, xs, i+1, machines.Next(s, d))\n}\n\n")
	b.WriteString("func foldG[S, E](m Machine[S, E, int], xs []E, i int, s S) S {\n\tif i == len(xs) {\n\t\treturn s\n\t}\n\tlet d = m.Step(s, xs[i])\n\tfoldG[S, E](m, xs, i+1, machines.Next(s, d))\n}\n\n")
	fmt.Fprintf(&b, "func outer(m Machine[St, Sig, int], xs []Sig, s St) int {\n\tlet r = fold(m, xs, 0, s)\n\tr + %d\n}\n\n", 1+g.n(9))
	b.WriteString("func runA(xs []Sig) int { fold(A{}, xs, 0, machines.Initial(A{})) }\n\n")
	b.WriteString("func runG(xs []Sig) int { num(foldG[St, Sig](A{}, xs, 0, machines.Initial(A{}))) }\n\n")
	b.WriteString("func runO(xs []Sig) int { outer(A{}, xs, machines.Initial(A{})) }\n\n")
	b.WriteString("func main() needs Console {\n")
	for i := 0; i < 3; i++ {
		var sig []string
		for j := 0; j < 3+g.n(6); j++ {
			sig = append(sig, fmt.Sprintf("Sig{v: %d}", g.n(50)))
		}
		fmt.Fprintf(&b, "\tlet s%d = []Sig{%s}\n", i, strings.Join(sig, ", "))
		fmt.Fprintf(&b, "\tConsole.Println(\"%d: \\(runA(s%d)) \\(runG(s%d)) \\(runO(s%d)) \\(fold(planA(), s%d, 0, machines.Initial(planA())))\")\n", i, i, i, i, i)
	}
	b.WriteString("}\n")
	return b.String()
}
