package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// FuseForm is what a GenerateFuse program's view is: where it lives, how
// it is called, whether it is generic, and how its results are written.
type FuseForm struct {
	Cross   bool // the view and its union in package rows, the matches in main
	Method  bool // called as c.Read(i, …), not Read(c, i, …)
	Generic bool // Read[T] takes a []T and reads its length
	Tails   bool // results in ifs, nested matches and an early return
	Big     bool // past fuseBudget: the matches keep the two-step form
}

// GenerateFuse writes the fused-view program of seed (IR-FORMS IRF-1) as a
// module's files: a union Row of 2 to 6 variants (records of zero, one or
// two int fields), a record Cols of columns, a view Read(c, i) that reads
// row i as a variant, and three matches on a Read call (walk's statement
// in a loop, pick's value, code's result) in main. seed % 4 forces one of
// the form's facts (Cross, Generic, Method, Tails) and the others are the
// seed's. With Tails, the view returns early for a negative kind and
// writes some arms as an if or a nested match over its lets; without it,
// the view is VW1's shape (lets, then a match whose every arm is one
// literal). With Big, the view has forty guards more, past the fusion
// budget (and not a view's shape). Some literals divide by a column that holds a zero: the
// variant panics where it is built, whatever arm takes it. main prints
// pick and code of each row, then walk.
func GenerateFuse(seed uint64) (map[string]string, FuseForm) {
	g := &fusegen{vgen: vgen{r: rand.New(rand.NewPCG(seed, seed^0x3c6ef372fe94f82b))}}
	f := FuseForm{Cross: g.n(2) == 0, Method: g.n(2) == 0, Generic: g.n(2) == 0, Tails: g.n(2) == 0, Big: g.n(5) == 0}
	switch seed % 4 {
	case 0:
		f.Cross = true
	case 1:
		f.Generic = true
	case 2:
		f.Method = true
	case 3:
		f.Tails = true
	}
	g.f = f
	return g.files(), f
}

type fusegen struct {
	vgen
	f   FuseForm
	lib strings.Builder
	m   strings.Builder
	p   string // the view package's qualifier in main: "rows." or ""
}

func (g *fusegen) files() map[string]string {
	if g.f.Cross {
		g.p = "rows."
	}
	k := 2 + g.n(5)
	g.fields = make([]int, k)
	var names []string
	for i := range k {
		g.fields[i] = g.n(3)
		names = append(names, fmt.Sprintf("V%d", i))
		switch g.fields[i] {
		case 0:
			fmt.Fprintf(&g.lib, "type V%d {}\n\n", i)
		case 1:
			fmt.Fprintf(&g.lib, "type V%d { A int }\n\n", i)
		default:
			fmt.Fprintf(&g.lib, "type V%d { A int, B int }\n\n", i)
		}
	}
	fmt.Fprintf(&g.lib, "type Row = %s\n\n", strings.Join(names, " | "))
	g.lib.WriteString("type Cols { Kinds []int, Vals []int, W int }\n\n")
	g.read(k)
	g.sites(k)
	g.main()
	head := "// generated by irspike.GenerateFuse\n\n"
	if !g.f.Cross {
		return map[string]string{"ergo.mod": "module p\n", "cmd/p/main.ergo": head + g.lib.String() + g.m.String()}
	}
	return map[string]string{
		"ergo.mod":        "module p\n",
		"rows/rows.ergo":  head + g.lib.String(),
		"cmd/p/main.ergo": head + "import p/rows\n\n" + g.m.String(),
	}
}

// read writes the view.
func (g *fusegen) read(k int) {
	if g.f.Generic {
		g.lib.WriteString("func Read[T](c Cols, i int, xs []T) Row {\n\tlet n = len(xs)\n")
	} else {
		g.lib.WriteString("func Read(c Cols, i int) Row {\n\tlet n = c.W\n")
	}
	g.lib.WriteString("\tlet kind = c.Kinds[i]\n\tlet x = c.Vals[i]\n\tlet y = x * 3 + kind - n\n")
	// Every let is read here, whatever the literals read: the guard never
	// holds for the rows main writes.
	fmt.Fprintf(&g.lib, "\tif x + y + n < -1000000 {\n\t\treturn %s\n\t}\n", g.lit(g.n(k)))
	if g.f.Big {
		for j := range 40 {
			fmt.Fprintf(&g.lib, "\tif x - y + n == %d {\n\t\treturn %s\n\t}\n", 100000+j, g.lit(g.n(k)))
		}
	}
	if g.f.Tails {
		fmt.Fprintf(&g.lib, "\tif kind < 0 {\n\t\treturn %s\n\t}\n", g.lit(g.n(k)))
	}
	g.lib.WriteString("\tmatch kind {\n")
	for kind := range k - 1 {
		v := g.n(k)
		body := g.lit(v)
		if g.f.Tails {
			switch g.n(3) {
			case 0:
				body = fmt.Sprintf("if x > y {\n\t\t\t%s\n\t\t} else {\n\t\t\t%s\n\t\t}", g.lit(v), g.lit(g.n(k)))
			case 1:
				body = fmt.Sprintf("match x %% 2 {\n\t\tcase 0:\n\t\t\t%s\n\t\tcase _:\n\t\t\t%s\n\t\t}", g.lit(v), g.lit(g.n(k)))
			}
		}
		fmt.Fprintf(&g.lib, "\tcase %d:\n\t\t%s\n", kind, body)
	}
	fmt.Fprintf(&g.lib, "\tcase _:\n\t\t%s\n\t}\n}\n\n", g.lit(g.n(k)))
}

// lit is a literal of variant v over the view's locals; a two-field
// variant may divide by x.
func (g *fusegen) lit(v int) string {
	operand := []string{"x", "y", "kind", "x + y", "i", "n", "c.W"}
	switch g.fields[v] {
	case 0:
		return fmt.Sprintf("V%d", v)
	case 1:
		return fmt.Sprintf("V%d{A: %s}", v, operand[g.n(len(operand))])
	}
	b := operand[g.n(len(operand))]
	if g.n(3) == 0 {
		b = "100 / x"
	}
	return fmt.Sprintf("V%d{A: %s, B: %s}", v, operand[g.n(len(operand))], b)
}

// call is a Read call of row i over c in main.
func (g *fusegen) call(c, i string) string {
	extra := ""
	if g.f.Generic {
		extra = ", " + []string{c + ".Vals", "[]string{\"a\", \"b\"}"}[g.n(2)]
	}
	if g.f.Method {
		return fmt.Sprintf("%s.Read(%s%s)", c, i, extra)
	}
	return fmt.Sprintf("%sRead(%s, %s%s)", g.p, c, i, extra)
}

// sites writes walk (a statement in a loop), pick (a value) and code (the
// result), each matching on a Read call.
func (g *fusegen) sites(k int) {
	arms := func(tail func(string) string) string {
		a := g.arms(k, tail)
		if g.p != "" {
			for v := range k {
				a = strings.ReplaceAll(a, fmt.Sprintf("V%d", v), fmt.Sprintf("%sV%d", g.p, v))
			}
			a = strings.ReplaceAll(a, g.p+g.p, g.p)
		}
		return a
	}
	cols := g.p + "Cols"
	fmt.Fprintf(&g.m, "func walk(c %s) int {\n\tlet mut s = 0\n\tlet mut i = 0\n\tfor i < len(c.Kinds) {\n\t\tmatch %s {\n", cols, g.call("c", "i"))
	g.m.WriteString(arms(func(e string) string { return "\ts = s * 31 + " + e }))
	g.m.WriteString("\t\t}\n\t\ti = i + 1\n\t}\n\ts\n}\n\n")
	fmt.Fprintf(&g.m, "func pick(c %s, i int) int {\n\tlet r = match %s {\n", cols, g.call("c", "i"))
	g.m.WriteString(arms(func(e string) string { return "\t" + e }))
	g.m.WriteString("\t}\n\tr + 1\n}\n\n")
	fmt.Fprintf(&g.m, "func code(c %s, i int) int {\n\tmatch %s {\n", cols, g.call("c", "i"))
	g.m.WriteString(arms(func(e string) string { return "\t" + e }))
	g.m.WriteString("\t}\n}\n\n")
}

// main prints pick and code of each row, then walk.
func (g *fusegen) main() {
	rows := 3 + g.n(8)
	kinds, vals := make([]string, rows), make([]string, rows)
	zero := g.n(2) == 0
	for i := range rows {
		kinds[i] = fmt.Sprint(g.n(8) - 1)
		vals[i] = fmt.Sprint(1 + g.n(40))
		if zero && g.n(3) == 0 {
			vals[i] = "0"
		}
	}
	g.m.WriteString("func main() needs Console {\n")
	fmt.Fprintf(&g.m, "\tlet c = %sCols{Kinds: []int{%s}, Vals: []int{%s}, W: %d}\n", g.p, strings.Join(kinds, ", "), strings.Join(vals, ", "), g.n(9))
	g.m.WriteString("\tlet mut i = 0\n\tfor i < len(c.Kinds) {\n\t\tConsole.Println(\"row \\(i) \\(pick(c, i)) \\(code(c, i))\")\n\t\ti = i + 1\n\t}\n")
	g.m.WriteString("\tConsole.Println(\"walk \\(walk(c))\")\n}\n")
}
