package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// taskLendFuncs are GenerateTaskLend's functions: each starts a task whose
// block borrows a resource of the frame (R27), so the block is a literal a
// task captures (check.TaskCapture) that moves nothing, and each has an IR
// body (IR1 TASK-CAPTURES: function literal that a task captures).
var taskLendFuncs = []string{"lendOne", "lendTwo"}

// GenerateTaskLend is a program of bodies whose task.Go blocks borrow the
// frame's resources (R27, R12 lends):
//   - lendOne lends a Res; its block reads the Res's field, the body waits
//     for the task, and the Res is closed at the frame's end, after the
//     body's own line;
//   - lendTwo lends two Res values, one made in an if block, and its block
//     prints through Console: the task's line comes before the body's, and
//     the two closes follow in release order.
//
// main calls each at seeded arguments. A lend that reads the wrong value,
// or a close that moves before the task's line or the body's, changes the
// output.
func GenerateTaskLend(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x3c6ef372fe94f82b))
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateTaskLend\n\nimport task\n\n")
	b.WriteString("type Res { id int } implements Closer\n\nfunc Close(r Res) needs Console {\n\tConsole.Println(\"close \\(r.id)\")\n}\n\n")
	fmt.Fprintf(&b, "func lendOne(k int) int needs Console {\n\tlet r = Res{id: k}\n\tlet t = task.Go() { r.id * %d + k }\n\tlet v = t.Wait()\n\tConsole.Println(\"lendOne \\(v)\")\n\tv + 1\n}\n\n", 2+r.IntN(5))
	fmt.Fprintf(&b, "func lendTwo(k int, s string) int needs Console {\n\tlet a = Res{id: k + %d}\n\tlet mut out = 0\n\tif k > %d {\n\t\tlet c = Res{id: k * 10}\n\t\tlet t = task.Go() {\n\t\t\tConsole.Println(\"task \\(s) \\(a.id) \\(c.id)\")\n\t\t\ta.id + c.id + len(s)\n\t\t}\n\t\tout = t.Wait()\n\t\tConsole.Println(\"block \\(out)\")\n\t}\n\tConsole.Println(\"lendTwo \\(out)\")\n\tout\n}\n\n", 100+r.IntN(50), r.IntN(4))
	b.WriteString("func main() needs Console {\n")
	for i, n := 0, 2+r.IntN(3); i < n; i++ {
		fmt.Fprintf(&b, "\tConsole.Println(\"one \\(lendOne(%d))\")\n", r.IntN(20)-5)
		fmt.Fprintf(&b, "\tConsole.Println(\"two \\(lendTwo(%d, %q))\")\n", r.IntN(8), []string{"", "ab", "xyz"}[r.IntN(3)])
	}
	b.WriteString("}\n")
	return b.String()
}
