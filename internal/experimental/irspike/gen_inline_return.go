package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateInlineReturn is a program whose calls sit in return position
// (INLINE-RETURN, lower/ir_forms_inline.go): the IR inliner copies such a
// call with the copy's returns and failures left the frame's own, and
// copies a fallible body that returns a fallible call's value and error
// as they are (`return f(…)`) into a site that binds both.
//   - a chain c1 … cL of fallible functions over Gone | Bad, each ending
//     in a tail call of the one before (the bare tail value, or an
//     explicit `return c(…)` under an if), with early value returns and
//     early failures, down to the fallible leaf c0; main catches the top
//     of the chain in its loop, so each failure of the chain's copy jumps
//     to the arm that takes it;
//   - a let-bound call (`let v = try c(…)`) returned after, and a call
//     caught in a loop inside a fallible function (run) whose last
//     call always fails and propagates through a `try` to main, which
//     catches it in even seeds and fails with it in odd ones (uncaught:
//     the program exits 1 with the cause);
//   - a chain of functions with no failure row, each returning the next
//     one's call from two arms;
//   - a generic fallible tail call (at2 of at), whose copy substitutes
//     the type argument;
//   - a fallible tail call of a body that loops (viaSpin of spin), which
//     stays a call: viaSpin's copy in main binds the value and error spin
//     returns.
//
// main prints the totals; a copy that returns, fails or binds wrong
// changes them or the exit status.
func GenerateInlineReturn(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x696e6c7265747572))
	n := func(k int) int { return r.IntN(k) }
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateInlineReturn\n\n")
	b.WriteString("type Gone { At int }\n\ntype Bad { Why int }\n\n")
	row := "Gone | Bad"
	fmt.Fprintf(&b, "func c0(x int) int fails %s {\n\tif x < -500 {\n\t\treturn Gone{At: x}\n\t}\n\tif x %% %d == 0 {\n\t\treturn Gone{At: x}\n\t}\n\tif x %% %d == 1 {\n\t\treturn Bad{Why: x}\n\t}\n\tx * %d\n}\n\n", row, 3+n(5), 4+n(5), 2+n(4))
	depth := 2 + n(3)
	for i := 1; i <= depth; i++ {
		fmt.Fprintf(&b, "func c%d(x int) int fails %s {\n", i, row)
		switch n(3) {
		case 0:
			fmt.Fprintf(&b, "\tif x > %d {\n\t\treturn x - %d\n\t}\n", 40+n(100), n(9))
		case 1:
			fmt.Fprintf(&b, "\tif x < %d {\n\t\treturn Bad{Why: x + %d}\n\t}\n", -n(5), n(9))
		}
		if n(2) == 0 {
			fmt.Fprintf(&b, "\tif x %% %d == 0 {\n\t\treturn c%d(x + %d)\n\t}\n", 2+n(3), i-1, 1+n(5))
		}
		fmt.Fprintf(&b, "\tc%d(x * %d - %d)\n}\n\n", i-1, 1+n(3), n(7))
	}
	top := fmt.Sprintf("c%d", depth)
	fmt.Fprintf(&b, "func viaLet(x int) int fails %s {\n\tlet v = try %s(x + %d)\n\tv + %d\n}\n\n", row, top, n(5), 1+n(5))
	fmt.Fprintf(&b, "func sq(x int) int {\n\tx * x %% %d\n}\n\n", 50+n(50))
	fmt.Fprintf(&b, "func n1(x int) int {\n\tif x %% 3 == 0 {\n\t\treturn x\n\t}\n\tsq(x + %d)\n}\n\n", 1+n(5))
	fmt.Fprintf(&b, "func n2(x int) int {\n\tif x > %d {\n\t\treturn n1(x - %d)\n\t}\n\tn1(x + %d)\n}\n\n", 20+n(30), 10+n(10), n(9))
	// spin loops, so it stays a call: viaSpin's copy binds the value and
	// error spin returns (a returned pair).
	fmt.Fprintf(&b, "func spin(x int) int fails Gone {\n\tlet mut t = x\n\tfor i in 0..3 {\n\t\tt = t + i\n\t}\n\tif t %% %d == 0 {\n\t\treturn Gone{At: t}\n\t}\n\tt\n}\n\n", 3+n(5))
	fmt.Fprintf(&b, "func viaSpin(x int) int fails %s {\n\tif x %% %d == 1 {\n\t\treturn Bad{Why: x}\n\t}\n\tspin(x)\n}\n\n", row, 5+n(4))
	b.WriteString("func at[T](a []T, i int) T fails Gone {\n\tif i >= len(a) {\n\t\treturn Gone{At: i}\n\t}\n\ta[i]\n}\n\n")
	b.WriteString("func at2[T](a []T, i int) T fails Gone {\n\tat(a, i % (len(a) + 2))\n}\n\n")
	// run's last call fails in odd seeds: main's try passes it on.
	fmt.Fprintf(&b, "func run(n int, last int) int fails %s {\n\tlet mut t = 0\n\tfor i in 0..n {\n\t\tt = t + (%s(i) catch {\n\t\tcase Gone as g:\n\t\t\tg.At\n\t\tcase Bad:\n\t\t\t1\n\t\t})\n\t}\n\tlet w = try %s(last)\n\tt + w\n}\n\n", row, top, top)
	// The chain keeps a value below -500 below it (each step multiplies
	// by at least 1 and adds little), so it fails: with Bad on an early
	// failure, else with Gone at c0.
	last := -1000 - n(50)
	fmt.Fprintf(&b, "func main() fails %s needs Console {\n", row)
	items := make([]string, 3+n(5))
	for i := range items {
		items[i] = fmt.Sprint(n(100) - 20)
	}
	fmt.Fprintf(&b, "\tlet xs = []int{%s}\n", strings.Join(items, ", "))
	b.WriteString("\tlet mut total = 0\n")
	fmt.Fprintf(&b, "\tfor i in 0..%d {\n", 40+n(120))
	fmt.Fprintf(&b, "\t\tlet a = %s(i - %d) catch {\n\t\tcase Gone as g:\n\t\t\tg.At\n\t\tcase Bad as e:\n\t\t\te.Why * 2\n\t\t}\n", top, n(10))
	b.WriteString("\t\tlet v = viaLet(i) catch {\n\t\tcase Gone:\n\t\t\t0\n\t\tcase Bad:\n\t\t\t1\n\t\t}\n")
	b.WriteString("\t\tlet s = viaSpin(i) catch {\n\t\tcase Gone as g:\n\t\t\tg.At % 5\n\t\tcase Bad:\n\t\t\t3\n\t\t}\n")
	b.WriteString("\t\tlet c = n2(i) + s\n")
	b.WriteString("\t\tlet d = at2(xs, i) catch {\n\t\tcase Gone as g:\n\t\t\t0 - g.At\n\t\t}\n")
	b.WriteString("\t\ttotal = total + a + v + c + d\n\t}\n")
	b.WriteString("\tConsole.Println(\"total \\(total)\")\n")
	if seed%2 == 1 {
		// Uncaught: main fails with run's failure and exits 1.
		fmt.Fprintf(&b, "\tlet z = try run(%d, %d)\n", 5+n(20), last)
	} else {
		fmt.Fprintf(&b, "\tlet z = run(%d, %d) catch {\n\tcase Gone as g:\n\t\tg.At\n\tcase Bad as e:\n\t\te.Why + 1\n\t}\n", 5+n(20), last)
	}
	b.WriteString("\tConsole.Println(\"z \\(z)\")\n}\n")
	return b.String()
}
