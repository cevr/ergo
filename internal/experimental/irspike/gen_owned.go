package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateOwnedParams is a program of functions with owned parameters
// (values.go V5, FLIP F7 wave 2 unit 3): each bumpN takes a slice into a
// let mut local once and writes it (an index store, an Append), so it
// lowers as an owned body that copies nothing and a wrapper under its
// own name that copies. main calls each bumpN in the forms the value
// analysis tells apart: an argument still read after the call (shared: it
// is copied), a rebinding (handed over), a fresh literal, and the
// function as a value (the wrapper). It prints every slice after the
// calls, so a write that reaches a caller's slice, or a copy dropped,
// changes the output.
func GenerateOwnedParams(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x3c6ef372fe94f82b))
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateOwnedParams\n\n")
	b.WriteString("func show(xs []int) string {\n\tlet mut out = \"\"\n\tfor x in xs {\n\t\tout = out + \" \" + strconv.Itoa(x)\n\t}\n\tout\n}\n\n")
	nf := 2 + r.IntN(3)
	for i := 0; i < nf; i++ {
		fmt.Fprintf(&b, "func bump%d(xs []int, n int) []int {\n\tlet k = len(xs)\n\tlet mut ys = xs\n", i)
		for j, m := 0, 1+r.IntN(3); j < m; j++ {
			switch r.IntN(3) {
			case 0:
				fmt.Fprintf(&b, "\tif k > %d {\n\t\tys[%d] = ys[%d] + n\n\t}\n", j%2, j%2, j%2)
			case 1:
				b.WriteString("\tys = ys.Append(n + k)\n")
			default:
				b.WriteString("\tif k > 0 {\n\t\tys[0] = n * 2\n\t}\n")
			}
		}
		b.WriteString("\tys\n}\n\n")
	}
	b.WriteString("func main() needs Console {\n")
	for i := 0; i < nf; i++ {
		n := 1 + r.IntN(9)
		fmt.Fprintf(&b, "\tlet a%d = []int{%d, %d}\n", i, n, n+1)
		switch r.IntN(4) {
		case 0:
			// Shared: a is read after the call.
			fmt.Fprintf(&b, "\tlet b%d = bump%d(a%d, %d)\n", i, i, i, n)
			fmt.Fprintf(&b, "\tConsole.Println(\"a%d\" + show(a%d) + \" b%d\" + show(b%d))\n", i, i, i, i)
		case 1:
			// Handed over: the rebinding consumes the old value.
			fmt.Fprintf(&b, "\tlet mut c%d = a%d.Append(%d)\n", i, i, n)
			fmt.Fprintf(&b, "\tc%d = bump%d(c%d, %d)\n", i, i, i, n)
			fmt.Fprintf(&b, "\tConsole.Println(\"a%d\" + show(a%d) + \" c%d\" + show(c%d))\n", i, i, i, i)
		case 2:
			// Fresh.
			fmt.Fprintf(&b, "\tlet d%d = bump%d([]int{%d}, %d)\n", i, i, n, n)
			fmt.Fprintf(&b, "\tConsole.Println(\"a%d\" + show(a%d) + \" d%d\" + show(d%d))\n", i, i, i, i)
		default:
			// A function value reaches the wrapper.
			fmt.Fprintf(&b, "\tlet f%d = bump%d\n", i, i)
			fmt.Fprintf(&b, "\tlet e%d = f%d(a%d, %d)\n", i, i, i, n)
			fmt.Fprintf(&b, "\tConsole.Println(\"a%d\" + show(a%d) + \" e%d\" + show(e%d))\n", i, i, i, i)
		}
	}
	b.WriteString("}\n")
	return "import strconv\n\n" + b.String()
}
