package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateAdapt is a program of std calls whose Go parameter is a function
// the call adapts (FLIP OPC-adapt): slices.SortFunc of a comparator
// literal over records, slices.SortStableFunc of a comparator passed as a
// function value, and a Ref's Update of a literal, each in a function the
// IR lowers. The comparators and the update are seeded, so an adapter
// that passes the operands in another order, or loses the value, changes
// the output.
func GenerateAdapt(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x510e527fade682d1))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateAdapt\n\nimport slices\nimport sync\n\ntype P { K int, N string }\n\n")
	cmp := []string{"a.K - b.K", "b.K - a.K"}[g.n(2)]
	fmt.Fprintf(&b, "func order(xs []P) []P {\n\tslices.SortFunc(xs, func(a P, b P) int { %s })\n}\n\n", cmp)
	b.WriteString("func orderBy(xs []int, cmp func(a int, b int) int) []int {\n\tslices.SortStableFunc(xs, cmp)\n}\n\n")
	fmt.Fprintf(&b, "func bump(i int) int {\n\tlet r = sync.NewRef[int](i)\n\tr.Update(func(v int) int { v * %d + %d })\n\tr.Get()\n}\n\n", 2+g.n(3), g.n(7))
	var ps []string
	for i, n := 0, 3+g.n(4); i < n; i++ {
		ps = append(ps, fmt.Sprintf("P{K: %d, N: \"n%d\"}", g.n(20)-10, i))
	}
	icmp := []string{"a - b", "b - a", "(a % 3) - (b % 3)"}[g.n(3)]
	fmt.Fprintf(&b, "func main() needs Console {\n\tfor p in order([]P{%s}) {\n\t\tConsole.Println(\"\\(p.K) \\(p.N)\")\n\t}\n", strings.Join(ps, ", "))
	fmt.Fprintf(&b, "\tfor v in orderBy(%s, func(a int, b int) int { %s }) {\n\t\tConsole.Println(\"\\(v)\")\n\t}\n", g.ints(), icmp)
	fmt.Fprintf(&b, "\tConsole.Println(\"\\(bump(%d))\")\n}\n", g.n(9))
	return b.String()
}
