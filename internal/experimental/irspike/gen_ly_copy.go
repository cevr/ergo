package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateCopy is a program whose functions the value rule copies in (F7,
// "value copy"): each binds a parameter to a `let mut` and writes the copy
// in place, so without the copy the write would reach the caller's value.
// The forms cover each Go form of the copy (values.go, cloneValue): a
// slice of ints and a Map of ints (slices.Clone, maps.Clone), a slice of
// records that hold a slice, a Map of slices and a record that holds one
// (the generated copy functions), and a generic slice (slices.Clone at a
// type parameter). The caller's slices have spare capacity, so an append
// of an uncopied slice writes the caller's array, and two appends of one
// source show it; a Map written in place shows in the caller's length.
func GenerateCopy(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x6c79636f70790a01))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateCopy\n\n")
	b.WriteString("type Box { items []int, tag string }\n\n")
	k := func() int { return 1 + g.n(40) }
	// copySlice: two copies of one source, each appended in place.
	fmt.Fprintf(&b, "func copySlice(xs []int, k int) int {\n\tlet mut ys = xs\n\tys = ys.Append(k)\n\tlet mut zs = xs\n\tzs = zs.Append(k + %d)\n\tys[len(ys)-1]*1000 + zs[len(zs)-1]*10 + len(xs)\n}\n\n", k())
	// copyMap: a copy written in place by Put.
	fmt.Fprintf(&b, "func copyMap(m Map[string, int], k int) int {\n\tlet mut o = m\n\to = o.Put(\"k%d\", k)\n\tlen(o)*100 + len(m)\n}\n\n", g.n(3))
	// copyBoxes: a slice of records that hold a slice, two copies appended.
	fmt.Fprintf(&b, "func copyBoxes(bs []Box, k int) int {\n\tlet mut out = bs\n\tout = out.Append(Box{items: []int{k}, tag: \"a\"})\n\tlet mut more = bs\n\tmore = more.Append(Box{items: []int{k + %d}, tag: \"b\"})\n\tout[len(out)-1].items[0]*100 + more[len(more)-1].items[0] + len(bs)\n}\n\n", k())
	// copyLists: a Map of slices written in place by Put.
	fmt.Fprintf(&b, "func copyLists(m Map[string, []int], k int) int {\n\tlet mut o = m\n\to = o.Put(\"n%d\", []int{k})\n\tlen(o)*100 + len(m)\n}\n\n", g.n(3))
	// copyBox: a record that holds a slice, rebuilt around its copy's
	// slice appended in place.
	fmt.Fprintf(&b, "func copyBox(x Box, k int) int {\n\tlet mut a = x\n\ta = Box{items: a.items.Append(k), tag: a.tag}\n\tlet mut c = x\n\tc = Box{items: c.items.Append(k + %d), tag: c.tag}\n\ta.items[len(a.items)-1]*100 + c.items[len(c.items)-1] + len(x.items)\n}\n\n", k())
	// copyAny: the generic form.
	b.WriteString("func copyAny[T comparable](xs []T, a T, c T) int {\n\tlet mut ys = xs\n\tys = ys.Append(a)\n\tlet mut zs = xs\n\tzs = zs.Append(c)\n\tlen(ys)*10 + len(zs)\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	b.WriteString("\tlet mut xs = []int{}\n")
	fmt.Fprintf(&b, "\tfor i in 0..%d {\n\t\txs = xs.Append(i * %d)\n\t}\n", 3+2*g.n(2), 1+g.n(5))
	b.WriteString("\tlet mut ss = []string{}\n\tfor i in 0..3 {\n\t\tss = ss.Append(\"s\\(i)\")\n\t}\n")
	b.WriteString("\tlet mut bs = []Box{}\n\tfor i in 0..3 {\n\t\tbs = bs.Append(Box{items: []int{i}, tag: \"t\"})\n\t}\n")
	fmt.Fprintf(&b, "\tlet m = Map[string, int]{\"k0\": %d}\n", g.n(9))
	b.WriteString("\tlet lists = Map[string, []int]{\"n0\": []int{1}}\n")
	b.WriteString("\tlet x = Box{items: xs, tag: \"x\"}\n")
	b.WriteString("\tlet sa = \"a\"\n\tlet sb = \"b\"\n")
	for i := 0; i < 2; i++ {
		v := g.n(50)
		fmt.Fprintf(&b, "\tConsole.Println(\"%d: \\(copySlice(xs, %d)) \\(copyMap(m, %d)) \\(len(m)) \\(copyBoxes(bs, %d)) \\(copyLists(lists, %d)) \\(len(lists)) \\(copyBox(x, %d)) \\(copyAny(xs, %d, %d)) \\(copyAny(ss, sa, sb)) \\(len(xs))\")\n", i, v, v, v, v, v, v, v+1)
	}
	b.WriteString("}\n")
	return b.String()
}
