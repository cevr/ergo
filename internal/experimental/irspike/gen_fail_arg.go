package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateFailArg is a program whose callees fail with a parameter used
// only as their failure (INLINE-FAILARG, lower/ir_forms_inline.go): the IR
// inliner puts the call's variant-literal argument in the copy in its
// place, so the literal is evaluated where the copy fails, not at the
// call. Each site reads a counter that something else changes:
//   - orFail (generic) and orFailN, called with a literal of the loop's
//     locals: the argument stands for the parameter;
//   - orFailN with a later argument that bumps the counter the literal
//     reads (`Gone{At: c.N}, bump(&c)`): the literal must read the counter
//     before the bump, so it stays bound at the copy's head;
//   - failAfter, whose body bumps the counter before it fails: the same;
//   - orFail with a literal that bumps the counter itself: the bump must
//     run on every call, hit or miss.
//
// main prints the total and the counter; a literal evaluated late, or not
// at all, changes them.
func GenerateFailArg(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x6661696c617267))
	n := func(k int) int { return r.IntN(k) }
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateFailArg\n\n")
	b.WriteString("type Gone { At int }\n\ntype Ctr { N int }\n\n")
	fmt.Fprintf(&b, "func bump(c mut Ctr) int {\n\tc.N = c.N + %d\n\tc.N\n}\n\n", 1+n(5))
	b.WriteString("func orFail[T, F](o Option[T], f F) T fails F {\n\tmatch o {\n\tcase Some[T] as s:\n\t\ts.Value\n\tcase None:\n\t\treturn f\n\t}\n}\n\n")
	b.WriteString("func orFailN(o Option[int], f Gone, n int) int fails Gone {\n\tmatch o {\n\tcase Some[int] as s:\n\t\ts.Value + n\n\tcase None:\n\t\treturn f\n\t}\n}\n\n")
	fmt.Fprintf(&b, "func failAfter(c mut Ctr, x int, f Gone) int fails Gone {\n\tlet k = bump(c)\n\tif (x + k) %% %d == 0 {\n\t\treturn f\n\t}\n\tx\n}\n\n", 2+n(3))
	b.WriteString("func main() needs Console {\n")
	keys := make([]string, 4+n(6))
	for i := range keys {
		keys[i] = fmt.Sprintf("%d: %d", 2*i+n(2), n(50))
	}
	fmt.Fprintf(&b, "\tlet m = Map[int, int]{%s}\n", strings.Join(keys, ", "))
	b.WriteString("\tlet mut c = Ctr{N: 0}\n\tlet mut total = 0\n")
	fmt.Fprintf(&b, "\tfor i in 0..%d {\n", 30+n(60))
	fmt.Fprintf(&b, "\t\tlet k = i %% %d\n", 12+n(8))
	fmt.Fprintf(&b, "\t\tlet a = orFail(m.Get(k), Gone{At: k * %d + c.N}) catch {\n\t\tcase Gone as g:\n\t\t\tg.At\n\t\t}\n", 2+n(5))
	fmt.Fprintf(&b, "\t\tlet a2 = orFailN(m.Get(k + 1), Gone{At: i - k}, %d) catch {\n\t\tcase Gone as g:\n\t\t\tg.At * 2\n\t\t}\n", n(9))
	b.WriteString("\t\tlet later = orFailN(m.Get(k), Gone{At: c.N}, bump(&c)) catch {\n\t\tcase Gone as g:\n\t\t\tg.At * 3\n\t\t}\n")
	b.WriteString("\t\tlet after = failAfter(&c, i, Gone{At: c.N + 1}) catch {\n\t\tcase Gone as g:\n\t\t\tg.At * 5\n\t\t}\n")
	b.WriteString("\t\tlet own = orFail(m.Get(k + 2), Gone{At: bump(&c)}) catch {\n\t\tcase Gone as g:\n\t\t\tg.At * 7\n\t\t}\n")
	b.WriteString("\t\ttotal = total + a + a2 + later + after + own\n\t}\n")
	b.WriteString("\tConsole.Println(\"total \\(total) counter \\(c.N)\")\n}\n")
	return b.String()
}
