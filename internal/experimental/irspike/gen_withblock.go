package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateWithBlock is a program of fallible calls of generic functions
// with Ergo bodies that take a trailing block (WITHREL): a user generic
// guard[T, E] that may fail Other before it runs its block, and std's
// term.Raw. Each call is caught or tried, its block has a value or none
// (T bound to no value: Go's struct{}, so the Go call returns a pair), and
// it runs after a `let s = try open(n)`. A catch arm returns a failure of
// the enclosing function or a value; the block fails by a seeded
// condition. It returns the program and the functions that must have IR
// bodies. main prints each function's value or failure, so a failure lost,
// misrouted or turned into a value changes the output.
func GenerateWithBlock(seed uint64) (string, []string) {
	r := rand.New(rand.NewPCG(seed, seed^0x77697468))
	n := func(k int) int { return r.IntN(k) }
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateWithBlock\n\nimport term\n\ntype Bad { Code int }\n\ntype Other { N int }\n\n")
	b.WriteString("func open(n int) int fails Bad {\n\tif n < 0 {\n\t\treturn Bad{Code: n}\n\t}\n\tn + 1\n}\n\n")
	b.WriteString("func failWhen(c bool, code int) fails Bad {\n\tif c {\n\t\treturn Bad{Code: code}\n\t}\n}\n\n")
	b.WriteString("func guard[T, E](k int, body func() T fails E) T fails E | Other {\n\tif k > 3 {\n\t\treturn Other{N: k}\n\t}\n\ttry body()\n}\n\n")
	type fn struct {
		name   string
		other  bool // the function's row holds Other
		raw    bool // it needs term.Terminal
		inputs []int
	}
	var fns []fn
	count := 6 + n(3)
	for i := range count {
		kind := i % 6
		if i >= 6 {
			kind = n(6)
		}
		if kind == 5 {
			// A frame with no value whose tail is the call: its pair is
			// tried and the frame returns with no value.
			fmt.Fprintf(&b, "func %s_t(n int) fails Bad | Other {\n\tguard(%d) {\n\t\ttry failWhen(n > %d, n)\n\t}\n}\n\n", fmt.Sprintf("f%d", i), n(6), n(5))
			fmt.Fprintf(&b, "func f%d(n int) int fails Bad | Other {\n\ttry f%d_t(n)\n\tn + %d\n}\n\n", i, i, 1+n(9))
			fns = append(fns, fn{name: fmt.Sprintf("f%d", i), other: true, inputs: []int{n(7) - 2, n(7) - 2, n(7)}}, fn{name: fmt.Sprintf("f%d_t", i)})
			continue
		}
		name := fmt.Sprintf("f%d", i)
		k, m, add := n(6), n(5), 1+n(9)
		inputs := []int{n(7) - 2, n(7) - 2, n(7)}
		switch kind {
		case 0: // no value, caught, guard; the arms return a failure or a value
			fmt.Fprintf(&b, "func %s(n int) int fails Bad {\n\tlet s = try open(n)\n\tguard(%d) {\n\t\ttry failWhen(s > %d, s)\n\t} catch {\n\tcase Bad as e:\n\t\treturn Bad{Code: e.Code + %d}\n\tcase Other as o:\n\t\treturn o.N * %d\n\t}\n\ts * 2\n}\n\n", name, k, m, 100*add, add)
			fns = append(fns, fn{name: name, inputs: inputs})
		case 1: // a value, caught, guard
			fmt.Fprintf(&b, "func %s(n int) int fails Bad {\n\tlet s = try open(n)\n\tlet v = guard(%d) {\n\t\ttry open(s - %d)\n\t} catch {\n\tcase Bad as e:\n\t\treturn Bad{Code: e.Code - %d}\n\tcase Other as o:\n\t\to.N + %d\n\t}\n\tv + s\n}\n\n", name, k, m, add, add)
			fns = append(fns, fn{name: name, inputs: inputs})
		case 2: // no value, tried, guard: the failure passes through
			fmt.Fprintf(&b, "func %s(n int) int fails Bad | Other {\n\tlet s = try open(n)\n\ttry guard(%d) {\n\t\ttry failWhen(s > %d, s + %d)\n\t}\n\ts + %d\n}\n\n", name, k, m, add, add)
			fns = append(fns, fn{name: name, other: true, inputs: inputs})
		case 3: // no value, caught, term.Raw (the gent shape)
			fmt.Fprintf(&b, "func %s(n int) int fails Bad needs term.Terminal {\n\tlet s = try open(n)\n\tterm.Raw() {\n\t\tlet _ = s\n\t\ttry failWhen(s > %d, s)\n\t} catch {\n\tcase Bad as e:\n\t\treturn Bad{Code: e.Code + %d}\n\tcase term.NotTerminal:\n\t\treturn -1\n\t}\n\ts * %d\n}\n\n", name, m, add, add)
			fns = append(fns, fn{name: name, raw: true, inputs: inputs})
		default: // a value, tried, term.Raw
			fmt.Fprintf(&b, "func %s(n int) int fails Bad | term.NotTerminal needs term.Terminal {\n\tlet s = try open(n)\n\tlet v = try term.Raw() {\n\t\ttry open(s - %d)\n\t}\n\tv * %d\n}\n\n", name, m, add)
			fns = append(fns, fn{name: name, raw: true, inputs: inputs})
		}
	}
	b.WriteString("func main() needs Console {\n\twith context { term.Terminal: term.NewScript([]term.Key{}, term.Window{Cols: 80, Rows: 24}) } {\n")
	var names []string
	for _, f := range fns {
		names = append(names, f.name)
		for j, in := range f.inputs {
			arms := "\t\tcase Bad as e:\n\t\t\t1000 + e.Code\n"
			if f.other {
				arms += "\t\tcase Other as o:\n\t\t\t2000 + o.N\n"
			}
			if strings.Contains(b.String(), "func "+f.name+"(n int) int fails Bad | term.NotTerminal") {
				arms += "\t\tcase term.NotTerminal:\n\t\t\t3000\n"
			}
			fmt.Fprintf(&b, "\t\tlet %s_%d = %s(%d) catch {\n%s\t\t}\n\t\tConsole.Println(\"%s(%d) \\(%s_%d)\")\n", f.name, j, f.name, in, arms, f.name, in, f.name, j)
		}
	}
	b.WriteString("\t}\n}\n")
	return b.String(), names
}
