package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateDefect is a program of the prelude's Unreachable (FLIP
// OPC-unreach) at each place a call stands: the last branch of an if
// chain that yields a function's value (classify), a returned value
// (half), a statement of a body with no value (guard), the branch of an if
// expression (capped) and the last statement of a catch arm with a value
// (caught). main prints each function's value over inputs none of them
// refuses, with seeded constants; then, by the seed, one call reaches its
// Unreachable, or the generic runtime leaf behind rpc.Lost (or none
// does), so the defect's reason and site, the output before it and the
// exit status show in the outcome. A second leaf returns an opaque value
// from a type argument of its generic caller.
func GenerateDefect(seed uint64) (text string, site int) {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x9e3779b97f4a7c15))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateDefect\n\nimport config\nimport rpc\n\ntype E1 { Code int }\n\n")
	fmt.Fprintf(&b, "func classify(n int) int {\n\tif n < %d {\n\t\tn * %d\n\t} else if n < 100 {\n\t\tn + %d\n\t} else {\n\t\tUnreachable(\"classify: out of range\")\n\t}\n}\n\n", 5+g.n(10), 2+g.n(3), g.n(9))
	fmt.Fprintf(&b, "func half(n int) int {\n\tif n %% 2 == 0 {\n\t\treturn n / 2 + %d\n\t}\n\treturn Unreachable(\"half: odd\")\n}\n\n", g.n(5))
	b.WriteString("func guard(n int) needs Console {\n\tif n > 50 {\n\t\tUnreachable(\"guard: too large\")\n\t}\n\tConsole.Println(\"g \\(n)\")\n}\n\n")
	fmt.Fprintf(&b, "func capped(n int) int {\n\tlet v = if n < 60 {\n\t\tn * %d\n\t} else {\n\t\tUnreachable(\"capped: too large\")\n\t}\n\tv + 1\n}\n\n", 1+g.n(4))
	b.WriteString("func probe(n int) int fails E1 {\n\tif n % 3 == 0 {\n\t\treturn E1{Code: n}\n\t}\n\tn + 1\n}\n\n")
	fmt.Fprintf(&b, "func caught(n int) int {\n\tlet r = probe(n) catch {\n\tcase E1 as e:\n\t\tnoted(e.Code)\n\t\tUnreachable(\"caught: probe failed\")\n\t}\n\tr * %d\n}\n\n", 2+g.n(3))
	b.WriteString("func noted(_ int) {}\n\n")
	b.WriteString("func leaf[T](v T, ok bool) T {\n\tif ok { return v }\n\trpc.Lost[T](rpc.Transport{Reason: \"lost at the leaf\"})\n}\n\n")
	b.WriteString("func keep[T](v T) config.Redacted[T] { config.NewRedacted(v) }\n\n")
	safe := []int{2, 4, 8, 10, 14, 16, 20, 22}
	g.r.Shuffle(len(safe), func(i, j int) { safe[i], safe[j] = safe[j], safe[i] })
	var ins []string
	for _, n := range safe[:2+g.n(5)] {
		ins = append(ins, fmt.Sprint(n))
	}
	b.WriteString("func main() needs Console {\n")
	fmt.Fprintf(&b, "\tlet kept = keep(%d)\n\tConsole.Println(\"kept \\(leaf(kept.Reveal(), true))\")\n", g.n(100))
	fmt.Fprintf(&b, "\tfor n in []int{%s} {\n", strings.Join(ins, ", "))
	b.WriteString("\t\tlet c = classify(n)\n\t\tlet h = half(n)\n\t\tlet p = capped(n)\n\t\tlet k = caught(n)\n")
	b.WriteString("\t\tguard(n)\n\t\tConsole.Println(\"\\(n): \\(c) \\(h) \\(p) \\(k)\")\n\t}\n")
	site = g.n(6)
	if seed%8 == 0 {
		site = 6
	}
	switch site {
	case 0:
		b.WriteString("\tlet t = classify(200)\n\tConsole.Println(\"t \\(t)\")\n")
	case 1:
		b.WriteString("\tlet t = half(7)\n\tConsole.Println(\"t \\(t)\")\n")
	case 2:
		b.WriteString("\tguard(90)\n")
	case 3:
		b.WriteString("\tlet t = capped(70)\n\tConsole.Println(\"t \\(t)\")\n")
	case 4:
		b.WriteString("\tlet t = caught(9)\n\tConsole.Println(\"t \\(t)\")\n")
	case 6:
		b.WriteString("\tConsole.Println(leaf(\"lost\", false))\n")
	}
	b.WriteString("\tConsole.Println(\"end\")\n}\n")
	return b.String(), site
}
