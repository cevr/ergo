package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// ptrWitnessSites are GeneratePtrWitness's generic functions, each of
// which calls operations through a pointer to its type parameter (a mut T
// parameter), with an IR body in every seed.
var ptrWitnessSites = []string{"bump", "twice"}

// GeneratePtrWitness is a program of generic functions over an operation
// type, Counter, whose parameter is a mut T (examples/vt's Apply[S
// Screen](s mut S, …)): bump calls a mut operation (Add, which writes
// through the pointer) and a plain one (Get, which reads the value the
// pointer points to); twice passes its pointer on to bump and reads Get
// after. They are called at two record types whose Add and Get bodies are
// drawn, and main prints each result and the record after, so a write
// that lands on a copy, or a read of the wrong value, changes the output.
func GeneratePtrWitness(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x51afd7ed558ccd))
	n := func(k int) int { return r.IntN(k) }
	var b strings.Builder
	b.WriteString("// generated by irspike.GeneratePtrWitness\n\n")
	b.WriteString("type Counter {\n\tGet() int,\n\tmut Add(n int),\n}\n\n")
	b.WriteString("type A { N int } implements Counter\n\ntype B { Xs []int } implements Counter\n\n")
	fmt.Fprintf(&b, "func Get(a A) int { a.N * %d }\n\n", 1+n(3))
	fmt.Fprintf(&b, "func Add(a mut A, n int) { a.N = a.N + n + %d }\n\n", n(3))
	fmt.Fprintf(&b, "func Get(b B) int {\n\tlet mut t = %d\n\tfor x in b.Xs {\n\t\tt = t + x\n\t}\n\tt\n}\n\n", n(4))
	b.WriteString("func Add(b mut B, n int) { b.Xs = b.Xs.Append(n) }\n\n")
	fmt.Fprintf(&b, "func bump[T Counter](c mut T, k int) int {\n\tlet before = c.Get()\n\tc.Add(k)\n\tc.Add(k + %d)\n\tc.Get() * 10 + before\n}\n\n", n(3))
	b.WriteString("func twice[T Counter](c mut T, k int) int {\n\tlet x = bump(c, k)\n\tx + c.Get()\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	for i := 0; i < 3; i++ {
		fmt.Fprintf(&b, "\tlet mut a%d = A{N: %d}\n\tlet x%d = twice(&a%d, %d)\n\tConsole.Println(\"a%d: \\(x%d) \\(a%d.N)\")\n", i, n(9)-4, i, i, n(5), i, i, i)
		fmt.Fprintf(&b, "\tlet mut b%d = B{Xs: []int{%d}}\n\tlet y%d = bump(&b%d, %d)\n\tConsole.Println(\"b%d: \\(y%d) \\(len(b%d.Xs))\")\n", i, n(5), i, i, n(5), i, i, i)
	}
	b.WriteString("}\n")
	return b.String()
}
