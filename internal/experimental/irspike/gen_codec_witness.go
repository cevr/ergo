package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// codecWitnessSites are GenerateCodecWitness's generic functions whose IR
// bodies read a codec witness parameter (PORT-WITNESS): each has an IR body
// in every seed. The test also checks the copies invoked by viaText.
var codecWitnessSites = []string{"enc", "dec", "back", "one", "many"}

// GenerateCodecWitness is a program of generic functions over type
// parameters under the codec constraint, whose codec witnesses are parameters of their bodies
// (PORT-WITNESS, the codec side of B-WITNESS):
//   - enc and dec pass their own witness on to json.Encode and json.Decode
//     (a call that passes the caller's codec witness), and back passes its
//     own on to both;
//   - one encodes a value of its type parameter on a codec.Events and
//     decodes it from a codec.Replay: the witness's Enc and Dec fields;
//   - many encodes and decodes []T and Option[T], types that hold the type
//     parameter: their generic codec functions take the witness after the
//     environment;
//   - viaText keeps its text body (its slice expression, s[1:], has no IR
//     form yet), so its calls of back, dec and enc go to monomorphic
//     copies, each a body with a codec witness parameter. When slices
//     take the IR, the copies go and the sites' check names them: move
//     viaText onto another text-only form, or drop the copy sites.
//
// main calls each at two record types, P and Q (Q holds a P), with drawn
// fields, and decodes a drawn text that is well formed or cut short, so a
// witness of the other type, a field misread, a failure lost or a value
// dropped changes the output.
func GenerateCodecWitness(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x5be0cd19137e2179))
	n := func(k int) int { return r.IntN(k) }
	word := func() string { return []string{"x", "yz", "", "a b", "q\\\"t"}[n(5)] }
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateCodecWitness\n\nimport codec\nimport json\n\n")
	b.WriteString("type P { A int, B string }\n\ntype Q { Xs []int, N bool, In P }\n\n")
	b.WriteString("func enc[T wire](v T) string needs wired[T] { json.Encode(json.Codec[T]{MaxBytes: 0, MaxDepth: 0}, v) }\n\n")
	b.WriteString("func dec[T wire](s string) T fails json.Malformed | wired[T] needs wired[T] {\n\tjson.Decode(json.Codec[T]{MaxBytes: 0, MaxDepth: 0}, s)\n}\n\n")
	b.WriteString("func back[T wire](v T) T fails json.Malformed | wired[T] needs wired[T] {\n\tlet s = enc(v)\n\ttry dec[T](s)\n}\n\n")
	b.WriteString("func one[T wire](v T) T fails wired[T] needs wired[T] {\n\tlet e = codec.NewEvents()\n\tencode(v, e)\n\tdecode[T](codec.NewReplay(codec.Recorded(e)))\n}\n\n")
	b.WriteString("func many[T wire](vs []T) ([]T, Option[T]) fails wired[Option[T]] needs wired[T] {\n\tlet e = codec.NewEvents()\n\tencode(vs, e)\n\tlet first Option[T] = if len(vs) > 0 { Some{Value: vs[0]} } else { None }\n\tencode(first, e)\n\tlet r = codec.NewReplay(codec.Recorded(e))\n\tlet xs = try decode[[]T](r)\n\tlet f = try decode[Option[T]](r)\n\t(xs, f)\n}\n\n")
	b.WriteString("func showP(p P) string { \"\\(p.A)/\\(p.B)\" }\n\n")
	b.WriteString("func showQ(q Q) string { \"\\(len(q.Xs)):\\(q.N):\\(showP(q.In))\" }\n\n")
	b.WriteString("func viaText(p P, q Q, s string) string {\n\tlet cut = s[1:]\n\tlet bp = back(p) catch {\n\tcase _:\n\t\tP{A: -1, B: \"lost\"}\n\t}\n\tlet d = dec[Q](cut) catch {\n\tcase _:\n\t\tQ{Xs: []int{}, N: false, In: p}\n\t}\n\tenc(q) + \" \" + showP(bp) + \" \" + showQ(d)\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	ps := make([]string, 3)
	for i := range ps {
		ps[i] = fmt.Sprintf("P{A: %d, B: \"%s\"}", n(200)-100, word())
	}
	xs := func() string {
		parts := make([]string, n(4))
		for i := range parts {
			parts[i] = fmt.Sprint(n(50) - 10)
		}
		return "[]int{" + strings.Join(parts, ", ") + "}"
	}
	q := fmt.Sprintf("Q{Xs: %s, N: %t, In: %s}", xs(), n(2) == 0, ps[1])
	fmt.Fprintf(&b, "\tlet p = %s\n\tlet q = %s\n", ps[0], q)
	b.WriteString("\tConsole.Println(enc(p))\n\tConsole.Println(enc(q))\n")
	b.WriteString("\tlet bq = back(q) catch {\n\tcase _:\n\t\tQ{Xs: []int{}, N: false, In: p}\n\t}\n\tConsole.Println(showQ(bq))\n")
	b.WriteString("\tlet bp = back(p) catch {\n\tcase _:\n\t\tP{A: -1, B: \"lost\"}\n\t}\n\tConsole.Println(showP(bp))\n")
	// The keys are the codec's (a, b); a text cut short is malformed.
	text := fmt.Sprintf(`{"a": %d, "b": "w"}`, n(90))
	if n(3) == 0 {
		text = text[:len(text)-1-n(4)]
	}
	text = strings.ReplaceAll(text, `"`, `\"`)
	fmt.Fprintf(&b, "\tlet d = dec[P](\"%s\") catch {\n\tcase json.Malformed:\n\t\tP{A: -2, B: \"malformed\"}\n\tcase _:\n\t\tP{A: -3, B: \"wired\"}\n\t}\n\tConsole.Println(showP(d))\n", text)
	b.WriteString("\tlet o = one(q) catch {\n\tcase _:\n\t\tQ{Xs: []int{}, N: false, In: p}\n\t}\n\tConsole.Println(showQ(o))\n")
	fmt.Fprintf(&b, "\tlet (ys, f) = many([]P{%s}) catch {\n\tcase _:\n\t\t([]P{}, None)\n\t}\n", strings.Join(ps[:n(4)], ", "))
	b.WriteString("\tlet fa = match f {\n\tcase Some as s:\n\t\tshowP(s.Value)\n\tcase None:\n\t\t\"none\"\n\t}\n")
	b.WriteString("\tlet mut all = \"\"\n\tfor y in ys {\n\t\tall = all + showP(y) + \";\"\n\t}\n\tConsole.Println(\"\\(len(ys)) \\(fa) \\(all)\")\n")
	qtext := fmt.Sprintf(` {"xs": [%d], "n": %t, "in": {"a": %d, "b": "v"}}`, n(9), n(2) == 0, n(50))
	if n(3) == 0 {
		qtext = qtext[:len(qtext)-1-n(5)]
	}
	fmt.Fprintf(&b, "\tConsole.Println(viaText(%s, q, \"%s\"))\n", ps[2], strings.ReplaceAll(qtext, `"`, `\"`))
	b.WriteString("}\n")
	return b.String()
}
