package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateLetDefault is a program of lets with no value (F7, "let
// pattern"): `let x T` at an int, a string, a bool, an array and a slice
// (a record has no default), each assigned on a seeded branch or left at its default,
// then folded into an int. A default read wrong (true for a bool, a
// length lost from an array) changes the output or stops the program.
func GenerateLetDefault(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x3c6ef372fe94f82b))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateLetDefault\n\n")
	// fold: every default read, each assigned when k passes a seeded bound.
	fmt.Fprintf(&b, "func fold(k int) int {\n\tlet mut n int\n\tlet mut s string\n\tlet mut ok bool\n\tlet a [4]int\n\tlet mut xs []int\n")
	fmt.Fprintf(&b, "\tif k > %d {\n\t\tn = k * %d\n\t\ts = \"ab\"\n\t}\n", g.n(6), 2+g.n(5))
	fmt.Fprintf(&b, "\tif k > %d {\n\t\tok = true\n\t\txs = []int{k, %d}\n\t}\n", g.n(6), g.n(9))
	fmt.Fprintf(&b, "\tlet mut c = 0\n\tif ok {\n\t\tc = %d\n\t}\n", 1+g.n(50))
	fmt.Fprintf(&b, "\tn + len(s) * %d + c + a[k %% 4] + len(xs) * %d\n}\n\n", 3+g.n(5), 7+g.n(5))
	b.WriteString("func main() needs Console {\n")
	for k := 0; k < 4; k++ {
		fmt.Fprintf(&b, "\tConsole.Println(\"%d: \\(fold(%d))\")\n", k, g.n(10))
	}
	b.WriteString("}\n")
	return b.String()
}
