package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// queueSeqFuncs are GenerateQueueSeq's functions: each calls queue.Queue's
// Values, whose runtime method returns Go's iter.Seq[T] for the Seq[T]
// (ADAPTED-RESULTS, shape 2), and each has an IR body.
var queueSeqFuncs = []string{"sumAll", "later", "stopAt", "words", "checked"}

// GenerateQueueSeq is a program of bodies over queues' Values
// (ADAPTED-RESULTS: an operation's iter.Seq made a Seq):
//   - sumAll fills and closes a queue, then sums its Values;
//   - later makes the Seq first, then pushes and closes, then iterates: the
//     method runs when the Seq is iterated, so it sees every value;
//   - stopAt breaks out of the loop at a seeded value, then polls what is
//     left: a Seq that went on after its loop's yield returned false would
//     panic, and one that stopped early would leave more;
//   - words iterates strings;
//   - checked fails inside the loop body at a seeded value: the failure
//     leaves the loop and the function, through yield's error.
//
// main calls each at seeded arguments and prints what they return.
func GenerateQueueSeq(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x9b05688c2b3e6c1f))
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateQueueSeq\n\nimport queue\n\n")
	b.WriteString("type Bad { N int }\n\n")
	fmt.Fprintf(&b, "func fill(n int) queue.Queue[int] fails queue.Closed {\n\tlet q = queue.New[int](n + 1)\n\tfor i in 0..n {\n\t\ttry q.Push(i * %d + 1)\n\t}\n\tq\n}\n\n", 1+r.IntN(4))
	b.WriteString("func sumAll(n int) int fails queue.Closed {\n\tlet q = try fill(n)\n\tq.End()\n\tlet mut s = 0\n\tfor v in q.Values() {\n\t\ts = s + v\n\t}\n\ts\n}\n\n")
	fmt.Fprintf(&b, "func later(n int) int fails queue.Closed {\n\tlet q = queue.New[int](n + 2)\n\tlet vs = q.Values()\n\tfor i in 0..n {\n\t\ttry q.Push(i + %d)\n\t}\n\tq.End()\n\tlet mut s = 0\n\tfor v in vs {\n\t\ts = s * 3 + v\n\t}\n\ts\n}\n\n", r.IntN(9))
	b.WriteString("func stopAt(n int, k int) int fails queue.Closed {\n\tlet q = try fill(n)\n\tq.End()\n\tlet mut s = 0\n\tfor v in q.Values() {\n\t\tif v > k {\n\t\t\tbreak\n\t\t}\n\t\ts = s + v\n\t}\n\tlet mut left = 0\n\tfor _ in 0..n + 1 {\n\t\tmatch q.Poll() {\n\t\tcase Some[int]:\n\t\t\tleft = left + 1\n\t\tcase None:\n\t\t}\n\t}\n\ts * 100 + left\n}\n\n")
	fmt.Fprintf(&b, "func words(ws []string) string fails queue.Closed {\n\tlet q = queue.New[string](len(ws))\n\tfor w in ws {\n\t\ttry q.Push(w + \"%s\")\n\t}\n\tq.End()\n\tlet mut out = \"\"\n\tfor w in q.Values() {\n\t\tout = out + w + \"/\"\n\t}\n\tout\n}\n\n", []string{"", "!", "ab"}[r.IntN(3)])
	b.WriteString("func check(v int, k int) int fails Bad {\n\tif v == k {\n\t\treturn Bad{N: v}\n\t}\n\tv\n}\n\n")
	b.WriteString("func checked(n int, k int) int fails queue.Closed | Bad {\n\tlet q = try fill(n)\n\tq.End()\n\tlet mut s = 0\n\tfor v in q.Values() {\n\t\ts = s + try check(v, k)\n\t}\n\ts\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	for i, n := 0, 2+r.IntN(3); i < n; i++ {
		fmt.Fprintf(&b, "\tlet a%d = sumAll(%d) catch {\n\tcase queue.Closed:\n\t\t0 - 9\n\t}\n\tConsole.Println(\"sum \\(a%d)\")\n", i, r.IntN(6), i)
		fmt.Fprintf(&b, "\tlet l%d = later(%d) catch {\n\tcase queue.Closed:\n\t\t0 - 9\n\t}\n\tConsole.Println(\"later \\(l%d)\")\n", i, r.IntN(5), i)
		fmt.Fprintf(&b, "\tlet s%d = stopAt(%d, %d) catch {\n\tcase queue.Closed:\n\t\t0 - 9\n\t}\n\tConsole.Println(\"stop \\(s%d)\")\n", i, 2+r.IntN(5), r.IntN(10), i)
		fmt.Fprintf(&b, "\tlet w%d = words([]string{%q, %q}) catch {\n\tcase queue.Closed:\n\t\t\"closed\"\n\t}\n\tConsole.Println(\"words \\(w%d)\")\n", i, []string{"a", "bc", ""}[r.IntN(3)], []string{"x", "yz"}[r.IntN(2)], i)
		fmt.Fprintf(&b, "\tlet c%d = checked(%d, %d) catch {\n\tcase queue.Closed:\n\t\t0 - 9\n\tcase Bad as e:\n\t\t0 - e.N\n\t}\n\tConsole.Println(\"checked \\(c%d)\")\n", i, 2+r.IntN(4), r.IntN(12), i)
	}
	b.WriteString("}\n")
	return b.String()
}
