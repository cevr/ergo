package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateGoLib is a program of the Go calls a third-party library needs
// (FLIP F7 FORK-GOLIB, examples/admit): each libN calls import go with
// one of them. A call that fails with go.Error (strconv.Atoi) and its
// text; one in a return (parse, the failure leaving through the call); a
// variadic call (strings.NewReplacer, errors.Join over go.Errors built
// from literals); an Option of a go.Ref result matched (the niche) and a
// Go method on it (Replacer.Replace); a call that takes the task's
// context (runtime/trace.Log); and a callback that fails with go.Error,
// passed to a Go method that reports it (flag.FlagSet.Func and Parse);
// and a Go method with two results bound by a tuple let
// (Regexp.LiteralPrefix; the window's d.w.Poll(), RU17's red); and a
// field read through a go.Ref a record holds (url.URL's Host, NAMING-ICE).
// main runs each libN on several inputs and prints the results, so a
// failure lost, a text changed, a spread dropped or a None read as Some
// changes the output.
func GenerateGoLib(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x5bd1e9955bd1e995))
	var b strings.Builder
	b.WriteString("func parse(s string) int fails go.Error { strconv.Atoi(s) }\n\n")
	// On even seeds a go.Ref goes through a generic function (boxed), so
	// no Option of a go.Ref is the pointer niche (nicheAdmitted): the Go
	// pointer result is converted to the Option struct (goResult).
	boxed := ""
	if seed%2 == 0 {
		b.WriteString("func boxed[T](x T) []T { []T{x} }\n\n")
		boxed = " + len(boxed(rp.Value))"
	}
	nf := 3 + r.IntN(3)
	sites := false
	for i := 0; i < nf; i++ {
		k := 1 + r.IntN(5)
		fmt.Fprintf(&b, "func lib%d(t int, s string) int needs go.Foreign {\n", i)
		switch r.IntN(7) {
		case 0:
			// A call that fails with go.Error, its text read.
			fmt.Fprintf(&b, "\tlet n = strconv.Atoi(s) catch {\n\tcase go.Error as e:\n\t\treturn len(e.Text) + t\n\t}\n\tn * %d + t\n", k)
		case 1:
			// A variadic call whose Option of a go.Ref is matched, then
			// a Go method on the pointer.
			olds := []string{`"a"`, `"b"`, `"Z"`, `"9"`}
			fmt.Fprintf(&b, "\tmatch strings.NewReplacer([]string{%s, \"%s\", s, \"\"}) {\n\tcase Some[go.Ref[strings.Replacer]] as rp:\n\t\tlen(rp.Value.Replace(\"ab9Z\" + s)) * %d + t%s\n\tcase None:\n\t\t-1\n\t}\n", olds[r.IntN(len(olds))], strings.Repeat("x", k), k, boxed)
		case 2:
			// The task's context, then a failure through a return.
			fmt.Fprintf(&b, "\ttrace.Log(\"lib\", s)\n\tparse(s) catch {\n\tcase go.Error as e:\n\t\treturn len(e.Text) * %d\n\t}\n", k)
		case 3:
			// errors.Join over go.Errors from literals, the zero one
			// Go's nil.
			fmt.Fprintf(&b, "\terrors.Join([]go.Error{go.Error{Text: s}, go.Error{}, go.Error{Text: \"%d\"}}) catch {\n\tcase go.Error as e:\n\t\treturn len(e.Text) + t\n\t}\n\t0\n", k)
		case 4:
			// A Go method with two results, bound by a tuple let.
			fmt.Fprintf(&b, "\tmatch regexp.MustCompile(s + \"x*\") {\n\tcase Some[go.Ref[regexp.Regexp]] as re:\n\t\tlet (p, whole) = re.Value.LiteralPrefix()\n\t\tif whole {\n\t\t\tlen(p) * %d + t\n\t\t} else {\n\t\t\tlen(p) + t\n\t\t}\n\tcase None:\n\t\t-1\n\t}\n", k)
		case 5:
			// A field read through a go.Ref (a Go *T) a record holds, as
			// std pace reads its MemStats (NAMING-ICE: the IR named the
			// go.Ref as a declaration): site's URL, its Host.
			sites = true
			fmt.Fprintf(&b, "\tlet w = site(s) catch {\n\tcase go.Error as e:\n\t\treturn len(e.Text) + t\n\t}\n\tlen(w.u.Host) * %d + w.n + t\n", k)
		default:
			// A callback that fails, through Go's flag package.
			fmt.Fprintf(&b, "\tlet mut seen = 0\n\tmatch flag.NewFlagSet(\"g\", flag.ErrorHandling(0)) {\n\tcase Some[go.Ref[flag.FlagSet]] as fs:\n\t\tfs.Value.Func(\"n\", \"a number\", func(v string) fails go.Error {\n\t\t\tif len(v) > %d {\n\t\t\t\treturn go.Error{Text: \"long \\(v)\"}\n\t\t\t}\n\t\t})\n\t\tfs.Value.Parse([]string{\"-n\", s}) catch {\n\t\tcase go.Error as e:\n\t\t\tseen = len(e.Text)\n\t\t}\n\tcase None:\n\t}\n\tseen + t\n", k%3+1)
		}
		b.WriteString("}\n\n")
	}
	if sites {
		b.WriteString("type Site {\n\tu go.Ref[url.URL],\n\tn int,\n}\n\n")
		b.WriteString("func site(s string) Site fails go.Error needs go.Foreign {\n\tSite{u: try url.Parse(\"http://h\" + s + \".x/p\"), n: len(s)}\n}\n\n")
	}
	b.WriteString("func main() needs Console | go.Foreign {\n")
	inputs := []string{`"12"`, `""`, `"zZ1a"`, `"-7"`, `"ab"`}
	for i := 0; i < nf; i++ {
		for t := 0; t < 3; t++ {
			s := inputs[r.IntN(len(inputs))]
			fmt.Fprintf(&b, "\tlet v%d_%d = lib%d(%d, %s)\n\tConsole.Println(\"lib%d %d \\(v%d_%d)\")\n", i, t, i, t, s, i, t, i, t)
		}
	}
	b.WriteString("}\n")
	var head strings.Builder
	head.WriteString("// generated by irspike.GenerateGoLib\n\n")
	for _, pkg := range []string{"errors", "flag", "net/url", "regexp", "runtime/trace", "strconv", "strings"} {
		name := pkg[strings.LastIndex(pkg, "/")+1:]
		if strings.Contains(b.String(), name+".") {
			head.WriteString("import go " + pkg + "\n")
		}
	}
	return head.String() + "\n" + b.String()
}
