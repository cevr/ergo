package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// queuePollFuncs are GenerateQueuePoll's functions: each calls
// queue.Queue's Poll, whose runtime method returns Go's comma-ok (T, bool)
// for the Option[T] (ADAPTED-RESULTS, shape 1), and each has an IR body.
var queuePollFuncs = []string{"drainInts", "pollEmpty", "pollRecs", "pollKept"}

// GenerateQueuePoll is a program of bodies that poll queues
// (ADAPTED-RESULTS: an operation's comma-ok result made an Option):
//   - drainInts pushes a seeded number of ints, closes or keeps the queue
//     open by the seed, and polls until None, matching each Option, at
//     most two polls past the last value (a Poll that never gives None
//     ends there, so a wrong Option changes the count, never hangs);
//   - pollEmpty polls a queue it never filled, at capacity 0 or not: None
//     whatever the seed;
//   - pollRecs polls records, reading two fields of each Some, one poll
//     past the last value;
//   - pollKept binds two polls' Options to lets first, with a push between
//     them, and matches them after, so each Option is the value at its
//     poll.
//
// main calls each at seeded arguments and prints what they return. An
// Option built from the wrong result, a Some when not ok or a None when
// ok, changes the output.
func GenerateQueuePoll(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x510e527fade682d1))
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateQueuePoll\n\nimport queue\n\n")
	b.WriteString("type P { a int, s string }\n\n")
	end := ""
	if r.IntN(2) == 0 {
		end = "\tq.End()\n"
	}
	fmt.Fprintf(&b, "func drainInts(n int) int fails queue.Closed {\n\tlet q = queue.New[int](n + 1)\n\tfor i in 0..n {\n\t\ttry q.Push(i * %d - n)\n\t}\n%s\tlet mut sum = 0\n\tlet mut count = 0\n\tfor _ in 0..n + 2 {\n\t\tmatch q.Poll() {\n\t\tcase Some[int] as s:\n\t\t\tsum = sum + s.Value\n\t\t\tcount = count + 1\n\t\tcase None:\n\t\t\tbreak\n\t\t}\n\t}\n\tsum * 100 + count\n}\n\n", 1+r.IntN(4), end)
	fmt.Fprintf(&b, "func pollEmpty(k int) int {\n\tlet q = queue.New[string](%d)\n\tmatch q.Poll() {\n\tcase Some[string] as s:\n\t\tlen(s.Value)\n\tcase None:\n\t\tk * 2\n\t}\n}\n\n", r.IntN(2))
	fmt.Fprintf(&b, "func pollRecs(n int, s string) string fails queue.Closed {\n\tlet q = queue.New[P](n + 1)\n\tfor i in 0..n {\n\t\ttry q.Push(P{a: i + %d, s: s})\n\t}\n\tlet mut out = \"\"\n\tfor _ in 0..n + 1 {\n\t\tmatch q.Poll() {\n\t\tcase Some[P] as p:\n\t\t\tout = out + p.Value.s + \"\\(p.Value.a)\"\n\t\tcase None:\n\t\t\tout = out + \".\"\n\t\t}\n\t}\n\tout\n}\n\n", r.IntN(9))
	fmt.Fprintf(&b, "func pollKept(k int) int fails queue.Closed {\n\tlet q = queue.New[int](2)\n\tlet first = q.Poll()\n\ttry q.Push(k + %d)\n\tlet second = q.Poll()\n\tlet a = match first {\n\tcase Some[int] as s:\n\t\ts.Value\n\tcase None:\n\t\t0 - 1\n\t}\n\tlet c = match second {\n\tcase Some[int] as s:\n\t\ts.Value\n\tcase None:\n\t\t0 - 2\n\t}\n\ta * 1000 + c\n}\n\n", r.IntN(50))
	b.WriteString("func main() needs Console {\n")
	for i, n := 0, 2+r.IntN(3); i < n; i++ {
		fmt.Fprintf(&b, "\tlet d%d = drainInts(%d) catch {\n\tcase queue.Closed:\n\t\t0 - 9\n\t}\n\tConsole.Println(\"drain \\(d%d)\")\n", i, r.IntN(6), i)
		fmt.Fprintf(&b, "\tConsole.Println(\"empty \\(pollEmpty(%d))\")\n", r.IntN(20)-5)
		fmt.Fprintf(&b, "\tlet r%d = pollRecs(%d, %q) catch {\n\tcase queue.Closed:\n\t\t\"closed\"\n\t}\n\tConsole.Println(\"recs \\(r%d)\")\n", i, r.IntN(4), []string{"", "x", "yz"}[r.IntN(3)], i)
		fmt.Fprintf(&b, "\tlet k%d = pollKept(%d) catch {\n\tcase queue.Closed:\n\t\t0 - 9\n\t}\n\tConsole.Println(\"kept \\(k%d)\")\n", i, r.IntN(30), i)
	}
	b.WriteString("}\n")
	return b.String()
}
