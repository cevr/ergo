package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// loopFuncs are GenerateLoops' functions: each has an IR body in every
// seed (FLIP F7 GP-LOOPS).
var loopFuncs = []string{"fillInts", "fillWords", "fillMarks", "moveInts", "Grid.shift"} // shift takes a *Grid first: a method of Grid's

// GenerateLoops is a program of the count loops loops.go's DT4 writes as
// calls (fill and move), with offsets of every form (i, i + c, c + i,
// i - c), forward and backward overlaps, empty ranges, zero and non-zero
// fill values of a scalar, a string and a record, and a move through a
// field a pointer reaches (vt's Screen.cells). Every index stays in
// bounds, so each loop runs to its end on both paths; main prints a hash
// of each result, so a guard that lets a smearing overlap through, a clear
// of a non-zero value, or an offset written wrong changes the output.
func GenerateLoops(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x9e3779b97f4a7c15))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateLoops\n\n")
	b.WriteString("type Mark { on bool, n int }\n\n")
	b.WriteString("type Grid { cells []int, w int }\n\n")
	b.WriteString("func seq(n int) []int {\n\tlet mut xs = []int{}\n\tfor i in 0..n {\n\t\txs = xs.Append(i * 7 + 1)\n\t}\n\txs\n}\n\n")
	b.WriteString("func hash(xs []int) int {\n\tlet mut h = 0\n\tfor x in xs {\n\t\th = h * 31 + x\n\t}\n\th\n}\n\n")
	// fillInts: P[i + d] = v, d >= 0; the caller keeps hi + d <= n.
	b.WriteString("func fillInts(n int, lo int, hi int, d int, v int) int {\n\tlet mut xs = seq(n)\n\tfor i in lo..hi {\n\t\txs[i + d] = v\n\t}\n\thash(xs)\n}\n\n")
	// fillWords: P[c + i] = s, a string (zero when empty).
	b.WriteString("func fillWords(n int, lo int, hi int, c int, s string) int {\n\tlet mut ws = []string{}\n\tfor _ in 0..n {\n\t\tws = ws.Append(\"w\")\n\t}\n\tfor i in lo..hi {\n\t\tws[c + i] = s\n\t}\n\tlet mut h = 0\n\tfor w in ws {\n\t\th = h * 31 + len(w)\n\t}\n\th\n}\n\n")
	// fillMarks: P[i - c] = a record, zero or not.
	b.WriteString("func fillMarks(n int, lo int, hi int, c int, on bool, k int) int {\n\tlet mut ms = []Mark{}\n\tfor i in 0..n {\n\t\tms = ms.Append(Mark{on: true, n: i})\n\t}\n\tfor i in lo..hi {\n\t\tms[i - c] = Mark{on: on, n: k}\n\t}\n\tlet mut h = 0\n\tfor m in ms {\n\t\th = h * 31 + m.n\n\t\tif m.on {\n\t\t\th = h + 1000\n\t\t}\n\t}\n\th\n}\n\n")
	// moveInts: P[i + d] = P[i + s], any overlap.
	b.WriteString("func moveInts(n int, lo int, hi int, d int, s int) int {\n\tlet mut xs = seq(n)\n\tfor i in lo..hi {\n\t\txs[i + d] = xs[i + s]\n\t}\n\thash(xs)\n}\n\n")
	// moveCells: vt's row move, through a pointer's field.
	b.WriteString("func shift(g *Grid, a int, b int) {\n\tfor j in 0..g.w {\n\t\tg.cells[b + j] = g.cells[a + j]\n\t}\n}\n\n")
	b.WriteString("func moveCells(rows int, w int, a int, b int) int {\n\tlet mut g = Grid{cells: seq(rows * w), w: w}\n\tshift(&g, a * w, b * w)\n\thash(g.cells)\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	for k := 0; k < 3; k++ {
		n := 4 + g.n(8)
		lo, hi := g.span(n)
		d := g.n(n - hi + 1)
		fmt.Fprintf(&b, "\tConsole.Println(\"\\(fillInts(%d, %d, %d, %d, %d))\")\n", n, lo, hi, d, []int{0, 0, 5, -3}[g.n(4)])
		lo, hi = g.span(n)
		c := g.n(n - hi + 1)
		fmt.Fprintf(&b, "\tConsole.Println(\"\\(fillWords(%d, %d, %d, %d, %s))\")\n", n, lo, hi, c, []string{`""`, `""`, `"ox"`}[g.n(3)])
		lo, hi = g.span(n)
		c = 0
		if lo > 0 {
			c = g.n(lo + 1)
		}
		fmt.Fprintf(&b, "\tConsole.Println(\"\\(fillMarks(%d, %d, %d, %d, %v, %d))\")\n", n, lo, hi, c, g.n(2) == 0, []int{0, 0, 4}[g.n(3)])
		// A move whose both parts stay in [0, n): offsets up to the room
		// past hi, so the target may start before, at, inside or after
		// the source.
		lo, hi = g.span(n)
		room := n - hi
		fmt.Fprintf(&b, "\tConsole.Println(\"\\(moveInts(%d, %d, %d, %d, %d))\")\n", n, lo, hi, g.n(room+1), g.n(room+1))
		rows, w := 2+g.n(4), 1+g.n(5)
		fmt.Fprintf(&b, "\tConsole.Println(\"\\(moveCells(%d, %d, %d, %d))\")\n", rows, w, g.n(rows), g.n(rows))
	}
	b.WriteString("}\n")
	return b.String()
}

// span is a range lo..hi inside [0, n]: empty a quarter of the time (hi
// at or below lo).
func (g *ggen) span(n int) (int, int) {
	lo := g.n(n + 1)
	if g.n(4) == 0 {
		return lo, lo - g.n(lo+1)
	}
	return lo, lo + g.n(n-lo+1)
}
