package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// loopFuncs are GenerateLoops' functions: each has an IR body in every
// seed (FLIP F7 GP-LOOPS).
var loopFuncs = []string{"fillInts", "fillWords", "fillMarks", "moveInts", "Grid.shift", // shift takes a *Grid first: a method of Grid's
	"collectAt", "collectAdd", "collectAddL", "collectSub"} // GP-COLLECT

// foldFuncs are GenerateLoops' folds (GP-FOLD): fused builds no slice;
// kept builds it, each for its own reason.
var foldFuncs = struct{ fused, kept []string }{
	fused: []string{"foldSum", "foldBreak"},
	kept:  []string{"foldUsed", "foldWrites", "foldPrefix"},
}

// resliceFuncs are GenerateLoops' reslices (GP-RESLICE): taken grows no
// slice (it takes the source's part); kept copies, each for its own
// reason.
var resliceFuncs = struct{ taken, kept []string }{
	taken: []string{"resliceSum", "resliceField", "resliceGap"},
	kept:  []string{"resliceLive", "resliceShared", "resliceOuter", "resliceFieldLive", "resliceFieldWhole", "resliceGapWritten"},
}

// GenerateLoops is a program of the count loops loops.go's DT4 writes as
// calls (fill and move), with offsets of every form (i, i + c, c + i,
// i - c), forward and backward overlaps, empty ranges, zero and non-zero
// fill values of a scalar, a string and a record, and a move through a
// field a pointer reaches (vt's Screen.cells). Every index stays in
// bounds, so each loop runs to its end on both paths; main prints a hash
// of each result, so a guard that lets a smearing overlap through, a clear
// of a non-zero value, or an offset written wrong changes the output.
//
// The collects (GP-COLLECT) append a part of a slice at every offset form
// to an empty slice or to one with room, so a part read at the wrong
// offset changes the output.
func GenerateLoops(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x9e3779b97f4a7c15))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateLoops\n\n")
	b.WriteString("type Mark { on bool, n int }\n\n")
	b.WriteString("type Grid { cells []int, w int }\n\n")
	b.WriteString("type Line { items []int, n int }\n\n")
	b.WriteString("func seq(n int) []int {\n\tlet mut xs = []int{}\n\tfor i in 0..n {\n\t\txs = xs.Append(i * 7 + 1)\n\t}\n\txs\n}\n\n")
	b.WriteString("func hash(xs []int) int {\n\tlet mut h = 0\n\tfor x in xs {\n\t\th = h * 31 + x\n\t}\n\th\n}\n\n")
	// fillInts: P[i + d] = v, d >= 0; the caller keeps hi + d <= n.
	b.WriteString("func fillInts(n int, lo int, hi int, d int, v int) int {\n\tlet mut xs = seq(n)\n\tfor i in lo..hi {\n\t\txs[i + d] = v\n\t}\n\thash(xs)\n}\n\n")
	// fillWords: P[c + i] = s, a string (zero when empty).
	b.WriteString("func fillWords(n int, lo int, hi int, c int, s string) int {\n\tlet mut ws = []string{}\n\tfor _ in 0..n {\n\t\tws = ws.Append(\"w\")\n\t}\n\tfor i in lo..hi {\n\t\tws[c + i] = s\n\t}\n\tlet mut h = 0\n\tfor w in ws {\n\t\th = h * 31 + len(w)\n\t}\n\th\n}\n\n")
	// fillMarks: P[i - c] = a record, zero or not.
	b.WriteString("func fillMarks(n int, lo int, hi int, c int, on bool, k int) int {\n\tlet mut ms = []Mark{}\n\tfor i in 0..n {\n\t\tms = ms.Append(Mark{on: true, n: i})\n\t}\n\tfor i in lo..hi {\n\t\tms[i - c] = Mark{on: on, n: k}\n\t}\n\tlet mut h = 0\n\tfor m in ms {\n\t\th = h * 31 + m.n\n\t\tif m.on {\n\t\t\th = h + 1000\n\t\t}\n\t}\n\th\n}\n\n")
	// moveInts: P[i + d] = P[i + s], any overlap.
	b.WriteString("func moveInts(n int, lo int, hi int, d int, s int) int {\n\tlet mut xs = seq(n)\n\tfor i in lo..hi {\n\t\txs[i + d] = xs[i + s]\n\t}\n\thash(xs)\n}\n\n")
	// moveCells: vt's row move, through a pointer's field.
	b.WriteString("func shift(g mut Grid, a int, b int) {\n\tfor j in 0..g.w {\n\t\tg.cells[b + j] = g.cells[a + j]\n\t}\n}\n\n")
	b.WriteString("func moveCells(rows int, w int, a int, b int) int {\n\tlet mut g = Grid{cells: seq(rows * w), w: w}\n\tshift(&g, a * w, b * w)\n\thash(g.cells)\n}\n\n")
	// The collects (GP-COLLECT): ys = ys.Append(src[x]) at every offset
	// form; the caller keeps every index of src in [0, n).
	for _, c := range []struct{ name, at string }{{"collectAt", "i"}, {"collectAdd", "i + s"}, {"collectAddL", "s + i"}, {"collectSub", "i - s"}} {
		fmt.Fprintf(&b, "func %s(n int, lo int, hi int, s int, k int) int {\n\tlet src = seqBy(n, 3)\n\tlet mut ys = seq(k)\n\tfor i in lo..hi {\n\t\tys = ys.Append(src[%s])\n\t}\n\thash(ys)\n}\n\n", c.name, c.at)
	}
	// The folds (GP-FOLD): a collect into an empty slice that the next loop
	// only folds. foldSum and foldBreak fuse; foldUsed reads the slice
	// after (and its source, so it is no reslice either), foldWrites
	// writes the source in its body, and foldPrefix
	// starts the slice with elements: those three keep the slice.
	b.WriteString("func foldSum(n int, lo int, hi int, s int) int {\n\tlet src = seqBy(n, 3)\n\tlet mut h = 7\n\tlet mut ys = []int{}\n\tfor i in lo..hi {\n\t\tys = ys.Append(src[i + s])\n\t}\n\tfor k, y in ys {\n\t\th = h * 31 + y * (k + 1)\n\t}\n\th\n}\n\n")
	b.WriteString("func foldBreak(n int, lo int, hi int, s int, limit int) int {\n\tlet src = seqBy(n, 3)\n\tlet mut h = 0\n\tlet mut ys = []int{}\n\tfor i in lo..hi {\n\t\tys = ys.Append(src[s + i])\n\t}\n\tfor y in ys {\n\t\tif y > limit {\n\t\t\tbreak\n\t\t}\n\t\th = h * 31 + y\n\t}\n\th\n}\n\n")
	b.WriteString("func foldUsed(n int, lo int, hi int, s int) int {\n\tlet src = seqBy(n, 3)\n\tlet mut h = 0\n\tlet mut ys = []int{}\n\tfor i in lo..hi {\n\t\tys = ys.Append(src[i + s])\n\t}\n\tfor y in ys {\n\t\th = h * 31 + y\n\t}\n\th * 100 + hash(ys) + len(src)\n}\n\n")
	b.WriteString("func foldWrites(n int, lo int, hi int, s int) int {\n\tlet mut src = seqBy(n, 3)\n\tlet mut h = 0\n\tlet mut ys = []int{}\n\tfor i in lo..hi {\n\t\tys = ys.Append(src[i + s])\n\t}\n\tfor k, y in ys {\n\t\th = h * 31 + y\n\t\tlet j = lo + s + k + 1\n\t\tif j < n {\n\t\t\tsrc[j] = 0\n\t\t}\n\t}\n\th\n}\n\n")
	b.WriteString("func foldPrefix(n int, lo int, hi int, s int) int {\n\tlet src = seqBy(n, 3)\n\tlet mut h = 0\n\tlet mut ys = seq(2)\n\tfor i in lo..hi {\n\t\tys = ys.Append(src[i + s])\n\t}\n\tfor y in ys {\n\t\th = h * 31 + y\n\t}\n\th\n}\n\n")
	// The reslices (GP-RESLICE): a collect into an empty slice that is read
	// after, then grown. resliceSum's source is dead after the collect, so
	// the slice takes the part itself; resliceLive reads the source after,
	// resliceShared's source shares base's array, and resliceOuter
	// collects from one source in each pass of a loop: those keep the copy.
	b.WriteString("func resliceSum(n int, lo int, hi int, s int, extra int) int {\n\tlet src = seqBy(n, 3)\n\tlet mut ys = []int{}\n\tfor i in lo..hi {\n\t\tys = ys.Append(src[i + s])\n\t}\n\tys = ys.Append(extra)\n\thash(ys)\n}\n\n")
	b.WriteString("func resliceLive(n int, lo int, hi int, s int, extra int) int {\n\tlet src = seqBy(n, 3)\n\tlet mut ys = []int{}\n\tfor i in lo..hi {\n\t\tys = ys.Append(src[i + s])\n\t}\n\tys = ys.Append(extra)\n\thash(ys) * 7 + hash(src)\n}\n\n")
	b.WriteString("func resliceShared(n int, lo int, hi int, s int, extra int) int {\n\tlet base = seqBy(n, 3)\n\tlet src = base\n\tlet mut ys = []int{}\n\tfor i in lo..hi {\n\t\tys = ys.Append(src[i + s])\n\t}\n\tys = ys.Append(extra)\n\thash(ys) * 7 + hash(base)\n}\n\n")
	b.WriteString("func resliceOuter(n int, lo int, hi int, s int, extra int) int {\n\tlet src = seqBy(n, 3)\n\tlet mut h = extra\n\tfor r in 0..2 {\n\t\tlet mut ys = []int{}\n\t\tfor i in lo..hi {\n\t\t\tys = ys.Append(src[i + s])\n\t\t}\n\t\tys = ys.Append(r)\n\t\th = h * 31 + hash(ys)\n\t}\n\th\n}\n\n")
	// The field reslices (GP-RESLICE-FIELD): the source is a field of a
	// local record. resliceField reads only rec.n after, a disjoint int
	// field, so the slice takes the part; resliceFieldLive reads rec.items
	// after and resliceFieldWhole reads the whole record after: those keep
	// the copy.
	b.WriteString("func resliceField(n int, lo int, hi int, s int, extra int) int {\n\tlet rec = Line{items: seqBy(n, 3), n: n}\n\tlet mut ys = []int{}\n\tfor i in lo..hi {\n\t\tys = ys.Append(rec.items[i + s])\n\t}\n\tys = ys.Append(extra)\n\thash(ys) * 7 + rec.n\n}\n\n")
	b.WriteString("func resliceFieldLive(n int, lo int, hi int, s int, extra int) int {\n\tlet rec = Line{items: seqBy(n, 3), n: n}\n\tlet mut ys = []int{}\n\tfor i in lo..hi {\n\t\tys = ys.Append(rec.items[i + s])\n\t}\n\tys = ys.Append(extra)\n\thash(ys) * 7 + hash(rec.items)\n}\n\n")
	b.WriteString("func resliceFieldWhole(n int, lo int, hi int, s int, extra int) int {\n\tlet rec = Line{items: seqBy(n, 3), n: n}\n\tlet mut ys = []int{}\n\tfor i in lo..hi {\n\t\tys = ys.Append(rec.items[i + s])\n\t}\n\tys = ys.Append(extra)\n\thash(ys) * 7 + lineHash(rec)\n}\n\n")
	// The gaps (GP-RESLICE-EMPTY): the empty let is further up the block.
	// resliceGap's statement between does not name ys, so the slice takes
	// the part; resliceGapWritten's appends to ys between, so it copies
	// (taking the part would drop that element).
	b.WriteString("func resliceGap(n int, lo int, hi int, s int, extra int) int {\n\tlet src = seqBy(n, 3)\n\tlet mut ys = []int{}\n\tlet k = extra * 2 + 1\n\tfor i in lo..hi {\n\t\tys = ys.Append(src[i + s])\n\t}\n\tys = ys.Append(k)\n\thash(ys)\n}\n\n")
	b.WriteString("func resliceGapWritten(n int, lo int, hi int, s int, extra int) int {\n\tlet src = seqBy(n, 3)\n\tlet mut ys = []int{}\n\tys = ys.Append(extra)\n\tfor i in lo..hi {\n\t\tys = ys.Append(src[i + s])\n\t}\n\tys = ys.Append(extra + 1)\n\thash(ys)\n}\n\n")
	b.WriteString("func lineHash(l Line) int {\n\thash(l.items) + l.n\n}\n\n")
	b.WriteString("func seqBy(n int, m int) []int {\n\tlet mut xs = []int{}\n\tfor i in 0..n {\n\t\txs = xs.Append(i * m + 2)\n\t}\n\txs\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	for k := 0; k < 3; k++ {
		n := 4 + g.n(8)
		lo, hi := g.span(n)
		d := g.n(n - hi + 1)
		fmt.Fprintf(&b, "\tConsole.Println(\"\\(fillInts(%d, %d, %d, %d, %d))\")\n", n, lo, hi, d, []int{0, 0, 5, -3}[g.n(4)])
		lo, hi = g.span(n)
		c := g.n(n - hi + 1)
		fmt.Fprintf(&b, "\tConsole.Println(\"\\(fillWords(%d, %d, %d, %d, %s))\")\n", n, lo, hi, c, []string{`""`, `""`, `"ox"`}[g.n(3)])
		lo, hi = g.span(n)
		c = 0
		if lo > 0 {
			c = g.n(lo + 1)
		}
		fmt.Fprintf(&b, "\tConsole.Println(\"\\(fillMarks(%d, %d, %d, %d, %v, %d))\")\n", n, lo, hi, c, g.n(2) == 0, []int{0, 0, 4}[g.n(3)])
		// A move whose both parts stay in [0, n): offsets up to the room
		// past hi, so the target may start before, at, inside or after
		// the source.
		lo, hi = g.span(n)
		room := n - hi
		fmt.Fprintf(&b, "\tConsole.Println(\"\\(moveInts(%d, %d, %d, %d, %d))\")\n", n, lo, hi, g.n(room+1), g.n(room+1))
		rows, w := 2+g.n(4), 1+g.n(5)
		fmt.Fprintf(&b, "\tConsole.Println(\"\\(moveCells(%d, %d, %d, %d))\")\n", rows, w, g.n(rows), g.n(rows))
		// Collects: the source part [lo+s, hi+s) inside [0, n), appended
		// to a slice of k elements (k = 0 is the empty slice).
		lo, hi = g.span(n)
		s := g.n(n - hi + 1)
		fmt.Fprintf(&b, "\tConsole.Println(\"\\(collectAt(%d, %d, %d, %d, %d))\")\n", n, lo, hi, 0, g.n(6))
		fmt.Fprintf(&b, "\tConsole.Println(\"\\(collectAdd(%d, %d, %d, %d, %d))\")\n", n, lo, hi, s, g.n(6))
		fmt.Fprintf(&b, "\tConsole.Println(\"\\(collectAddL(%d, %d, %d, %d, %d))\")\n", n, lo, hi, s, g.n(6))
		lo, hi = g.span(n)
		s = g.n(lo + 1)
		fmt.Fprintf(&b, "\tConsole.Println(\"\\(collectSub(%d, %d, %d, %d, %d))\")\n", n, lo, hi, s, g.n(6))
		// Folds: the part [lo+s, hi+s) inside [0, n).
		lo, hi = g.span(n)
		s = g.n(n - hi + 1)
		for _, f := range []string{"foldSum", "foldUsed", "foldWrites", "foldPrefix"} {
			fmt.Fprintf(&b, "\tConsole.Println(\"\\(%s(%d, %d, %d, %d))\")\n", f, n, lo, hi, s)
		}
		fmt.Fprintf(&b, "\tConsole.Println(\"\\(foldBreak(%d, %d, %d, %d, %d))\")\n", n, lo, hi, s, 3*g.n(n+1)+2)
		// Reslices: the part [lo+s, hi+s) inside [0, n), often short of n,
		// so a slice grown in place past it would write the source.
		lo, hi = g.span(n)
		s = g.n(n - hi + 1)
		for _, f := range []string{"resliceSum", "resliceLive", "resliceShared", "resliceOuter", "resliceField", "resliceFieldLive", "resliceFieldWhole", "resliceGap", "resliceGapWritten"} {
			fmt.Fprintf(&b, "\tConsole.Println(\"\\(%s(%d, %d, %d, %d, %d))\")\n", f, n, lo, hi, s, 900+g.n(50))
		}
	}
	b.WriteString("}\n")
	return b.String()
}

// span is a range lo..hi inside [0, n]: empty a quarter of the time (hi
// at or below lo).
func (g *ggen) span(n int) (int, int) {
	lo := g.n(n + 1)
	if g.n(4) == 0 {
		return lo, lo - g.n(lo+1)
	}
	return lo, lo + g.n(n-lo+1)
}
