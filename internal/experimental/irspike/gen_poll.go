package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GeneratePoll is a program of loop nests for POLL-AMORT's counted law
// (TestIRPollAmortBound): functions nestN, which need Console; each is
// a nest of count and while loops, up to three deep, whose bodies fold
// into acc through mix, a pure function, and may continue or break. A
// nest is quiet (every call pure) unless the generator gave one of its
// loops a Console.Println, which can wait: then that loop and the loops
// around it check at every back edge. Inner loops run few iterations and
// outer ones many, so a counter per loop would let a stop go unseen for
// far more than pollEvery back edges. Each nestN prints acc after its
// nest, so it is a polling frame; main runs each at two sizes.
func GeneratePoll(seed uint64) string {
	g := &pgen{r: rand.New(rand.NewPCG(seed, seed^0x2545f4914f6cdd1d))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GeneratePoll\n\nfunc mix(a int, b int) int {\n\t(a * 31 + b + 7) % 1000003\n}\n\n")
	nf := 3 + g.r.IntN(3)
	for f := 0; f < nf; f++ {
		g.vars = 0
		g.loud = f%3 == 2 // one nest in three may call Console.Println
		fmt.Fprintf(&b, "func nest%d(n int) int needs Console {\n\tlet mut acc = %d\n", f, g.r.IntN(50))
		g.loop(&b, 1, "n")
		fmt.Fprintf(&b, "\tConsole.Println(\"nest%d \\(acc)\")\n\tacc\n}\n\n", f)
	}
	b.WriteString("func main() needs Console {\n")
	for f := 0; f < nf; f++ {
		fmt.Fprintf(&b, "\tlet a%d = nest%d(%d)\n\tlet b%d = nest%d(%d)\n\tConsole.Println(\"\\(a%d) \\(b%d)\")\n", f, f, 1+g.r.IntN(40), f, f, 600+g.r.IntN(2400), f, f)
	}
	b.WriteString("}\n")
	return b.String()
}

type pgen struct {
	r    *rand.Rand
	vars int
	loud bool
}

func indent(d int) string { return strings.Repeat("\t", d) }

// loop writes a loop at depth d (1 is the nest's outermost) whose bound is
// bound, then its body.
func (g *pgen) loop(b *strings.Builder, d int, bound string) {
	g.vars++
	v := fmt.Sprintf("i%d", g.vars)
	in := indent(d)
	if g.r.IntN(2) == 0 {
		fmt.Fprintf(b, "%sfor %s in 0..%s {\n", in, v, bound)
	} else {
		fmt.Fprintf(b, "%slet mut %s = 0\n%sfor %s < %s {\n%s\t%s = %s + 1\n", in, v, in, v, bound, in, v, v)
	}
	g.body(b, d+1, v)
	fmt.Fprintf(b, "%s}\n", in)
}

// body writes a loop body at depth d, its loop's variable v.
func (g *pgen) body(b *strings.Builder, d int, v string) {
	in := indent(d)
	fmt.Fprintf(b, "%sacc = mix(acc, %s)\n", in, v) // every loop writes acc
	for k, n := 0, 1+g.r.IntN(3); k < n; k++ {
		switch g.r.IntN(8) {
		case 0, 1:
			if d < 4 {
				// an inner loop: few iterations, so a counter of its own
				// would rarely reach zero
				g.loop(b, d, fmt.Sprint(1+g.r.IntN(12)))
				continue
			}
			fmt.Fprintf(b, "%sacc = mix(acc, %s)\n", in, v)
		case 2:
			fmt.Fprintf(b, "%sif mix(acc, %s) %% %d == 0 {\n%s\tcontinue\n%s}\n", in, v, 2+g.r.IntN(5), in, in)
		case 3:
			fmt.Fprintf(b, "%sif acc %% 4093 == %d {\n%s\tbreak\n%s}\n", in, g.r.IntN(4093), in, in)
		case 4:
			if g.loud {
				fmt.Fprintf(b, "%sif acc %% 997 == %d {\n%s\tConsole.Println(\"at \\(%s)\")\n%s}\n", in, g.r.IntN(997), in, v, in)
				continue
			}
			fmt.Fprintf(b, "%sacc = mix(acc, %s + %d)\n", in, v, g.r.IntN(9))
		default:
			fmt.Fprintf(b, "%sacc = mix(acc, %s)\n", in, v)
		}
	}
}
