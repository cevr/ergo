package irspike

import (
	"fmt"
	"math/rand/v2"
	"strconv"
	"strings"
)

// GenerateFold is a program that prints calls of reviewed-pure Go
// functions on seeded constants (LAWFFI LF3c, the fold pass;
// lower/ir_fold.go): strconv.Quote, QuoteToASCII, Itoa and FormatBool,
// strings.ToUpper, ToLower and TrimSpace, and filepath.Clean. The
// constants mix ASCII, quotes, backslashes, control characters, spaces
// Unicode trims, letters whose case mapping changes their length, and
// characters outside the BMP, so a fold that spelled its constant wrongly
// in the IR, or computed it with other tables, prints something else. The
// calls stand as a let's value, inside an interpolation, nested in one
// another, inside a loop, on a let of a constant (which folds), and on a
// parameter or a written let mut (operands that are not constants, which
// do not fold).
func GenerateFold(seed uint64) string {
	g := &foldGen{r: rand.New(rand.NewPCG(seed, seed^0xf01dca11))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateFold\nimport go strconv\nimport go strings\nimport go path/filepath\n\n")
	// show uses each import, on a parameter.
	b.WriteString("func show(p string) string {\n\tstrconv.Quote(strings.TrimSpace(filepath.Clean(p)))\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	for j, n := 0, 6+g.r.IntN(8); j < n; j++ {
		b.WriteString(g.stmt(j))
	}
	b.WriteString("}\n")
	return b.String()
}

type foldGen struct{ r *rand.Rand }

// foldRunes are the characters a constant is made of.
var foldRunes = []string{"a", "Z", "q", " ", "\t", "\n", "\"", "\\", "(", "/", ".", "..", "\x01", "\x7f",
	"é", "ß", "ǅ", "İ", "ﬀ", "Σ", "\u00a0", "\u2028", "\u200b", "\u3000", "😀", "𝔸", "\ufeff"}

// lit is a seeded constant string, spelled as an Ergo literal (Go's
// escapes, so Go's Quote spells it).
func (g *foldGen) lit() string {
	var s strings.Builder
	for i, n := 0, g.r.IntN(7); i < n; i++ {
		s.WriteString(foldRunes[g.r.IntN(len(foldRunes))])
	}
	return strconv.Quote(s.String())
}

// call is a call of one of the folded functions on a constant.
func (g *foldGen) call() string {
	switch g.r.IntN(8) {
	case 0:
		return "strconv.Quote(" + g.lit() + ")"
	case 1:
		return "strconv.QuoteToASCII(" + g.lit() + ")"
	case 2:
		return fmt.Sprintf("strconv.Itoa(%d)", g.r.Int64N(1<<40)-1<<39)
	case 3:
		return fmt.Sprintf("strconv.FormatBool(%t)", g.r.IntN(2) == 0)
	case 4:
		return "strings.ToUpper(" + g.lit() + ")"
	case 5:
		return "strings.ToLower(" + g.lit() + ")"
	case 6:
		return "strings.TrimSpace(" + g.lit() + ")"
	default:
		return "filepath.Clean(" + g.lit() + ")"
	}
}

// stmt is the j-th statement of main.
func (g *foldGen) stmt(j int) string {
	switch g.r.IntN(7) {
	case 0:
		return fmt.Sprintf("\tlet v%d = %s\n\tConsole.Println(strconv.Quote(v%d))\n", j, g.call(), j)
	case 1:
		return fmt.Sprintf("\tConsole.Println(\"%d: \\(%s)\")\n", j, g.call())
	case 2:
		// Nested: the outer call's operand folds first.
		return fmt.Sprintf("\tConsole.Println(strconv.Quote(strings.ToUpper(%s)))\n", g.call())
	case 3:
		return fmt.Sprintf("\tfor i%d in 0..2 {\n\t\tlet w%d = %s\n\t\tConsole.Println(\"\\(i%d) \\(strconv.Quote(w%d))\")\n\t}\n", j, j, g.call(), j, j)
	case 4:
		// A let of a constant as the operand: it folds through the let.
		return fmt.Sprintf("\tlet s%d = %s\n\tConsole.Println(strconv.Quote(strings.ToLower(s%d)))\n", j, g.lit(), j)
	case 5:
		// A let mut bound to a constant and then written: not a constant.
		return fmt.Sprintf("\tlet mut m%d = %s\n\tm%d = m%d + \"x\"\n\tConsole.Println(strconv.Quote(m%d))\n", j, g.lit(), j, j, j)
	default:
		return fmt.Sprintf("\tConsole.Println(show(%s))\n", g.lit())
	}
}
