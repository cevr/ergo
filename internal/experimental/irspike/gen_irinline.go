package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateInline is a program whose loops call small Ergo bodies that the
// IR inliner (RED17, lower/ir_forms_inline.go) copies to their sites, as
// the text path's OPT4a does:
//   - generic helpers on a pointer to a generic record (lru's shape: a
//     method that reads, one that writes through the pointer, one with no
//     result), non-generic helpers that call other bodies (no Go leaf),
//     and chains of them, so a copy holds sites of its own (nested);
//   - early returns from an if, so a copy's returns jump past its block
//     (bump's, whose threshold the loop's operands cross);
//   - a copy `let z = w` of a local that changes after it, so the pass
//     that drops copies must keep this one;
//   - an operand that is no local (a field, an arithmetic), so a
//     parameter is bound; and a local the callee only reads, so it
//     stands for itself;
//   - a value parameter the callee copies into a let mut and changes, so
//     the caller's variable must not change; and a generic helper that
//     changes its copy of a slice field (a package call, slices.Clone,
//     whose type arguments name the callee's type parameter);
//   - a fallible helper (fails Gone) whose catch the loop takes, so a
//     copy's failure jumps to the arm that takes it (FAIL-INLINE); and a
//     fallible leaf (parity, which Go would inline) whose arm binds the
//     failure, so the IR copies it for its failure's jump and the arm's
//     binding is the variant itself;
//   - a match on an inlined helper that returns an Option (one binding
//     Some, one with a wildcard arm), so each return jumps to its arm
//     with no Option built (IR-GETMATCH); and one whose tail is a match
//     on a Map's Get (lru's Cache.Get), whose arms' values reach the site
//     through the copy's result local;
//   - a call of a body the inliner leaves (it loops) whose value a
//     statement drops, so it calls the variant with no result (IR-DROP);
//   - a call whose result a statement drops (let _ =), one whose result
//     sets a let mut, and one whose result a let binds;
//   - lru's arena shape (DROPPED-IR): a helper takes a value out of a std
//     arena (Free, whose copy holds vacate's: a call inside a std body,
//     IR-STDINL; its result's zero value set dead, IR-DEADZERO) and puts
//     a record literal in its freed slot through a field (Put's reuse:
//     a stored call and a stored literal, IR-STOREFIELDS), all generic,
//     so a copy's stored call and literal spell the site's types (a
//     field of type T read from old gets a temporary of the site's
//     type); the loop
//     drops that helper's value once and reads it once;
//   - the variant with no result of the looping body above is the IR's
//     (IR-DROPBODY), not the emitter's text;
//   - in odd seeds a defect inside a nested inlined body after the loop
//     (an index past the end, or Unreachable), so the defect report's
//     frames come from the inline table.
//
// main prints the totals; a copy that binds, renames, substitutes or
// returns wrong changes them, and a defect report that loses a frame
// changes the run's stderr.
func GenerateInline(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x69726e6c696e6531))
	n := func(k int) int { return r.IntN(k) }
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateInline\n\nimport arena\n\n")
	b.WriteString("type Acc[T] { items []T, hits int, last T, idx Map[int, int] }\n\n")
	b.WriteString("type Pair { a int, b int }\n\n")
	b.WriteString("type Gone { At int }\n\n")
	b.WriteString("type Slot[T] { v T, w T, n int }\n\n")
	b.WriteString("type Holder[T] { r arena.Ref[Slot[T]] }\n\n")
	b.WriteString("func take[T](ar mut arena.Of[Slot[T]], r arena.Ref[Slot[T]]) Slot[T] {\n\tlet v = ar.Free(r) catch {\n\tcase arena.Stale:\n\t\tUnreachable(\"take of a freed ref\")\n\t}\n\tv\n}\n\n")
	fmt.Fprintf(&b, "func cycle[T](ar mut arena.Of[Slot[T]], h mut Holder[T], x T, i int) Slot[T] {\n\tlet old = take(ar, h.r)\n\th.r = ar.Put(Slot[T]{v: x, w: old.v, n: old.n + i - %d})\n\told\n}\n\n", 1+n(9))
	fmt.Fprintf(&b, "func fetch[T](a mut Acc[T], i int) T fails Gone {\n\tif i >= len(a.items) {\n\t\treturn Gone{At: i}\n\t}\n\ta.hits = a.hits + %d\n\ta.items[i]\n}\n\n", 1+n(3))
	fmt.Fprintf(&b, "func parity(i int) int fails Gone {\n\tif i %% %d == 0 {\n\t\treturn Gone{At: i}\n\t}\n\ti * 2\n}\n\n", 2+n(3))
	fmt.Fprintf(&b, "func at[T](a mut Acc[T], i int) T {\n\ta.hits = a.hits + 1\n\ta.items[i %% len(a.items)]\n}\n\n")
	b.WriteString("func sumTo(a mut Acc[int], n int) int {\n\tlet mut t = 0\n\tfor i in 0..n {\n\t\tt = t + a.items[i % len(a.items)]\n\t}\n\ta.hits = a.hits + 1\n\tt\n}\n\n")
	b.WriteString("func peek[T](a mut Acc[T], i int) Option[T] {\n\tmatch a.idx.Get(i) {\n\tcase Some[int] as v:\n\t\ta.hits = a.hits + 1\n\t\tSome{Value: a.items[v.Value % len(a.items)]}\n\tcase None:\n\t\tNone\n\t}\n}\n\n")
	fmt.Fprintf(&b, "func look[T](a mut Acc[T], i int) Option[T] {\n\tif i >= len(a.items) {\n\t\treturn None\n\t}\n\ta.hits = a.hits + %d\n\tSome{Value: a.items[i]}\n}\n\n", 1+n(3))
	b.WriteString("func first[T](a mut Acc[T], i int) T {\n\tlet mut xs = a.items\n\txs[0] = xs[i % len(xs)]\n\txs[0]\n}\n\n")
	fmt.Fprintf(&b, "func bump[T](a mut Acc[T], by int) {\n\tif by > %d {\n\t\ta.hits = a.hits + by - %d\n\t\treturn\n\t}\n\ta.hits = a.hits + by\n}\n\n", 1+n(2), 1+n(3))
	fmt.Fprintf(&b, "func keep[T](a mut Acc[T], v T) T {\n\ta.last = v\n\ta.bump(%d)\n\tv\n}\n\n", 1+n(4))
	fmt.Fprintf(&b, "func clamp(v int, lo int, hi int) int {\n\tif v < lo {\n\t\treturn lo\n\t}\n\tif v > hi {\n\t\treturn hi\n\t}\n\tv\n}\n\n")
	fmt.Fprintf(&b, "func pick(x int, y int) int {\n\tlet c = clamp(x - y, %d, %d)\n\tif c == 0 {\n\t\treturn y\n\t}\n\tc * %d\n}\n\n", -n(50), 20+n(80), 1+n(3))
	fmt.Fprintf(&b, "func shift(p Pair, d int) int {\n\tlet mut q = p\n\tq.a = q.a + d\n\tclamp(q.a * q.b, %d, %d)\n}\n\n", -n(1000), 500+n(2000))
	fmt.Fprintf(&b, "func step(a mut Acc[int], i int, x int) int {\n\tlet v = a.at(i + x)\n\tlet w = a.keep(pick(v, i))\n\tif w > %d {\n\t\treturn w - a.hits\n\t}\n\tw + clamp(v, 0, %d)\n}\n\n", 10+n(40), 5+n(30))
	defect := seed%2 == 1
	if defect {
		if n(2) == 0 {
			b.WriteString("func deep(a mut Acc[int], i int) int {\n\tlet v = a.at(0)\n\ta.items[i + v * 0]\n}\n\n")
		} else {
			b.WriteString("func deep(a mut Acc[int], i int) int {\n\tif i > len(a.items) {\n\t\tUnreachable(\"deep past \\(i)\")\n\t}\n\ta.at(i)\n}\n\n")
		}
		b.WriteString("func outer(a mut Acc[int], i int) int {\n\tlet v = deep(a, i)\n\tv + 1\n}\n\n")
	}
	b.WriteString("func main() needs Console {\n")
	items := make([]string, 3+n(6))
	for i := range items {
		items[i] = fmt.Sprint(n(100) - 20)
	}
	fmt.Fprintf(&b, "\tlet mut a = Acc[int]{items: []int{%s}, hits: 0, last: 0, idx: Map[int, int]{1: 0, 4: 2, 6: 1}}\n", strings.Join(items, ", "))
	fmt.Fprintf(&b, "\tlet mut s = Acc[string]{items: []string{\"x\", \"yy\", \"zzz\"}, hits: 0, last: \"\", idx: Map[int, int]{0: 2, 2: 1}}\n")
	fmt.Fprintf(&b, "\tlet p = Pair{a: %d, b: %d}\n", n(30), 1+n(9))
	b.WriteString("\tlet mut total = 0\n\tlet mut text = 0\n")
	b.WriteString("\tlet mut ar = arena.New[Slot[int]]()\n")
	fmt.Fprintf(&b, "\tlet mut h = Holder[int]{r: ar.Put(Slot[int]{v: %d, w: 0, n: %d})}\n", n(20), n(20))
	fmt.Fprintf(&b, "\tfor i in 0..%d {\n", 50+n(200))
	b.WriteString("\t\ttotal = total + step(&a, i, total % 7)\n")
	b.WriteString("\t\tlet _ = s.keep(s.at(i))\n")
	b.WriteString("\t\ttext = text + len(s.at(i + total % 3))\n")
	b.WriteString("\t\ta.bump(i % 5)\n")
	b.WriteString("\t\tlet _ = sumTo(&a, i % 4)\n\t\tlet _ = sumTo(&a, 2) + 0\n")
	b.WriteString("\t\tmatch a.look(i % (len(a.items) + 2)) {\n\t\tcase Some[int] as v:\n\t\t\ttotal = total + v.Value\n\t\tcase None:\n\t\t\ttotal = total - 1\n\t\t}\n")
	b.WriteString("\t\tmatch a.peek(i % 9) {\n\t\tcase Some[int] as v:\n\t\t\ttotal = total + v.Value * 2\n\t\tcase None:\n\t\t\ttotal = total + 3\n\t\t}\n")
	b.WriteString("\t\tmatch s.look(i % 5) {\n\t\tcase None:\n\t\t\ttext = text + 2\n\t\tcase _:\n\t\t\ttext = text + 1\n\t\t}\n")
	b.WriteString("\t\tlet fs = s.first(i)\n\t\tlet fa = a.first(i + 2)\n\t\ttext = text + len(fs) + fa - a.items[0]\n")
	b.WriteString("\t\tlet mut w = a.at(i + 1)\n\t\tlet z = w\n\t\tw = w + 1\n\t\ttotal = total + z * 2 + w\n")
	b.WriteString("\t\tlet got = a.fetch(i % (len(a.items) + 2)) catch {\n\t\tcase Gone:\n\t\t\t-1\n\t\t}\n")
	b.WriteString("\t\ttotal = total + got\n")
	b.WriteString("\t\tlet par = parity(i) catch {\n\t\tcase Gone as g:\n\t\t\tg.At + 1\n\t\t}\n\t\ttotal = total + par\n")
	b.WriteString("\t\ttotal = total + shift(p, i) + p.a\n")
	b.WriteString("\t\tlet _ = cycle(&ar, &h, i, i)\n\t\tlet o = cycle(&ar, &h, total % 11, i)\n\t\ttotal = total + o.v + o.w - o.n\n")
	b.WriteString("\t}\n")
	b.WriteString("\tConsole.Println(\"total \\(total) text \\(text) hits \\(a.hits) \\(s.hits) last \\(a.last) \\(s.last) p \\(p.a)\")\n")
	if defect {
		fmt.Fprintf(&b, "\tConsole.Println(\"deep \\(outer(&a, len(a.items) + %d))\")\n", 1+n(5))
	}
	b.WriteString("}\n")
	return b.String()
}
