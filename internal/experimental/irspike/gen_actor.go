package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateActor is a program that starts actors on machines (hidden
// arguments, the graph: std actor's launch passes the machine's graph to
// the runtime's start, v1.Graph): a seeded machine over a counter state
// and number signals that emits, ignores, finishes or enters by the
// signal and the state; runA starts it with actor.StartMachine, sends
// seeded signals (a Send after Done fails Stopped), and prints the
// actor's state and the outputs its sink heard, in order. runW starts a
// machine whose work is the only sender (the send std launch gives the
// work, wrapped for the uniform shape: givenFunc) and prints the output
// of the Done its last signal steps, which the sink hands main through a
// queue.
func GenerateActor(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x6163746f720a0b03))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateActor\n\nimport actor\nimport machines\nimport queue\n\n")
	b.WriteString("type St { n int }\n\ntype Sig { v int }\n\n")
	emit, ignore, done := 2+g.n(3), 30+g.n(20), 200+g.n(300)
	fmt.Fprintf(&b, "func stepA(s St, e Sig) Decision[St, int] {\n\tif e.v %% %d == 0 {\n\t\treturn Emit[St, int]{Next: St{n: s.n + e.v}, Output: s.n}\n\t}\n\tif e.v > %d {\n\t\treturn Ignore\n\t}\n\tif s.n > %d {\n\t\treturn Done[int]{Output: s.n - e.v}\n\t}\n\tEnter[St]{Next: St{n: s.n*2 + e.v}}\n}\n\n", emit, ignore, done)
	fmt.Fprintf(&b, "type A machine[St, Sig] {\n\tinitial: St{n: %d},\n\tstep:    stepA,\n}\n\n", 1+g.n(9))
	b.WriteString("func planA() Machine[St, Sig, int] { A{} }\n\n")
	b.WriteString("func runA(signals []Sig) string needs Scheduler {\n\tlet a = actor.StartMachine(planA(), 1, func(o int) {})\n\tlet mut refused = 0\n\tfor e in signals {\n\t\ta.Send(e) catch {\n\t\tcase actor.Stopped:\n\t\t\trefused = refused + 1\n\t\t}\n\t}\n\tlet s = a.State()\n\ta.Stop()\n\t\"actor \\(s.n) refused \\(refused)\"\n}\n\n")
	// W's work is the only sender: it sends seeded signals, then -1, whose
	// step is Done; every other step Stays or Ignores, which keep the
	// entry and its work (no signal of it is dropped), so the state at the
	// end depends only on the signals, in the one order the work sent them.
	var ws []string
	for j := 0; j < 3+g.n(8); j++ {
		ws = append(ws, fmt.Sprintf("%d", g.n(60)))
	}
	keep := 2 + g.n(4)
	fmt.Fprintf(&b, "func stepW(s St, e Sig) Decision[St, int] {\n\tif e.v < 0 {\n\t\treturn Done[int]{Output: s.n}\n\t}\n\tif e.v %% %d == 0 {\n\t\treturn Ignore\n\t}\n\tStay[St]{Next: St{n: s.n*3 + e.v}}\n}\n\n", keep)
	fmt.Fprintf(&b, "func workW(s St) Option[machines.Work[Sig, Scheduler]] {\n\tSome[machines.Work[Sig, Scheduler]]{Value: machines.Work[Sig, Scheduler]{Start: func(send entry func(e Sig)) needs Scheduler {\n\t\tfor v in []int{%s, -1} {\n\t\t\tsend(Sig{v: v})\n\t\t}\n\t}}}\n}\n\n", strings.Join(ws, ", "))
	fmt.Fprintf(&b, "type W machine[St, Sig] {\n\tinitial: St{n: %d},\n\tstep:    stepW,\n\twork:    workW,\n}\n\n", 1+g.n(9))
	b.WriteString("func runW() string needs Scheduler {\n\tlet q = queue.New[int](1)\n\tlet a = actor.StartMachine(W{}, 1, func(o int) {\n\t\tq.Push(o) catch {\n\t\tcase queue.Closed:\n\t\t}\n\t})\n\tlet n = q.Pop() catch {\n\tcase queue.Closed:\n\t\t-1\n\t}\n\ta.Stop()\n\t\"work \\(n)\"\n}\n\n")
	b.WriteString("func main() needs Console | Ambient {\n")
	b.WriteString("\twith context { Scheduler: NewLiveScheduler() } {\n")
	for i := 0; i < 3; i++ {
		var sig []string
		for j := 0; j < 3+g.n(8); j++ {
			sig = append(sig, fmt.Sprintf("Sig{v: %d}", g.n(60)))
		}
		fmt.Fprintf(&b, "\t\tConsole.Println(\"%d: \\(runA([]Sig{%s}))\")\n", i, strings.Join(sig, ", "))
	}
	b.WriteString("\t\tConsole.Println(runW())\n")
	b.WriteString("\t}\n}\n")
	return b.String()
}
