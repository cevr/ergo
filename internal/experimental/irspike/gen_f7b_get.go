package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GetShape is one drawn match on m.Get(k) (F7 lane B): where the match
// stands, how Some's arm and None's arm are written, and which comes first.
type GetShape struct {
	Context, Some, None string
	SomeFirst           bool
}

// The shapes GenerateGetMatch draws, as lower's TestGetMatchAgrees does: a
// context places the match (the tail, a let, a parenthesized subject, a
// loop whose arms break and continue, the Option bound first and read
// after); Some's arm binds the variant, binds its value, matches it with
// no binding, tests it, or ("both") takes None too in one case; None's arm
// is None, None bound, a wildcard, a test of the Option or a binding of
// the whole Option.
var (
	getContexts = []string{"tail", "let", "paren", "loop", "after"}
	getSomes    = []string{"as", "record", "recordWild", "test", "both"}
	getNones    = []string{"none", "noneAs", "wild", "option", "bind"}
)

// Fused reports whether the lowering reads the Map with the comma-ok form:
// the subject is the call itself and no arm binds the whole Option.
func (s GetShape) Fused() bool {
	return s.Context != "after" && (s.Some == "both" || s.None != "bind")
}

// GenerateGetMatch is a program of functions f0..f(n-1), each a match on
// m.Get(k) of a drawn shape, called from main on present and missing keys,
// so an arm taken for the wrong variant, a value read wrong or a break that
// leaves the wrong statement changes the output. Its main then takes a
// drawn key out of m and calls the prelude's Put, Append and Get as values,
// so their bodies (the lowering's intrinsics, ir_intrinsic.go) run and a
// wrong one changes the output. It returns the shapes.
func GenerateGetMatch(seed uint64) (string, []GetShape) {
	r := rand.New(rand.NewPCG(seed, seed^0x9e3779b97f4a7c15))
	pick := func(xs []string) string { return xs[r.IntN(len(xs))] }
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateGetMatch\n\nfunc gone(_ None) int {\n\t100\n}\n\nfunc took(o Option[int]) int {\n\tmatch o {\n\tcase Some[int] as s:\n\t\ts.Value\n\tcase None:\n\t\t-1\n\t}\n}\n\n")
	var shapes []GetShape
	for i := 0; i < 10; i++ {
		s := GetShape{Context: pick(getContexts), Some: pick(getSomes), None: pick(getNones)}
		// A wildcard, a test of the Option or a binding takes both
		// variants, so it comes last.
		s.SomeFirst = s.None == "wild" || s.None == "option" || s.None == "bind" || r.IntN(2) == 0
		shapes = append(shapes, s)
		b.WriteString(s.fn(i, 1+r.IntN(5)))
		b.WriteString("\n")
	}
	b.WriteString("func main() needs Console {\n")
	fmt.Fprintf(&b, "\tlet m = Map[string, int]{\"a\": %d, \"b\": %d, \"c\": 0}\n", r.IntN(4), 2+r.IntN(5))
	for i := range shapes {
		for _, k := range []string{"a", "b", "c", "z"} {
			fmt.Fprintf(&b, "\tlet r%d%s = f%d(m, %q)\n", i, k, i, k)
		}
		fmt.Fprintf(&b, "\tConsole.Println(\"f%d: \\(r%da) \\(r%db) \\(r%dc) \\(r%dz)\")\n", i, i, i, i, i)
	}
	fmt.Fprintf(&b, "\tlet o, rest = m.Take(%q)\n\tlet m2 = rest.Put(\"q\", %d)\n\tlet xs = []int{%d}.Append(len(m2))\n", pick([]string{"a", "b", "c", "z"}), r.IntN(9), r.IntN(9))
	b.WriteString("\tConsole.Println(\"tail: \\(took(o)) \\(len(rest)) \\(len(m)) \\(took(m2.Get(\"q\"))) \\(took(m2.Get(\"z\"))) \\(xs[0]) \\(xs[1])\")\n}\n")
	return b.String(), shapes
}

// arms is the match's arms; a loop's arms are statements, the others
// values. c is the function's constant.
func (s GetShape) arms(ind string, c int) string {
	loop := s.Context == "loop"
	val := map[string]string{"as": "s.Value", "record": "x", "recordWild": "1", "test": "2", "both": "4"}[s.Some]
	head := map[string]string{"as": "case Some[int] as s:", "record": "case Some{x}:", "recordWild": "case Some{_}:", "test": "case Some[int]:", "both": "case Some[int], None:"}[s.Some]
	var some, none string
	switch {
	case loop && s.Some == "both":
		some = head + "\n" + ind + "\ttotal = total + " + val + " + i\n"
	case loop:
		some = head + "\n" + ind + "\tif " + val + " > " + fmt.Sprint(c) + " {\n" + ind + "\t\tbreak\n" + ind + "\t}\n" + ind + "\ttotal = total + " + val + " + i\n"
	default:
		some = head + "\n" + ind + "\t" + val + " * 3 + " + fmt.Sprint(c) + "\n"
	}
	nhead := map[string]string{"none": "case None:", "noneAs": "case None as n:", "wild": "case _:", "option": "case Option[int]:", "bind": "case opt:"}[s.None]
	// `None as n` is read by a call (gone): a comparison of n with None
	// is equality on a union, another family's (lane CS).
	bound := map[string]string{"bind": "opt"}[s.None]
	switch {
	case loop && bound != "":
		none = nhead + "\n" + ind + "\tif " + bound + " == None {\n" + ind + "\t\ttotal = total + 100\n" + ind + "\t}\n" + ind + "\tcontinue\n"
	case loop && s.None == "noneAs":
		none = nhead + "\n" + ind + "\ttotal = total + gone(n)\n" + ind + "\tcontinue\n"
	case s.None == "noneAs":
		none = nhead + "\n" + ind + "\tgone(n) - " + fmt.Sprint(c) + "\n"
	case loop:
		none = nhead + "\n" + ind + "\ttotal = total + 100\n" + ind + "\tcontinue\n"
	case bound != "":
		none = nhead + "\n" + ind + "\tif " + bound + " == None {\n" + ind + "\t\t-2\n" + ind + "\t} else {\n" + ind + "\t\t-3\n" + ind + "\t}\n"
	default:
		none = nhead + "\n" + ind + "\t-" + fmt.Sprint(c+7) + "\n"
	}
	if s.Some == "both" {
		return ind + some
	}
	if s.SomeFirst {
		return ind + some + ind + none
	}
	return ind + none + ind + some
}

// fn is f<i>(m, k) int, whose body is the shape's match.
func (s GetShape) fn(i, c int) string {
	body := ""
	switch s.Context {
	case "tail":
		body = "\tmatch m.Get(k) {\n" + s.arms("\t", c) + "\t}\n"
	case "let":
		body = "\tlet r = match m.Get(k) {\n" + s.arms("\t", c) + "\t}\n\tr * 2\n"
	case "paren":
		body = "\tmatch (m.Get(k)) {\n" + s.arms("\t", c) + "\t}\n"
	case "loop":
		body = "\tlet mut total = 0\n\tfor i in 0..3 {\n\t\tmatch m.Get(k) {\n" + s.arms("\t\t", c) + "\t\t}\n\t\ttotal = total + 1\n\t}\n\ttotal\n"
	case "after":
		body = "\tlet o = m.Get(k)\n\tlet r = match o {\n" + s.arms("\t", c) + "\t}\n\tif o == None {\n\t\tr + 1000\n\t} else {\n\t\tr\n\t}\n"
	}
	return fmt.Sprintf("func f%d(m Map[string, int], k string) int {\n%s}\n", i, body)
}
