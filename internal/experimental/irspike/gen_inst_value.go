package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// instValueFuncs are GenerateInstValue's functions that must each get an
// IR body in every seed.
// counted reads s.Put.Calls(), a std call with a converted result (another
// reason): it runs, but needs no IR body.
var instValueFuncs = []string{"bound", "passed", "stored", "made", "single", "answer", "viaStore"}

// instValueLines are the functions main prints each of, before scripted.
var instValueLines = []string{"bound", "passed", "stored", "made", "single"}

// GenerateInstValue is a program of the forms the small reasons held
// (SMALL-REASONS): a generic function named at its type arguments as a
// value, first[int, string] and wrap[int] (one argument or several: the
// reasons "index form" and "index of a non-slice"), bound to a let,
// passed to a function, stored in a record's field and named inside a
// generic function at its own type parameters (std ui's PlainCrashes); and
// a testing.Script's operation fields, s.Get.Answer and s.Put.Calls() (the
// reason "selector that is not a field"). Seeded constants and the order
// of the uses vary; every value is read into what main prints, so a value
// of the wrong instance or a field of the wrong operation changes it.
func GenerateInstValue(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x2f6b1d9e83c4a705))
	k, m := 1+r.IntN(9), 2+r.IntN(7)
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateInstValue\nimport testing\n\n")
	b.WriteString("type Store {\n\tGet(k int) int,\n\tPut(k int, v int),\n}\n\n")
	b.WriteString("type Pick[A, B] { F func(a A, b B) A, G func(a A, b B) B }\n\n")
	b.WriteString("func first[A, B](a A, b B) A {\n\ta\n}\n\n")
	b.WriteString("func second[A, B](a A, b B) B {\n\tb\n}\n\n")
	b.WriteString("func wrap[A](x A) []A {\n\t[]A{x, x}\n}\n\n")
	fmt.Fprintf(&b, "func apply(f func(a int, b string) int, a int, b string) int {\n\tf(a, b) * %d\n}\n\n", k)
	b.WriteString("func mk[A, B]() Pick[A, B] {\n\tPick[A, B]{F: first[A, B], G: second[A, B]}\n}\n\n")
	fmt.Fprintf(&b, "func bound(n int) int {\n\tlet f = first[int, string]\n\tlet g = second[string, int]\n\tf(n, \"x\") + g(\"y\", n * %d)\n}\n\n", m)
	b.WriteString("func passed(n int) int {\n\tapply(first[int, string], n, \"z\") + apply(func(a int, b string) int { len(b) }, n, \"zz\")\n}\n\n")
	b.WriteString("func stored(n int) int {\n\tlet p = Pick[int, string]{F: first[int, string], G: second[int, string]}\n\tp.F(n, \"q\") * 3 + len(p.G(n, \"qq\"))\n}\n\n")
	b.WriteString("func made(n int) int {\n\tlet p = mk[int, string]()\n\tlet q = mk[string, int]()\n\tp.F(n, \"w\") + q.G(\"w\", n + 1) * 7\n}\n\n")
	fmt.Fprintf(&b, "func single(n int) int {\n\tlet w = wrap[int]\n\tlet ws = wrap[string]\n\tlen(w(n)) * %d + w(n)[1] + len(ws(\"s\")[0])\n}\n\n", k)
	b.WriteString("func useStore(n int) int needs Store {\n\tStore.Put(n, n * 2)\n\tStore.Get(n) + Store.Get(n + 1)\n}\n\n")
	// The Script's fields are read in functions of their own: answer gets
	// an IR body; counted's Calls() is a std call with a converted result.
	// scripted builds the Script (a record literal without every field,
	// another reason) and calls them.
	fmt.Fprintf(&b, "func answer(s testing.Script[Store], n int) {\n\ts.Get.Answer(func(k int) int { k * %d + n })\n}\n\n", m)
	b.WriteString("func counted(s testing.Script[Store]) int {\n\tlen(s.Put.Calls()) * 10 + len(s.Get.Calls())\n}\n\n")
	// viaStore converts the Script to Store's operations (G6: operations
	// conversion of a script) and calls them through useStore.
	b.WriteString("func viaStore(s testing.Script[Store], n int) int {\n\twith context { Store: s } { useStore(n) }\n}\n\n")
	b.WriteString("func scripted(n int) int {\n\tlet s = testing.Script[Store]{}\n\tanswer(s, n)\n\tlet got = viaStore(s, n)\n\tgot * 100 + counted(s)\n}\n\n")
	// scripted is last: the evaluator does not run a Script literal yet,
	// so it stops there, after every instance value's line.
	values := instValueLines
	order := r.Perm(len(values))
	b.WriteString("func main() needs Console {\n")
	for _, in := range []int{0, 1, 5, -3} {
		for _, i := range order {
			f := values[i]
			fmt.Fprintf(&b, "\tConsole.Println(\"%s(%d) \\(%s(%d))\")\n", f, in, f, in)
		}
	}
	for _, in := range []int{0, 1, 5, -3} {
		fmt.Fprintf(&b, "\tConsole.Println(\"scripted(%d) \\(scripted(%d))\")\n", in, in)
	}
	b.WriteString("}\n")
	return b.String()
}
