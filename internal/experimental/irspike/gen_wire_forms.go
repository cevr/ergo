package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// formSites are GenerateWireForms's callers, with an IR body in every
// seed, by their Go names (their first parameter is an F); the codec
// functions are checked by their CodecText (TestIRWireFormsMatchSource).
var formSites = []string{"F.viaText", "F.viaCounter"}

// GenerateWireForms is a program that encodes std json's declared wire
// forms on two cell writers, json's Text and Counter (GenerateOmittable),
// PORT-WIRE r2:
//   - json.Value, the bare form: a switch on its variant with no tag,
//     json.Null as Null, a one-field variant (Boolean, Str, Array) as its
//     field, Num and Object as themselves;
//   - json.Num, the number-text form: Number(Wire's spelling);
//   - json.Object, the members form: its entries in order, repeated keys
//     kept;
//   - json.Nullable[int] and json.Nullable[time.Time], the nullable form
//     of an instance: Null or the payload.
//
// Values nest to depth 3, so a Value's Array and Object reach Value again
// (a codec function's call of itself).
func GenerateWireForms(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x6c8e9cf570932bd5))
	n := func(k int) int { return r.IntN(k) }
	str := func() string { return []string{"\"a\"", "\"c&d\"", "\"<b>\"", "\"\"", "\"é\\n\""}[n(5)] }
	num := func() string {
		if n(2) == 0 {
			return fmt.Sprintf("json.IntNumber(%d)", int64(n(2_000_001))-1_000_000)
		}
		return fmt.Sprintf("numOf(\"%s\")", []string{"0", "-1.5", "2e10", "3.25E-3", "17"}[n(5)])
	}
	var value func(d int) string
	members := func(d int) string {
		var ms []string
		for i := n(4); i > 0; i-- {
			ms = append(ms, fmt.Sprintf("json.Member{Key: %s, Value: %s}", str(), value(d+1)))
		}
		return "json.Object{Members: []json.Member{" + strings.Join(ms, ", ") + "}}"
	}
	value = func(d int) string {
		k := n(6)
		if d >= 3 && k >= 4 {
			k = n(4)
		}
		switch k {
		case 0:
			return "json.Null"
		case 1:
			return fmt.Sprintf("json.Boolean{Value: %v}", n(2) == 0)
		case 2:
			return num()
		case 3:
			return fmt.Sprintf("json.Str{Value: %s}", str())
		case 4:
			var xs []string
			for i := n(4); i > 0; i-- {
				xs = append(xs, value(d+1))
			}
			return "json.Array{Items: []json.Value{" + strings.Join(xs, ", ") + "}}"
		}
		return members(d)
	}
	nullInt := func() string {
		if n(2) == 0 {
			return "json.Null"
		}
		return fmt.Sprintf("json.NonNull{Value: %d}", n(2001)-1000)
	}
	nullAt := func() string {
		if n(2) == 0 {
			return "json.Null"
		}
		return fmt.Sprintf("json.NonNull{Value: time.Unix(%d, 0)}", n(1_700_000_000))
	}
	list := func(f func() string) string {
		var xs []string
		for i := n(3); i > 0; i-- {
			xs = append(xs, f())
		}
		return strings.Join(xs, ", ")
	}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateWireForms\n\nimport json\nimport time\n\n")
	b.WriteString(counterDecls)
	b.WriteString(formDecls)
	b.WriteString("func viaText(f F) string {\n\tlet w = json.NewText()\n\tencode(f, w)\n\tw.Written()\n}\n\n")
	b.WriteString("func viaCounter(f F) string {\n\tlet w = newCounter()\n\tencode(f, w)\n\tw.Written()\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	for i := 0; i < 3; i++ {
		f := fmt.Sprintf("F{V: %s, N: %s, O: %s, I: %s, At: %s, Vs: []json.Value{%s}, Is: []json.Nullable[int]{%s}}",
			value(0), num(), members(1), nullInt(), nullAt(), list(func() string { return value(2) }), list(nullInt))
		fmt.Fprintf(&b, "\tlet f%d = %s\n\tConsole.Println(viaText(f%d))\n\tConsole.Println(viaCounter(f%d))\n", i, f, i, i)
	}
	b.WriteString("}\n")
	return b.String()
}

// formDecls are GenerateWireForms's F, which holds each form, and numOf,
// a Num from a valid spelling.
const formDecls = `type F { V json.Value, N json.Num, O json.Object, I json.Nullable[int], At json.Nullable[time.Time], Vs []json.Value, Is []json.Nullable[int] }

func numOf(s string) json.Num {
	json.ParseNum(s) catch {
	case _:
		json.IntNumber(0)
	}
}

`
