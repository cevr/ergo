package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// witcopyGenerics are GenerateWitnessCopy's generic functions whose
// copies for a known witness (witspec.go) take IR bodies (G4); each is
// called at both Rect and Sq, so each has two copies.
var witcopyGenerics = []string{"scaledK", "areaK", "chainK"}

// GenerateWitnessCopy is a program whose generic functions over an
// operation type, Shape, are called only at named types whose operations
// are package functions, so every call goes to a copy for that known
// witness (witspec.go), and in each copy every operation call is a direct
// call of the implementing function (G4):
//   - scaledK calls an operation with no result (Note), a fallible one
//     under try (Scale) and one with a value (Area);
//   - areaK reads Area of each element of a slice of its type parameter;
//   - chainK passes its known witness on to scaledK and areaK, whose
//     copies for the same type it calls (copy to copy), catches scaledK's
//     failure and Scale's, called on its own value;
//   - bumpK is called at a *Box, a witness whose functions take the
//     pointer: its copy's receiver is a pointer already, never its
//     address (examples/vt's Screen), and Note writes through it, which
//     main prints.
//
// main prints every function at drawn operands for both types, so an
// operation of the other type, a failure lost or a value misread changes
// the output.
func GenerateWitnessCopy(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x6a09e667f3bcc909))
	n := func(k int) int { return r.IntN(k) }
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateWitnessCopy\n\n")
	b.WriteString("type Neg { At int }\n\n")
	b.WriteString("type Shape {\n\tArea() int,\n\tScale(k int) int fails Neg,\n\tNote(k int),\n}\n\n")
	b.WriteString("type Rect { W int, H int } implements Shape\n\ntype Sq { S int } implements Shape\n\ntype Box { B int } implements Shape\n\n")
	fmt.Fprintf(&b, "func Area(r Rect) int {\n\tr.W * r.H + %d\n}\n\n", n(5))
	fmt.Fprintf(&b, "func Scale(r Rect, k int) int fails Neg {\n\tif k < %d {\n\t\tNeg{At: k}\n\t} else {\n\t\tr.W * k + r.H\n\t}\n}\n\n", n(3)-1)
	b.WriteString("func Note(r Rect, k int) {\n\tlet _ = r.W + k\n}\n\n")
	fmt.Fprintf(&b, "func Area(s Sq) int {\n\ts.S * s.S - %d\n}\n\n", n(4))
	fmt.Fprintf(&b, "func Scale(s Sq, k int) int fails Neg {\n\tif k %% %d == 0 {\n\t\tNeg{At: k + 1}\n\t} else {\n\t\ts.S * %d + k\n\t}\n}\n\n", 2+n(3), 1+n(6))
	b.WriteString("func Note(s Sq, k int) {\n\tlet _ = s.S - k\n}\n\n")
	b.WriteString("func scaledK[T Shape](t T, k int) int fails Neg {\n\tt.Note(k)\n\tlet a = try t.Scale(k)\n\ta * 7 + t.Area()\n}\n\n")
	b.WriteString("func areaK[T Shape](xs []T) int {\n\tlet mut s = 0\n\tfor x in xs {\n\t\ts = s * 3 + x.Area()\n\t}\n\ts\n}\n\n")
	b.WriteString("func chainK[T Shape](t T, k int) int {\n\tlet x = scaledK(t, k) catch {\n\tcase Neg as e:\n\t\te.At * 10\n\t}\n\tlet z = t.Scale(k + 1) catch {\n\tcase Neg as e:\n\t\te.At - 50\n\t}\n\tx * 1000 + areaK([]T{t, t}) + t.Area() * z\n}\n\n")
	fmt.Fprintf(&b, "func Area(x mut Box) int {\n\tx.B * %d\n}\n\n", 2+n(4))
	fmt.Fprintf(&b, "func Scale(x mut Box, k int) int fails Neg {\n\tif k > %d {\n\t\tNeg{At: x.B}\n\t} else {\n\t\tx.B + k\n\t}\n}\n\n", n(6))
	b.WriteString("func Note(x mut Box, k int) {\n\tx.B = x.B * 2 + k\n}\n\n")
	b.WriteString("func bumpK[T Shape](t mut T, k int) int {\n\tt.Note(k)\n\tlet z = t.Scale(k) catch {\n\tcase Neg as e:\n\t\te.At - 9\n\t}\n\tt.Note(z)\n\tt.Area() * 100 + z\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	for i := 0; i < 4; i++ {
		rect := fmt.Sprintf("Rect{W: %d, H: %d}", n(7), n(7)-2)
		sq := fmt.Sprintf("Sq{S: %d}", n(9)-3)
		k := n(10) - 3
		fmt.Fprintf(&b, "\tConsole.Println(\"%d: \\(chainK(%s, %d)) \\(chainK(%s, %d)) \\(areaK([]Sq{%s, %s}))\")\n", i, rect, k, sq, k+1, sq, sq)
		fmt.Fprintf(&b, "\tlet mut bx%d = Box{B: %d}\n\tlet v%d = bumpK(&bx%d, %d)\n\tConsole.Println(\"box %d: \\(v%d) \\(bx%d.B)\")\n", i, n(9)-4, i, i, k, i, i, i)
	}
	b.WriteString("}\n")
	return b.String()
}
