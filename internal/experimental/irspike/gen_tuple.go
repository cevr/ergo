package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateTuple is a program of tuple lets and returns (FLIP F4b): each
// function t<i>(a, b) binds pairs from Go's multi-result calls of import
// go math/bits (Add64, Sub64, Mul64), from earlier functions' tuples, from
// tuple literals and if expressions, in both let forms, `let (x, y) = e`
// and `let x, y = e`, with _ for a discarded element; it may return early
// and yields a tuple last. main prints every function's pair at several
// inputs, so a result bound to the wrong name, or an element read from
// the wrong field, changes the output.
func GenerateTuple(seed uint64) string {
	g := &tugen{r: rand.New(rand.NewPCG(seed, seed^0x7b2c4e01d9a35f17))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateTuple\nimport go math/bits\n\n")
	nf := 3 + g.r.IntN(3)
	for i := 0; i < nf; i++ {
		g.pool = []string{"a", "b"}
		fmt.Fprintf(&b, "func t%d(a uint64, b uint64) (uint64, uint64) {\n", i)
		for j, n := 0, 3+g.r.IntN(4); j < n; j++ {
			b.WriteString(g.step(i))
		}
		// Every name is read: the first element folds them, in order,
		// with a multiply so that two names swapped change it.
		fold := g.pool[0]
		for _, v := range g.pool[1:] {
			fold = "(" + fold + ") * 31 + " + v
		}
		fmt.Fprintf(&b, "\t(%s, %s)\n}\n\n", fold, g.mix())
	}
	b.WriteString("func main() needs Console {\n")
	for i := 0; i < nf; i++ {
		for j, in := range []string{"0, 0", "1, 2", "18446744073709551615, 3", "12345678901234567, 9876543210987"} {
			fmt.Fprintf(&b, "\tlet (x%d_%d, y%d_%d) = t%d(%s)\n", i, j, i, j, i, in)
			fmt.Fprintf(&b, "\tConsole.Println(\"t%d(%s) \\(x%d_%d) \\(y%d_%d)\")\n", i, in, i, j, i, j)
		}
	}
	b.WriteString("}\n")
	return b.String()
}

type tugen struct {
	r    *rand.Rand
	pool []string // the uint64 names in scope
	next int
}

func (g *tugen) pick() string { return g.pool[g.r.IntN(len(g.pool))] }

// mix is a uint64 expression of names in scope.
func (g *tugen) mix() string {
	switch g.r.IntN(4) {
	case 0:
		return g.pick()
	case 1:
		return g.pick() + " ^ " + g.pick()
	case 2:
		return g.pick() + " + " + g.pick()
	}
	return g.pick() + " * 3"
}

// fresh is a new name, added to the pool after the step that binds it.
func (g *tugen) fresh() string {
	g.next++
	return fmt.Sprintf("v%d", g.next)
}

// step is one statement of t<fn>: a let of a pair, or an early return.
func (g *tugen) step(fn int) string {
	x, y := g.fresh(), g.fresh()
	var value string
	switch k := g.r.IntN(8); {
	case k == 7:
		// A pair whose first element is a Go call's pair: the let binds
		// the inner pair whole, then destructures it.
		w, z := g.fresh(), g.fresh()
		s := fmt.Sprintf("\tlet (%s, %s) = (bits.Mul64(%s, %s), %s)\n", w, z, g.pick(), g.pick(), g.mix())
		s += fmt.Sprintf("\tlet (%s, %s) = %s\n", x, y, w)
		g.pool = append(g.pool, x, y, z)
		return s
	case k == 0:
		value = fmt.Sprintf("bits.Add64(%s, %s, %d)", g.pick(), g.pick(), g.r.IntN(2))
	case k == 1:
		value = fmt.Sprintf("bits.Sub64(%s, %s, %d)", g.pick(), g.pick(), g.r.IntN(2))
	case k == 2:
		value = fmt.Sprintf("bits.Mul64(%s, %s)", g.pick(), g.pick())
	case k == 3 && fn > 0:
		value = fmt.Sprintf("t%d(%s, %s)", g.r.IntN(fn), g.mix(), g.mix())
	case k == 4:
		value = "(" + g.mix() + ", " + g.mix() + ")"
	case k == 5:
		p, q := g.pick(), g.pick()
		value = fmt.Sprintf("if %s < %s {\n\t\t(%s, %s)\n\t} else {\n\t\t(%s, %s)\n\t}", p, q, p, q, g.mix(), p)
	default:
		// An early return of a pair, then a Go call bound whole and
		// destructured after.
		p := g.pick()
		s := fmt.Sprintf("\tif %s == %d {\n\t\treturn (%s, %s)\n\t}\n", p, g.r.IntN(3), g.mix(), p)
		w := g.fresh()
		s += fmt.Sprintf("\tlet %s = bits.Mul64(%s, %s)\n", w, g.pick(), g.pick())
		s += fmt.Sprintf("\tlet (%s, %s) = %s\n", x, y, w)
		g.pool = append(g.pool, x, y)
		return s
	}
	var s string
	switch g.r.IntN(3) {
	case 0:
		s = fmt.Sprintf("\tlet %s, %s = %s\n", x, y, value)
		g.pool = append(g.pool, x, y)
	case 1:
		s = fmt.Sprintf("\tlet (%s, _) = %s\n", x, value)
		g.pool = append(g.pool, x)
	default:
		s = fmt.Sprintf("\tlet (%s, %s) = %s\n", x, y, value)
		g.pool = append(g.pool, x, y)
	}
	return s
}
