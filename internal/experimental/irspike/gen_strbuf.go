package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateStrBuf is a program whose functions grow let mut strings by
// concatenation in loops (MAPCOPY RU12, the built string; lower/strbuf.go)
// among the statements that read or reset them between concatenations: a
// reset to another string (s = w), a read into a list, len, an
// interpolation, a call that takes it, a read just after a reset, a part
// whose evaluation prints or divides by zero (the program stops there),
// and the look-alikes the form must leave alone: a prepend, a let mut
// declared inside the loop, a closure that reads it. main prints each
// function's text at several inputs, so a buffer that keeps stale bytes,
// shares its array with a string it returned, or appends a part before
// the parts after it ran changes what the program prints.
func GenerateStrBuf(seed uint64) string {
	g := &strBufGen{r: rand.New(rand.NewPCG(seed, seed^0x57b0f))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateStrBuf\n\n")
	b.WriteString("func tag(i int) string needs Console {\n\tConsole.Println(\"tag \\(i)\")\n\t\"<\\(i)>\"\n}\n\n")
	b.WriteString("func cut(z int) string {\n\t\"\\(100 / z)\"\n}\n\n")
	b.WriteString("func twice(s string) string {\n\ts + s\n}\n\n")
	b.WriteString("func join(xs []string) string {\n\tlet mut s = \"\"\n\tfor x in xs {\n\t\ts = s + \"|\" + x\n\t}\n\ts\n}\n\n")
	nf := 3 + g.r.IntN(3)
	for i := 0; i < nf; i++ {
		fmt.Fprintf(&b, "func f%d(n int, z int, w string) string needs Console {\n", i)
		b.WriteString("\tlet mut s = w\n\tlet mut t = \"\"\n\tlet mut out = []string{}\n")
		for s, ns := 0, 2+g.r.IntN(4); s < ns; s++ {
			b.WriteString(g.stmt("\t", s, 0))
		}
		// Each let mut is written at least once (the checker refuses one
		// that is not).
		b.WriteString("\tout = out.Append(t)\n\tt = t + \"!\"\n\ts = s + \"$\"\n")
		b.WriteString("\ts + \"/\" + t + \"/\" + join(out)\n}\n\n")
	}
	b.WriteString("func main() needs Console {\n")
	ins := []string{"0, 1, \"a\"", "1, 2, \"\"", "3, 5, \"bc\"", "6, 7, \"long word\""}
	for i := 0; i < nf; i++ {
		for _, in := range ins {
			fmt.Fprintf(&b, "\tConsole.Println(\"f%d \\(f%d(%s))\")\n", i, i, in)
		}
	}
	// A last input divides by zero where a part calls cut(z).
	for i := 0; i < nf; i++ {
		fmt.Fprintf(&b, "\tConsole.Println(\"f%d \\(f%d(4, 0, \"z\"))\")\n", i, i)
	}
	b.WriteString("}\n")
	return b.String()
}

type strBufGen struct{ r *rand.Rand }

// part is a string operand of a concatenation at statement s.
func (g *strBufGen) part(s int, iv string) string {
	switch g.r.IntN(7) {
	case 0:
		return "\" \""
	case 1:
		return "w"
	case 2:
		if iv != "" {
			return "\"\\(" + iv + ")\""
		}
		return "\"k\""
	case 3:
		return fmt.Sprintf("tag(%d)", s)
	case 4:
		return "cut(z)"
	case 5:
		return "t"
	}
	return "\"\""
}

// stmt is the s-th statement at indent ind, d loops deep; iv is the loop
// variable or "".
func (g *strBufGen) stmt(ind string, s, d int) string {
	return g.stmtIn(ind, s, d, "")
}

func (g *strBufGen) stmtIn(ind string, s, d int, iv string) string {
	v := []string{"s", "t"}[g.r.IntN(2)]
	switch g.r.IntN(12) {
	case 0, 1, 2:
		parts := []string{}
		for k, nk := 0, 1+g.r.IntN(3); k < nk; k++ {
			p := g.part(s, iv)
			if p == v {
				p = "w"
			}
			parts = append(parts, p)
		}
		return fmt.Sprintf("%s%s = %s + %s\n", ind, v, v, strings.Join(parts, " + "))
	case 3:
		p := g.part(s, iv)
		if p == v {
			p = "\"+\""
		}
		return fmt.Sprintf("%s%s += %s\n", ind, v, p)
	case 4:
		return fmt.Sprintf("%s%s = w\n", ind, v)
	case 5:
		return fmt.Sprintf("%sout = out.Append(%s)\n", ind, v)
	case 6:
		return fmt.Sprintf("%sConsole.Println(\"%s \\(len(%s)) \\(%s)\")\n", ind, v, v, v)
	case 7:
		return fmt.Sprintf("%sout = out.Append(twice(%s))\n%s%s = %s + \".\"\n", ind, v, ind, v, v)
	case 8:
		// A prepend: t is then no built string (a look-alike when v is t).
		if v == "t" && g.r.IntN(2) == 0 {
			return fmt.Sprintf("%st = \"^\" + t\n", ind)
		}
		return fmt.Sprintf("%s%s = %s + \"-\"\n", ind, v, v)
	case 9:
		// A let mut inside the loop, grown at its own depth.
		return fmt.Sprintf("%slet mut u%d = %s\n%su%d = u%d + \"u\"\n%sout = out.Append(u%d)\n", ind, s, v, ind, s, s, ind, s)
	}
	if d == 0 && g.r.IntN(4) == 0 {
		// A closure that reads it: v is then no built string.
		return fmt.Sprintf("%slet c%d = func() string { %s + \"c\" }\n%sout = out.Append(c%d())\n", ind, s, v, ind, s)
	}
	if d > 1 {
		return fmt.Sprintf("%s%s = %s + \"x\"\n", ind, v, v)
	}
	var b strings.Builder
	lv := fmt.Sprintf("i%d", s)
	if g.r.IntN(2) == 0 {
		fmt.Fprintf(&b, "%sfor %s in 0..n {\n", ind, lv)
	} else {
		fmt.Fprintf(&b, "%sfor %s in []int{1, 2, n} {\n", ind, lv)
	}
	for j, nj := 0, 1+g.r.IntN(4); j < nj; j++ {
		b.WriteString(g.stmtIn(ind+"\t", 100+s*10+j, d+1, lv))
	}
	fmt.Fprintf(&b, "%s\t%s = %s + \"\\(%s)\"\n%s}\n", ind, v, v, lv, ind)
	return b.String()
}
