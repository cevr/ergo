package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// definedFuncs are GenerateDefined's functions: each gets an IR body in
// every seed (GP-DEFINED, "type defined over a non-basic type": lane B's
// 6cebc4c40, its array half).
var definedFuncs = []string{"atq", "fill"}

// GenerateDefined is a program of values of Quad, a type defined over an
// array (as kmeans' Point of [8]int32): atq reads a Quad by index; fill
// starts from the zero Quad{}, writes some of its elements and returns it.
// Each function folds what it reads with seeded weights, and main prints
// it all, so an element read or written at another position, or a Quad{}
// that is not zero, changes the output.
func GenerateDefined(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x3c6ef372fe94f82b))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateDefined\n\ntype Quad [5]int\n\n")
	// atq: the elements of a Quad at i and at its mirror.
	fmt.Fprintf(&b, "func atq(q Quad, i int) int {\n\tlet j = i %% 5\n\tq[j] * %d + q[4 - j]\n}\n\n", 2+g.n(9))
	// fill: the zero Quad with two elements written, one of them twice.
	fmt.Fprintf(&b, "func fill(n int) Quad {\n\tlet mut q = Quad{}\n\tq[n %% 5] = n * %d\n\tq[(n + %d) %% 5] += n\n\tq\n}\n\n", 1+g.n(7), 1+g.n(4))
	b.WriteString("func main() needs Console {\n")
	for k := 0; k < 3; k++ {
		fmt.Fprintf(&b, "\tlet mut q%d Quad\n", k)
		for i := 0; i < 5; i++ {
			fmt.Fprintf(&b, "\tq%d[%d] = %d\n", k, i, g.n(20))
		}
		fmt.Fprintf(&b, "\tlet f%d = fill(%d)\n", k, g.n(13))
		fmt.Fprintf(&b, "\tConsole.Println(\"%d: \\(atq(q%d, %d)) \\(atq(f%d, %d)) \\(f%d[0]) \\(f%d[4])\")\n", k, k, g.n(9), k, g.n(9), k, k)
	}
	b.WriteString("}\n")
	return b.String()
}
