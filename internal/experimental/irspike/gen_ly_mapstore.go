package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateMapStore is a program whose IR bodies store to a Map's entry
// (F7 LY-PLACE, "place that is not addressable"; ir_mapstore.go): fill
// stores under computed and constant keys, and stores the value of a
// fallible call that moves its own key (bump through &k) after the key
// was read; wipe stores the value of a call that replaces the whole map
// (reset through &m), so the entry goes to the map that was there before;
// boxed stores through a record's Map field; held stores a slice and then
// changes the local it came from (the value rule's copy), which firstOf
// reads back. main prints
// each map's entries in key order, and catches bump's failure.
func GenerateMapStore(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x6c796d6170730a06))}
	n := 4 + g.n(6)
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateMapStore\n\ntype Bad { At int }\n\ntype Box { Tab Map[int, int] }\n\n")
	fmt.Fprintf(&b, "func bump(p *int) int fails Bad {\n\t*p = *p + %d\n\tif *p > %d {\n\t\treturn Bad{At: *p}\n\t}\n\t*p * 3\n}\n\n", 1+g.n(3), 3+g.n(n))
	b.WriteString("func reset(p mut Box) int fails Bad {\n\tp.Tab = Map[int, int]{}\n\tif p.Tab.Get(0) != None {\n\t\treturn Bad{At: 0}\n\t}\n\t7\n}\n\n")
	fmt.Fprintf(&b, "func show(m Map[int, int]) string {\n\tlet mut s = \"\"\n\tfor i in 0..%d {\n\t\tmatch m.Get(i) {\n\t\tcase Some as v:\n\t\t\ts = s + \" \\(i)=\\(v.Value)\"\n\t\tcase None:\n\t\t}\n\t}\n\ts\n}\n\n", n)
	fmt.Fprintf(&b, "func fill(xs []int, k0 int) string fails Bad {\n\tlet mut m = Map[int, int]{}\n\tfor x in xs {\n\t\tm[x %% %d] = x\n\t}\n\tm[%d] = %d\n\tlet mut k = k0\n\tm[k] = try bump(&k)\n\tm[k] = k\n\tshow(m)\n}\n\n", n, g.n(n), 100+g.n(900))
	fmt.Fprintf(&b, "func wipe(xs []int) string fails Bad {\n\tlet mut bx = Box{Tab: Map[int, int]{}}\n\tfor x in xs {\n\t\tbx.Tab[x %% %d] = x * 2\n\t}\n\tlet before = bx.Tab\n\tbx.Tab[%d] = try reset(&bx)\n\t\"\\(show(before)) |\\(show(bx.Tab))\"\n}\n\n", n, g.n(n))
	fmt.Fprintf(&b, "func boxed(xs []int) string {\n\tlet mut bx = Box{Tab: Map[int, int]{}}\n\tfor x in xs {\n\t\tbx.Tab[(x + %d) %% %d] = x + 1\n\t}\n\tshow(bx.Tab)\n}\n\n", g.n(5), n)
	b.WriteString("func firstOf(m Map[int, []int]) int {\n\tmatch m.Get(0) {\n\tcase Some as v:\n\t\tv.Value[0]\n\tcase None:\n\t\t-1\n\t}\n}\n\n")
	b.WriteString("func held(xs []int) int {\n\tlet mut m = Map[int, []int]{}\n\tlet mut ys = xs\n\tm[0] = ys\n\tys[0] = 999\n\tfirstOf(m) + ys[0]\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	for i := 0; i < 3; i++ {
		var xs []string
		for j := 0; j < 1+g.n(8); j++ {
			xs = append(xs, fmt.Sprint(g.n(50)))
		}
		fmt.Fprintf(&b, "\tlet xs%d = []int{%s}\n", i, strings.Join(xs, ", "))
		fmt.Fprintf(&b, "\tlet f%d = fill(xs%d, %d) catch {\n\tcase Bad as e:\n\t\t\"bad \\(e.At)\"\n\t}\n", i, i, g.n(n))
		fmt.Fprintf(&b, "\tlet w%d = wipe(xs%d) catch {\n\tcase Bad as e:\n\t\t\"bad \\(e.At)\"\n\t}\n", i, i)
		fmt.Fprintf(&b, "\tConsole.Println(\"%d:\\(f%d) /\\(w%d) /\\(boxed(xs%d)) / \\(held(xs%d))\")\n", i, i, i, i, i)
	}
	b.WriteString("}\n")
	return b.String()
}
