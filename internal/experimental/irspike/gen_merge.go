package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateMerge is a program whose functions call the same pure and
// impure functions again and again (LAWFFI LF3b, the merge pass;
// lower/ir_merge.go). The callees: sq, a pure Ergo function; inv, a pure
// one that divides by its operand (a defect at 0); noisy, an impure one
// that prints; filepath.Clean, a reviewed-pure Go function; rand.Int64,
// an impure Go function that takes no Ergo context (each function prints
// whether two of its calls differ). The operands:
// a parameter, a `let`, a `let mut` the function writes between two
// calls, a constant, and a loop's own variable. A call stands as a let's
// value, as an operator's operand, inside an if's branch, and inside a
// loop. main prints every function at several inputs, the last of which
// divides by zero, so a call merged with one that did not run first, that
// read a changed operand, or that was impure changes what the program
// prints or where it stops.
func GenerateMerge(seed uint64) string {
	g := &mergeGen{r: rand.New(rand.NewPCG(seed, seed^0x3e26e5ca11ab1e))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateMerge\nimport go path/filepath\nimport go math/rand/v2\n\n")
	b.WriteString("func sq(a int) int {\n\ta * a + 1\n}\n\n")
	b.WriteString("func inv(a int) int {\n\t100 / a\n}\n\n")
	b.WriteString("func noisy(a int) int needs Console {\n\tConsole.Println(\"noisy \\(a)\")\n\ta + 1\n}\n\n")
	nf := 3 + g.r.IntN(3)
	for i := 0; i < nf; i++ {
		fmt.Fprintf(&b, "func h%d(n int, k int, z int, p string) int needs Console | go.Foreign {\n\tlet mut acc = 0\n\tlet mut m = k\n\tm = m + 1\n\tlet c = k + 2\n\tlet lp = len(filepath.Clean(p))\n\tlet r0 = rand.Int64()\n\tlet r1 = rand.Int64()\n\tConsole.Println(\"fresh \\(r0 != r1)\")\n", i)
		pool := g.pool()
		for j, ns := 0, 4+g.r.IntN(6); j < ns; j++ {
			b.WriteString(g.stmt(j, pool))
		}
		b.WriteString("\tacc + c + m + lp\n}\n\n")
	}
	b.WriteString("func main() needs Console | go.Foreign {\n")
	ins := []string{"3, 2, 5, \"a/./b\"", "0, 4, 1, \"/x/../y\"", "2, -1, 4, \"\"", "4, 3, 0, \"c//d\""}
	for i := 0; i < nf; i++ {
		for _, in := range ins[:3] {
			fmt.Fprintf(&b, "\tConsole.Println(\"h%d(%s) \\(h%d(%s))\")\n", i, strings.ReplaceAll(in, "\"", "'"), i, in)
		}
	}
	// The last input divides by zero in a function that calls inv(z): the
	// program stops there, after the same prints.
	for i := 0; i < nf; i++ {
		fmt.Fprintf(&b, "\tConsole.Println(\"h%d(%s) \\(h%d(%s))\")\n", i, strings.ReplaceAll(ins[3], "\"", "'"), i, ins[3])
	}
	b.WriteString("}\n")
	return b.String()
}

type mergeGen struct{ r *rand.Rand }

// pool is a function's few calls, so that they repeat: each an Ergo call
// on an operand, or Clean's length.
func (g *mergeGen) pool() []string {
	ops := []string{"k", "c", "m", "z", "7"}
	var out []string
	for i, n := 0, 2+g.r.IntN(3); i < n; i++ {
		op := ops[g.r.IntN(len(ops))]
		switch g.r.IntN(5) {
		case 0, 1:
			out = append(out, "sq("+op+")")
		case 2:
			out = append(out, "inv("+op+")")
		case 3:
			out = append(out, "noisy("+op+")")
		default:
			out = append(out, "len(filepath.Clean(p))")
		}
	}
	return out
}

// stmt is the j-th statement of a function over its call pool.
func (g *mergeGen) stmt(j int, pool []string) string {
	call := pool[g.r.IntN(len(pool))]
	switch g.r.IntN(7) {
	case 0, 1:
		return fmt.Sprintf("\tlet a%d = %s\n\tacc = acc + a%d\n", j, call, j)
	case 2:
		return fmt.Sprintf("\tacc = acc + %s\n", call)
	case 3:
		// The written operand between two equal calls.
		return fmt.Sprintf("\tlet w%d = sq(m)\n\tm = m + 1\n\tlet x%d = sq(m)\n\tacc = acc + w%d + x%d\n", j, j, j, j)
	case 4:
		return fmt.Sprintf("\tif k > %d {\n\t\tlet b%d = %s\n\t\tacc = acc + b%d\n\t}\n", g.r.IntN(4), j, call, j)
	case 5:
		// The loop's variable as an operand: equal calls inside one
		// iteration merge, across iterations they do not.
		return fmt.Sprintf("\tfor i%d in 0..n {\n\t\tlet c%d = sq(i%d)\n\t\tlet d%d = sq(i%d)\n\t\tacc = acc + c%d + d%d + %s\n\t}\n", j, j, j, j, j, j, j, call)
	default:
		return "\tConsole.Println(\"at \\(acc)\")\n"
	}
}
