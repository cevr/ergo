package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateAdaptBlock is a program of calls of std functions with Ergo
// bodies that take a trailing block (FLIP OPC-ADAPT2): tasks.Retry and
// tasks.Repeat under schedule.Recurs, each from a function the IR lowers,
// the block bumping a Ref and failing until a seeded run. main prints each
// result or failure; a block passed in the wrong place, run the wrong
// number of times, or whose failure is lost, changes the output.
func GenerateAdaptBlock(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x6a09e667f3bcc909))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateAdaptBlock\n\nimport schedule\nimport sync\nimport tasks\nimport time\n\ntype Bad { N int }\n\n")
	b.WriteString("func check(n int, m int) int fails Bad {\n\tif n < m {\n\t\treturn Bad{N: n}\n\t}\n\tn * 10\n}\n\n")
	fmt.Fprintf(&b, "func retried(k int, m int) int needs Scheduler | time.Clock {\n\tlet r = sync.NewRef[int](0)\n\tlet v = tasks.Retry(schedule.Recurs(k)) {\n\t\tr.Update(func(x int) int { x + 1 })\n\t\tcheck(r.Get(), m)\n\t} catch {\n\tcase Bad as e:\n\t\treturn -e.N - %d\n\t}\n\tv\n}\n\n", 100*(1+g.n(9)))
	b.WriteString("func repeated(k int) int needs Scheduler | time.Clock {\n\tlet r = sync.NewRef[int](0)\n\ttasks.Repeat(schedule.Recurs(k)) {\n\t\tr.Update(func(x int) int { x + 2 })\n\t\tr.Get()\n\t}\n}\n\n")
	// Each function is called (an unused one is not lowered), then seeded
	// extras.
	calls := []string{fmt.Sprintf("retried(%d, %d)", g.n(4), g.n(5)), fmt.Sprintf("repeated(%d)", g.n(4))}
	for i, n := 0, g.n(4); i < n; i++ {
		if g.n(2) == 0 {
			calls = append(calls, fmt.Sprintf("retried(%d, %d)", g.n(4), g.n(5)))
		} else {
			calls = append(calls, fmt.Sprintf("repeated(%d)", g.n(4)))
		}
	}
	b.WriteString("func main() needs Console | Ambient {\n\twith context { time.Clock: time.NewHost(), Scheduler: NewLiveScheduler() } {\n")
	for _, c := range calls {
		fmt.Fprintf(&b, "\t\tConsole.Println(\"%s \\(%s)\")\n", c, c)
	}
	b.WriteString("\t}\n}\n")
	return b.String()
}
