package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// ownFuncs are the functions GenerateOwn writes besides the owN: give
// returns the value it owns (v1.ReturnStatic), keep owns its taken
// parameter, guarded owns two in a frame with an error row, tried leaves
// its frame through a try while it owns two (TryReleases), temped owns
// statement temporaries (OwnedTemps), and Res's
// checked Close runs masked (v1.Release).
var ownFuncs = []string{"give", "Res.keep", "guarded", "tried", "temped", "Res.Close"}

// GenerateOwn is a program of owned values in static frames (FLIP F7
// wave 2): a resource Res whose Close prints its id, and functions
// owN(k int) int that open several (each let owns its value), lend them
// (use), hand some to a taking function (keep, which releases it) or
// take one back from give, own a generic Box (its Close generic), and
// leave early on some k. main runs each owN
// at several k, and at the last one a Close that fails (bad) shows a
// defect's release order. Each release prints, so a value released twice,
// never, out of order (last acquired first), or after a hand-off changes
// the output.
func GenerateOwn(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x5be0cd19137e2179))
	var b strings.Builder
	b.WriteString(`// generated by irspike.GenerateOwn

type Res { id int, bad bool } implements Closer

func Close(r Res) needs Console {
	Console.Println("close \(r.id)")
	if r.bad {
		// A defect in a checked Close (an index out of range).
		let none = []int{}
		let v = none[r.id]
		Console.Println("never \(v)")
	}
}

func open(id int, bad bool) Res needs Console {
	Console.Println("open \(id)")
	Res{id: id, bad: bad}
}

func use(r Res) int needs Console {
	Console.Println("use \(r.id)")
	r.id
}

func keep(r own Res) needs Console {
	Console.Println("keep \(r.id)")
}

type Oops { code int }

func risky(k int) int fails Oops needs Console {
	if k > 0 {
		return Oops{code: k}
	}
	k
}

// caught owns a value in a catch arm, a scope the IR builder does not
// release yet: the body must keep its source form (ownVisited), or the
// arm's value is released only at the frame's exit, after "caught".
func caught(k int) int needs Console {
	let r = open(1, false)
	let x = risky(k) catch {
	case Oops as o:
		let t = open(2, false)
		let u = use(t)
		u + o.code
	}
	Console.Println("caught \(x)")
	let v = use(r)
	x + v
}

// guarded is a static frame with an error row (unit 4): a failure
// releases both values, a success returns r and releases t. With bad,
// t's Close fails: on a failure the defect joins the frame's Oops
// (StaticBegin and Static.End on the error result's address).
func guarded(k int, bad bool) Res fails Oops needs Console {
	let r = open(50 + k, false)
	let t = open(60 + k, bad)
	let u = use(t)
	if k > 1 {
		return Oops{code: u}
	}
	r
}

func guardedAt(k int, bad bool) int needs Console {
	let x = guarded(k, bad) catch {
	case Oops as o:
		return o.code
	}
	use(x)
}

// tried is a static frame whose try leaves it while it owns values
// (OWNED-LOCAL-2, Info.TryReleases): the failure edge releases what the
// frame holds then, t before r, through the frame's deferred release, as
// the source path's does; a success hands r on and releases t. With bad,
// t's Close fails beside the propagated Oops.
func tried(k int, bad bool) Res fails Oops needs Console {
	let r = open(70 + k, false)
	let t = open(80 + k, bad)
	let x = try risky(k - 1)
	let u = use(t)
	Console.Println("tried \(x + u)")
	r
}

func triedAt(k int, bad bool) int needs Console {
	let x = tried(k, bad) catch {
	case Oops as o:
		return o.code
	}
	use(x)
}

// temped owns statement temporaries in a static frame (OWNED-LOCAL-2,
// Info.OwnedTemps): each call's Res is released at its statement's
// end, before the next statement; a fallible one only once it is built,
// and a try that leaves releases r through the frame. With bad, the
// first temporary's Close fails at its statement's end.
func temped(k int, bad bool) int fails Oops needs Console {
	let r = open(60 + k, false)
	let u = use(open(61 + k, bad))
	Console.Println("temped \(u)")
	let w = use(try openOr(k))
	Console.Println("temped w \(w)")
	use(r) + use(open(63 + k, false)) + w
}

func openOr(k int) Res fails Oops needs Console {
	if k == 1 {
		return Oops{code: 7}
	}
	open(62 + k, false)
}

func tempedAt(k int, bad bool) int needs Console {
	temped(k, bad) catch {
	case Oops as o:
		o.code
	}
}

// Box is a generic resource: its Close is generic, which a frame's
// release helper calls on each instance (RELEASE-IR).
type Box[T] { id int, v T } implements Closer

func Close[T](b Box[T]) needs Console {
	Console.Println("close box \(b.id)")
}

func boxed[T](id int, v T) Box[T] needs Console {
	Console.Println("open box \(id)")
	Box[T]{id: id, v: v}
}

func peek[T](b Box[T]) int needs Console {
	Console.Println("peek \(b.id)")
	b.id
}

func give(id int, k int) Res needs Console {
	let r = open(id, false)
	if k > 2 {
		Console.Println("give early \(id)")
		return r
	}
	let u = use(r)
	Console.Println("give \(u)")
	r
}

`)
	nf := 3 + r.IntN(3)
	for i := 0; i < nf; i++ {
		fmt.Fprintf(&b, "func ow%d(k int, bad bool) int needs Console {\n\tlet mut s = k\n\ts = s * 2\n", i)
		var live []string // names that are still owned here
		n := 2 + r.IntN(4)
		for j := 0; j < n; j++ {
			name := fmt.Sprintf("r%d", j)
			id := 10*(i+1) + j
			switch r.IntN(4) {
			case 0:
				fmt.Fprintf(&b, "\tlet %s = give(%d, k)\n", name, id)
			default:
				badArg := "false"
				if j == n-1 {
					badArg = "bad"
				}
				fmt.Fprintf(&b, "\tlet %s = open(%d, %s)\n", name, id, badArg)
			}
			live = append(live, name)
			switch r.IntN(4) {
			case 0:
				fmt.Fprintf(&b, "\tlet u%d = use(%s)\n\ts = s + u%d\n", j, name, j)
			case 1:
				if r.IntN(2) == 0 {
					fmt.Fprintf(&b, "\tkeep(%s)\n", name)
					live = live[:len(live)-1]
				}
			case 2:
				fmt.Fprintf(&b, "\tif k == %d {\n\t\treturn s + %d\n\t}\n", r.IntN(4), j)
			case 3:
				// A scope inside the frame (unit 2): its value is released
				// at the scope's end, or before a break leaves the loop.
				id := 100*(i+1) + j
				if r.IntN(2) == 0 {
					fmt.Fprintf(&b, "\tif k > %d {\n\t\tlet t%d = open(%d, false)\n\t\tlet v%d = use(t%d)\n\t\ts = s + v%d\n\t}\n", r.IntN(3), j, id, j, j, j)
				} else {
					fmt.Fprintf(&b, "\tfor q in 0..3 {\n\t\tlet t%d = open(%d + q, false)\n\t\tlet v%d = use(t%d)\n\t\ts = s + v%d\n\t\tif q == k {\n\t\t\tbreak\n\t\t}\n\t}\n", j, id, j, j, j)
				}
			}
		}
		if r.IntN(2) == 0 {
			// A generic resource in the frame, released at its exit.
			v := `"x"`
			if r.IntN(2) == 0 {
				v = "k"
			}
			fmt.Fprintf(&b, "\tlet bx = boxed(%d, %s)\n\tlet px = peek(bx)\n\ts = s + px\n", 200*(i+1), v)
		}
		if len(live) > 0 && r.IntN(2) == 0 {
			fmt.Fprintf(&b, "\tlet un = use(%s)\n\ts = s + un\n", live[r.IntN(len(live))])
		}
		b.WriteString("\ts\n}\n\n")
	}
	b.WriteString("func main() needs Console {\n\tfor k in 0..4 {\n")
	for i := 0; i < nf; i++ {
		fmt.Fprintf(&b, "\t\tConsole.Println(\"ow%d \\(k) \\(ow%d(k, false))\")\n", i, i)
	}
	b.WriteString("\t}\n")
	b.WriteString("\tConsole.Println(\"\\(caught(0)) \\(caught(1))\")\n")
	b.WriteString("\tfor k in 0..4 {\n\t\tConsole.Println(\"guarded \\(guardedAt(k, false))\")\n\t}\n")
	b.WriteString("\tfor k in 0..3 {\n\t\tConsole.Println(\"tried \\(triedAt(k, false))\")\n\t}\n")
	b.WriteString("\tfor k in 0..3 {\n\t\tConsole.Println(\"temped \\(tempedAt(k, false))\")\n\t}\n")
	if seed%3 == 0 {
		// A try's failure whose release fails too.
		b.WriteString("\tConsole.Println(\"tried bad \\(triedAt(2, true))\")\n")
	}
	if seed%3 == 1 {
		// A statement temporary whose release fails at its statement's end.
		b.WriteString("\tConsole.Println(\"temped bad \\(tempedAt(2, true))\")\n")
	}
	last := r.IntN(nf)
	if seed%2 == 0 {
		// A failure whose release fails too.
		b.WriteString("\tConsole.Println(\"bad \\(guardedAt(3, true))\")\n}\n")
		return b.String()
	}
	fmt.Fprintf(&b, "\tConsole.Println(\"bad \\(ow%d(1, true))\")\n}\n", last)
	return b.String()
}
