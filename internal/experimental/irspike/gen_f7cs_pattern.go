package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// PatternFuncs are the functions of GeneratePatterns whose matches and
// catches have patterns (FLIP F7 patterns): each must have an IR body.
var PatternFuncs = []string{"classify", "walk", "pair", "rescue", "partial", "passOn", "opv", "outOfOrder"}

// GeneratePatterns is a program of matches and catches with patterns:
// record patterns nested in records and variants, constants in fields,
// bindings, an or-pattern whose arms share a binding (an arm that several
// leaves of the tree reach), a match on two subjects, a match in result,
// statement and value position, over a union the lowering may keep flat
// (Shape) and a recursive one (Tree), and catches with record patterns,
// `case err:` and a partial catch under try. The constants and the inputs
// are seeded; main prints every function over its inputs.
func GeneratePatterns(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x6a09e667f3bcc909))}
	c := func() int { return g.n(9) }
	var b strings.Builder
	b.WriteString("// generated by irspike.GeneratePatterns\n\n")
	b.WriteString("type Pt { x int, y int }\n\n")
	large := g.n(2) == 1
	if !large {
		b.WriteString("type Shape = Dot{p Pt} | Box{a Pt, b Pt} | Lbl{s string, n int}\n\n")
	} else {
		// A large variant: the union stays a Go interface.
		b.WriteString("type Shape = Dot{p Pt} | Box{a Pt, b Pt, c Pt, d Pt, e Pt} | Lbl{s string, n int}\n\n")
	}
	b.WriteString("type Tree = Leaf{n int} | Node{l Tree, r Tree, k int}\n\n")
	b.WriteString("type Short { n int }\n\ntype Bad { code int, why string }\n\n")
	// Op is small: the lowering keeps it flat, and the tree switches on
	// its tag.
	b.WriteString("type Nop {}\n\ntype Neg { v int }\n\ntype Lit { n int }\n\ntype Op = Nop | Neg | Lit\n\n")
	// opv: two subjects over the flat union, an or-pattern whose arm the
	// tree reaches from two variants.
	fmt.Fprintf(&b, "func opv(o Op, k int) int {\n\tmatch (o, k) {\n")
	fmt.Fprintf(&b, "\tcase (Lit{n: %d}, _):\n\t\t%d\n", g.n(3), c())
	fmt.Fprintf(&b, "\tcase (Lit{n: n}, 1), (Neg{v: n}, 1):\n\t\tn * %d\n", 1+c())
	b.WriteString("\tcase (Neg{v: v}, _):\n\t\t-v\n")
	b.WriteString("\tcase (Nop, j):\n\t\tj + 100\n")
	fmt.Fprintf(&b, "\tcase _:\n\t\t%d\n\t}\n}\n\n", c())
	// classify: result position; the second arm is an or-pattern whose
	// alternatives bind x in two variants.
	fmt.Fprintf(&b, "func classify(s Shape) int {\n\tmatch s {\n")
	fmt.Fprintf(&b, "\tcase Dot{p: Pt{x: %d, y: y}}:\n\t\ty + %d\n", c(), c())
	fmt.Fprintf(&b, "\tcase Dot{p: Pt{x: x}}, Box{a: Pt{x: x}}:\n\t\tif x > %d {\n\t\t\treturn x * %d\n\t\t}\n\t\t-x\n", g.n(5), 1+c())
	fmt.Fprintf(&b, "\tcase Lbl{s: \"a\", n: n}:\n\t\tn + %d\n", c())
	fmt.Fprintf(&b, "\tcase Lbl{n: %d}:\n\t\t%d\n", c(), c())
	fmt.Fprintf(&b, "\tcase _:\n\t\t%d\n\t}\n}\n\n", c())
	// outOfOrder: the tree writes arm 2 (inside the tree) before the shared
	// arm 1 (after it), and both open blocks, so the scopes would go back
	// in the source: the IR moves them up (ir_tree.go monotone).
	fmt.Fprintf(&b, "func outOfOrder(s Shape) int {\n\tmatch s {\n")
	fmt.Fprintf(&b, "\tcase Dot{p: Pt{x: %d}}:\n\t\t%d\n", c(), c())
	fmt.Fprintf(&b, "\tcase Dot{p: Pt{x: x}}, Box{a: Pt{x: x}}:\n\t\tif x > %d {\n\t\t\treturn x\n\t\t}\n\t\t-x\n", g.n(5))
	fmt.Fprintf(&b, "\tcase Lbl{n: n}:\n\t\tif n > %d {\n\t\t\treturn n\n\t\t}\n\t\t0\n\t}\n}\n\n", g.n(5))
	// walk: a statement match on a recursive union with nested patterns.
	fmt.Fprintf(&b, "func walk(t Tree) int {\n\tlet mut n = 0\n\tmatch t {\n")
	fmt.Fprintf(&b, "\tcase Leaf{n: %d}:\n\t\tn = %d\n", c(), c())
	fmt.Fprintf(&b, "\tcase Node{l: Leaf{n: a}, r: Leaf{n: b}}:\n\t\tn = a * %d + b\n", 1+c())
	fmt.Fprintf(&b, "\tcase Node{l: Node{k: k}, k: j}:\n\t\tn = k + j * %d\n", 1+c())
	fmt.Fprintf(&b, "\tcase Node{k: k}:\n\t\tn = k + %d\n", c())
	fmt.Fprintf(&b, "\tcase Leaf{n: m}:\n\t\tn = m - %d\n\t}\n\tn\n}\n\n", c())
	// pair: two subjects, a match in value position.
	fmt.Fprintf(&b, "func pair(a int, s string) string {\n\tlet r = match (a, s) {\n")
	fmt.Fprintf(&b, "\tcase (%d, \"x\"):\n\t\t\"zx\"\n", c())
	fmt.Fprintf(&b, "\tcase (%d, _):\n\t\t\"z\"\n", c())
	b.WriteString("\tcase (_, \"x\"):\n\t\t\"x\"\n")
	b.WriteString("\tcase (n, t):\n\t\tt + \"\\(n)\"\n\t}\n\t\"<\" + r + \">\"\n}\n\n")
	// fetch fails Short below lo and Bad above hi.
	lo, hi := 1+g.n(3), 5+g.n(3)
	fmt.Fprintf(&b, "func fetch(i int) int fails Short | Bad {\n\tif i < %d {\n\t\treturn Short{n: i}\n\t}\n\tif i > %d {\n\t\treturn Bad{code: i, why: \"big\"}\n\t}\n\ti * 2\n}\n\n", lo, hi)
	fmt.Fprintf(&b, "func rescue(i int) int {\n\tfetch(i) catch {\n")
	fmt.Fprintf(&b, "\tcase Short{n: 0}:\n\t\t%d\n", c())
	fmt.Fprintf(&b, "\tcase Short{n: n}:\n\t\tn + %d\n", c())
	fmt.Fprintf(&b, "\tcase Bad{code: %d, why: w}:\n\t\tlen(w)\n", hi+1+g.n(2))
	b.WriteString("\tcase _:\n\t\t-1\n\t}\n}\n\n")
	fmt.Fprintf(&b, "func partial(i int) int fails Bad {\n\ttry fetch(i) catch {\n\tcase Short{n: n}:\n\t\tn * %d\n\t}\n}\n\n", 1+c())
	fmt.Fprintf(&b, "func passOn(i int) int fails Short | Bad {\n\tfetch(i) catch {\n\tcase Short{n: %d}:\n\t\t%d\n\tcase err:\n\t\treturn err\n\t}\n}\n\n", g.n(3), c())
	b.WriteString("func main() needs Console {\n")
	shapeOf := func() string {
		switch g.n(4) {
		case 0:
			return fmt.Sprintf("Dot{p: Pt{x: %d, y: %d}}", g.n(9), g.n(9))
		case 1:
			extra := ""
			if large {
				extra = ", c: Pt{x: 0, y: 0}, d: Pt{x: 0, y: 0}, e: Pt{x: 0, y: 0}"
			}
			return fmt.Sprintf("Box{a: Pt{x: %d, y: %d}, b: Pt{x: 1, y: 2}%s}", g.n(9), g.n(9), extra)
		case 2:
			return fmt.Sprintf("Lbl{s: \"a\", n: %d}", g.n(9))
		}
		return fmt.Sprintf("Lbl{s: \"b\", n: %d}", g.n(9))
	}
	trees := []string{"Leaf{n: %d}", "Node{l: Leaf{n: %d}, r: Leaf{n: 2}, k: 3}", "Node{l: Node{l: Leaf{n: 1}, r: Leaf{n: 1}, k: %d}, r: Leaf{n: 0}, k: 4}", "Node{l: Leaf{n: 1}, r: Node{l: Leaf{n: 0}, r: Leaf{n: 0}, k: %d}, k: 5}"}
	words := []string{"\"x\"", "\"y\"", "\"\""}
	for k := 0; k < 6; k++ {
		shape := shapeOf()
		tree := fmt.Sprintf(trees[g.n(len(trees))], g.n(9))
		fmt.Fprintf(&b, "\tlet c%d = classify(%s)\n", k, shape)
		fmt.Fprintf(&b, "\tlet w%d = walk(%s) + outOfOrder(%s)\n", k, tree, shapeOf())
		ops := []string{"Nop", fmt.Sprintf("Neg{v: %d}", g.n(5)), fmt.Sprintf("Lit{n: %d}", g.n(3))}
		fmt.Fprintf(&b, "\tlet p%d = pair(%d, %s) + \"\\(opv(%s, %d))\"\n", k, g.n(9), words[g.n(len(words))], ops[g.n(3)], g.n(3))
		fmt.Fprintf(&b, "\tlet r%d = rescue(%d)\n", k, g.n(12))
		fmt.Fprintf(&b, "\tlet q%d = partial(%d) catch {\n\tcase Bad{code: c}:\n\t\t-c\n\t}\n", k, g.n(12))
		fmt.Fprintf(&b, "\tlet o%d = passOn(%d) catch {\n\tcase Bad as e:\n\t\te.code + 100\n\tcase Short as e:\n\t\te.n + 50\n\t}\n", k, g.n(12))
		fmt.Fprintf(&b, "\tConsole.Println(\"%d: \\(c%d) \\(w%d) \\(p%d) \\(r%d) \\(q%d) \\(o%d)\")\n", k, k, k, k, k, k, k)
	}
	b.WriteString("}\n")
	return b.String()
}
