package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateTakeAt is a program of std calls whose Go result is a tuple of a
// runtime body's generic types (CONV-RESULT): xs.TakeAt(i), the prelude's
// (T, []T) at T an int, a string, a record, a tuple or a slice, bound by
// both let forms. Each function take<k>(n) builds a seeded slice, takes the
// element at n modulo its length and reads the element and every rest
// element into an int, so a result bound to the wrong name or an element
// read from the wrong field changes what main prints.
func GenerateTakeAt(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x6c8e9bf2a4d17053))
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateTakeAt\n\n")
	b.WriteString("type Rec { A int, B string }\n\n")
	type elem struct{ typ, mk, rd string }
	elems := []elem{
		{"int", "i * %d + n", "v"},
		{"string", "\"e\\(i * %d + n)\"", "len(v)"},
		{"Rec", "Rec{A: i * %d + n, B: \"r\\(i)\"}", "v.A * 3 + len(v.B)"},
		{"(int, string)", "(i * %d + n, \"t\\(i)\")", "tupleRead(v)"},
		{"[]int", "[]int{i * %d, n}", "len(v) * 7 + v[0] + v[1]"},
	}
	b.WriteString("func tupleRead(v (int, string)) int {\n\tlet (a, s) = v\n\ta * 5 + len(s)\n}\n\n")
	nf := 3 + r.IntN(3)
	for k := 0; k < nf; k++ {
		e := elems[r.IntN(len(elems))]
		size := 1 + r.IntN(5)
		mul := 2 + r.IntN(7)
		mk := e.mk
		if strings.Contains(mk, "%d") {
			mk = fmt.Sprintf(mk, mul)
		}
		fmt.Fprintf(&b, "func take%d(n int) int {\n", k)
		fmt.Fprintf(&b, "\tlet mut xs = []%s{}\n\tfor i in 0..%d {\n\t\txs = xs.Append(%s)\n\t}\n", e.typ, size, mk)
		fmt.Fprintf(&b, "\tlet at = if n < 0 { -n %% %d } else { n %% %d }\n", size, size)
		if r.IntN(2) == 0 {
			b.WriteString("\tlet (x, rest) = xs.TakeAt(at)\n")
		} else {
			b.WriteString("\tlet x, rest = xs.TakeAt(at)\n")
		}
		fmt.Fprintf(&b, "\tlet mut t = len(rest)\n\tfor v in rest {\n\t\tt = t * 31 + %s\n\t}\n", e.rd)
		fmt.Fprintf(&b, "\tlet v = x\n\tt * 17 + %s\n}\n\n", e.rd)
	}
	b.WriteString("func main() needs Console {\n")
	for _, in := range []int{0, 1, 4, -3} {
		for k := 0; k < nf; k++ {
			fmt.Fprintf(&b, "\tConsole.Println(\"take%d(%d) \\(take%d(%d))\")\n", k, in, k, in)
		}
	}
	b.WriteString("}\n")
	return b.String()
}
