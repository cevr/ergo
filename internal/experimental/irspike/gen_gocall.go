package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateGoCall is a program of Go calls (SP4): user externs and import go
// functions of the reviewed pure tier, over basic types, called inside
// binary expressions, as statements' values and under try and catch. Two
// of them fail go.Error (strconv.Atoi through a user extern and through
// import go). Each function g<i>(a int, s string) int folds them; main
// prints every function's result, or its failure's text, at several
// inputs, some of which Atoi refuses. A call moved out of its order, a
// failure that loses Go's error text, or a value read beside a failure
// changes the output.
func GenerateGoCall(seed uint64) string {
	g := &gcgen{r: rand.New(rand.NewPCG(seed, seed^0x3d5a9c17e2b4f60b))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateGoCall\nimport go strconv\nimport go strings\n\n")
	b.WriteString("extern go strings.Count func count(s string, sub string) int\n")
	b.WriteString("extern go strings.ToUpper func upper(s string) string\n")
	b.WriteString("extern go strconv.Atoi func atoi(s string) int fails go.Error\n")
	b.WriteString("extern go strconv.Itoa func itoa(n int) string\n\n")
	nf := 3 + g.r.IntN(3)
	for i := 0; i < nf; i++ {
		g.ints, g.strs = []string{"a"}, []string{"s"}
		fmt.Fprintf(&b, "func g%d(a int, s string) int fails go.Error {\n", i)
		for j, n := 0, 2+g.r.IntN(4); j < n; j++ {
			b.WriteString(g.step())
		}
		fold := g.ints[0]
		for _, v := range g.ints[1:] {
			fold = "(" + fold + ") * 31 + " + v
		}
		for _, v := range g.strs {
			fold = "(" + fold + ") * 7 + len(" + v + ")"
		}
		fmt.Fprintf(&b, "\t%s\n}\n\n", fold)
	}
	b.WriteString("func main() needs Console {\n")
	for i := 0; i < nf; i++ {
		for j, in := range []string{`3, "12"`, `-1, "x1"`, `7, "0110"`, `2, ""`} {
			fmt.Fprintf(&b, "\tlet r%d_%d = g%d(%s) catch {\n\tcase go.Error as e:\n\t\tConsole.Println(\"g%d fails \\(e.Text)\")\n\t\t-1\n\t}\n", i, j, i, in, i)
			fmt.Fprintf(&b, "\tConsole.Println(\"g%d(%s) \\(r%d_%d)\")\n", i, strings.ReplaceAll(in, `"`, `'`), i, j)
		}
	}
	b.WriteString("}\n")
	return b.String()
}

type gcgen struct {
	r          *rand.Rand
	ints, strs []string // the names in scope
	next       int
}

func (g *gcgen) fresh(pre string) string {
	g.next++
	return fmt.Sprintf("%s%d", pre, g.next)
}

func (g *gcgen) int() string { return g.ints[g.r.IntN(len(g.ints))] }
func (g *gcgen) str() string { return g.strs[g.r.IntN(len(g.strs))] }

// intExpr is an int expression whose operands include Go calls.
func (g *gcgen) intExpr() string {
	switch g.r.IntN(5) {
	case 0:
		return g.int() + " + count(" + g.str() + ", \"1\")"
	case 1:
		return "strings.Count(" + g.str() + ", \"0\") * " + g.int()
	case 2:
		return "len(itoa(" + g.int() + ")) - " + g.int()
	case 3:
		return "len(upper(" + g.str() + ") + strconv.Itoa(" + g.int() + "))"
	}
	return g.int() + " * 3 + count(upper(" + g.str() + "), \"X\")"
}

// strExpr is a string expression whose operands include Go calls.
func (g *gcgen) strExpr() string {
	switch g.r.IntN(3) {
	case 0:
		return "itoa(" + g.int() + ") + " + g.str()
	case 1:
		return "strings.ToUpper(" + g.str() + ") + strconv.Itoa(" + g.int() + ")"
	}
	return "upper(" + g.str() + ")"
}

// step is one let: an int or a string from Go calls, or a fallible Atoi
// under try (failing the function) or catch (a fallback value).
func (g *gcgen) step() string {
	switch g.r.IntN(5) {
	case 0, 1:
		v := g.fresh("n")
		out := "\tlet " + v + " = " + g.intExpr() + "\n"
		g.ints = append(g.ints, v)
		return out
	case 2:
		v := g.fresh("t")
		out := "\tlet " + v + " = " + g.strExpr() + "\n"
		g.strs = append(g.strs, v)
		return out
	case 3:
		v := g.fresh("p")
		target := "atoi"
		if g.r.IntN(2) == 0 {
			target = "strconv.Atoi"
		}
		out := "\tlet " + v + " = try " + target + "(" + g.str() + ")\n"
		g.ints = append(g.ints, v)
		return out
	}
	v := g.fresh("q")
	target := "atoi"
	if g.r.IntN(2) == 0 {
		target = "strconv.Atoi"
	}
	out := "\tlet " + v + " = " + target + "(" + g.str() + ") catch {\n\tcase go.Error:\n\t\t" + g.int() + " - 100\n\t}\n"
	g.ints = append(g.ints, v)
	return out
}
