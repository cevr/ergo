package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// FnNameFuncs are GenerateFnName's functions that use a declared function
// as a value: each gets an IR body in every seed (F7-cs-fnname).
var FnNameFuncs = []string{"values", "halves", "says", "odds", "heavier", "grown"}

// GenerateFnName is a program of two packages whose functions pass
// declared functions as values (F7-cs-fnname, "name that is not a local"
// and pkg.F): a pure function with a value, one that needs Console (its
// environment passes through the value), a fallible one with a value and
// one with none, a function the lowering writes as a Go method of a
// record and of a pointer to one, each written bare and qualified. The
// functions of a pair have the same type and seeded constants, so a value
// that calls the other function, drops the environment, the receiver or
// the error prints differently. It returns the files, by path from the
// module's folder; the program is cmd/p.
func GenerateFnName(seed uint64) map[string]string {
	r := rand.New(rand.NewPCG(seed, seed^0x3c6ef372fe94f82b))
	n := func(k int) int { return r.IntN(k) }
	var lib strings.Builder
	lib.WriteString("// generated by irspike.GenerateFnName\n\n")
	lib.WriteString("// Odd is an odd number refused.\ntype Odd { N int }\n\n")
	lib.WriteString("// Box is a weighed thing.\ntype Box { W int }\n\n")
	fmt.Fprintf(&lib, "// Double scales x.\nfunc Double(x int) int {\n\tx * %d\n}\n\n", 2+n(5))
	fmt.Fprintf(&lib, "// Half halves an even x.\nfunc Half(x int) int fails Odd {\n\tif x %% 2 != 0 {\n\t\treturn Odd{N: x}\n\t}\n\tx / 2 + %d\n}\n\n", n(9))
	fmt.Fprintf(&lib, "// Heavier compares two boxes.\nfunc Heavier(a Box, b Box) int {\n\ta.W - b.W * %d\n}\n\n", 1+n(3))

	var m strings.Builder
	m.WriteString("// generated by irspike.GenerateFnName\n\nimport p/lib\n\n")
	m.WriteString("type Cell { V int }\n\n")
	m.WriteString("func apply(f func(int) int, x int) int {\n\tlet r = f(x)\n\tr\n}\n\n")
	m.WriteString("func tryApply(f func(int) int fails lib.Odd, x int) int fails lib.Odd {\n\tlet v = try f(x)\n\tv\n}\n\n")
	m.WriteString("func check(f func(int) fails lib.Odd, x int) fails lib.Odd {\n\ttry f(x)\n}\n\n")
	m.WriteString("func run(x int, f func(int) needs Console) needs Console {\n\tf(x)\n}\n\n")
	m.WriteString("func cmp(f func(lib.Box, lib.Box) int, a int, b int) int {\n\tlet r = f(lib.Box{W: a}, lib.Box{W: b})\n\tr\n}\n\n")
	m.WriteString("func grow(f func(mut Cell, int) int, c mut Cell, d int) int {\n\tlet r = f(c, d)\n\tr\n}\n\n")
	fmt.Fprintf(&m, "func triple(x int) int {\n\tx * %d + 1\n}\n\n", 3+n(4))
	fmt.Fprintf(&m, "func say(x int) needs Console {\n\tConsole.Println(\"say \\(x * %d)\")\n}\n\n", 1+n(5))
	fmt.Fprintf(&m, "func odd(x int) fails lib.Odd {\n\tif x %% 2 != 0 {\n\t\treturn lib.Odd{N: x + %d}\n\t}\n}\n\n", n(9))
	fmt.Fprintf(&m, "func smaller(a lib.Box, b lib.Box) int {\n\tb.W - a.W * %d\n}\n\n", 2+n(3))
	fmt.Fprintf(&m, "func bump(c *Cell, d int) int {\n\tc.V = c.V + d * %d\n\tc.V\n}\n\n", 1+n(4))
	m.WriteString("func values(x int) int {\n\tlet a = apply(triple, x)\n\tlet b = apply(lib.Double, x)\n\ta * 1000 + b\n}\n\n")
	m.WriteString("func halves(x int) int {\n\tlet v = tryApply(lib.Half, x) catch {\n\tcase lib.Odd as e:\n\t\t0 - e.N\n\t}\n\tv\n}\n\n")
	m.WriteString("func says(x int) needs Console {\n\trun(x, say)\n}\n\n")
	m.WriteString("func odds(x int) int {\n\tlet mut w = 1\n\tcheck(odd, x) catch {\n\tcase lib.Odd as e:\n\t\tw = e.N * 100\n\t}\n\tw\n}\n\n")
	m.WriteString("func heavier(a int, b int) int {\n\tlet h = cmp(lib.Heavier, a, b)\n\tlet s = cmp(smaller, a, b)\n\th * 1000 + s\n}\n\n")
	m.WriteString("func grown(x int) int {\n\tlet mut c = Cell{V: x}\n\tlet a = grow(bump, &c, 2)\n\tlet b = grow(bump, &c, 3)\n\ta * 1000 + b + c.V\n}\n\n")
	m.WriteString("func main() needs Console {\n")
	for k := 0; k < 4; k++ {
		x, y := n(15)-4, n(12)
		fmt.Fprintf(&m, "\tConsole.Println(\"%d: \\(values(%d)) \\(halves(%d)) \\(odds(%d)) \\(heavier(%d, %d)) \\(grown(%d))\")\n", k, x, x, y, x, y, y)
		fmt.Fprintf(&m, "\tsays(%d)\n", x)
	}
	m.WriteString("}\n")
	return map[string]string{
		"ergo.mod":        "module p\n",
		"lib/lib.ergo":    lib.String(),
		"cmd/p/main.ergo": m.String(),
	}
}
