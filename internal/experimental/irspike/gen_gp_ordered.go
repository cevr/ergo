package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// orderedFuncs are GenerateOrdered's generic functions: each gets an IR
// body in every seed (GP-ORDER, "operator … on a non-basic type").
var orderedFuncs = []string{"least", "clamp", "atLeast", "bubble"}

// GenerateOrdered is a program of generic functions over a type parameter
// constrained by ordered (GP-ORDER), each comparing its operands with <,
// <=, > or >= (the seed picks each operator, strict or not):
//   - least is the smaller of two values; clamp keeps a value between two
//     bounds; atLeast counts the elements on one side of a bound; bubble
//     is one pass of a bubble sort over a copy.
//
// main instantiates them at int, int64, float64 and string, with seeded
// values that hold ties, and, for float64, a NaN, -0 and +0, so an
// operator lowered as another (strict for not, or its operands swapped)
// or compared on another type changes the output. It also prints std
// cmp.Compare and cmp.Less on the same values, which read a NaN through
// a != a before they order.
func GenerateOrdered(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x1f83d9abfb41bd6b))}
	pick := func(a, b string) string {
		if g.n(2) == 0 {
			return a
		}
		return b
	}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateOrdered\n\nimport cmp\nimport math\n\n")
	fmt.Fprintf(&b, "func least[T ordered](a T, b T) T {\n\tif a %s b {\n\t\treturn a\n\t}\n\tb\n}\n\n", pick("<", "<="))
	fmt.Fprintf(&b, "func clamp[T ordered](x T, lo T, hi T) T {\n\tif x %s lo {\n\t\treturn lo\n\t}\n\tif x %s hi {\n\t\treturn hi\n\t}\n\tx\n}\n\n", pick("<", "<="), pick(">", ">="))
	fmt.Fprintf(&b, "func atLeast[T ordered](xs []T, k T) int {\n\tlet mut n = 0\n\tfor x in xs {\n\t\tif x %s k {\n\t\t\tn += 1\n\t\t}\n\t}\n\tn\n}\n\n", pick(">", ">="))
	fmt.Fprintf(&b, "func bubble[T ordered](xs []T) []T {\n\tlet mut ys = []T{}\n\tfor x in xs {\n\t\tys = ys.Append(x)\n\t}\n\tfor i in 1..len(ys) {\n\t\tif ys[i - 1] %s ys[i] {\n\t\t\tlet t = ys[i]\n\t\t\tys[i] = ys[i - 1]\n\t\t\tys[i - 1] = t\n\t\t}\n\t}\n\tys\n}\n\n", pick(">", ">="))
	// One show per type (a value of a type parameter has no text form):
	// each prints what the generic functions give at that type.
	for _, ty := range []string{"int", "int64", "float64", "string"} {
		fmt.Fprintf(&b, "func show%s(xs []%s) needs Console {\n", strings.ToUpper(ty[:1])+ty[1:], ty)
		fmt.Fprintf(&b, "\tConsole.Println(\"%s atLeast \\(atLeast(xs, xs[0]))\")\n", ty)
		b.WriteString("\tfor y in bubble(xs) {\n\t\tConsole.Println(\"bubble \\(y)\")\n\t}\n")
		b.WriteString("\tfor i in 1..len(xs) {\n")
		b.WriteString("\t\tlet a = xs[i - 1]\n\t\tlet b = xs[i]\n")
		b.WriteString("\t\tConsole.Println(\"\\(i) least \\(least(a, b)) clamp \\(clamp(a, b, xs[0])) \\(clamp(b, xs[0], a)) cmp \\(cmp.Compare(a, b)) \\(cmp.Less(a, b))\")\n")
		b.WriteString("\t}\n}\n\n")
	}
	n := 4 + g.n(3)
	ints := make([]string, n)
	longs := make([]string, n)
	strs := make([]string, n)
	floats := make([]string, n)
	words := []string{"\"\"", "\"a\"", "\"ab\"", "\"b\"", "\"B\"", "\"ba\""}
	special := []string{"nan", "negz", "posz"}
	for i := 0; i < n; i++ {
		ints[i] = fmt.Sprint(g.n(7) - 3)
		longs[i] = fmt.Sprintf("int64(%d)", g.n(7)-3)
		strs[i] = words[g.n(len(words))]
		if g.n(3) == 0 {
			floats[i] = special[g.n(len(special))]
		} else {
			floats[i] = fmt.Sprintf("%d.5", g.n(5)-2)
		}
	}
	// Every float64 row holds a NaN and a -0 somewhere.
	at := g.n(n)
	floats[at] = "nan"
	floats[(at+1+g.n(n-1))%n] = "negz"
	b.WriteString("func main() needs Console {\n")
	b.WriteString("\tlet nan = math.NaN()\n\tlet posz = 0.0\n\tlet negz = -posz\n")
	fmt.Fprintf(&b, "\tshowInt([]int{%s})\n", strings.Join(ints, ", "))
	fmt.Fprintf(&b, "\tshowInt64([]int64{%s})\n", strings.Join(longs, ", "))
	fmt.Fprintf(&b, "\tshowFloat64([]float64{%s})\n", strings.Join(floats, ", "))
	fmt.Fprintf(&b, "\tshowString([]string{%s})\n", strings.Join(strs, ", "))
	b.WriteString("}\n")
	return b.String()
}
