package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// arrayLitFuncs are GenerateArrayLit's functions: each gets an IR body in
// every seed (INDEX-NONSLICE, "literal of *check.Array").
var arrayLitFuncs = []string{"quad", "blank", "tags"}

// GenerateArrayLit is a program of fixed array literals (types.md, Arrays
// 2), as lz's [65536]byte{} and look's [4]float32{…}: quad lists every
// element of a [5]int, each from its own seeded expression of the
// parameters; blank starts from the empty [5]int{} and writes two of its
// elements; tags lists a [3]string. main prints every element, so an
// element out of place, a literal that is not zero, or a lost element
// changes the output.
func GenerateArrayLit(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x9e3779b97f4a7c15))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateArrayLit\n\n")
	// quad: five distinct expressions of a and b, so a swap shows.
	es := make([]string, 5)
	for i := range es {
		es[i] = fmt.Sprintf("a * %d + b * %d + %d", 1+g.n(9), 1+g.n(9), i*10+g.n(10))
	}
	fmt.Fprintf(&b, "func quad(a int, b int) [5]int {\n\t[5]int{%s}\n}\n\n", strings.Join(es, ", "))
	// blank: the zero [5]int with two elements written, one of them twice.
	fmt.Fprintf(&b, "func blank(n int) [5]int {\n\tlet mut q = [5]int{}\n\tq[n %% 5] = n * %d\n\tq[(n + %d) %% 5] += n\n\tq\n}\n\n", 1+g.n(7), 1+g.n(4))
	// tags: three strings, one from the parameter.
	fmt.Fprintf(&b, "func tags(s string) [3]string {\n\t[3]string{\"t%d\", s, \"u%d\"}\n}\n\n", g.n(100), g.n(100))
	b.WriteString("func main() needs Console {\n")
	for k := 0; k < 3; k++ {
		fmt.Fprintf(&b, "\tlet q%d = quad(%d, %d)\n", k, g.n(20), g.n(20))
		fmt.Fprintf(&b, "\tlet z%d = blank(%d)\n", k, g.n(13))
		fmt.Fprintf(&b, "\tlet s%d = tags(\"w%d\")\n", k, g.n(100))
		var parts []string
		for i := 0; i < 5; i++ {
			parts = append(parts, fmt.Sprintf("\\(q%d[%d])", k, i))
		}
		for i := 0; i < 5; i++ {
			parts = append(parts, fmt.Sprintf("\\(z%d[%d])", k, i))
		}
		for i := 0; i < 3; i++ {
			parts = append(parts, fmt.Sprintf("\\(s%d[%d])", k, i))
		}
		fmt.Fprintf(&b, "\tConsole.Println(\"%d: %s\")\n", k, strings.Join(parts, " "))
	}
	b.WriteString("}\n")
	return b.String()
}
