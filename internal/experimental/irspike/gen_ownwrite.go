package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// ownTape is GenerateOwnWrite's writer: a sealed Writer whose one
// provider, the record tape, is a cell, and a type attr of the same
// package with its own write (WireWrite; types.md, Codecs 10), as module
// xml's Attribute is: on a tape, an attr right after its field's key
// joins the key as `key@value`, the attribute of xml's start tag; anywhere
// else (an item of a list, the root) it is a string, as xml writes it.
const ownTape = `import json

type Tape {
	..Writer,
	mut Written() string,
	mut seal(),
}

type tape { out string, key string, open bool } implements Tape

type attr { V string }

func WireWrite(a attr, t mut tape) {
	if t.open {
		t.open = false
		t.out = t.out + t.key + "@" + a.V + " "
		return
	}
	t.String(a.V)
}

func seal(t mut tape) {}
func flush(t mut tape) {
	if t.open {
		t.open = false
		t.out = t.out + t.key + ": "
	}
}
func Null(t mut tape) { t.flush(); t.out = t.out + "null " }
func Number(t mut tape, s string) { t.flush(); t.out = t.out + s + " " }
func Bool(t mut tape, b bool) { t.flush(); t.out = t.out + "\(b) " }
func Int(t mut tape, n int64) { t.flush(); t.out = t.out + "\(n) " }
func Uint(t mut tape, n uint64) { t.flush(); t.out = t.out + "u\(n) " }
func Float(t mut tape, f float64) { t.flush(); t.out = t.out + "f\(f) " }
func String(t mut tape, s string) { t.flush(); t.out = t.out + "'" + s + "' " }
func StringBytes(t mut tape, b []byte) { t.flush(); t.out = t.out + "bytes " }
func BeginList(t mut tape, n int) { t.flush(); t.out = t.out + "[ " }
func EndList(t mut tape) { t.out = t.out + "] " }
func BeginObject(t mut tape, n int) { t.flush(); t.out = t.out + "{ " }
func Tag(t mut tape, s string) { t.out = t.out + "#" + s + " " }
func Key(t mut tape, k string) { t.key = k; t.open = true }
func EndObject(t mut tape) { t.out = t.out + "} " }
func Written(t mut tape) string { t.out }

func newTape() Tape { tape{out: "", key: "", open: false} }
`

// GenerateOwnWrite is a program that encodes records holding attr fields
// (first, between other fields, in a nested record, in a list of attr and
// as the root) on a Tape, where attr takes its own write, and on json's
// Text, where it is the record {"V": …} (XML-ATTR). main prints each text.
func GenerateOwnWrite(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x6a09e667f3bcc909))
	word := func() string { return []string{"", "a", "id7", "x y"}[r.IntN(4)] }
	at := func() string { return fmt.Sprintf("attr{V: %q}", word()) }
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateOwnWrite\n\n" + ownTape + "\n")
	b.WriteString("type inner { Lang attr, N int }\n\n")
	b.WriteString("type entry { ID attr, Title string, Ref attr, In inner, Tags []attr }\n\n")
	b.WriteString("func onTape[T wire](v T) string needs wired[T] {\n\tlet t = newTape()\n\tencode(v, t)\n\tt.Written()\n}\n\n")
	b.WriteString("func onText[T wire](v T) string needs wired[T] {\n\tlet t = json.NewText()\n\tencode(v, t)\n\tt.Written()\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	for i := range 3 {
		var tags []string
		for range r.IntN(3) {
			tags = append(tags, at())
		}
		e := fmt.Sprintf("entry{ID: %s, Title: %q, Ref: %s, In: inner{Lang: %s, N: %d}, Tags: []attr{%s}}", at(), word(), at(), at(), r.IntN(9), strings.Join(tags, ", "))
		fmt.Fprintf(&b, "\tlet e%d = %s\n\tConsole.Println(\"tape %d \\(onTape(e%d))\")\n\tConsole.Println(\"text %d \\(onText(e%d))\")\n", i, e, i, i, i, i)
	}
	fmt.Fprintf(&b, "\tConsole.Println(\"root \\(onTape(%s))\")\n", at())
	b.WriteString("}\n")
	return b.String()
}
