package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateWitnessSlots is a program in which the inliner copies a callee
// with a string parameter into a body that has witness parameters (vt's
// Apply[S lent Screen] and its u.note("osc")): walk is generic over two
// type parameters of an operation type, so no call goes to a copy for a
// known witness and its body runs with a witness parameter slot for each;
// beside a caught fallible operation it calls note, whose parameters
// become locals of walk's frame, after every Go parameter slot.
//
// The drawn constants and words reach the output, so a local the inliner
// numbers onto another (the vt ICE: `def: string is not error`) fails the
// IR build or prints differently.
func GenerateWitnessSlots(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x9e3779b97f4a7c15))
	n := func(k int) int { return r.IntN(k) }
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateWitnessSlots\n\n")
	b.WriteString("type Bad { At int }\n\n")
	b.WriteString("type Tally { n int, last string }\n\n")
	b.WriteString("type Shape {\n\tArea() int,\n\tScale(k int) int fails Bad,\n}\n\n")
	b.WriteString("type Rect { W int, H int } implements Shape\n\ntype Sq { S int } implements Shape\n\n")
	fmt.Fprintf(&b, "func Area(r Rect) int {\n\tr.W * r.H + %d\n}\n\n", n(5))
	fmt.Fprintf(&b, "func Scale(r Rect, k int) int fails Bad {\n\tif k < %d {\n\t\tBad{At: k}\n\t} else {\n\t\tr.W * k + r.H\n\t}\n}\n\n", n(4)-1)
	fmt.Fprintf(&b, "func Area(s Sq) int {\n\ts.S * s.S - %d\n}\n\n", n(4))
	fmt.Fprintf(&b, "func Scale(s Sq, k int) int fails Bad {\n\tif k %% %d == 0 {\n\t\tBad{At: k + 1}\n\t} else {\n\t\ts.S * %d + k\n\t}\n}\n\n", 2+n(3), 1+n(6))
	// note calls mix, so it is no Go leaf: the inliner copies a small
	// non-leaf in (irInlSite.pays), as it copies vt's note.
	fmt.Fprintf(&b, "func mix(a int, k int) int {\n\ta * %d + k\n}\n\n", 3+n(5))
	fmt.Fprintf(&b, "func note(t mut Tally, what string) {\n\tt.n = mix(t.n, len(what) + %d)\n\tt.last = what\n}\n\n", n(7))
	words := []string{"osc", "csi", "esc", "dcs", "apc"}
	w := func() string { return words[n(len(words))] }
	b.WriteString("func walk[P Shape, Q Shape](p P, q Q, k int, t mut Tally) int {\n")
	fmt.Fprintf(&b, "\tlet x = p.Scale(k) catch {\n\tcase Bad as e:\n\t\tt.note(%q)\n\t\te.At * 10\n\t}\n", w())
	fmt.Fprintf(&b, "\tif x > %d {\n\t\tt.note(%q)\n\t} else {\n\t\tt.note(%q)\n\t}\n", n(30), w(), w())
	fmt.Fprintf(&b, "\tlet y = q.Scale(k + 1) catch {\n\tcase Bad as e:\n\t\te.At - %d\n\t}\n", n(9))
	fmt.Fprintf(&b, "\tt.note(%q)\n\tx * 100 + y + q.Area() - p.Area()\n}\n\n", w())
	b.WriteString("func main() needs Console {\n\tlet mut t = Tally{n: 0, last: \"\"}\n")
	for i := 0; i < 4; i++ {
		rect := fmt.Sprintf("Rect{W: %d, H: %d}", n(7), n(7)-2)
		sq := fmt.Sprintf("Sq{S: %d}", n(9)-3)
		k := n(12) - 3
		fmt.Fprintf(&b, "\tlet a%d = walk(%s, %s, %d, &t)\n", i, rect, sq, k)
		fmt.Fprintf(&b, "\tlet b%d = walk(%s, %s, %d, &t)\n", i, sq, rect, k+1)
		fmt.Fprintf(&b, "\tConsole.Println(\"%d: \\(a%d) \\(b%d) \\(t.n) \\(t.last)\")\n", i, i, i)
	}
	b.WriteString("}\n")
	return b.String()
}
