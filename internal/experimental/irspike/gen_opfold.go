package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateOpFold is a program whose package lets are checked constants
// (the IR reads each as a constant, constLet; a float let stays a Go
// variable, so float constants come from conversions of integer lets and
// literals) combined by operators and
// conversions, so the IR builder folds them before gc (PATCH-MIN M6,
// ir_constfold.go). Each function folds* returns an expression of
// constants only, which the fold must leave as one constant; each stays*
// returns one Go keeps as an operation: an integer division by a zero let
// (the run's defect, in the last line main prints) and an int8 sum past
// 127 (it wraps when the program runs). Every function also
// mixes its constants with a run-time operand, and main prints each, so a
// fold that rounds, truncates or fits wrong changes the output:
//   - float64 chains whose exact value differs from the rounded one
//     (float64(BigI) + 1.0 - float64(BigI) is 0 in float64, 1 exactly;
//     float64(Three) * 0.1 - 0.3 is not 0);
//   - a float32 product that rounds differently from float64;
//   - integer division and remainder of negative lets (truncation);
//   - unsigned and narrow integers at their bounds; conversions between
//     them; string concatenation; ! of a bool let; len of a string let
//     and of a concatenation (Go's constant len), in an expression and
//     as a call's argument.
func GenerateOpFold(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x6366666f6c645f6d))
	n := func(k int) int { return r.IntN(k) }
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateOpFold\n\nimport strings\n\n")
	fmt.Fprintf(&b, "let A int = %d\nlet B int = %d\nlet Neg int = -%d\nlet Zero int = 0\n", 1+n(1000), 1+n(50), 1+n(97))
	fmt.Fprintf(&b, "let Three int = 3\nlet BigI int = 1%s\n", strings.Repeat("0", 16+n(3)))
	fmt.Fprintf(&b, "let Small int8 = int8(%d)\nlet Top uint8 = uint8(%d)\nlet Wide uint64 = uint64(%d)\n", 60+n(60), 200+n(55), 1<<40+n(1000))
	fmt.Fprintf(&b, "let Name string = \"n%d\"\nlet Flag bool = %v\n\n", n(99), n(2) == 0)
	folds := []string{
		"A * B + Neg",
		"(A + Neg) / B",
		"Neg / B",
		"Neg % B",
		"A % B - Neg",
		"(A & B) | (A ^ B) &^ B",
		"int(Small) * 3",
		"int(Top) + int(Wide % uint64(1000))",
		"-A + +B",
		"len(Name) * B + len(Name + \"xy\")",
	}
	ffolds := []string{
		"float64(BigI) + 1.0 - float64(BigI)",
		"float64(Three) * 0.1 - 0.3",
		"float64(float32(Three) * float32(0.1)) - 0.3",
		"float64(A) / 3.0",
		"-float64(A) * 0.7",
	}
	var mains []string
	for i, x := range folds {
		fmt.Fprintf(&b, "func foldsI%d(x int) int {\n\tlet k = %s\n\tk * 1000 + x\n}\n\n", i, x)
		mains = append(mains, fmt.Sprintf("foldsI%d(%d)", i, n(9)))
	}
	for i, x := range ffolds {
		fmt.Fprintf(&b, "func foldsF%d(x float64) float64 {\n\tlet k = %s\n\tk + x\n}\n\n", i, x)
		mains = append(mains, fmt.Sprintf("foldsF%d(0.0)", i))
	}
	b.WriteString("func foldsS() string { Name + \"-\" + Name }\n\n")
	b.WriteString("func foldsB() bool { !Flag }\n\n")
	b.WriteString("func foldsN() uint8 { Top + uint8(1) - uint8(1) }\n\n")
	// A len of a constant as a call's argument (lzpack's strings.Slice(packed, 0, len(Magic))).
	b.WriteString("func foldsL(s string) string { strings.Slice(s + Name, 0, len(Name)) }\n\n")
	mains = append(mains, "foldsS()", "foldsB()", "foldsN()", "foldsL(\"ab\")")
	b.WriteString("func staysWrap() int8 { Small + Small + Small }\n\n")
	b.WriteString("func staysDiv() int { A / Zero }\n\n")
	mains = append(mains, "staysWrap()")
	b.WriteString("func main() needs Console {\n")
	for i, m := range mains {
		fmt.Fprintf(&b, "\tConsole.Println(\"%d: \\(%s)\")\n", i, m)
	}
	b.WriteString("\tConsole.Println(\"div: \\(staysDiv())\")\n")
	b.WriteString("}\n")
	return b.String()
}
