package irspike

import (
	"fmt"
	"math/rand/v2"
	"slices"
	"strings"
)

// GenerateFail writes the failure program of seed (IRG2): fallible
// functions over int with rows drawn from {E1, E2}, try, total and
// partial catches (`T as e` arms too), failure returns, unit fallible
// functions, impure functions that print trace lines (the order of
// effects), an operation type with a fallible operation, polling loops,
// operands that must run before a later operand's statements (a slice
// index, rarely out of range), and a rare division by zero. main catches
// every function's failures and prints its result.
func GenerateFail(seed uint64) string {
	g := &fgen{r: rand.New(rand.NewPCG(seed, seed^0x51ed270b2c3f4a19))}
	return g.program()
}

type ffunc struct {
	name   string
	params int
	row    []string // the failure row: E1, E2 or both; empty: cannot fail
	unit   bool     // no value
	needs  []string // Console, Log
}

func (f ffunc) fails(e string) bool { return slices.Contains(f.row, e) }

func (f ffunc) impure() bool { return len(f.needs) > 0 }

// within reports a row that f's row holds.
func (f ffunc) within(row []string) bool {
	for _, e := range row {
		if !f.fails(e) {
			return false
		}
	}
	return true
}

type fgen struct {
	r      *rand.Rand
	b      strings.Builder
	funcs  []ffunc
	cur    ffunc
	locals []string
	mut    int
}

func (g *fgen) n(k int) int { return g.r.IntN(k) }

func (g *fgen) program() string {
	g.b.WriteString("// generated by irspike.GenerateFail\n\n")
	g.b.WriteString("type E1 { Code int }\n\ntype E2 { Why string }\n\n")
	g.b.WriteString("type Log {\n\tNote(n int) int,\n\tProbe(n int) int fails E1,\n}\n\n")
	g.b.WriteString("type Prov {}\n\n")
	fmt.Fprintf(&g.b, "func Note(_ Prov, n int) int {\n\tn*%d + 1\n}\n\n", 2+g.n(3))
	fmt.Fprintf(&g.b, "func Probe(_ Prov, n int) int fails E1 {\n\tif n %% %d == 0 {\n\t\treturn E1{Code: n}\n\t}\n\tn - 1\n}\n\n", 2+g.n(3))
	g.b.WriteString("func pick(a int, b int) int {\n\ta*2 + b\n}\n\n")
	nf := 4 + g.n(5)
	for i := 0; i < nf; i++ {
		g.function(i)
	}
	g.main()
	return g.b.String()
}

var rows = [][]string{{"E1"}, {"E2"}, {"E1", "E2"}, {"E1", "E2"}, nil}

func (g *fgen) function(i int) {
	f := ffunc{name: fmt.Sprintf("f%d", i), params: 1 + g.n(3), row: rows[g.n(len(rows))]}
	if len(f.row) > 0 && g.n(5) == 0 {
		f.unit = true
	}
	if g.n(3) > 0 {
		f.needs = append(f.needs, "Console")
	}
	if g.n(2) == 0 {
		f.needs = append(f.needs, "Log")
	}
	if len(f.row) == 0 && len(f.needs) == 0 {
		f.needs = []string{"Console"}
	}
	g.cur = f
	g.locals = nil
	var ps []string
	for j := 0; j < f.params; j++ {
		ps = append(ps, fmt.Sprintf("p%d int", j))
		g.locals = append(g.locals, fmt.Sprintf("p%d", j))
	}
	head := "func " + f.name + "(" + strings.Join(ps, ", ") + ")"
	if !f.unit {
		head += " int"
	}
	if len(f.row) > 0 {
		head += " fails " + strings.Join(f.row, " | ")
	}
	if len(f.needs) > 0 {
		head += " needs " + strings.Join(f.needs, " | ")
	}
	g.b.WriteString(head + " {\n")
	if slices.Contains(f.needs, "Console") {
		// A trace line: the order of calls shows in the output.
		fmt.Fprintf(&g.b, "\tConsole.Println(\"%s\")\n", f.name)
	}
	for j, ns := 0, 2+g.n(5); j < ns; j++ {
		g.stmt("\t", 2)
	}
	g.tail()
	g.b.WriteString("}\n\n")
	g.funcs = append(g.funcs, f)
}

// callable are the earlier functions the current one may call: a pure
// function calls only pure ones, and an impure one only those whose needs
// it has.
func (g *fgen) callable(pred func(ffunc) bool) []ffunc {
	var out []ffunc
	for _, f := range g.funcs {
		ok := true
		for _, n := range f.needs {
			ok = ok && slices.Contains(g.cur.needs, n)
		}
		if ok && pred(f) {
			out = append(out, f)
		}
	}
	return out
}

func (g *fgen) args(f ffunc) string {
	var as []string
	for j := 0; j < f.params; j++ {
		as = append(as, g.expr(1))
	}
	return f.name + "(" + strings.Join(as, ", ") + ")"
}

func (g *fgen) local() string { return g.locals[g.n(len(g.locals))] }

// expr is a pure int expression; never a constant zero divisor.
func (g *fgen) expr(d int) string {
	if d <= 0 || g.n(3) == 0 {
		if g.n(3) == 0 {
			return fmt.Sprint(g.n(19) - 9)
		}
		return g.local()
	}
	switch g.n(4) {
	case 0:
		return "(" + g.expr(d-1) + " + " + g.expr(d-1) + ")"
	case 1:
		return "(" + g.expr(d-1) + " - " + g.expr(d-1) + ")"
	case 2:
		return "(" + g.expr(d-1) + " * " + fmt.Sprint(1+g.n(3)) + ")"
	}
	return "(" + g.expr(d-1) + " % " + fmt.Sprint(2+g.n(5)) + ")"
}

// let writes `let v = rhs` with a fresh v, after rhs is drawn (so rhs
// never names v).
func (g *fgen) let(in, rhs string) {
	fmt.Fprintf(&g.b, "%slet %s = %s\n", in, g.fresh(), rhs)
}

func (g *fgen) fresh() string {
	v := fmt.Sprintf("v%d", len(g.locals))
	g.locals = append(g.locals, v)
	return v
}

// stmt writes one statement of the current function.
func (g *fgen) stmt(in string, budget int) {
	f := g.cur
	switch k := g.n(14); {
	case k == 0 && slices.Contains(f.needs, "Console"):
		fmt.Fprintf(&g.b, "%sConsole.Println(\"%s.%d\")\n", in, f.name, g.n(100))
	case k == 1 && f.fails("E1"):
		fmt.Fprintf(&g.b, "%sif %s > %d {\n%s\treturn E1{Code: %s}\n%s}\n", in, g.local(), 3+g.n(6), in, g.expr(1), in)
	case k == 2 && f.fails("E2"):
		fmt.Fprintf(&g.b, "%sif %s < %d {\n%s\treturn E2{Why: \"w%d\"}\n%s}\n", in, g.local(), -g.n(6), in, g.n(9), in)
	case k == 3 && len(f.row) > 0:
		// try of a fallible callee whose row the current one holds.
		cs := g.callable(func(c ffunc) bool { return len(c.row) > 0 && f.within(c.row) })
		if len(cs) == 0 {
			break
		}
		c := cs[g.n(len(cs))]
		if c.unit {
			fmt.Fprintf(&g.b, "%stry %s\n", in, g.args(c))
			return
		}
		g.let(in, fmt.Sprintf("try %s", g.args(c)))
		return
	case k == 4 || k == 5:
		// A total catch of a fallible callee.
		cs := g.callable(func(c ffunc) bool { return len(c.row) > 0 })
		if len(cs) == 0 {
			break
		}
		c := cs[g.n(len(cs))]
		var arms []string
		for _, e := range c.row {
			arms = append(arms, g.arm(in, e, c.unit))
		}
		if c.unit {
			fmt.Fprintf(&g.b, "%s%s catch {\n%s%s}\n", in, g.args(c), strings.Join(arms, ""), in)
			return
		}
		g.let(in, fmt.Sprintf("%s catch {\n%s%s}", g.args(c), strings.Join(arms, ""), in))
		return
	case k == 6 && len(f.row) > 0:
		// A partial catch: the callee fails E1 and E2; one is caught, the
		// other leaves the current function, whose row holds it.
		cs := g.callable(func(c ffunc) bool { return len(c.row) == 2 && !c.unit })
		if len(cs) == 0 {
			break
		}
		caught, rest := "E1", "E2"
		if g.n(2) == 0 {
			caught, rest = rest, caught
		}
		if !f.fails(rest) {
			break
		}
		c := cs[g.n(len(cs))]
		g.let(in, fmt.Sprintf("try %s catch {\n%s%s}", g.args(c), g.arm(in, caught, false), in))
		return
	case k == 7 && slices.Contains(f.needs, "Log"):
		g.let(in, fmt.Sprintf("Log.Note(%s)", g.expr(2)))
		return
	case k == 8 && slices.Contains(f.needs, "Log") && f.fails("E1"):
		g.let(in, fmt.Sprintf("try Log.Probe(%s)", g.expr(2)))
		return
	case k == 9 && budget > 0 && f.impure():
		// A counting loop in an impure frame: it polls at each back edge.
		i := g.fresh()
		fmt.Fprintf(&g.b, "%slet mut %s = 0\n%sfor %s < %d {\n", in, i, in, i, 1+g.n(3))
		saved := len(g.locals)
		g.stmt(in+"\t", budget-1)
		g.sinkFrom(in+"\t", saved)
		g.locals = g.locals[:saved]
		fmt.Fprintf(&g.b, "%s\t%s = %s + 1\n%s}\n", in, i, i, in)
		return
	case k == 10 && budget > 0 && f.impure():
		v := fmt.Sprintf("x%d", len(g.locals))
		fmt.Fprintf(&g.b, "%sfor %s in []int{%d, %d} {\n", in, v, g.n(9), g.n(9))
		saved := len(g.locals)
		g.locals = append(g.locals, v)
		g.stmt(in+"\t", budget-1)
		g.sinkFrom(in+"\t", saved)
		g.locals = g.locals[:saved]
		fmt.Fprintf(&g.b, "%s}\n", in)
		return
	case k == 11 && len(f.row) > 0:
		// Operands in order: the index runs before the try's statements
		// (rarely out of range: the defect must come first on both paths).
		cs := g.callable(func(c ffunc) bool { return !c.unit && len(c.row) > 0 && f.within(c.row) })
		if len(cs) == 0 {
			break
		}
		// try covers the whole expression: the callee's failure leaves.
		g.let(in, fmt.Sprintf("try pick(%s, %s)", g.indexed(), g.args(cs[g.n(len(cs))])))
		return
	case k == 12:
		// Divides by zero when the two locals are equal: the defect.
		g.let(in, fmt.Sprintf("%s / (%s - %s)", g.local(), g.local(), g.local()))
		return
	case k == 13 && f.impure():
		// An impure call that cannot fail.
		cs := g.callable(func(c ffunc) bool { return len(c.row) == 0 && !c.unit })
		if len(cs) == 0 {
			break
		}
		c := cs[g.n(len(cs))]
		if g.n(2) == 0 {
			// Inside an expression: IR keeps the emitter's order by
			// leaving this body to the source path.
			g.let(in, fmt.Sprintf("%s + %s", g.indexed(), g.args(c)))
			return
		}
		g.let(in, g.args(c))
		return
	}
	g.let(in, g.expr(2))
}

// indexed reads a two-element slice: in range, or rarely past its end
// (the defect must come before a later operand's effects on both paths).
func (g *fgen) indexed() string {
	idx := fmt.Sprintf("(%s %% 2 + 2) %% 2", g.local())
	if g.n(6) == 0 {
		idx = "2 + " + g.local() + "*" + g.local()
	}
	return fmt.Sprintf("([]int{%d, %d})[%s]", g.n(9), g.n(9), idx)
}

// arm is a catch arm of the error e: `e as x` reads its payload.
func (g *fgen) arm(in, e string, unit bool) string {
	val := fmt.Sprint(g.n(50))
	switch {
	case unit && slices.Contains(g.cur.needs, "Console"):
		return fmt.Sprintf("%s\tcase %s:\n%s\t\tConsole.Println(\"%s caught %s\")\n", in, e, in, g.cur.name, e)
	case unit:
		return fmt.Sprintf("%s\tcase %s:\n%s\t\tpick(1, 2)\n", in, e, in)
	case g.n(2) == 0 && e == "E1":
		return fmt.Sprintf("%s\tcase E1 as x:\n%s\t\tx.Code + %s\n", in, in, val)
	case e == "E2" && g.n(2) == 0:
		return fmt.Sprintf("%s\tcase E2 as x:\n%s\t\tlen(x.Why) + %s\n", in, in, val)
	}
	return fmt.Sprintf("%s\tcase %s:\n%s\t\t%s\n", in, e, in, val)
}

// sinkFrom reads the locals from index from on, so none is unread.
func (g *fgen) sinkFrom(in string, from int) {
	if len(g.locals) <= from {
		return
	}
	g.mut++
	ret := "0"
	if g.cur.unit {
		ret = ""
	}
	fmt.Fprintf(&g.b, "%sif %s == %d {\n%s\treturn %s\n%s}\n", in, strings.Join(g.locals[from:], " + "), 7777+g.mut, in, ret, in)
}

func (g *fgen) tail() {
	f := g.cur
	if f.unit {
		g.sinkFrom("\t", 0)
		return
	}
	g.sinkFrom("\t", f.params)
	sum := strings.Join(g.locals[:f.params], " + ")
	cs := g.callable(func(c ffunc) bool { return !c.unit && len(c.row) > 0 && f.within(c.row) })
	switch {
	case len(cs) > 0 && g.n(3) == 0:
		c := cs[g.n(len(cs))]
		if slices.Equal(c.row, f.row) && g.n(2) == 0 {
			fmt.Fprintf(&g.b, "\t%s\n", g.args(c)) // untried: its value and error pass on
			return
		}
		fmt.Fprintf(&g.b, "\ttry pick(%s, %s)\n", sum, g.args(c))
		return
	}
	fmt.Fprintf(&g.b, "\t%s\n", sum)
}

func (g *fgen) main() {
	g.b.WriteString("func main() needs Console {\n\twith context { Log: Prov } {\n")
	for _, f := range g.funcs {
		var as []string
		for j := 0; j < f.params; j++ {
			as = append(as, fmt.Sprint(g.n(21)-10))
		}
		call := f.name + "(" + strings.Join(as, ", ") + ")"
		if len(f.row) == 0 {
			fmt.Fprintf(&g.b, "\t\tConsole.Println(\"%s \\(%s)\")\n", f.name, call)
			continue
		}
		var arms []string
		for _, e := range f.row {
			field := "x.Code"
			if e == "E2" {
				field = "x.Why"
			}
			arm := fmt.Sprintf("\t\tcase %s as x:\n\t\t\tConsole.Println(\"%s %s \\(%s)\")\n", e, f.name, e, field)
			if !f.unit {
				arm += "\t\t\t0\n"
			}
			arms = append(arms, arm)
		}
		if f.unit {
			fmt.Fprintf(&g.b, "\t\t%s catch {\n%s\t\t}\n", call, strings.Join(arms, ""))
			continue
		}
		fmt.Fprintf(&g.b, "\t\tlet r%s = %s catch {\n%s\t\t}\n\t\tConsole.Println(\"%s \\(r%s)\")\n", f.name, call, strings.Join(arms, ""), f.name, f.name)
	}
	g.b.WriteString("\t}\n}\n")
}
