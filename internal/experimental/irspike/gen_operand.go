package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateOperand is a program of std calls whose operand is a variant
// passed where its union is the parameter (FLIP OPC-conv): a generic std
// body (sync.NewRef[Small] of a variant) and a std operation (a Ref's Set
// of one), each made by a function the IR lowers. The cells hold seeded
// variants on seeded inputs, so a variant put into the union wrong, or the
// wrong operand passed, changes the output.
func GenerateOperand(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x6a09e667f3bcc909))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateOperand\n\nimport sync\n\ntype A {}\n\ntype B { N int }\n\ntype Small = A | B\n\n")
	fmt.Fprintf(&b, "func weight(s Small) int {\n\tmatch s {\n\tcase A:\n\t\t%d\n\tcase B as x:\n\t\tx.N * %d\n\t}\n}\n\n", 1+g.n(9), 2+g.n(3))
	first := []string{"A", fmt.Sprintf("B{N: %d}", g.n(9))}[g.n(2)]
	fmt.Fprintf(&b, "func cell(i int) int {\n\tlet r = sync.NewRef[Small](%s)\n\tif i %% %d == 0 {\n\t\tr.Set(B{N: i + %d})\n\t}\n\tif i > %d {\n\t\tr.Set(A)\n\t}\n\tweight(r.Get())\n}\n\n", first, 2+g.n(2), g.n(5), 4+g.n(6))
	var ins []string
	for i, n := 0, 3+g.n(4); i < n; i++ {
		ins = append(ins, fmt.Sprint(g.n(12)))
	}
	fmt.Fprintf(&b, "func main() needs Console {\n\tfor i in []int{%s} {\n\t\tlet c = cell(i)\n\t\tConsole.Println(\"\\(i): \\(c)\")\n\t}\n}\n", strings.Join(ins, ", "))
	return b.String()
}
