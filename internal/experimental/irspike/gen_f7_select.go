package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateSelect is a program of two packages (F7, "selector on a
// non-record"): package lib declares lets and records with no fields, and
// package main reads them qualified, lib.Name. The lets are of the same
// type in pairs (two int slices, two Points), and the records are the
// variants of one union, so a name read as another of its package reads
// a different value or variant. It returns the files, by path from the
// module's folder; the program is cmd/p.
func GenerateSelect(seed uint64) map[string]string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x6a09e667f3bcc909))}
	var lib strings.Builder
	lib.WriteString("// generated by irspike.GenerateSelect\n\n")
	lib.WriteString("// Point is a pair of ints.\ntype Point { X int, Y int }\n\n")
	lib.WriteString("// North, South, East and West are the directions.\ntype North {}\n\ntype South {}\n\ntype East {}\n\ntype West {}\n\n")
	lib.WriteString("// Dir is one direction.\ntype Dir = North | South | East | West\n\n")
	fmt.Fprintf(&lib, "// Steps and Costs are int lists.\nlet Steps = %s\n\nlet Costs = %s\n\n", g.nonEmpty(), g.nonEmpty())
	fmt.Fprintf(&lib, "// Start and Goal are points.\nlet Start = Point{X: %d, Y: %d}\n\nlet Goal = Point{X: %d, Y: %d}\n\n", g.n(9), g.n(9), g.n(9), g.n(9))
	fmt.Fprintf(&lib, "// Name is a text.\nlet Name = \"n%d\"\n", g.n(99))

	var m strings.Builder
	m.WriteString("// generated by irspike.GenerateSelect\n\nimport p/lib\n\n")
	// dir picks a variant written bare and qualified.
	dirs := []string{"lib.North", "lib.South", "lib.East", "lib.West"}
	g.r.Shuffle(len(dirs), func(i, j int) { dirs[i], dirs[j] = dirs[j], dirs[i] })
	fmt.Fprintf(&m, "func dir(i int) lib.Dir {\n\tif i %% 4 == 0 {\n\t\t%s\n\t} else if i %% 4 == 1 {\n\t\t%s\n\t} else if i %% 4 == 2 {\n\t\t%s\n\t} else {\n\t\t%s\n\t}\n}\n\n", dirs[0], dirs[1], dirs[2], dirs[3])
	m.WriteString("func dirName(d lib.Dir) string {\n\tmatch d {\n\tcase lib.North:\n\t\t\"N\"\n\tcase lib.South:\n\t\t\"S\"\n\tcase lib.East:\n\t\t\"E\"\n\tcase lib.West:\n\t\t\"W\"\n\t}\n}\n\n")
	// sum reads the two lists, at seeded weights.
	fmt.Fprintf(&m, "func sum(k int) int {\n\tlet mut s = 0\n\tfor x in lib.Steps {\n\t\ts = s + x * %d\n\t}\n\tfor x in lib.Costs {\n\t\ts = s + x * %d + k\n\t}\n\ts + len(lib.Steps) * %d\n}\n\n", 1+g.n(5), 7+g.n(5), 100+g.n(9))
	// span reads the two points' fields.
	fmt.Fprintf(&m, "func span() int {\n\t(lib.Goal.X - lib.Start.X) * %d + lib.Goal.Y * %d - lib.Start.Y\n}\n\n", 1+g.n(4), 10+g.n(4))
	m.WriteString("func label(i int) string {\n\tlib.Name + \"-\" + dirName(dir(i))\n}\n\n")
	m.WriteString("func main() needs Console {\n")
	for k := 0; k < 3; k++ {
		i := g.n(8)
		fmt.Fprintf(&m, "\tConsole.Println(\"%d: \\(sum(%d)) \\(span()) \\(label(%d))\")\n", k, g.n(5), i)
	}
	m.WriteString("}\n")
	return map[string]string{
		"ergo.mod":        "module p\n",
		"lib/lib.ergo":    lib.String(),
		"cmd/p/main.ergo": m.String(),
	}
}

// nonEmpty is an int slice literal of one to five elements.
func (g *ggen) nonEmpty() string {
	var xs []string
	for i, n := 0, 1+g.n(5); i < n; i++ {
		xs = append(xs, fmt.Sprint(g.n(9)))
	}
	return "[]int{" + strings.Join(xs, ", ") + "}"
}
