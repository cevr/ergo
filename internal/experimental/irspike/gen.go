package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// Generate writes the Ergo program of seed: package lets, records, an
// operation type and its provider (the interface call), functions over
// int, int64, uint8, float64, duration, bool, string, records and slices
// in the IR subset (if expressions, discards, op-assignments, interpolated
// strings, loops with break and continue, unnamed parameters), some
// functions outside it (planted constructs: they keep their source bodies,
// and IR bodies call them), and a main that prints every function's
// result. Loops are bounded by construction; an index is in range unless
// the seed draws a raw one (the out-of-range negative control: both paths
// must fail the same way).
func Generate(seed uint64) string {
	text, _ := GeneratePlanted(seed)
	return text
}

// GeneratePlanted is Generate's program and, for each function outside
// the subset, the census reasons of the constructs planted in it: the
// reference a census of the program must contain.
func GeneratePlanted(seed uint64) (string, map[string][]string) {
	g := &gen{r: rand.New(rand.NewPCG(seed, seed^0x9e3779b97f4a7c15)), planted: map[string][]string{}, oob: seed%8 == 0}
	return g.program(), g.planted
}

// GenerateN is Generate with n functions: the decode-cost receipt's large
// programs.
func GenerateN(seed uint64, n int) string {
	g := &gen{r: rand.New(rand.NewPCG(seed, seed^0x9e3779b97f4a7c15)), planted: map[string][]string{}, funcs0: n}
	return g.program()
}

// The planted constructs and the census reason of each: constructs the IR
// builder does not lower yet.
const (
	reasonIfExpr  = "expression *syntax.IfStmt" // an if expression inside an operand
	reasonFuncLit = "expression *syntax.FuncLit"
	reasonRange   = "operator .."
)

var plants = []struct{ reason string }{{reasonIfExpr}, {reasonFuncLit}, {reasonRange}}

type gtype string

const (
	tInt  gtype = "int"
	tI64  gtype = "int64"
	tU8   gtype = "uint8"
	tF64  gtype = "float64"
	tDur  gtype = "duration"
	tBool gtype = "bool"
	tStr  gtype = "string"
	tRec  gtype = "Rec"
	tInts gtype = "[]int"
	tRecs gtype = "[]Rec"
)

// scalars are the types an interpolated string prints.
var scalars = []gtype{tInt, tI64, tU8, tF64, tDur, tBool, tStr}

// The package lets every function may read.
var globals = []gvar{{name: "Base", t: tInt}, {name: "Label", t: tStr}}

type gvar struct {
	name string
	t    gtype
	mut  bool
}

type gfunc struct {
	name   string
	params []gvar
	result gtype
	src    bool // outside the subset on purpose
	// impure: a function literal makes it impure, and an IR body calls
	// only pure functions, so no generated function calls it.
	impure bool
}

type gen struct {
	r      *rand.Rand
	b      strings.Builder
	funcs  []gfunc
	scope  []gvar
	locals int
	depth  int             // statement nesting
	used   map[string]bool // the locals read so far
	// assigned are the mut locals reassigned so far.
	assigned map[string]bool
	// retired are the names of locals whose block ended: a later block
	// may declare the name again, with another type (Ergo refuses only a
	// name of an enclosing scope).
	retired []string
	// planted are the census reasons planted in each function outside the
	// subset.
	planted map[string][]string
	// funcs0, when set, is the number of functions (GenerateN).
	funcs0 int
	// oob: main ends with an out-of-range read in an IR body (every
	// eighth seed).
	oob bool
}

func (g *gen) n(k int) int { return g.r.IntN(k) }

func (g *gen) program() string {
	g.b.WriteString("// generated by irspike.Generate\n\n")
	fmt.Fprintf(&g.b, "let Base = %d\n\nlet Label = %q\n\n", g.n(9), []string{"L", "lab", ""}[g.n(3)])
	g.b.WriteString("type Rec { A int, B bool, S string, L []int }\n\n")
	g.b.WriteString("type Op {\n\tApply(a int, b int) int,\n}\n\n")
	g.b.WriteString("type Prov {}\n\n")
	k := 1 + g.n(4)
	fmt.Fprintf(&g.b, "func Apply(_ Prov, a int, b int) int {\n\ta*%d - b\n}\n\n", k)
	g.b.WriteString("func viaOp(a int, b int) int needs Op {\n\tOp.Apply(a, b)\n}\n\n")
	nf := 3 + g.n(5)
	if g.funcs0 > 0 {
		nf = g.funcs0
	}
	for i := 0; i < nf; i++ {
		g.function(i)
	}
	if g.oob {
		// The out-of-range negative control, in an IR body: both paths
		// must fail the same way.
		g.b.WriteString("func oob(xs []int, i int) int {\n\txs[len(xs) + i*i]\n}\n\n")
	}
	g.main()
	return g.b.String()
}

var resultTypes = []gtype{tInt, tInt, tInt, tBool, tStr, tStr, tRec, tInts, tI64, tF64, tU8, tDur}
var paramTypes = []gtype{tInt, tInt, tBool, tStr, tRec, tInts, tRecs, tI64, tF64, tU8, tDur}

func (g *gen) function(i int) {
	f := gfunc{name: fmt.Sprintf("f%d", i), result: resultTypes[g.n(len(resultTypes))], src: g.n(5) == 0}
	np := 1 + g.n(4)
	for j := 0; j < np; j++ {
		p := gvar{name: fmt.Sprintf("p%d", j), t: paramTypes[g.n(len(paramTypes))]}
		if j > 0 && g.n(6) == 0 {
			p.name = "_" // an unnamed parameter: callers pass it, no body reads it
		}
		f.params = append(f.params, p)
	}
	var ps []string
	for _, p := range f.params {
		ps = append(ps, p.name+" "+string(p.t))
	}
	start := g.b.Len()
	defer g.mutFix(start)
	fmt.Fprintf(&g.b, "func %s(%s) %s {\n", f.name, strings.Join(ps, ", "), f.result)
	g.assigned = map[string]bool{}
	g.scope = nil
	for _, p := range f.params {
		if p.name != "_" {
			g.scope = append(g.scope, p)
		}
	}
	params := len(g.scope)
	g.locals = 0
	g.depth = 1
	g.used = map[string]bool{}
	g.retired = nil
	if f.src {
		// Outside the subset: one to three planted constructs, each its
		// own statement, so a census must name every one (Planted).
		for {
			for _, p := range plants {
				if g.n(2) == 0 {
					continue
				}
				switch p.reason {
				case reasonIfExpr:
					fmt.Fprintf(&g.b, "\tlet pick = 1 + (if %s { %s } else { %s })\n", g.expr(tBool, 1), g.expr(tInt, 1), g.expr(tInt, 1))
					g.scope = append(g.scope, gvar{name: "pick", t: tInt})
				case reasonFuncLit:
					fmt.Fprintf(&g.b, "\tlet fl = func(x int) int { x + %d }\n\tlet flv = fl(%s)\n", g.n(5), g.expr(tInt, 1))
					g.scope = append(g.scope, gvar{name: "flv", t: tInt})
					f.impure = true
				case reasonRange:
					fmt.Fprintf(&g.b, "\tfor k in 0..%d {\n\t\tif k == 7 {\n\t\t\treturn %s\n\t\t}\n\t}\n", 1+g.n(3), g.expr(f.result, 1))
				}
				g.planted[f.name] = append(g.planted[f.name], p.reason)
			}
			if len(g.planted[f.name]) > 0 {
				break
			}
		}
	}
	ns := g.n(6)
	for j := 0; j < ns; j++ {
		g.stmt(f.result, 2)
	}
	g.sink(f.result, params)
	if f.result == tStr {
		// A string result ends with the text of every scalar in scope, so
		// a wrong local (an op-assignment, a loop's counter, a value's
		// text) shows in the output.
		fmt.Fprintf(&g.b, "\t(%s) + %s\n}\n\n", g.expr(tStr, 3), g.trace())
	} else {
		fmt.Fprintf(&g.b, "\t%s\n}\n\n", g.value(f.result, 3))
	}
	g.funcs = append(g.funcs, f)
}

func (g *gen) indent() string { return strings.Repeat("\t", g.depth) }

func (g *gen) fresh(t gtype, mut bool) gvar {
	g.locals++
	return gvar{name: fmt.Sprintf("v%d", g.locals), t: t, mut: mut}
}

// value is an expression of type t in a whole-value position (a let, an
// assignment, a result): sometimes an if expression.
func (g *gen) value(t gtype, d int) string {
	if d > 0 && g.n(6) == 0 {
		return "if " + g.expr(tBool, d-1) + " { " + g.expr(t, d-1) + " } else { " + g.expr(t, d-1) + " }"
	}
	return g.expr(t, d)
}

// stmt writes one statement of a function whose result is res.
func (g *gen) stmt(res gtype, budget int) {
	in := g.indent()
	switch k := g.n(14); {
	case k < 5 || budget <= 0:
		t := paramTypes[g.n(len(paramTypes))]
		mut := g.n(2) == 0
		v := g.fresh(t, mut)
		if !mut && len(g.retired) > 0 && g.n(2) == 0 {
			// A name of an ended sibling block, declared again.
			j := g.n(len(g.retired))
			v.name = g.retired[j]
			g.retired = append(g.retired[:j], g.retired[j+1:]...)
			g.used[v.name] = false
		}
		kw := "let"
		if mut {
			// Ergo refuses a mut that is never reassigned: the keyword is
			// decided when the function ends (mutFix).
			kw = "let @mut:" + v.name + "@"
		}
		fmt.Fprintf(&g.b, "%s%s %s %s = %s\n", in, kw, v.name, v.t, g.value(t, 3))
		g.scope = append(g.scope, v)
		if mut && g.n(2) == 0 {
			g.assign(v)
		}
	case k < 6:
		var muts []gvar
		for _, v := range g.scope {
			if v.mut {
				muts = append(muts, v)
			}
		}
		if len(muts) == 0 {
			g.stmt(res, 0)
			return
		}
		g.assign(muts[g.n(len(muts))])
	case k < 7:
		fmt.Fprintf(&g.b, "%slet _ = %s\n", in, g.expr(scalars[g.n(len(scalars))], 2))
	case k < 9:
		fmt.Fprintf(&g.b, "%sif %s {\n", in, g.expr(tBool, 3))
		g.block(res, budget-1)
		if g.n(2) == 0 {
			fmt.Fprintf(&g.b, "%s} else {\n", in)
			g.block(res, budget-1)
		}
		fmt.Fprintf(&g.b, "%s}\n", in)
	case k < 10:
		// A bounded counting loop; only the loop's own lines write its
		// counter: a continue counts first, a break leaves.
		i := g.fresh(tInt, true)
		bound := 1 + g.n(6)
		g.used[i.name] = true
		if g.n(3) == 0 {
			fmt.Fprintf(&g.b, "%slet mut %s = 0\n%sfor {\n%s\tif %s >= %d {\n%s\t\tbreak\n%s\t}\n", in, i.name, in, in, i.name, bound, in, in)
		} else {
			fmt.Fprintf(&g.b, "%slet mut %s = 0\n%sfor %s < %d {\n", in, i.name, in, i.name, bound)
		}
		g.scope = append(g.scope, gvar{name: i.name, t: tInt})
		if g.n(3) == 0 {
			fmt.Fprintf(&g.b, "%s\tif %s {\n%s\t\t%s = %s + 1\n%s\t\tcontinue\n%s\t}\n", in, g.expr(tBool, 1), in, i.name, i.name, in, in)
		}
		if g.n(4) == 0 {
			fmt.Fprintf(&g.b, "%s\tif %s {\n%s\t\tbreak\n%s\t}\n", in, g.expr(tBool, 1), in, in)
		}
		g.block(res, budget-1)
		fmt.Fprintf(&g.b, "%s\t%s = %s + 1\n%s}\n", in, i.name, i.name, in)
	case k < 11:
		x := g.expr(tInts, 2)
		v := g.fresh(tInt, false)
		if g.n(2) == 0 {
			ix := g.fresh(tInt, false)
			fmt.Fprintf(&g.b, "%sfor %s, %s in %s {\n", in, ix.name, v.name, x)
			g.block(res, budget-1, ix, v)
		} else {
			fmt.Fprintf(&g.b, "%sfor %s in %s {\n", in, v.name, x)
			g.block(res, budget-1, v)
		}
		fmt.Fprintf(&g.b, "%s}\n", in)
	default:
		fmt.Fprintf(&g.b, "%sif %s {\n%s\treturn %s\n%s}\n", in, g.expr(tBool, 2), in, g.value(res, 2), in)
	}
}

// assign writes an assignment of the mut local v: often an op-assignment.
func (g *gen) assign(v gvar) {
	in := g.indent()
	g.assigned[v.name] = true
	if op := g.opAssign(v.t); op != "" {
		fmt.Fprintf(&g.b, "%s%s %s= %s\n", in, v.name, op, g.expr(v.t, 2))
		return
	}
	fmt.Fprintf(&g.b, "%s%s = %s\n", in, v.name, g.value(v.t, 3))
}

// opAssign is an assignment operator for a local of type t, or "" for a
// plain assignment.
func (g *gen) opAssign(t gtype) string {
	if g.n(2) == 0 {
		return ""
	}
	switch t {
	case tInt, tI64:
		return []string{"+", "-", "*", "|", "&", "^", "&^"}[g.n(7)]
	case tU8:
		return []string{"+", "*", "|", "^"}[g.n(4)]
	case tF64:
		return []string{"+", "-", "*"}[g.n(3)]
	case tDur, tStr:
		return "+"
	}
	return ""
}

// mutFix decides each placeholder `@mut:NAME@` of the function written
// from start: `mut` when NAME is reassigned, else nothing.
func (g *gen) mutFix(start int) {
	text := g.b.String()
	body := text[start:]
	for {
		i := strings.Index(body, "@mut:")
		if i < 0 {
			break
		}
		j := strings.Index(body[i+5:], "@")
		name := body[i+5 : i+5+j]
		kw := ""
		if g.assigned[name] {
			kw = "mut "
		}
		body = body[:i] + kw + body[i+5+j+1:]
	}
	body = strings.ReplaceAll(body, "let  ", "let ")
	g.b.Reset()
	g.b.WriteString(text[:start] + body)
}

// block writes a nested statement list, with pre (loop bindings) in scope;
// its names go out of scope after it, each one read at least once.
func (g *gen) block(res gtype, budget int, pre ...gvar) {
	saved := len(g.scope)
	g.scope = append(g.scope, pre...)
	g.depth++
	for j, n := 0, 1+g.n(3); j < n; j++ {
		g.stmt(res, budget)
	}
	g.sink(res, saved)
	g.depth--
	for _, v := range g.scope[saved:] {
		g.retired = append(g.retired, v.name)
	}
	g.scope = g.scope[:saved]
}

// sink reads every unread local of scope[from:]: Ergo refuses a local that
// is never read.
func (g *gen) sink(res gtype, from int) {
	for _, v := range g.scope[from:] {
		if g.used[v.name] {
			continue
		}
		g.used[v.name] = true
		var use string
		switch v.t {
		case tInt, tI64, tU8:
			use = v.name + " == 7"
		case tF64:
			use = v.name + " > 7.5"
		case tDur:
			use = v.name + " == 7s"
		case tBool:
			use = v.name
		case tStr:
			use = v.name + ` == "q"`
		case tRec:
			use = v.name + ".A == 7"
		default:
			use = "len(" + v.name + ") == 7"
		}
		in := g.indent()
		fmt.Fprintf(&g.b, "%sif %s {\n%s\treturn %s\n%s}\n", in, use, in, g.expr(res, 1), in)
	}
}

func (g *gen) pick(t gtype) (gvar, bool) {
	var vs []gvar
	for _, v := range g.scope {
		if v.t == t {
			vs = append(vs, v)
		}
	}
	if g.used != nil {
		for _, v := range globals {
			if v.t == t && g.n(4) == 0 {
				vs = append(vs, v)
			}
		}
	}
	if len(vs) == 0 {
		return gvar{}, false
	}
	return vs[g.n(len(vs))], true
}

// read is v's name, marked read.
func (g *gen) read(v gvar) string {
	if g.used != nil {
		g.used[v.name] = true
	}
	return v.name
}

// call is a call of an earlier function returning t, or "".
func (g *gen) call(t gtype, d int) string {
	var fs []gfunc
	for _, f := range g.funcs {
		if f.result == t && !f.impure {
			fs = append(fs, f)
		}
	}
	if len(fs) == 0 {
		return ""
	}
	f := fs[g.n(len(fs))]
	var args []string
	for _, p := range f.params {
		args = append(args, g.expr(p.t, d-1))
	}
	return f.name + "(" + strings.Join(args, ", ") + ")"
}

// variable is a local or parameter of type t, read, or "".
func (g *gen) variable(t gtype) string {
	var vs []gvar
	for _, v := range g.scope {
		if v.t == t {
			vs = append(vs, v)
		}
	}
	if len(vs) == 0 {
		return ""
	}
	return g.read(vs[g.n(len(vs))])
}

// expr is an expression of type t, at most d deep.
func (g *gen) expr(t gtype, d int) string {
	if d > 0 && g.n(5) == 0 {
		if c := g.call(t, d); c != "" {
			return c
		}
	}
	if v, ok := g.pick(t); ok && (d <= 0 || g.n(3) == 0) {
		return g.read(v)
	}
	if d <= 0 {
		return g.leaf(t)
	}
	switch t {
	case tInt:
		switch g.n(10) {
		case 0, 1:
			ops := []string{"+", "-", "*"}
			return "(" + g.expr(tInt, d-1) + " " + ops[g.n(3)] + " " + g.expr(tInt, d-1) + ")"
		case 2:
			ops := []string{"/", "%"}
			return "(" + g.expr(tInt, d-1) + " " + ops[g.n(2)] + " " + fmt.Sprint(1+g.n(9)) + ")"
		case 3:
			return g.expr(tRec, d-1) + ".A"
		case 4:
			return "len(" + g.expr(tInts, d-1) + ")"
		case 5:
			return "len(" + g.expr(tStr, d-1) + ")"
		case 6:
			return g.index(d)
		case 7:
			return "(-(" + g.expr(tInt, d-1) + "))"
		case 8:
			ops := []string{"&", "|", "^", "&^"}
			return "(" + g.expr(tInt, d-1) + " " + ops[g.n(4)] + " " + g.expr(tInt, d-1) + ")"
		default:
			return g.leaf(tInt)
		}
	case tI64:
		switch g.n(7) {
		case 0, 1:
			ops := []string{"+", "-", "&", "|", "^", "&^"}
			return "(" + g.expr(tI64, d-1) + " " + ops[g.n(len(ops))] + " " + g.expr(tI64, d-1) + ")"
		case 2:
			ops := []string{"/", "%"}
			return "(" + g.expr(tI64, d-1) + " " + ops[g.n(2)] + " " + fmt.Sprint(1+g.n(9)) + ")"
		case 3:
			// * and << have a variable on their left: a constant product
			// that overflows does not check (the run-time one wraps).
			v := g.variable(tI64)
			if v == "" {
				return g.leaf(tI64)
			}
			if g.n(2) == 0 {
				return "(" + v + " * " + g.expr(tI64, d-1) + ")"
			}
			ops := []string{"<<", ">>"}
			return "(" + v + " " + ops[g.n(2)] + " (" + g.expr(tI64, d-1) + " & 7))"
		case 4:
			return []string{"(-(", "(^(", "(+("}[g.n(3)] + g.expr(tI64, d-1) + "))"
		default:
			return g.leaf(tI64)
		}
	case tU8:
		// A uint8 constant expression that overflows does not check, so
		// arithmetic has a variable on its left.
		if g.n(3) == 0 {
			return g.leaf(tU8)
		}
		v := g.variable(tU8)
		if v == "" {
			return g.leaf(tU8)
		}
		ops := []string{"+", "-", "*", "&", "|", "^", "<<"}
		op := ops[g.n(len(ops))]
		if op == "<<" {
			return "(" + v + " << (" + g.expr(tU8, d-1) + " & 7))"
		}
		return "(" + v + " " + op + " " + g.expr(tU8, d-1) + ")"
	case tF64:
		switch g.n(5) {
		case 0, 1:
			ops := []string{"+", "-", "*"}
			return "(" + g.expr(tF64, d-1) + " " + ops[g.n(3)] + " " + g.expr(tF64, d-1) + ")"
		case 2:
			return "(" + g.expr(tF64, d-1) + " / " + []string{"2.0", "0.5", "3.0", "1.25"}[g.n(4)] + ")"
		case 3:
			return "(-(" + g.expr(tF64, d-1) + "))"
		default:
			return g.leaf(tF64)
		}
	case tDur:
		if g.n(2) == 0 {
			ops := []string{"+", "-"}
			return "(" + g.expr(tDur, d-1) + " " + ops[g.n(2)] + " " + g.expr(tDur, d-1) + ")"
		}
		return g.leaf(tDur)
	case tBool:
		switch g.n(8) {
		case 0:
			ops := []string{"<", "<=", ">", ">=", "==", "!="}
			return "(" + g.expr(tInt, d-1) + " " + ops[g.n(6)] + " " + g.expr(tInt, d-1) + ")"
		case 1:
			ops := []string{"&&", "||"}
			return "(" + g.expr(tBool, d-1) + " " + ops[g.n(2)] + " " + g.expr(tBool, d-1) + ")"
		case 2:
			return "!" + g.expr(tBool, d-1)
		case 3:
			return g.expr(tRec, d-1) + ".B"
		case 4:
			return "(" + g.expr(tStr, d-1) + " == " + g.expr(tStr, d-1) + ")"
		case 5:
			nt := []gtype{tI64, tU8, tF64, tDur}[g.n(4)]
			ops := []string{"<", "<=", ">", ">=", "==", "!="}
			return "(" + g.expr(nt, d-1) + " " + ops[g.n(6)] + " " + g.expr(nt, d-1) + ")"
		default:
			return g.leaf(tBool)
		}
	case tStr:
		switch g.n(5) {
		case 0:
			return "(" + g.expr(tStr, d-1) + " + " + g.expr(tStr, d-1) + ")"
		case 1:
			return g.expr(tRec, d-1) + ".S"
		case 2, 3:
			return g.interp(d)
		default:
			return g.leaf(tStr)
		}
	case tRec:
		if g.n(3) == 0 {
			return g.recsIndex(d)
		}
		return "(Rec{A: " + g.expr(tInt, d-1) + ", B: " + g.expr(tBool, d-1) + ", S: " + g.expr(tStr, d-1) + ", L: " + g.expr(tInts, d-1) + "})"
	case tInts:
		if g.n(3) == 0 {
			return g.expr(tRec, d-1) + ".L"
		}
		return g.leaf(tInts)
	case tRecs:
		return "([]Rec{" + g.expr(tRec, d-1) + ", " + g.expr(tRec, d-1) + "})"
	}
	panic("gen: type " + string(t))
}

// trace is an interpolated string of every scalar parameter and local in
// scope.
func (g *gen) trace() string {
	var b strings.Builder
	b.WriteString(`"`)
	for _, v := range g.scope {
		for _, s := range scalars {
			if v.t == s {
				b.WriteString(`|\(` + g.read(v) + `)`)
			}
		}
	}
	b.WriteString(`"`)
	return b.String()
}

// interp is an interpolated string of one to three scalar values.
func (g *gen) interp(d int) string {
	var b strings.Builder
	b.WriteString(`"`)
	for i, n := 0, 1+g.n(3); i < n; i++ {
		b.WriteString([]string{"", "x", "a b", "=", `\n`}[g.n(5)])
		t := scalars[g.n(len(scalars))]
		x := g.expr(t, d-1)
		if (t == tInt || t == tI64 || t == tF64) && g.n(2) == 0 {
			x = "-(" + x + ")" // a signed value's text keeps its sign
		}
		b.WriteString(`\(` + x + `)`)
	}
	b.WriteString([]string{"", "!", "z"}[g.n(3)] + `"`)
	return b.String()
}

// index reads a slice element: in range by construction, or (rarely) past
// its end, the out-of-range negative control.
func (g *gen) index(d int) string {
	var xs string
	if v, ok := g.pick(tInts); ok {
		xs = g.read(v)
	} else {
		xs = g.expr(tInts, d-1)
	}
	i := g.expr(tInt, d-1)
	if g.n(25) == 0 {
		// Past the end, never a constant (the checker refuses a constant
		// negative index).
		return xs + "[len(" + xs + ") + (" + i + ") * (" + i + ")]"
	}
	// ((i % n) + n) % n, with n >= 1: the generated slices are never empty.
	return xs + "[((" + i + " % len(" + xs + ")) + len(" + xs + ")) % len(" + xs + ")]"
}

func (g *gen) recsIndex(d int) string {
	v, ok := g.pick(tRecs)
	if !ok {
		return "(Rec{A: " + g.leaf(tInt) + ", B: true, S: \"r\", L: ([]int{1})})"
	}
	return g.read(v) + "[((" + g.expr(tInt, d-1) + " % 2) + 2) % 2]"
}

func (g *gen) leaf(t gtype) string {
	switch t {
	case tInt:
		return fmt.Sprint(g.n(41) - 20)
	case tI64:
		return []string{"0", "3", "-7", "40", "1", "-9"}[g.n(6)]
	case tU8:
		return fmt.Sprint(g.n(10))
	case tF64:
		return []string{"1.5", "-0.25", "2.0", "0.1", "3.75", "-6.0"}[g.n(6)]
	case tDur:
		return []string{"5s", "250ms", "0s", "90s", "3ms"}[g.n(5)]
	case tBool:
		return []string{"true", "false"}[g.n(2)]
	case tStr:
		return []string{`"a"`, `"bc"`, `"xyz"`, `""`}[g.n(4)]
	case tInts:
		var es []string
		for i, n := 0, 1+g.n(4); i < n; i++ {
			es = append(es, fmt.Sprint(g.n(21)-10))
		}
		return "([]int{" + strings.Join(es, ", ") + "})"
	case tRec:
		return "(Rec{A: " + g.leaf(tInt) + ", B: " + g.leaf(tBool) + ", S: " + g.leaf(tStr) + ", L: " + g.leaf(tInts) + "})"
	case tRecs:
		return "([]Rec{" + g.leaf(tRec) + "})"
	}
	panic("gen: type " + string(t))
}

func (g *gen) main() {
	g.b.WriteString("func main() needs Console {\n\twith context { Op: Prov } {\n")
	g.scope = nil
	g.used = nil
	g.depth = 2
	for _, f := range g.funcs {
		var args []string
		for _, p := range f.params {
			args = append(args, g.expr(p.t, 2))
		}
		c := f.name + "(" + strings.Join(args, ", ") + ")"
		switch f.result {
		case tRec:
			c += ".A"
		case tInts:
			c = "len(" + c + ")"
		}
		fmt.Fprintf(&g.b, "\t\tConsole.Println(\"%s \\(%s)\")\n", f.name, c)
	}
	fmt.Fprintf(&g.b, "\t\tConsole.Println(\"op \\(viaOp(%s, %s))\")\n", g.leaf(tInt), g.leaf(tInt))
	if g.oob {
		g.b.WriteString("\t\tConsole.Println(\"oob \\(oob([]int{1, 2}, 1))\")\n")
	}
	g.b.WriteString("\t}\n}\n")
}
