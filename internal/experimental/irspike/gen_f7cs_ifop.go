package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// IfOpFuncs are GenerateIfOp's functions, each with an if or a match
// inside an operand: each gets an IR body in every seed (F7-cs-ifop).
var IfOpFuncs = []string{"args", "bin", "lit", "rec", "text", "same", "tup", "pair", "idx", "sidx", "area", "nested"}

// GenerateIfOp is a program whose ifs and matches stand inside an operand
// (F7-cs-ifop, "expression *syntax.IfStmt"): a call's argument, a binary
// operator's right operand, a slice and a record literal's element, an
// interpolation, an equality's operand, the element of a tuple inside a
// slice literal and an index, and an if inside another's branch. Most arms assign a local that an
// operand to their left reads, so an IR that runs the arm before reading
// that operand prints another value; the seeded constants pick which arm
// runs. main prints every function's result for seeded operands.
func GenerateIfOp(seed uint64) string {
	r := rand.New(rand.NewPCG(seed, seed^0x510e527fade682d1))
	k := func() int { return r.IntN(9) }
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateIfOp\n\n")
	b.WriteString("type Pt { X int, Y int }\n\n")
	b.WriteString("type Circle { R int }\n\ntype Sq { S int }\n\n")
	b.WriteString("type Shape = Circle | Sq\n\n")
	b.WriteString("func pick(a int, c int) int {\n\ta * 10 + c\n}\n\n")
	fmt.Fprintf(&b, "func args(x int) int {\n\tlet mut n = x\n\tlet v = pick(n, if x > %d {\n\t\tn = n + 3\n\t\tn * 2\n\t} else {\n\t\tn - 1\n\t})\n\tv + n\n}\n\n", k())
	fmt.Fprintf(&b, "func bin(x int) int {\n\tlet mut n = x\n\tlet v = n * 100 + if x %% 2 == %d {\n\t\tn = n + 7\n\t\tn\n\t} else {\n\t\t1\n\t}\n\tv * 1000 + n\n}\n\n", r.IntN(2))
	fmt.Fprintf(&b, "func lit(x int) []int {\n\tlet mut n = x\n\t[]int{n, if x > %d {\n\t\tn = n * 3\n\t\tn\n\t} else {\n\t\t0 - n\n\t}, n}\n}\n\n", k())
	fmt.Fprintf(&b, "func rec(x int) Pt {\n\tlet mut n = x\n\tPt{X: n, Y: if x < %d {\n\t\tn = 0\n\t\t5\n\t} else {\n\t\tn + 1\n\t}}\n}\n\n", k())
	fmt.Fprintf(&b, "func text(x int) string {\n\tlet n = x\n\t\"\\(n) \\(if x > %d { n + 1 } else { n * 2 }) \\(n)\"\n}\n\n", k())
	fmt.Fprintf(&b, "func same(x int, y int) bool {\n\tlet mut p = Pt{X: x, Y: 1}\n\tp == if y > %d {\n\t\tp = Pt{X: y, Y: 1}\n\t\tPt{X: x, Y: 1}\n\t} else {\n\t\tPt{X: y, Y: 1}\n\t}\n}\n\n", k())
	fmt.Fprintf(&b, "func tup(x int) (int, int) {\n\tlet mut n = x\n\t(n, if x > %d {\n\t\tn = n + 1\n\t\tn\n\t} else {\n\t\tn * 2\n\t})\n}\n\n", k())
	b.WriteString("func sum2(t (int, int)) int {\n\tlet a, c = t\n\ta * 100 + c\n}\n\n")
	fmt.Fprintf(&b, "func pair(x int) int {\n\tlet mut n = x\n\tlet ts = [](int, int){(n, if x > %d {\n\t\tn = n + 5\n\t\tn\n\t} else {\n\t\t1\n\t})}\n\tsum2(ts[0]) + n\n}\n\n", k())
	fmt.Fprintf(&b, "func idx(x int) int {\n\tlet xs = []int{%d, %d, %d}\n\tlet mut i = 0\n\tlet v = xs[if x > %d {\n\t\ti = 1\n\t\t2\n\t} else {\n\t\ti\n\t}]\n\tv * 10 + i\n}\n\n", k(), k(), k(), k())
	fmt.Fprintf(&b, "func sidx(x int) int {\n\tlet mut s = \"abc\"\n\tlet v = s[if x > %d {\n\t\ts = \"xyz\"\n\t\t1\n\t} else {\n\t\t2\n\t}]\n\tint(v) * 1000 + len(s)\n}\n\n", k())
	fmt.Fprintf(&b, "func area(s Shape, x int) int {\n\tx * 1000 + match s {\n\tcase Circle as c:\n\t\tc.R * %d\n\tcase Sq as q:\n\t\tq.S * q.S\n\t}\n}\n\n", 1+k())
	fmt.Fprintf(&b, "func nested(x int) int {\n\tlet mut n = x\n\tpick(n, if x > %d {\n\t\tif x > %d {\n\t\t\tn = 1\n\t\t\t1\n\t\t} else {\n\t\t\t2\n\t\t}\n\t} else {\n\t\t3\n\t}) + n\n}\n\n", k(), k())
	b.WriteString("func main() needs Console {\n")
	for i := 0; i < 5; i++ {
		x, y := r.IntN(12), r.IntN(12)
		fmt.Fprintf(&b, "\tlet a%d, c%d = tup(%d)\n", i, i, x)
		fmt.Fprintf(&b, "\tConsole.Println(\"%d: \\(args(%d)) \\(bin(%d)) \\(lit(%d)[1]) \\(rec(%d).Y) \\(text(%d)) \\(same(%d, %d)) \\(a%d) \\(c%d) \\(idx(%d)) \\(pair(%d)) \\(sidx(%d)) \\(area(Circle{R: %d}, %d)) \\(area(Sq{S: %d}, %d)) \\(nested(%d))\")\n",
			i, x, x, x, x, x, x, y, i, i, x, x, x, y, x, y, x, x)
	}
	b.WriteString("}\n")
	return b.String()
}
