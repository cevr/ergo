package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// fieldFuncs are GenerateField's functions: each gets an IR body in every
// seed (B-CONVFIELD, "record field of a converted value").
var fieldFuncs = []string{"shapeOf", "maybe", "failWith", "failOther"}

// GenerateField is a program of record literals whose field values are
// converted into the field's type, as Go assigns them: a variant into a
// union field (shapeOf), None or Some into an Option field (maybe), and a
// failure type into a field of a row type (failWith, failOther: the row's
// Go type is error). main reads each record back by a match and prints
// what it finds with seeded weights, so a value put into the wrong variant,
// or lost, changes the output.
func GenerateField(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0xa54ff53a5f1d36f1))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateField\n\n")
	b.WriteString("type Circle { R int }\ntype Square { S int }\ntype Shape = Circle | Square\n\n")
	b.WriteString("type Box { Label string, Shape Shape, Size Option[int] }\n\n")
	b.WriteString("type Bad { N int }\ntype Worse { S string }\n\ntype carrier[F] { Error F }\ntype failure = carrier[Bad | Worse]\n\n")
	fmt.Fprintf(&b, "func shapeOf(n int) Box {\n\tif n %% %d == 0 {\n\t\treturn Box{Label: \"c\", Shape: Circle{R: n}, Size: Some{Value: n}}\n\t}\n\tBox{Label: \"s\", Shape: Square{S: n * %d}, Size: None}\n}\n\n", 2+g.n(3), 2+g.n(5))
	fmt.Fprintf(&b, "func maybe(n int) Box {\n\tif n > %d {\n\t\treturn Box{Label: \"m\", Shape: Square{S: n}, Size: Some{Value: n - 1}}\n\t}\n\tBox{Label: \"m\", Shape: Circle{R: n + 1}, Size: None}\n}\n\n", g.n(6))
	b.WriteString("func failWith(n int) failure {\n\tfailure{Error: Bad{N: n}}\n}\n\n")
	b.WriteString("func failOther(s string) failure {\n\tfailure{Error: Worse{S: s}}\n}\n\n")
	b.WriteString("func weigh(x Box) int {\n\tlet a = match x.Shape {\n\tcase Circle as c:\n\t\tc.R * 3\n\tcase Square as q:\n\t\tq.S * 5\n\t}\n\tlet z = match x.Size {\n\tcase Some as v:\n\t\tv.Value\n\tcase None:\n\t\t-1\n\t}\n\ta * 100 + z\n}\n\n")
	b.WriteString("func reason(f failure) int {\n\tmatch f.Error {\n\tcase Bad as e:\n\t\te.N\n\tcase Worse as e:\n\t\tlen(e.S) * 1000\n\t}\n}\n\n")
	b.WriteString("func main() needs Console {\n")
	words := []string{`"a"`, `"bb"`, `"ccc"`, `""`}
	for k := 0; k < 4; k++ {
		fmt.Fprintf(&b, "\tConsole.Println(\"%d: \\(weigh(shapeOf(%d))) \\(weigh(maybe(%d))) \\(reason(failWith(%d))) \\(reason(failOther(%s)))\")\n", k, g.n(20)-5, g.n(12), g.n(50), words[g.n(len(words))])
	}
	b.WriteString("}\n")
	return b.String()
}
