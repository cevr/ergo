package irspike

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// GenerateInstances is a program whose generic bodies, its own and std's,
// run at its types (FLIP F7 LY-FIX; the class of I-FLIP's a461a6b13 reds):
// std slices.Fold and the program's fold at a record of the program's
// (each a monomorphic copy, mono.go, beside the generic function); size
// at a known provider (a copy for a provider, provider.go); a machine
// whose after function gives a machines.Every timer and whose step cannot
// fail, run by std machines.Run, which tries the step through a field
// whose row can (a copy for a known record of a generic std body). Each
// copy is a Go function of its own beside its function; an IR body built
// for one under its function's name does not build. Box's count and show
// are functions of a generic record, Go methods, whose copies are plain
// functions; show's takes the environment before its receiver
// (MONO-HOOKS-MIN).
func GenerateInstances(seed uint64) string {
	g := &ggen{r: rand.New(rand.NewPCG(seed, seed^0x6c79696e73740a07))}
	var b strings.Builder
	b.WriteString("// generated by irspike.GenerateInstances\n\nimport machines\nimport slices\nimport time\n\n")
	b.WriteString("type Ints []int implements Sized\n\ntype Sized { Size() int }\n\nfunc Size(xs Ints) int { len(xs) }\n\nfunc size(s Sized) int { s.Size() }\n\n")
	b.WriteString("type Acc { N int, Sum int }\n\n")
	b.WriteString("func fold[T, A](xs []T, a A, f func(acc A, x T) A) A {\n\tlet mut out = a\n\tfor x in xs {\n\t\tout = f(out, x)\n\t}\n\tout\n}\n\n")
	fmt.Fprintf(&b, "func tally(xs []int) Acc {\n\tslices.Fold(xs, Acc{N: 0, Sum: %d}, func(a Acc, x int) Acc { Acc{N: a.N + 1, Sum: a.Sum + x} })\n}\n\n", g.n(9))
	fmt.Fprintf(&b, "func spans(ds []duration) duration {\n\tfold(ds, %dms, func(a duration, d duration) duration { a + d })\n}\n\n", g.n(5))
	b.WriteString("type Lamp = Off{Count int} | On{Count int}\n\ntype Flip = Toggle{} | Tick{At time.Time}\n\n")
	fmt.Fprintf(&b, "func step(l Lamp, f Flip) Decision[Lamp, int] {\n\tmatch (l, f) {\n\tcase (Off as o, Toggle):\n\t\tEnter[Lamp]{Next: On{Count: o.Count + 1}}\n\tcase (On as o, Toggle):\n\t\tif o.Count >= %d {\n\t\t\treturn Done[int]{Output: o.Count}\n\t\t}\n\t\tEnter[Lamp]{Next: Off{Count: o.Count}}\n\tcase (_, Tick):\n\t\tIgnore\n\t}\n}\n\n", 2+g.n(4))
	b.WriteString("func ticker(l Lamp) Option[machines.Every[Flip]] {\n\tmatch l {\n\tcase On:\n\t\tSome{machines.Every[Flip]{In: 5ms, Signal: tickAt}}\n\tcase Off:\n\t\tNone\n\t}\n}\n\n")
	b.WriteString("func tickAt(at time.Time) Flip { Tick{At: at} }\n\n")
	b.WriteString("type Switch machine[Lamp, Flip] { initial: Off{Count: 0}, step: step, after: ticker }\n\n")
	b.WriteString("func flips(n int) string {\n\tlet mut fs = []Flip{}\n\tfor _ in 0..n {\n\t\tfs = fs.Append(Toggle)\n\t}\n\tlet o = machines.Run(Switch{}, fs) catch {\n\tcase machines.Rejected as r:\n\t\treturn \"rejected \\(r.At)\"\n\t}\n\tmatch o {\n\tcase machines.Finished[Lamp, int] as f:\n\t\t\"done \\(f.Output)\"\n\tcase machines.Running[Lamp, int] as r:\n\t\t\"running \\(len(r.Emitted))\"\n\t}\n}\n\n")
	b.WriteString("func stepOnce[S, E, O, F, R, W](m Machine[S, E, O, F, R, W], e E) int fails F needs R {\n\tlet d = try m.Step(m.Initial, e)\n\tmatch d {\n\tcase Done[O]:\n\t\t1\n\tcase Enter[S], Stay[S], Emit[S, O], Tell[S, O], Ignore, Reject:\n\t\t0\n\t}\n}\n\n")
	b.WriteString("type Bag { N int } implements Sized\n\nfunc Size(g Bag) int { g.N * 2 }\n\n")
	b.WriteString("func sized(xs []int) int {\n\tsize(Bag{N: len(xs)})\n}\n\n")
	b.WriteString("type Box[T] { items []T }\n\nfunc count[T](b Box[T]) int { len(b.items) }\n\n")
	b.WriteString("func show[T](b Box[T], tag string) needs Console {\n\tConsole.Println(\"\\(tag) \\(b.count())\")\n}\n\n")
	fmt.Fprintf(&b, "func boxes() needs Console {\n\tlet bx = Box[int]{items: []int{%d, %d}}\n\tbx.show(\"box\")\n\tConsole.Println(\"count \\(bx.count())\")\n}\n\n", g.n(9), g.n(9))
	b.WriteString("func main() needs Console {\n")
	b.WriteString("\tConsole.Println(\"once \\(stepOnce(Switch{}, Toggle))\")\n")
	b.WriteString("\tboxes()\n")
	for i := 0; i < 3; i++ {
		var xs, ds []string
		for j := 0; j < 1+g.n(6); j++ {
			xs = append(xs, fmt.Sprint(g.n(40)))
			ds = append(ds, fmt.Sprintf("%dms", g.n(30)))
		}
		fmt.Fprintf(&b, "\tlet a%d = tally([]int{%s})\n", i, strings.Join(xs, ", "))
		fmt.Fprintf(&b, "\tConsole.Println(\"%d: \\(a%d.N) \\(a%d.Sum) \\(spans([]duration{%s})) \\(sized([]int{%s})) \\(flips(%d))\")\n", i, i, i, strings.Join(ds, ", "), strings.Join(xs, ", "), 1+g.n(9))
	}
	b.WriteString("}\n")
	return b.String()
}
