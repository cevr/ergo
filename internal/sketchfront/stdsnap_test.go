var updateStdSnapshot = flag.Bool("update-std-snapshot", false, "rewrite stdsnap/std.snap and stdsnap_gen.go from the checker's source")

// modulePath is the import path prefix of this module's packages.
const modulePath = "ergo.local/prototype"

// checkerDigest is the digest of every file of the checker's import
// closure within the module: each package directory the checker reaches,
// from internal/sketch/check, with every file below it except tests and
// testdata, under any build tag (so the digest is the same on every
// platform). A change of any of them may change the checked std.
func checkerDigest(t *testing.T, root string) string {
	t.Helper()
	seen := map[string]bool{}
	var dirs []string
	var visit func(pkg string)
	visit = func(pkg string) {
		if seen[pkg] {
			return
		}
		seen[pkg] = true
		dir := filepath.Join(root, strings.TrimPrefix(pkg, modulePath))
		dirs = append(dirs, dir)
		entries, err := os.ReadDir(dir)
		if err != nil {
			t.Fatal(err)
		}
		for _, e := range entries {
			name := e.Name()
			if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
				continue
			}
			f, err := parser.ParseFile(token.NewFileSet(), filepath.Join(dir, name), nil, parser.ImportsOnly)
			if err != nil {
				t.Fatal(err)
			}
			for _, s := range f.Imports {
				p, _ := strconv.Unquote(s.Path.Value)
				if strings.HasPrefix(p, modulePath+"/") {
					visit(p)
				}
			}
		}
	}
	visit(modulePath + "/internal/sketch/check")
	files := map[string]bool{}
	for _, dir := range dirs {
		err := filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if d.IsDir() {
				if path != dir && (d.Name() == "testdata" || strings.HasPrefix(d.Name(), ".")) {
					return filepath.SkipDir
				}
				return nil
			}
			if !strings.HasSuffix(path, "_test.go") {
				files[path] = true
			}
			return nil
		})
		if err != nil {
			t.Fatal(err)
		}
	}
	paths := slices.Sorted(func(yield func(string) bool) {
		for p := range files {
			if !yield(p) {
				return
			}
		}
	})
	h := sha256.New()
	fmt.Fprint(h, "ergo-std-checker-1")
	for _, p := range paths {
		data, err := os.ReadFile(p)
		if err != nil {
			t.Fatal(err)
		}
		rel, _ := filepath.Rel(root, p)
		sum := sha256.Sum256(data)
		fmt.Fprintf(h, "\x00%s %x", filepath.ToSlash(rel), sum)
	}
	return hex.EncodeToString(h.Sum(nil))
}

// TestStdSnapshotIsCurrent: the embedded snapshot was made from this head's
// std sources and this head's checker (stdsnap_gen.go names both digests),
// so a std or checker edit without a new snapshot fails the gate before a
// compiler is built from it; and at run time the compiler refuses a
// snapshot of other std sources. Rewrite the snapshot with
//
//	go test ./internal/sketchfront -run TestStdSnapshotIsCurrent -update-std-snapshot
func TestStdSnapshotIsCurrent(t *testing.T) {
	root, err := filepath.Abs("../..")
	if err != nil {
		t.Fatal(err)
	}
	deps := stdDependencies()
	sources, checker := stdSourcesDigest(deps), checkerDigest(t, root)
	if *updateStdSnapshot {
		check.ResetStdForTest()
		t.Cleanup(check.ResetStdForTest)
		data, err := check.ExportStd()
		if err != nil {
			t.Fatal(err)
		}
		gen := fmt.Sprintf("// Code generated by TestStdSnapshotIsCurrent -update-std-snapshot. DO NOT EDIT.\n\npackage sketchfront\n\n// embeddedStdSources is the digest of the std sources stdsnap/std.snap\n// was checked from (stdSourcesDigest).\nconst embeddedStdSources = %q\n\n// embeddedStdChecker is the digest of the checker's source that checked\n// them (checkerDigest in stdsnap_test.go).\nconst embeddedStdChecker = %q\n", sources, checker)
		src, err := format.Source([]byte(gen))
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile("stdsnap/std.snap", data, 0o644); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile("stdsnap_gen.go", src, 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("wrote stdsnap/std.snap (%d bytes) and stdsnap_gen.go; rebuild the test binary to read them", len(data))
		return
	}
	const again = "; rewrite it with go test ./internal/sketchfront -run TestStdSnapshotIsCurrent -update-std-snapshot"
	if sources != embeddedStdSources {
		t.Errorf("the embedded std snapshot was checked from other std sources%s", again)
	}
	if checker != embeddedStdChecker {
		t.Errorf("the embedded std snapshot was checked by another checker%s", again)
	}
	if embeddedSnapshot(deps) == nil {
		t.Error("the compiler refuses the snapshot of its own std sources")
	}
	for i := range deps {
		edited := slices.Clone(deps)
		edited[i].Implementation += "edit"
		if embeddedSnapshot(edited) != nil {
			t.Fatalf("the compiler accepts the embedded snapshot for an edited std package %s", deps[i].Name)
		}
	}
}

// TestColdCheckReadsNoStdSource: a process that uses the embedded snapshot,
// with every cache empty, parses no std file and checks no std package,
// and decodes exactly the std packages that the check from source checks
// (the snapshot is read lazily, one segment per first import).
func TestColdCheckReadsNoStdSource(t *testing.T) {
	stdCache.mu.Lock()
	savedRoot := stdCache.root
	stdCache.mu.Unlock()
	t.Setenv(StdSnapshotEnv, "")
	t.Cleanup(func() {
		UseEmbeddedStd(false)
		UseStdCache(savedRoot)
		resetStdCache(t)
	})
	UseStdCache("")
	source := "import time\nimport strings\n\nfunc main() needs Console {\n\tConsole.Println(strings.ToUpper(\"t\\(time.NewManual(0).Now().UnixSeconds())\"))\n}\n"
	work := func(embed bool) check.Work {
		t.Helper()
		UseEmbeddedStd(embed)
		resetStdCache(t)
		if a := Check(source); len(a.Diagnostics) != 0 {
			t.Fatal(a.Diagnostics)
		}
		return check.WorkDone()
	}
	ref := work(false)
	if ref.StdPackagesChecked == 0 {
		t.Fatalf("the reference checked no std package: %+v", ref)
	}
	got := work(true)
	if sourceWork(got) {
		t.Fatalf("a cold check with the embedded snapshot did std source work: %+v", got)
	}
	if got.StdPackagesDecoded != ref.StdPackagesChecked {
		t.Fatalf("the embedded snapshot decoded %d std packages; the check from source checks %d", got.StdPackagesDecoded, ref.StdPackagesChecked)
	}
}
