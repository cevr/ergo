// synPath is the synthetic bound Go package of TestInspectGoReach.
const synPath = "syn" // a std-shaped path: a user extern of a module package is still S109 (IG7 gap)

// goImporter reads one synthetic binding for synPath and no Ergo package.
type goImporter struct{ set *check.GoBindings }

func (g goImporter) Import(path string) (*check.Package, error) {
	return nil, fmt.Errorf("no Ergo package %s", path)
}
func (g goImporter) GoBindings() *check.GoBindings { return g.set }

// goSym is one declaration of the synthetic package: G<k>() int.
type goSym struct {
	foreign, context bool
}

func (s goSym) wait() string {
	switch {
	case !s.foreign:
		return WaitNone
	case s.context:
		return WaitInterruptible
	}
	return WaitUninterruptible
}

func (s goSym) goText(k int) string {
	if s.context {
		return fmt.Sprintf("func G%d(ctx context.Context) int", k)
	}
	return fmt.Sprintf("func G%d() int", k)
}

// reachProgram is one generated program: its source, the binding of the
// synthetic package, and the reference graph the generator built.
type reachProgram struct {
	src, binding string
	syms         []goSym
	direct       map[string][]int    // a function's direct Go symbols, by index
	edges        map[string][]string // a function's direct program functions
}

// genReach writes a program of n functions f<i> over the synthetic
// package. Each body reaches Go symbols and other functions through every
// form the walk follows: a direct call, a call of a function of the
// program, a function literal called where it is written, a literal passed
// as a value, a function named as a value, a user extern (Level 2), and a
// record put into an operation type, whose operation reaches Go.
func genReach(r *rand.Rand) reachProgram {
	p := reachProgram{direct: map[string][]int{}, edges: map[string][]string{}}
	nsym := 2 + r.IntN(5)
	p.syms = append(p.syms, goSym{}) // G0 is pure: every provider has a pure symbol
	for k := 1; k < nsym; k++ {
		foreign := r.IntN(3) > 0
		p.syms = append(p.syms, goSym{foreign: foreign, context: foreign && r.IntN(2) == 0})
	}
	var bind strings.Builder
	bind.WriteString("// Code generated by ergo bind go; DO NOT EDIT.\n// ergo:bind " + synPath + " go1.27 darwin/arm64 linux/amd64\n// ergo:module " + synPath + " v1.0.0\n")
	for k, s := range p.syms {
		fmt.Fprintf(&bind, "\n// ergo:go %s\n", s.goText(k))
		if s.context {
			bind.WriteString("// ergo:context\n")
		}
		row := ""
		if s.foreign {
			row = " needs go.Foreign"
		}
		fmt.Fprintf(&bind, "extern go %s.G%d func G%d() int%s\n", synPath, k, k, row)
	}
	bind.WriteString("\n// ergo:go func Bad(p uintptr)\n// ergo:refused Bad: parameter 1: Ergo has no uintptr\n")
	bind.WriteString("\n// ergo:go type Src interface\nextern go " + synPath + ".Src type Src {\n\tNext() int needs go.Foreign,\n}\n")
	p.binding = bind.String()

	var b strings.Builder
	b.WriteString("import go " + synPath + "\n\n")
	// A user extern of each symbol: the reviewed pure tier writes no row.
	for k, s := range p.syms {
		row := ""
		if s.foreign {
			row = " needs go.Foreign"
		}
		fmt.Fprintf(&b, "extern go %s.G%d func u%d() int%s\n", synPath, k, k, row)
	}
	b.WriteString("\nfunc apply(f func() int needs go.Foreign) int needs go.Foreign { return f() }\n")
	p.edges["apply"], p.direct["apply"] = nil, nil
	// An operation of a Go interface type, on a host value.
	b.WriteString("func next(s syn.Src) int needs go.Foreign { return s.Next() }\n")
	p.edges["next"], p.direct["next"] = nil, nil
	pure := func() int {
		for {
			if k := r.IntN(nsym); !p.syms[k].foreign {
				return k
			}
		}
	}
	nprov := 1 + r.IntN(3)
	for k := 0; k < nprov; k++ {
		g := pure()
		fmt.Fprintf(&b, "\ntype Op%d { Run%d() int }\ntype P%d { V int }\n", k, k, k)
		fmt.Fprintf(&b, "func Run%d(p P%d) int { return syn.G%d() }\n", k, k, g)
		fmt.Fprintf(&b, "func run%d(s Op%d) int { return s.Run%d() }\n", k, k, k)
		p.direct[fmt.Sprintf("Run%d", k)] = []int{g}
		p.edges[fmt.Sprintf("Run%d", k)] = nil
		p.direct[fmt.Sprintf("run%d", k)] = nil
		p.edges[fmt.Sprintf("run%d", k)] = nil
	}
	n := 2 + r.IntN(6)
	for i := 0; i < n; i++ {
		name := fmt.Sprintf("f%d", i)
		p.direct[name], p.edges[name] = nil, nil
		fmt.Fprintf(&b, "\nfunc %s() int needs go.Foreign {\n", name)
		lets := r.IntN(4)
		var vars []string
		for v := 0; v < lets; v++ {
			k, j := r.IntN(nsym), fmt.Sprintf("f%d", r.IntN(n))
			atom, sym := fmt.Sprintf("syn.G%d()", k), true
			if r.IntN(2) == 0 {
				atom, sym = j+"()", false
			}
			var expr string
			switch r.IntN(7) {
			case 0:
				expr, atom = fmt.Sprintf("syn.G%d()", k), ""
				p.direct[name] = append(p.direct[name], k)
			case 1:
				expr, atom = j+"()", ""
				p.edges[name] = append(p.edges[name], j)
			case 2:
				expr = "func() int needs go.Foreign { return " + atom + " }()"
			case 3:
				expr = "apply(func() int needs go.Foreign { return " + atom + " })"
				p.edges[name] = append(p.edges[name], "apply")
			case 4:
				expr, atom = "apply("+j+")", ""
				p.edges[name] = append(p.edges[name], "apply", j)
			case 5:
				expr, atom = fmt.Sprintf("u%d()", k), ""
				p.direct[name] = append(p.direct[name], k)
			case 6:
				prov := r.IntN(nprov)
				expr, atom = fmt.Sprintf("run%d(P%d{V: 1})", prov, prov), ""
				p.edges[name] = append(p.edges[name], fmt.Sprintf("run%d", prov), fmt.Sprintf("Run%d", prov))
			}
			switch {
			case atom == "":
			case sym:
				p.direct[name] = append(p.direct[name], k)
			default:
				p.edges[name] = append(p.edges[name], j)
			}
			v := fmt.Sprintf("v%d", v)
			fmt.Fprintf(&b, "\tlet %s = %s\n", v, expr)
			vars = append(vars, v)
		}
		if len(vars) == 0 {
			vars = []string{"0"}
		}
		fmt.Fprintf(&b, "\treturn %s\n}\n", strings.Join(vars, " + "))
	}
	b.WriteString("\nfunc main() needs go.Foreign {\n")
	p.direct["main"] = nil
	for i := 0; i < n; i++ {
		fmt.Fprintf(&b, "\tf%d()\n", i)
		p.edges["main"] = append(p.edges["main"], fmt.Sprintf("f%d", i))
	}
	b.WriteString("}\n")
	p.src = b.String()
	return p
}

// want is the reference reach of each function: a walk of the generated
// graph, written independently of the walk over the checker's model.
func (p reachProgram) want() map[string][]string {
	out := map[string][]string{}
	for f := range p.direct {
		seen := map[string]bool{f: true}
		syms := map[string]bool{}
		queue := []string{f}
		for len(queue) > 0 {
			g := queue[0]
			queue = queue[1:]
			if g == "next" {
				syms[synPath+".Src.Next"] = true
			}
			for _, k := range p.direct[g] {
				syms[fmt.Sprintf("%s.G%d", synPath, k)] = true
			}
			for _, e := range p.edges[g] {
				if !seen[e] {
					seen[e] = true
					queue = append(queue, e)
				}
			}
		}
		list := []string{}
		for s := range syms {
			list = append(list, s)
		}
		sort.Strings(list)
		out[f] = list
	}
	return out
}

// TestInspectGoReach is IG8's acceptance: on generated call graphs over a
// synthetic bound Go package, the Go symbols ergo inspect lists for each
// function are the transitive set a reference walk of the generated graph
// computes; each symbol has its binding's Go text, tier, wait and
// provenance; and the import lists the binding's refusals. A failing seed
// prints the program.
//
// Mutants it kills (no other test reads the inspect core): the walk skips
// function literals; it skips a function named as a value (Uses); it skips
// the operation-type conversion; a user extern does not reach its target;
// every Go symbol is foreign; the context marker is ignored (wait); the
// reach is not transitive.
func TestInspectGoReach(t *testing.T) {
	seeds := 200
	if testing.Short() {
		seeds = 60
	}
	for seed := 0; seed < seeds; seed++ {
		r := rand.New(rand.NewPCG(uint64(seed), 8))
		p := genReach(r)
		fail := func(format string, args ...any) {
			t.Helper()
			t.Fatalf("seed %d (replay: -run TestInspectGoReach, seed loop): %s\nprogram:\n%s\nbinding:\n%s", seed, fmt.Sprintf(format, args...), p.src, p.binding)
		}
		file, err := syntax.Parse(p.src)
		if err != nil {
			fail("parse: %v", err)
		}
		set := check.NewGoBindings(func(path string) (string, bool) {
			return p.binding, path == synPath
		})
		pkg, diags := check.Check("main", []*syntax.File{file}, goImporter{set})
		if len(diags) > 0 {
			fail("check: %v", diags)
		}
		got := InspectGo([]*check.Package{pkg})
		want := p.want()
		reach := map[string][]string{}
		for _, f := range got.Functions {
			reach[f.Name] = f.Reach
		}
		if !reflect.DeepEqual(reach, want) {
			fail("reach:\n got %v\nwant %v", reach, want)
		}
		syms := map[string]GoSymbol{}
		for _, s := range got.Symbols {
			syms[s.Target] = s
		}
		for _, f := range got.Functions {
			var waits []string
			for _, target := range f.Reach {
				if syms[target].Wait == WaitUninterruptible {
					waits = append(waits, target)
				}
			}
			if strings.Join(waits, ",") != strings.Join(f.Waits, ",") {
				fail("%s: waits %v, want %v", f.Name, f.Waits, waits)
			}
		}
		for k, s := range p.syms {
			target := fmt.Sprintf("%s.G%d", synPath, k)
			g, ok := syms[target]
			if !ok {
				continue // not reached by any function
			}
			tier := "pure"
			if s.foreign {
				tier = "foreign"
			}
			wantSym := GoSymbol{Target: target, Go: s.goText(k), Ergo: g.Ergo, Tier: tier, Provenance: "module " + synPath + " v1.0.0", Wait: s.wait()}
			if g != wantSym {
				fail("symbol %+v, want %+v", g, wantSym)
			}
		}
		op := GoSymbol{Target: synPath + ".Src.Next", Go: "interface method Src.Next", Ergo: "func() int needs go.Foreign", Tier: "foreign", Provenance: "module " + synPath + " v1.0.0", Wait: WaitUninterruptible}
		if syms[op.Target] != op {
			fail("symbol %+v, want %+v", syms[op.Target], op)
		}
		wantImport := []GoImport{{Path: synPath, Provenance: "module " + synPath + " v1.0.0", Refused: []GoRefusal{{Name: "Bad", Reason: "parameter 1: Ergo has no uintptr"}}}}
		if !reflect.DeepEqual(got.Imports, wantImport) {
			fail("imports %+v, want %+v", got.Imports, wantImport)
		}
	}
}
