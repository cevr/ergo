package sketchfront

import (
	"path/filepath"
	"strings"
	"testing"
)

// TestImportGoModuleBinding (IG2; owner q37): a Go package outside the
// standard library is read from the module's committed binding at
// ergo.bind/<import path>/<last element>.ergo, a program with no binding
// for its path gets S104 with the command, and an edited binding that does
// not check is diagnosed at the import. Mutants it alone catches: the
// loader not reading ergo.bind (the module binding is S104), and a broken
// binding accepted silently.
func TestImportGoModuleBinding(t *testing.T) {
	const binding = "// Code generated by ergo bind go; DO NOT EDIT.\n" +
		"// ergo:bind example.com/greet go1.27 darwin/arm64 linux/amd64\n" +
		"// ergo:module example.com/greet v1.0.0\n\n" +
		"// ergo:go func Hello(name string) string\n" +
		"extern go example.com/greet.Hello func Hello(name string) string needs go.Foreign\n"
	root := writeTree(t, map[string]string{
		"ergo.mod":                               "module app\n",
		"go.mod":                                 "module app\n\ngo 1.27\n\nrequire (\n\texample.com/greet v1.0.0\n\texample.com/stale v1.0.0\n)\n",
		"ergo.bind/example.com/greet/greet.ergo": binding,
		"ergo.bind/example.com/stale/stale.ergo": strings.ReplaceAll(strings.ReplaceAll(binding, "greet", "stale"),
			"(name string) string needs", "(name Nope) string needs"),
		"cmd/good/main.ergo":    "import go example.com/greet\n\nfunc main() needs Console | go.Foreign {\n\tConsole.Println(greet.Hello(\"a\"))\n}\n",
		"cmd/missing/main.ergo": "import go example.com/absent\n\nfunc main() {\n}\n",
		"cmd/stale/main.ergo":   "import go example.com/stale\n\nfunc main() needs Console | go.Foreign {\n\tConsole.Println(stale.Hello(\"a\"))\n}\n",
	})
	good, err := CheckDir(filepath.Join(root, "cmd", "good"))
	if err != nil || len(good.Diagnostics) > 0 {
		t.Fatalf("a module binding: %v\n%s", err, diagnosticLines(good))
	}
	for _, tc := range []struct{ dir, want string }{
		{"missing", `S104 1:11 no binding for Go package "example.com/absent"; run ergo bind go example.com/absent`},
		{"stale", `the binding of Go package "example.com/stale" does not check`},
	} {
		got, err := CheckDir(filepath.Join(root, "cmd", tc.dir))
		if err != nil {
			t.Fatal(err)
		}
		if lines := diagnosticLines(got); !strings.Contains(lines, tc.want) {
			t.Errorf("%s: diagnostics\n%s\nwant %q", tc.dir, lines, tc.want)
		}
	}
}
