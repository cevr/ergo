type cbindTestImporter struct {
	gb *GoBindings
}

func (g *cbindTestImporter) Import(path string) (*Package, error) { return nil, nil }
func (g *cbindTestImporter) GoBindings() *GoBindings              { return g.gb }

const (
	testCHeaderSHA   = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef"
	testCContractSHA = "fedcba9876543210fedcba9876543210fedcba9876543210fedcba9876543210"
)

func testCBindingHeader(path string) string {
	return "// Code generated by ergo bind c (internal/bindc); DO NOT EDIT.\n" +
		"// ergo:bind c " + path + " " + testCHeaderSHA + " " + testCContractSHA + " darwin/amd64 darwin/arm64 linux/amd64 linux/arm64\n\n"
}

func checkCBindProgram(t *testing.T, path, binding, mainSrc string, verifyStamp func(string, string, string) string) (*Package, []Diagnostic) {
	t.Helper()
	f, err := syntax.Parse(mainSrc)
	if err != nil {
		t.Fatalf("parse main: %v\n%s", err, mainSrc)
	}
	f.Name = "main.ergo"
	gb := NewGoBindings(func(p string) (string, bool) {
		if p == path {
			return binding, true
		}
		return "", false
	})
	gb.VerifyCStamp = verifyStamp
	return Check("main", []*syntax.File{f}, &cbindTestImporter{gb: gb})
}

// independentPointerOracle is an independent structural reachability oracle
// over a generated graph of types, returning true iff no Go pointer, slice,
// map, string, interface, func, or go.Ref is reachable at any depth.
func independentPointerOracle(t Type) bool {
	seen := map[Type]bool{}
	var walk func(Type) bool
	walk = func(u Type) bool {
		switch x := u.(type) {
		case *Basic:
			return x.Kind >= Bool && x.Kind <= Float64 && x.Kind != String
		case *Array:
			return walk(x.Elem)
		case *Struct:
			for _, f := range x.Fields {
				if !walk(f.Type) {
					return false
				}
			}
			return true
		case *Tuple:
			for _, e := range x.Types {
				if !walk(e) {
					return false
				}
			}
			return true
		case *Named:
			if refElem(x) != nil || IsGoError(x) || IsGoAny(x) || seen[x] {
				return false
			}
			seen[x] = true
			defer delete(seen, x)
			return walk(under(x))
		default:
			return false
		}
	}
	return walk(t)
}

// TestCBindingCDataDepthProperty tests IsCData and C-binding verification
// across seeded recursive record/array graphs of depth 1..6 (with and without
// planted Go pointers/strings/slices/maps/go.Ref/interfaces/funcs at depth k)
// against an independent structural reachability oracle. Explicitly defeats
// cgo's depth-2 cutoff (kills cffi2-cdata-depth-2-cutoff).
func TestCBindingCDataDepthProperty(t *testing.T) {
	const pkgPath = "example.test/cffi/cdata"
	cScalars := []string{"bool", "int8", "int16", "int32", "int64", "uint8", "uint16", "uint32", "uint64", "float32", "float64"}
	poisonTypes := []string{"string", "[]byte", "Map[string, int]", "go.Ref[Leaf]", "func(int) int", "go.Error", "go.Any"}

	r := rand.New(rand.NewPCG(0xcff12, 0xda7a6))
	for depth := 1; depth <= 6; depth++ {
		for _, poisoned := range []bool{false, true} {
			for trial := range 3 {
				name := fmt.Sprintf("depth=%d/poison=%v/trial=%d", depth, poisoned, trial)
				t.Run(name, func(t *testing.T) {
					var b strings.Builder
					b.WriteString(testCBindingHeader(pkgPath))
					b.WriteString("extern go " + pkgPath + ".Leaf type Leaf {}\n")

					// Build a chain L0 (deepest) -> L1 -> ... -> L<depth-1> (outermost).
					for lvl := 0; lvl < depth; lvl++ {
						var fields []string
						if lvl == 0 {
							if poisoned {
								pt := poisonTypes[(depth+trial+r.IntN(len(poisonTypes)))%len(poisonTypes)]
								fields = append(fields, "\tBad "+pt+",")
							}
							fields = append(fields, "\tVal "+cScalars[r.IntN(len(cScalars))]+",")
						} else {
							prev := fmt.Sprintf("L%d", lvl-1)
							if r.IntN(2) == 0 {
								fields = append(fields, fmt.Sprintf("\tInner [%d]%s,", 1+r.IntN(4), prev))
							} else {
								fields = append(fields, "\tInner "+prev+",")
							}
							fields = append(fields, "\tTag "+cScalars[r.IntN(len(cScalars))]+",")
						}
						tname := fmt.Sprintf("L%d", lvl)
						b.WriteString("// ergo:cdata\n")
						fmt.Fprintf(&b, "extern go %s.%s type %s {\n%s\n}\n\n", pkgPath, tname, tname, strings.Join(fields, "\n"))
					}
					top := fmt.Sprintf("L%d", depth-1)
					fmt.Fprintf(&b, "extern go %s.Pass func Pass(x %s) int32 fails go.Error needs go.Foreign\n", pkgPath, top)

					gb := NewGoBindings(func(p string) (string, bool) {
						if p == pkgPath {
							return b.String(), true
						}
						return "", false
					})
					if !gb.ResolveAll(pkgPath) {
						t.Fatalf("ResolveAll(%q) = false", pkgPath)
					}
					pkg, _ := gb.Package(pkgPath)
					tn := pkg.Scope.names[top].(*TypeName)
					gotCData, why := IsCData(tn.Type)
					wantCData := independentPointerOracle(tn.Type)
					if gotCData != wantCData {
						t.Fatalf("IsCData(%s) = (%v, %q), oracle = %v\n%s", top, gotCData, why, wantCData, b.String())
					}
					if wantCData != !poisoned {
						t.Fatalf("oracle = %v, expected %v", wantCData, !poisoned)
					}
					ds := gb.Diagnostics()
					if poisoned && len(ds) == 0 {
						t.Fatalf("poisoned depth-%d // ergo:cdata type was accepted!\n%s", depth, b.String())
					}
					if !poisoned && len(ds) != 0 {
						t.Fatalf("clean depth-%d // ergo:cdata type rejected: %v\n%s", depth, ds, b.String())
					}
				})
			}
		}
	}
}

const sampleCHandleBinding = `// Code generated by ergo bind c (internal/bindc); DO NOT EDIT.
// ergo:bind c example.test/cffi/handle 0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef fedcba9876543210fedcba9876543210fedcba9876543210fedcba9876543210 darwin/amd64 darwin/arm64 linux/amd64 linux/arm64

extern go example.test/cffi/handle.Context type Context {} implements Closer
extern go example.test/cffi/handle.Context.Close func (h own *Context) Close() fails go.Error needs go.Foreign

extern go example.test/cffi/handle.Open func Open() go.Ref[Context] fails go.Error needs go.Foreign
extern go example.test/cffi/handle.Use func Use(ctx *Context) int32 fails go.Error needs go.Foreign
extern go example.test/cffi/handle.Destroy func Destroy(ctx own *Context) fails go.Error needs go.Foreign
`

// TestCBindingHandleOwnership verifies handle resource linearity over C handles
// across straight-line code, branches, loops, and try early exits: use-after-destroy,
// maybe-moved use, and discarded handles are refused as S108, while valid code
// records deterministic automatic release at scope exit.
func TestCBindingHandleOwnership(t *testing.T) {
	const pkgPath = "example.test/cffi/handle"

	t.Run("valid-auto-release", func(t *testing.T) {
		src := `import go example.test/cffi/handle

func run(flag bool) int32 fails go.Error needs go.Foreign {
	let ctx = try handle.Open()
	let a = try handle.Use(ctx)
	if flag {
		let b = try handle.Use(ctx)
		return a + b
	}
	a
}
`
		pkg, ds := checkCBindProgram(t, pkgPath, sampleCHandleBinding, src, nil)
		if len(ds) != 0 {
			t.Fatalf("valid handle program failed check: %v", ds)
		}
		if len(pkg.Info.Releases) == 0 {
			t.Fatalf("expected automatic scope-exit release in Info.Releases, got none")
		}
	})

	t.Run("valid-explicit-destroy", func(t *testing.T) {
		src := `import go example.test/cffi/handle

func run() int32 fails go.Error needs go.Foreign {
	let ctx = try handle.Open()
	let n = try handle.Use(ctx)
	try handle.Destroy(ctx)
	n
}
`
		if _, ds := checkCBindProgram(t, pkgPath, sampleCHandleBinding, src, nil); len(ds) != 0 {
			t.Fatalf("valid explicit destroy failed check: %v", ds)
		}
	})

	t.Run("use-after-destroy", func(t *testing.T) {
		src := `import go example.test/cffi/handle

func bad() int32 fails go.Error needs go.Foreign {
	let ctx = try handle.Open()
	try handle.Destroy(ctx)
	try handle.Use(ctx)
}
`
		_, ds := checkCBindProgram(t, pkgPath, sampleCHandleBinding, src, nil)
		if len(ds) == 0 || ds[0].Code != "S108" {
			t.Fatalf("expected S108 for use-after-destroy, got %v", ds)
		}
	})

	t.Run("use-after-branch-destroy", func(t *testing.T) {
		src := `import go example.test/cffi/handle

func bad(cond bool) int32 fails go.Error needs go.Foreign {
	let ctx = try handle.Open()
	if cond {
		try handle.Destroy(ctx)
	}
	try handle.Use(ctx)
}
`
		_, ds := checkCBindProgram(t, pkgPath, sampleCHandleBinding, src, nil)
		if len(ds) == 0 || ds[0].Code != "S108" {
			t.Fatalf("expected S108 for use after conditional destroy, got %v", ds)
		}
	})

	t.Run("use-after-loop-destroy", func(t *testing.T) {
		src := `import go example.test/cffi/handle

func bad() int32 fails go.Error needs go.Foreign {
	let ctx = try handle.Open()
	for _ in 0..3 {
		try handle.Destroy(ctx)
	}
	0
}
`
		_, ds := checkCBindProgram(t, pkgPath, sampleCHandleBinding, src, nil)
		if len(ds) == 0 || ds[0].Code != "S108" {
			t.Fatalf("expected S108 for repeated destroy in loop, got %v", ds)
		}
	})

	t.Run("discarded-handle-leak", func(t *testing.T) {
		src := `import go example.test/cffi/handle

func bad() fails go.Error needs go.Foreign {
	let _ = try handle.Open()
}
`
		_, ds := checkCBindProgram(t, pkgPath, sampleCHandleBinding, src, nil)
		if len(ds) == 0 || ds[0].Code != "S108" {
			t.Fatalf("expected S108 for discarded handle, got %v", ds)
		}
	})
}

// TestCBindingRequiresGoForeign verifies that calling any C-bound function
// without `needs go.Foreign` (pure function or `test` body) is refused as S102,
// and that tampering a C binding to drop `needs go.Foreign` is refused as S108.
func TestCBindingRequiresGoForeign(t *testing.T) {
	const pkgPath = "example.test/cffi/handle"

	t.Run("pure-function-refused", func(t *testing.T) {
		src := `import go example.test/cffi/handle

func pure() int32 fails go.Error {
	let ctx = try handle.Open()
	try handle.Use(ctx)
}
`
		_, ds := checkCBindProgram(t, pkgPath, sampleCHandleBinding, src, nil)
		found := false
		for _, d := range ds {
			if d.Code == "S102" && strings.Contains(d.Message, "go.Foreign") {
				found = true
			}
		}
		if !found {
			t.Fatalf("expected S102 requiring go.Foreign from pure function, got %v", ds)
		}
	})

	t.Run("test-body-refused", func(t *testing.T) {
		src := `import go example.test/cffi/handle

test no_foreign_in_unit_test {
	let ctx = try handle.Open()
	let _ = try handle.Use(ctx)
}
`
		_, ds := checkCBindProgram(t, pkgPath, sampleCHandleBinding, src, nil)
		found := false
		for _, d := range ds {
			if d.Code == "S102" && strings.Contains(d.Message, "go.Foreign") {
				found = true
			}
		}
		if !found {
			t.Fatalf("expected S102 requiring go.Foreign from test body, got %v", ds)
		}
	})

	t.Run("tampered-binding-missing-foreign", func(t *testing.T) {
		tampered := strings.Replace(sampleCHandleBinding,
			"extern go example.test/cffi/handle.Use func Use(ctx *Context) int32 fails go.Error needs go.Foreign",
			"extern go example.test/cffi/handle.Use func Use(ctx *Context) int32 fails go.Error",
			1)
		src := `import go example.test/cffi/handle

func ok() int32 fails go.Error needs go.Foreign {
	let ctx = try handle.Open()
	try handle.Use(ctx)
}
`
		_, ds := checkCBindProgram(t, pkgPath, tampered, src, nil)
		found := false
		for _, d := range ds {
			if d.Code == "S108" && strings.Contains(d.Message, "needs go.Foreign") {
				found = true
			}
		}
		if !found {
			t.Fatalf("expected S108 rejecting tampered C binding without needs go.Foreign, got %v", ds)
		}
	})
}

// TestCBindingStaleHeaderRejected verifies fail-closed S108 rejection when a
// `// ergo:bind c` binding's header SHA-256, contract SHA-256, import path, or
// disk stamp is corrupted, missing, or stale. Kills cffi2-skip-sha-stamp.
func TestCBindingStaleHeaderRejected(t *testing.T) {
	const pkgPath = "example.test/cffi/handle"
	mainSrc := `import go example.test/cffi/handle

func run() int32 fails go.Error needs go.Foreign {
	let ctx = try handle.Open()
	try handle.Use(ctx)
}
`
	cases := []struct {
		name        string
		binding     string
		verifyStamp func(string, string, string) string
		wantSubstr  string
	}{
		{
			name:       "corrupted-header-sha",
			binding:    strings.Replace(sampleCHandleBinding, testCHeaderSHA, "deadbeef", 1),
			wantSubstr: "header sha256",
		},
		{
			name:       "corrupted-contract-sha",
			binding:    strings.Replace(sampleCHandleBinding, testCContractSHA, "not-a-sha", 1),
			wantSubstr: "contract sha256",
		},
		{
			name:       "wrong-import-path",
			binding:    strings.Replace(sampleCHandleBinding, "// ergo:bind c "+pkgPath, "// ergo:bind c example.test/other", 1),
			wantSubstr: "does not match",
		},
		{
			name:       "missing-bind-c-header",
			binding:    strings.Replace(sampleCHandleBinding, "// ergo:bind c "+pkgPath+" "+testCHeaderSHA+" "+testCContractSHA+" darwin/amd64 darwin/arm64 linux/amd64 linux/arm64\n", "", 1),
			wantSubstr: "missing",
		},
		{
			name:    "stale-stamp-callback",
			binding: sampleCHandleBinding,
			verifyStamp: func(path, hsha, csha string) string {
				return "fixture.h sha256 changed on disk"
			},
			wantSubstr: "stamp mismatch",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			_, ds := checkCBindProgram(t, pkgPath, tc.binding, mainSrc, tc.verifyStamp)
			found := false
			for _, d := range ds {
				if d.Code == "S108" && strings.Contains(d.Message, tc.wantSubstr) {
					found = true
				}
			}
			if !found {
				t.Fatalf("expected S108 containing %q, got %v", tc.wantSubstr, ds)
			}
		})
	}
}
