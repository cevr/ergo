package check

import (
	"strings"
	"testing"
)

// TestOwnershipGlueRefused is the text and position row of the S109 that
// an owned value whose resource sits inside an aggregate gets until its
// generated release exists (#197 L8 B1; B2 builds the drop glue). The
// release lowering registers only a value whose type has a checked Close
// (Info.OwnedVars); every other owned value would leak without this
// refusal.
//
// Mutant it catches that nothing else does: the S109 for a value that
// needs a generated release not reported (an owned Pair silently never
// released).
func TestOwnershipGlueRefused(t *testing.T) {
	src := ofPrelude + "type Pair { a Res, b Res }\n\nfunc pair() {\n\tlet p = Pair{a: open(1), b: open(2)}\n\tlet _ = p.a.id\n}\n\nfunc main() {}\n"
	_, diags := checkFor(src)
	want := "the release of Pair, which holds a resource inside it, is generated by #197 B2"
	line := strings.Count(ofPrelude, "\n") + 4
	if len(diags) != 1 || diags[0].Code != CodeOutside || !strings.Contains(diags[0].Message, want) || diags[0].Line != line || diags[0].Column != 6 {
		t.Errorf("got %+v, want one S109 at %d:6 containing %q", diags, line, want)
	}
}
