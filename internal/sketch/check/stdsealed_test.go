var updateSealed = flag.Bool("update-sealed", false, "rewrite stdsealed_gen.go from the embedded std sources")

// stdSealedPath is the generated table SealedStd reads.
const stdSealedPath = "stdsealed_gen.go"

// TestStdSealedTableIsCurrent is the staleness check of the generated
// sealed std set (CHK1): stdsealed_gen.go must be what stdExternResultSet
// reads from the embedded std sources, so a std edit that changes what an
// extern returns fails here until the table is rewritten, and never makes
// a check differ silently. It catches the mutant sealed-table-stale of the
// ledger (a name dropped from or added to the table). Rewrite the table
// with: go test ./internal/sketch/check -run TestStdSealedTableIsCurrent -update-sealed
func TestStdSealedTableIsCurrent(t *testing.T) {
	want := renderSealedTable(stdExternResultSet())
	if *updateSealed {
		if err := os.WriteFile(stdSealedPath, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(stdSealedPath)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != want {
		t.Errorf("%s is not the set the std sources give; rewrite it with go test ./internal/sketch/check -run TestStdSealedTableIsCurrent -update-sealed\n got: %v\nwant: %v", stdSealedPath, sortedKeys(stdSealedTable), sortedKeys(stdExternResultSet()))
	}
}

// renderSealedTable is the Go source of stdsealed_gen.go for set.
func renderSealedTable(set map[string]bool) string {
	names := make([]string, 0, len(set))
	for n := range set {
		names = append(names, n)
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString("// Code generated by TestStdSealedTableIsCurrent (internal/sketch/check); DO NOT EDIT.\n")
	b.WriteString("// Rewrite it with: go test ./internal/sketch/check -run TestStdSealedTableIsCurrent -update-sealed\n\n")
	b.WriteString("package check\n\n")
	b.WriteString("// stdSealedTable is the set, as path.Name, of the std types the results\n")
	b.WriteString("// of std extern functions name, at any depth of the result and its fails\n")
	b.WriteString("// row (not its needs row), and the types the parameters of their function\n")
	b.WriteString("// parameters name (SealedStd). An unqualified name is the declaring\n")
	b.WriteString("// package's type when it declares one, else the prelude's. It is\n")
	b.WriteString("// generated from the embedded std sources (stdExternResultSet), so a\n")
	b.WriteString("// check parses no std package it does not import (CHK1).\n")
	b.WriteString("var stdSealedTable = map[string]bool{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: true,\n", n)
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(err)
	}
	return string(src)
}

// stdExternResultSet is stdSealedTable read from the std sources with the
// parser: the reference the generated table must equal.
func stdExternResultSet() map[string]bool {
	sources := map[string]map[string]string{std.PreludePath: std.Prelude()}
	for _, path := range std.Packages() {
		if files, ok := std.Package(path); ok {
			sources[path] = files
		}
	}
	set := map[string]bool{}
	for path, files := range sources {
		var parsed []*syntax.File
		declared := map[string]bool{}
		for _, src := range files {
			f, err := syntax.Parse(src)
			if err != nil {
				// Std always parses; a file that did not would unseal
				// what its externs return.
				panic(fmt.Sprintf("std package %s does not parse: %v", path, err))
			}
			parsed = append(parsed, f)
			for _, d := range f.Decls {
				if td, ok := d.(*syntax.TypeDecl); ok {
					declared[td.Name.Name] = true
				}
			}
		}
		for _, f := range parsed {
			imports := map[string]string{}
			for _, d := range f.Decls {
				id, ok := d.(*syntax.ImportDecl)
				if !ok {
					continue
				}
				for _, s := range id.Specs {
					p := strings.Trim(s.Path.Value, "\"`")
					name := p[strings.LastIndex(p, "/")+1:]
					if s.Name != nil {
						name = s.Name.Name
					}
					imports[name] = p
				}
			}
			for _, d := range f.Decls {
				fd, ok := d.(*syntax.FuncDecl)
				if !ok || fd.Extern == nil || fd.Type == nil {
					continue
				}
				// The host gives the program a value through an extern's
				// result and through the parameters of a function the
				// extern calls (http's serve hands each handler its
				// request's Exchange): both are runtime values, so one
				// rule seals both.
				var given []*syntax.Field
				if fd.Type.Results != nil {
					given = append(given, fd.Type.Results.List...)
				}
				if fd.Type.Params != nil {
					for _, p := range fd.Type.Params.List {
						if ft, ok := p.Type.(*syntax.FuncType); ok && ft.Params != nil {
							given = append(given, ft.Params.List...)
						}
					}
				}
				for _, r := range given {
					syntax.Inspect(r.Type, func(x syntax.Node) bool {
						switch x := x.(type) {
						case *syntax.SelectorExpr:
							if q, ok := x.X.(*syntax.Ident); ok {
								if p, ok := imports[q.Name]; ok {
									set[p+"."+x.Sel.Name] = true
								}
							}
							return false
						case *syntax.Ident:
							if declared[x.Name] {
								set[path+"."+x.Name] = true
							} else {
								set[std.PreludePath+"."+x.Name] = true
							}
						}
						return true
					})
				}
			}
		}
	}
	return set
}
