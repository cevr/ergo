// checks fails with the checker's diagnostics when a generated program
// does not check, so a generator slip names its cause.
func checks(t *testing.T, p *planted) {
	t.Helper()
	if a := sketchfront.Check(p.b.String()); len(a.Diagnostics) != 0 {
		t.Fatalf("the generated program does not check: %v\n%s", a.Diagnostics, numbered(p.b.String()))
	}
}

// An operand of the sign-decided generator: its spelling over the
// parameters (u of the seed's unsigned type, i int, xs []int), whether
// its value is never negative, and whether it is signed (so a negative
// constant is representable against it).
type signOperand struct {
	text        string
	nonNegative bool
	signed      bool
}

var signOperands = []signOperand{
	{"u", true, false},
	{"(u)", true, false},
	{"u + 1", true, false},
	{"len(xs)", true, true},
	{"i", false, true},
	{"int(u)", false, true},       // a conversion to a signed type may be negative
	{"int(u) - 1", false, true},   // and so may arithmetic on it
	{"uint64(i)", true, false},    // a conversion to an unsigned type never is
	{"len(xs) - 1", false, true},  // a length minus one may be -1
	{"int(len(xs))", false, true}, // a conversion, not a call of len: its type int decides
}

// signDecides is the reference: a comparison `v op k` (v never negative,
// k an integer constant of sign s) is decided by the sign alone.
func signDecides(op string, s int) bool {
	switch op {
	case ">=":
		return s <= 0
	case ">", "!=":
		return s < 0
	case "<":
		return s <= 0
	case "<=", "==":
		return s < 0
	}
	return false
}

// mirrored is the operator with its operands swapped.
func mirrored(op string) string {
	return map[string]string{"<": ">", ">": "<", "<=": ">=", ">=": "<=", "==": "==", "!=": "!="}[op]
}

// TestSignDecidedAgreesWithReference writes comparisons of an operand
// with an integer constant, either side first, and checks that
// sign-decided-comparison fires on exactly those whose operand is never
// negative and whose verdict the constant's sign alone decides. A
// conversion to a signed type (int(u) < 0) is a signed value and never
// fires. One kind is the evalgen program of the g25c1 report (`if v < 0`
// over a uint64 in classify, line 6): the checker accepts it, and the
// rule names that comparison, as a warning, only when a lint run asks. A
// seed whose file starts with Go's generated-file line expects nothing; a
// hand-written comment that only holds its words, or the line after a
// declaration (TestSelfAssignmentAgreesWithReference), silences nothing.
// Mutants: vet-sign-none, vet-sign-geq-strict, vet-sign-no-mirror,
// vet-sign-through-conversion, vet-generated-linted,
// vet-generated-unanchored, vet-generated-anywhere.
func TestSignDecidedAgreesWithReference(t *testing.T) {
	ops := []string{"<", "<=", ">", ">=", "==", "!="}
	uints := []string{"uint", "uint8", "uint32", "uint64"}
	for _, seed := range propertySeeds(60) {
		r := rand.New(rand.NewPCG(seed, 0x5d))
		p := newPlanted()
		generated := false
		switch r.IntN(6) {
		case 0:
			p.write("// Code generated by evalgen. DO NOT EDIT.", false, 0)
			generated = true
		case 1:
			// Hand-written comments that only hold the words are no mark.
			p.write("// Notes: the Code generated by evalgen. DO NOT EDIT. line was removed.\n// Code generated by hand, DO NOT EDIT", false, 0)
		}
		ut := uints[r.IntN(len(uints))]
		p.write("type Size = Small{ V uint64 } | Big{ V uint64 }\n\nfunc classify(v uint64) Size {\n\tif v < 0 {\n\t\tSmall{V: v}\n\t} else {\n\t\tBig{V: v}\n\t}\n}", !generated, 3)
		for n := range 2 + r.IntN(8) {
			o := signOperands[r.IntN(len(signOperands))]
			op := ops[r.IntN(len(ops))]
			ks := []int{0, 1, 7}
			if o.signed {
				ks = append(ks, -1, -3)
			}
			k := ks[r.IntN(len(ks))]
			expr := fmt.Sprintf("%s %s %d", o.text, op, k)
			if k < 0 {
				expr = fmt.Sprintf("%s %s (%d)", o.text, op, k)
			}
			if r.IntN(2) == 0 {
				expr = fmt.Sprintf("%d %s %s", k, mirrored(op), o.text)
				if k < 0 {
					expr = fmt.Sprintf("(%d) %s %s", k, mirrored(op), o.text)
				}
			}
			s := 0
			if k > 0 {
				s = 1
			} else if k < 0 {
				s = -1
			}
			fires := !generated && o.nonNegative && signDecides(op, s)
			p.write(fmt.Sprintf("\nfunc c%d(u %s, i int, xs []int) bool { %s }", n, ut, expr), fires, 1)
		}
		p.write("\nfunc main() {\n}", false, 0)
		checks(t, p)
		p.check(t, "sign-decided-comparison", "TestSignDecidedAgreesWithReference", seed)
	}
}

// selfAssigns are the self-assignment generator's statements, each in a
// function over a mutable local x, a record r and a list xs: the text and
// whether it stores a place's own value.
var selfAssigns = []struct {
	text  string
	fires bool
}{
	{"x = x", true},
	{"x = (x)", true},
	{"r.N = r.N", true},
	{"xs[0] = xs[0]", true},
	{"xs[x] = xs[x]", true},
	{"x = x + 0", false},
	{"r.N = r.M", false},
	{"xs[0] = xs[1]", false},
	{"xs[x] = xs[0]", false},
	{"x = r.N", false},
}

// TestSelfAssignmentAgreesWithReference writes assignments that store a
// place's own value (a local, a field, an element at one name or literal
// index) and ones that store another, and checks that self-assignment
// fires on exactly the first; a generated file expects nothing. Mutants:
// vet-self-assign-none, vet-self-assign-any-index, vet-generated-linted.
func TestSelfAssignmentAgreesWithReference(t *testing.T) {
	for _, seed := range propertySeeds(40) {
		r := rand.New(rand.NewPCG(seed, 0x5a))
		generated := r.IntN(5) == 0
		p := newPlanted()
		if generated {
			p.write("// Code generated by ergo gen; DO NOT EDIT.", false, 0)
		}
		p.write("type Rec { N int, M int }", false, 0)
		if !generated && r.IntN(3) == 0 {
			// The mark after the first declaration is a comment, not the mark.
			p.write("// Code generated by ergo gen; DO NOT EDIT.", false, 0)
		}
		for n := range 1 + r.IntN(6) {
			a := selfAssigns[r.IntN(len(selfAssigns))]
			p.write(fmt.Sprintf("\nfunc s%d(r0 Rec, ys []int) int {\n\tlet mut x = 0\n\tlet mut r = r0\n\tlet mut xs = ys\n\t%s\n\tx = x + 1\n\tr.M = r.N + 1\n\txs[1] = x\n\tx + r.M + xs[0]\n}", n, a.text), a.fires && !generated, 5)
		}
		p.write("\nfunc main() {\n}", false, 0)
		checks(t, p)
		p.check(t, "self-assignment", "TestSelfAssignmentAgreesWithReference", seed)
	}
}

// wireKeys are the wire-key generator's field keys (as Ergo string
// literals) and whether each holds a double quote.
var wireKeys = []struct {
	lit   string
	fires bool
}{
	{`"json:\"age,omitempty\""`, true},
	{`"\"age\""`, true},
	{`"xml:\"lang\""`, true},
	{`"age"`, false},
	{`"xml:lang"`, false},
	{`"json:name"`, false},
	{`"a b"`, false},
}

// TestWireKeyQuoteAgreesWithReference writes record fields with keys,
// some holding a double quote (the Go struct-tag habit) and some with a
// colon alone, and checks that wire-key-quote fires on exactly the
// first. Mutants: vet-wirekey-none, vet-wirekey-colon.
func TestWireKeyQuoteAgreesWithReference(t *testing.T) {
	for _, seed := range propertySeeds(30) {
		r := rand.New(rand.NewPCG(seed, 0x5b))
		p := newPlanted()
		for n := range 1 + r.IntN(5) {
			k := wireKeys[r.IntN(len(wireKeys))]
			p.write(fmt.Sprintf("type W%d {\n\tAge int %s,\n\tCity string \"city\",\n}", n, k.lit), k.fires, 1)
		}
		p.write("\nfunc main() {\n}", false, 0)
		checks(t, p)
		p.check(t, "wire-key-quote", "TestWireKeyQuoteAgreesWithReference", seed)
	}
}
