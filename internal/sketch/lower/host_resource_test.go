const hresGo = `package hostres

import (
	"errors"
	"fmt"
)

type Handle struct {
	id          int
	bad, closed bool
}

type Peeker interface{ Peek() string }

func Open(id int, bad bool) (*Handle, error) {
	fmt.Println("open", id)
	return &Handle{id: id, bad: bad}, nil
}

func (h *Handle) Use() {
	if h.closed {
		fmt.Println("use after close", h.id)
		return
	}
	fmt.Println("use", h.id)
}

func (h *Handle) Peek() string {
	if h.closed { return fmt.Sprint("use after close ", h.id) }
	return fmt.Sprint("peek ", h.id)
}

var keptHandle *Handle
func (h *Handle) Hold() { keptHandle = h }

func (h *Handle) Close() error {
	if h.closed {
		fmt.Println("double close", h.id)
	}
	h.closed = true
	fmt.Println("close", h.id)
	if h.bad {
		return errors.New("flush failed")
	}
	return nil
}

func Show(p Peeker) { fmt.Println(p.Peek()) }

var kept Peeker
func Unknown(p Peeker) { kept = p }

func UseKept() {
	fmt.Println(kept.Peek())
	_ = kept.(*Handle).Close()
	kept = nil
}

func Say(s string) { fmt.Println(s) }

var Shared = &Handle{}
`

// hresFiles are the Go module files of hostres beside a program: its
// source, its own module, and the program module's replace of it.
func hresFiles() []File {
	return []File{
		{Path: "go.mod", Data: []byte(goMod + "\nrequire " + hresPath + " v0.0.0\n\nreplace " + hresPath + " => ./" + hresPath + "\n")},
		{Path: hresPath + "/go.mod", Data: []byte("module " + hresPath + "\n\ngo " + goVersion + "\n")},
		{Path: hresPath + "/hostres.go", Data: []byte(hresGo)},
	}
}

// hresImporter gives the hostres binding beside Go's standard library.
type hresImporter struct{ set *check.GoBindings }

func newHresImporter() hresImporter {
	return hresImporter{check.NewGoBindings(func(path string) (string, bool) {
		if path == hresPath {
			return hresBinding, true
		}
		return gostd.Binding(path)
	})}
}

func (hresImporter) Import(path string) (*check.Package, error) {
	return nil, fmt.Errorf("no Ergo package %s", path)
}

func (h hresImporter) GoBindings() *check.GoBindings { return h.set }

// hrStmt is a generated statement of run's body.
type hrStmt struct {
	kind  int // hrOpen, hrUse, hrShared, hrShow, hrClose, hrKeep, hrBlock
	id    int
	bad   bool
	body  []hrStmt
	line  int // the statement's line in the source, set when written
	after int // an injected violation after this statement (verdict test)
}

const (
	hrOpen = iota
	hrUse
	hrShared
	hrShow
	hrClose
	hrKeep
	hrBlock
)

type hrGen struct {
	r      *rand.Rand
	nextID int
}

// block generates a statement list; live are the handles owned by the
// enclosing scopes, which a statement may lend.
func (g *hrGen) block(depth int, live []int) []hrStmt {
	var out []hrStmt
	var own []int // this scope's handles, still owned
	n := 1 + g.r.IntN(5)
	for range n {
		all := append(append([]int(nil), live...), own...)
		k := g.r.IntN(7)
		switch {
		case k == hrOpen || len(all) == 0 && k != hrShared && k != hrBlock:
			g.nextID++
			out = append(out, hrStmt{kind: hrOpen, id: g.nextID, bad: g.r.IntN(5) == 0})
			own = append(own, g.nextID)
		case k == hrUse || k == hrShow:
			out = append(out, hrStmt{kind: k, id: all[g.r.IntN(len(all))]})
		case k == hrShared:
			out = append(out, hrStmt{kind: hrShared})
		case (k == hrClose || k == hrKeep) && len(own) > 0:
			i := g.r.IntN(len(own))
			out = append(out, hrStmt{kind: k, id: own[i]})
			own = append(own[:i], own[i+1:]...)
		case k == hrBlock && depth < 2:
			out = append(out, hrStmt{kind: hrBlock, body: g.block(depth+1, all)})
		default:
			out = append(out, hrStmt{kind: hrShared})
		}
	}
	return out
}

// hrSource writes the program; it numbers each statement's line.
func hrSource(body []hrStmt, inject func(s *hrStmt) string) string {
	var b strings.Builder
	line := 1
	w := func(s string) {
		b.WriteString(s + "\n")
		line++
	}
	w("import go " + hresPath)
	w("")
	w("func keep(h go.Ref[hostres.Handle]) needs go.Foreign takes h {")
	w("\th.Use()")
	w("}")
	w("")
	w("func run(flag bool) fails go.Error needs go.Foreign {")
	var list func([]hrStmt, string)
	list = func(ss []hrStmt, ind string) {
		for i := range ss {
			s := &ss[i]
			s.line = line
			switch s.kind {
			case hrOpen:
				w(fmt.Sprintf("%slet h%d = try hostres.Open(%d, %t)", ind, s.id, s.id, s.bad))
			case hrUse:
				w(fmt.Sprintf("%sh%d.Use()", ind, s.id))
			case hrShared:
				w(ind + "hostres.Shared.Use()")
			case hrShow:
				w(fmt.Sprintf("%shostres.Show(h%d)", ind, s.id))
			case hrClose:
				w(fmt.Sprintf("%stry h%d.Close()", ind, s.id))
			case hrKeep:
				w(fmt.Sprintf("%skeep(h%d)", ind, s.id))
			case hrBlock:
				w(ind + "if flag {")
				list(s.body, ind+"\t")
				w(ind + "}")
			}
			if inject != nil {
				if extra := inject(s); extra != "" {
					s.after = line
					w(ind + extra)
				}
			}
		}
	}
	list(body, "\t")
	w("}")
	w("")
	w("func main() needs go.Foreign {")
	w("\trun(true) catch { case go.Error: hostres.Say(\"failed\") }")
	w("\thostres.Say(\"end\")")
	w("}")
	return b.String()
}

// hrModel is the reference: one list of owned handles per scope, released
// last first at the scope's end; a failure or a defect releases every
// list left, innermost first, each release after an earlier defect (R5,
// R7, R9). A Go Close's error at an automatic release is a defect naming
// the acquisition's line (q61); the package variable is never released
// (q62); a handle lent to Go stays owned.
type hrModel struct {
	out     []string
	scopes  [][]hrEntry
	defects []int // the acquisition lines of the failing releases
	keepAt  int
}

type hrEntry struct {
	id, line int
	bad      bool
}

func (m *hrModel) say(s string) { m.out = append(m.out, s) }

func (m *hrModel) release(e hrEntry) {
	m.say("close " + strconv.Itoa(e.id))
	if e.bad {
		m.defects = append(m.defects, e.line)
	}
}

// endScope releases the innermost scope's handles.
func (m *hrModel) endScope() {
	top := m.scopes[len(m.scopes)-1]
	m.scopes = m.scopes[:len(m.scopes)-1]
	for i := len(top) - 1; i >= 0; i-- {
		m.release(top[i])
	}
}

func (m *hrModel) take(id int) hrEntry {
	top := m.scopes[len(m.scopes)-1]
	for i, e := range top {
		if e.id == id {
			m.scopes[len(m.scopes)-1] = append(top[:i], top[i+1:]...)
			return e
		}
	}
	panic("hrModel: taking a handle the scope does not own")
}

// exit codes of a statement list.
const (
	hrDone = iota
	hrFailed
	hrDefect
)

func (m *hrModel) list(ss []hrStmt) int {
	for _, s := range ss {
		switch s.kind {
		case hrOpen:
			m.say("open " + strconv.Itoa(s.id))
			top := len(m.scopes) - 1
			m.scopes[top] = append(m.scopes[top], hrEntry{s.id, s.line, s.bad})
		case hrUse:
			m.say("use " + strconv.Itoa(s.id))
		case hrShared:
			m.say("use 0")
		case hrShow:
			m.say("peek " + strconv.Itoa(s.id))
		case hrClose:
			e := m.take(s.id)
			m.say("close " + strconv.Itoa(s.id))
			if e.bad {
				return hrFailed // an explicit Close fails go.Error
			}
		case hrKeep:
			e := m.take(s.id)
			m.say("use " + strconv.Itoa(s.id))
			e.line = m.keepAt
			m.release(e) // keep's frame releases its taken parameter
			if e.bad {
				return hrDefect
			}
		case hrBlock:
			m.scopes = append(m.scopes, nil)
			if exit := m.list(s.body); exit != hrDone {
				return exit
			}
			n := len(m.defects)
			m.endScope()
			if len(m.defects) > n {
				return hrDefect
			}
		}
	}
	return hrDone
}

// run predicts the program's output and its defect lines.
func (m *hrModel) run(body []hrStmt) (string, []int) {
	m.scopes = [][]hrEntry{nil}
	exit := m.list(body)
	n := len(m.defects)
	for len(m.scopes) > 0 {
		m.endScope()
	}
	if len(m.defects) > n {
		exit = hrDefect
	}
	switch exit {
	case hrFailed:
		m.say("failed")
		m.say("end")
	case hrDone:
		m.say("end")
	default:
		m.say("defect")
	}
	return strings.Join(m.out, "\n") + "\n", m.defects
}

func hrSeeds(t *testing.T, n int) (int, int) {
	if s := os.Getenv("ERGO_SEED"); s != "" {
		v, err := strconv.Atoi(s)
		if err != nil {
			t.Fatalf("ERGO_SEED %q: %v", s, err)
		}
		return v, 1
	}
	return 1, n
}

// TestHostResourceRun is IG9's runtime property: generated bodies over a
// Go handle (open, lend to Ergo and to a Go interface parameter, an
// explicit `try h.Close()`, a hand-off to a taking function, the package
// variable's lend, nested blocks) run against hrModel: each handle is
// closed once, last acquired first at its scope's end and on the failure
// and defect edges; the package variable is never closed; a Close error at
// an automatic release is a defect whose report names the acquisition's
// Ergo line. A failing seed prints the Ergo source, both outputs and the
// replay command (ERGO_SEED=n).
//
// It builds Go because its subject is the release of a Go value by Go's
// own Close on the emitted exit edges, with Go's error turned into a
// defect: go/types cannot run them, and Ergo has no reference interpreter
// for Go calls.
//
// Mutants it catches that nothing else does (internal/sketch/lower
// mutants.json, IG9): a Close error dropped at an automatic release; a
// Go type's Close() error not counted as a release (the handle leaks).
func TestHostResourceRun(t *testing.T) {
	needsBuild(t)
	first, n := hrSeeds(t, 24)
	type runCase struct {
		name, src, want string
		defects         []int
	}
	var cases []runCase
	var programs []*lowered
	// ESC1 r2: the foreign callee, not the caller's frame, owns this
	// hand-off. It reads and closes the retained value after give returns.
	// The binary is needed to observe the absence of a premature release.
	foreign := `import go hostres
func give() fails go.Error needs go.Foreign {
	let h = try hostres.Open(41, false)
	hostres.Unknown(h)
}
func main() needs go.Foreign {
	give() catch { case go.Error: hostres.Say("failed") }
	hostres.UseKept()
}`
	foreignProgram := lowerSourceWith("foreign_retains", foreign, true, newHresImporter())
	if foreignProgram.err != nil || len(foreignProgram.diags) > 0 || foreignProgram.panicked != nil || len(foreignProgram.refused) > 0 {
		t.Fatalf("foreign hand-off does not lower: %+v\n%s", foreignProgram, foreign)
	}
	foreignProgram.extra = hresFiles()
	programs = append(programs, foreignProgram)
	cases = append(cases, runCase{"foreign_retains", foreign, "open 41\npeek 41\nclose 41\n", nil})
	for seed := first; seed < first+n; seed++ {
		g := &hrGen{r: rand.New(rand.NewPCG(uint64(seed), 197))}
		body := g.block(0, nil)
		src := hrSource(body, nil)
		want, defects := (&hrModel{keepAt: 3}).run(body)
		name := fmt.Sprintf("hostres_%d", seed)
		o := lowerSourceWith(name, src, true, newHresImporter())
		if o.err != nil || len(o.diags) > 0 || o.panicked != nil || len(o.refused) > 0 {
			t.Fatalf("seed %d (ERGO_SEED=%d replays): does not lower: %v %v %v %+v\n%s", seed, seed, o.err, o.diags, o.panicked, o.refused, numbered(src))
		}
		o.extra = hresFiles()
		cases = append(cases, runCase{name, src, want, defects})
		programs = append(programs, o)
	}
	exes := buildAll(t, programs, true)
	if exes == nil {
		return
	}
	for i, c := range cases {
		cmd := exec.Command(exes[c.name])
		var stdout, stderr bytes.Buffer
		cmd.Stdout, cmd.Stderr = &stdout, &stderr
		err := runProgram(t, cmd)
		got := stdout.String()
		if err != nil {
			got += "defect\n"
		}
		bad := got != c.want
		for _, line := range c.defects {
			if !strings.Contains(stderr.String(), fmt.Sprintf("release of the value acquired at %s:%d:", testSourcePath, line)) {
				bad = true
			}
		}
		if bad {
			t.Errorf("seed %d (ERGO_SEED=%d replays)\n%s\ngot:\n%s\nwant:\n%s\nwant defects at lines %v\nstderr:\n%s", first+i, first+i, numbered(c.src), got, c.want, c.defects, stderr.String())
		}
	}
}

// TestHostResourceVerdicts is IG9's checker property, in process: each
// generated body of TestHostResourceRun checks clean, and the same body
// with one violation injected after a random statement is S108 at the
// injected line: a use of a handle after its Close or its hand-off (a
// double close is one), a take of the package variable (q62: it is
// borrowed), or a discarded handle (a leak, D4).
//
// Mutants it catches that nothing else does (internal/sketch/check
// mutants.json, IG9): a Go type with Close() error crosses; the package
// variable may be taken; R22 refuses a handle lent to a Go interface
// parameter.
func TestHostResourceVerdicts(t *testing.T) {
	first, n := hrSeeds(t, 64)
	for seed := first; seed < first+n; seed++ {
		g := &hrGen{r: rand.New(rand.NewPCG(uint64(seed), 197))}
		body := g.block(0, nil)
		clean := hrSource(body, nil)
		if o := lowerSourceWith("clean", clean, true, newHresImporter()); len(o.diags) > 0 || o.err != nil {
			t.Fatalf("seed %d (ERGO_SEED=%d replays): the clean body: %v %v\n%s", seed, seed, o.diags, o.err, numbered(clean))
		}
		r := rand.New(rand.NewPCG(uint64(seed), 61))
		var at *hrStmt
		count := 0
		var why string
		src := hrSource(body, func(s *hrStmt) string {
			count++
			if at != nil || r.IntN(count+2) != 0 && count < 6 {
				return ""
			}
			at = s
			switch {
			case s.kind == hrClose || s.kind == hrKeep:
				why = "a use after the hand-off"
				return fmt.Sprintf("h%d.Use()", s.id)
			case r.IntN(2) == 0:
				why = "a take of the package variable"
				return "try hostres.Shared.Close()"
			default:
				why = "a discarded handle"
				return "try hostres.Open(99, false)"
			}
		})
		if at == nil {
			continue
		}
		o := lowerSourceWith("bad", src, true, newHresImporter())
		ok := len(o.diags) > 0 && o.diags[0].Code == "S108" && o.diags[0].Line == at.after
		if !ok {
			t.Errorf("seed %d (ERGO_SEED=%d replays): %s at line %d: want S108 there, got %v\n%s", seed, seed, why, at.after, o.diags, numbered(src))
		}
	}
}
