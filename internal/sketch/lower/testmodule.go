// One test binary for many packages (TEST-one). `ergo test DIR/...` checks
// the module once and links one Go binary that holds the test build of
// every selected package; the binary runs once per package, so each
// package's report, exit status and receipt stay what its own test binary
// gives (Go's go test ./... spelling, as output and not as processes).
//
// LowerTestModule lowers each unit with LowerTests, unchanged: the per-
// package test build is the reference, and this file only moves it. Each
// build becomes the Go package ergotestK in the folder ergotestK of one
// module: its package clause names ergotestK, its entry main becomes Main,
// and each of its init functions (the source map, RegisterCalls, and each
// machine's graph, RegisterMachine) becomes a plain function that Main
// calls first. So a package's registrations run only in its own run, in
// file order, after its package variables, as Go's init order runs them
// before main: one run never reads another package's source map. The
// module's main.go reads `--ergo-package K` as its first two arguments,
// removes them, and runs package K's Main.
//
// Prior art: Cargo links one test harness per crate for every module's
// tests; mix test and gleam test run every module's tests in one VM; go
// test keeps one binary per package and amortises the cost with its
// build and test caches.

// TestPackageFlag is the test module's first argument: the index of the
// package whose tests a run runs, in the order LowerTestModule took.
const TestPackageFlag = "--ergo-package"

// testPackageDir is the folder and Go package name of the k-th unit.
func testPackageDir(k int) string { return "ergotest" + strconv.Itoa(k) }

// LowerTestModule lowers the test build of each unit (LowerTests) into one
// Go module whose binary runs the tests of unit K when its first arguments
// are TestPackageFlag K. The units are the packages of one Ergo module, so
// their Go requirements are one go.mod; units whose go.mod or go.sum differ
// are an error. A unit's refusal is returned as LowerTests returns it.
func LowerTestModule(units []Unit) ([]File, error) {
	if len(units) == 0 {
		return nil, fmt.Errorf("lower: a test module has no package")
	}
	var head, body []File
	for k, u := range units {
		files, err := LowerTests(u)
		if err != nil {
			return nil, err
		}
		dir := testPackageDir(k)
		sum := false
		for _, f := range files {
			switch f.Path {
			case "go.mod", "go.sum":
				sum = sum || f.Path == "go.sum"
				if k == 0 {
					head = append(head, f)
					continue
				}
				if i := indexFile(head, f.Path); i < 0 || !bytes.Equal(head[i].Data, f.Data) {
					return nil, fmt.Errorf("lower: the packages of a test module require different Go modules (%s)", f.Path)
				}
			case "main.go":
				data, err := rehomeTest(f.Data, dir)
				if err != nil {
					return nil, err
				}
				body = append(body, File{Path: dir + "/main.go", Data: data})
			default:
				body = append(body, File{Path: dir + "/" + f.Path, Data: f.Data})
			}
		}
		if k > 0 && sum != (indexFile(head, "go.sum") >= 0) {
			return nil, fmt.Errorf("lower: the packages of a test module require different Go modules (go.sum)")
		}
	}
	head = append(head, File{Path: "main.go", Data: testDispatch(len(units))})
	return append(head, body...), nil
}

func indexFile(files []File, path string) int {
	for i, f := range files {
		if f.Path == path {
			return i
		}
	}
	return -1
}

// testDispatch is the test module's main.go: it runs the Main of the
// package that TestPackageFlag names, with the two arguments removed, so
// the package's runner reads the arguments its own binary reads.
func testDispatch(n int) []byte {
	var b strings.Builder
	b.WriteString("// Code generated by ergo: the test module's entry (TEST-one). DO NOT EDIT.\n\npackage main\n\nimport (\n\t\"fmt\"\n\t\"os\"\n\n")
	for k := 0; k < n; k++ {
		b.WriteString("\t" + testPackageDir(k) + " " + strconv.Quote(programModule+"/"+testPackageDir(k)) + "\n")
	}
	b.WriteString(")\n\nfunc main() {\n")
	b.WriteString("\tif len(os.Args) > 2 && os.Args[1] == " + strconv.Quote(TestPackageFlag) + " {\n")
	b.WriteString("\t\tk := os.Args[2]\n\t\tos.Args = append(os.Args[:1:1], os.Args[3:]...)\n\t\tswitch k {\n")
	for k := 0; k < n; k++ {
		b.WriteString("\t\tcase " + strconv.Quote(strconv.Itoa(k)) + ":\n\t\t\t" + testPackageDir(k) + ".Main()\n\t\t\treturn\n")
	}
	b.WriteString("\t\t}\n\t}\n")
	b.WriteString("\tfmt.Fprintln(os.Stderr, " + strconv.Quote("usage: "+TestPackageFlag+" K [test flags]: K is a package of this test module, 0 to "+strconv.Itoa(n-1)) + ")\n")
	b.WriteString("\tos.Exit(2)\n}\n")
	return []byte(b.String())
}

// rehomeTest makes the test build's main.go the Go package name: the
// package clause names it, main becomes Main, and each init function
// becomes a function of a fresh name that Main calls first, in file order.
// It edits the text in place on each line, so no line moves and every
// //line directive keeps its line.
func rehomeTest(src []byte, name string) ([]byte, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "main.go", src, 0)
	if err != nil {
		return nil, fmt.Errorf("lower: a test build does not parse (a compiler defect): %w", err)
	}
	used := map[string]bool{}
	ast.Inspect(f, func(n ast.Node) bool {
		if id, ok := n.(*ast.Ident); ok {
			used[id.Name] = true
		}
		return true
	})
	if f.Scope.Lookup("Main") != nil {
		return nil, fmt.Errorf("lower: a test build already names Main (a compiler defect)")
	}
	type edit struct {
		at, end int
		text    string
	}
	offset := func(p token.Pos) int { return fset.Position(p).Offset }
	edits := []edit{{offset(f.Name.Pos()), offset(f.Name.End()), name}}
	var entry *ast.FuncDecl
	var inits []string
	for _, d := range f.Decls {
		fd, ok := d.(*ast.FuncDecl)
		if !ok || fd.Recv != nil {
			continue
		}
		switch fd.Name.Name {
		case "main":
			entry = fd
		case "init":
			fresh := "ergoTestInit"
			for k := 2; used[fresh]; k++ {
				fresh = "ergoTestInit" + strconv.Itoa(k)
			}
			used[fresh] = true
			inits = append(inits, fresh)
			edits = append(edits, edit{offset(fd.Name.Pos()), offset(fd.Name.End()), fresh})
		}
	}
	if entry == nil || entry.Body == nil {
		return nil, fmt.Errorf("lower: a test build has no main (a compiler defect)")
	}
	// main is a Go function only the runtime calls; any other use of the
	// name is a local or a field, which keeps it.
	ast.Inspect(f, func(n ast.Node) bool {
		if id, ok := n.(*ast.Ident); ok && id.Name == "main" && id != f.Name && id.Obj != nil && id.Obj.Decl == entry {
			edits = append(edits, edit{offset(id.Pos()), offset(id.End()), "Main"})
		}
		return true
	})
	if len(inits) > 0 {
		at := offset(entry.Body.Lbrace) + 1
		edits = append(edits, edit{at, at, " " + strings.Join(inits, "(); ") + "();"})
	}
	sort.Slice(edits, func(i, j int) bool { return edits[i].at > edits[j].at })
	out := append([]byte{}, src...)
	for _, e := range edits {
		out = append(out[:e.at], append([]byte(e.text), out[e.end:]...)...)
	}
	return out, nil
}
