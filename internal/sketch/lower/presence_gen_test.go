package lower

import (
	"strings"
	"testing"
)

// presenceLaw is CU8's shape: an operation law whose providers are
// generated from a record that holds each presence wrapper of std json.
// Kept is built by its constructor from a generated Entry (the pilot's
// repro), DropsNote and DropsTag field by field. DropsInner has a
// constructor because a field-built provider spends one level of the
// generators' depth (testDepth), and Present{NonNull} inside Both needs
// all four. Each Drops* provider loses one present
// state on its way to the text, so its law is refuted only when the
// generator draws that state: Present for Note, NonNull for Tag, Present
// for Both, and Present{NonNull} inside Both.
const presenceLaw = `import json

type Entry {
	Note json.Optional[string],
	Tag json.Nullable[int],
	Both json.Optional[json.Nullable[string]],
}

func codec() json.Codec[Entry] { json.Codec[Entry]{MaxBytes: 0, MaxDepth: 0} }

func readsBack(text string, want Entry) bool {
	let back = json.Decode(codec(), text) catch { case _: return false }
	back == want
}

type Notes {
	Text() string,
	Value() Entry,
	law TextReadsBack() { readsBack(Text(), Value()) },
}

type Kept { e Entry }

func NewKept(e Entry) Kept { Kept{e: e} }

func Text(k Kept) string { json.Encode(codec(), k.e) }

func Value(k Kept) Entry { k.e }

type DropsNote { e Entry }

func Text(d DropsNote) string { json.Encode(codec(), Entry{..d.e, Note: json.Absent}) }

func Value(d DropsNote) Entry { d.e }

type DropsTag { e Entry }

func Text(d DropsTag) string { json.Encode(codec(), Entry{..d.e, Tag: json.Null}) }

func Value(d DropsTag) Entry { d.e }

type DropsBoth { e Entry }

func NewDropsBoth(e Entry) DropsBoth { DropsBoth{e: e} }

func Text(d DropsBoth) string { json.Encode(codec(), Entry{..d.e, Both: json.Absent}) }

func Value(d DropsBoth) Entry { d.e }

type DropsInner { e Entry }

func NewDropsInner(e Entry) DropsInner { DropsInner{e: e} }

func inner(b json.Optional[json.Nullable[string]]) json.Optional[json.Nullable[string]] {
	match b {
	case json.Absent: json.Absent
	case json.Present[json.Nullable[string]]: json.Present{Value: json.Null}
	}
}

func Text(d DropsInner) string { json.Encode(codec(), Entry{..d.e, Both: inner(d.e.Both)}) }

func Value(d DropsInner) Entry { d.e }

func main() needs Console {
	Console.Println(NewKept(Entry{Note: json.Absent, Tag: json.Null, Both: json.Absent}).Text())
}
`

// TestPresenceWrappersGenerate is CU8's acceptance check: std's
// json.Optional and json.Nullable are generated by the general rule, so
// the law runs for every provider (none is a skip), holds for Kept, and is
// refuted for each provider that drops a present state. It kills the
// mutants cu8-std-refused (std types refused again: every run is a skip)
// and cu8-pick-least-only (a union always draws its variant of least rank,
// that is Absent and Null: every Drops* law holds).
//
// It builds Go because a law runs only in the built test binary (ergo
// test); no in-process check observes a generated value.
func TestPresenceWrappersGenerate(t *testing.T) {
	needsBuild(t)
	exes := buildAll(t, []*lowered{lowerTestBuild(t, "presence_law", presenceLaw)}, true)
	if exes == nil {
		return
	}
	for _, seed := range []string{"1", "7"} {
		stdout, stderr, code := runExeArgs(t, exes["presence_law"], "--seed", seed)
		got := lines(stdout)
		want := map[string]string{
			"Kept":       "ok law Notes.TextReadsBack for Kept (100 cases)",
			"DropsNote":  "FAIL law Notes.TextReadsBack for DropsNote (case ",
			"DropsTag":   "FAIL law Notes.TextReadsBack for DropsTag (case ",
			"DropsBoth":  "FAIL law Notes.TextReadsBack for DropsBoth (case ",
			"DropsInner": "FAIL law Notes.TextReadsBack for DropsInner (case ",
		}
		for name, prefix := range want {
			found := false
			for _, l := range got {
				if strings.HasPrefix(l, prefix) {
					found = true
				}
			}
			if !found {
				t.Errorf("seed %s: no line for %s starts with %q", seed, name, prefix)
			}
		}
		if code != 1 || len(got) == 0 || got[len(got)-1] != "FAIL (4 of 5 tests)" {
			t.Errorf("seed %s: exit %d, stdout:\n%s\nstderr:\n%s", seed, code, stdout, firstLines(stderr, 8))
		}
	}
}
