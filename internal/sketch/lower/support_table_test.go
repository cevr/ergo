package lower

import (
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"
	"testing"
)

// supportPath is the support table of the language specification.
const supportPath = "../../../docs/spec/support.md"

var updateSupport = flag.Bool("update-support", false, "rewrite docs/spec/support.md from the family inventory")

// ownerText says what each open owner that a refusal may name builds
// (openOwners, stage4_refusals_test.go).
var ownerText = map[string]string{
	"196b": "imported contexts",
	"#197": "further resource ownership",
	"#199": "the runtime",
	"#57":  "the actor library and its machine runner",
	"#162": "running laws",
	"#49":  "derived text forms",
	"#196": "the syntax that the checker admits and no rule defines yet",
}

// omittedFamilies are implemented families that no build contains: the
// checker checks them, and the lowering leaves them out whole. A law is
// checked and not run (#162).
var omittedFamilies = map[string]string{
	"LawDecl":    "#162",
	"call:LawOp": "#162",
}

// The status labels of support.md (D-S5-8).
const (
	statusRuns    = "Checked; runs"
	statusRefused = "Checked; build refused (S109)"
	statusOmitted = "Checked; not in any build"
)

// familyText says what each family of the inventory is, for a reader.
func familyText(f string) string {
	kind, name, ok := strings.Cut(f, ":")
	if !ok {
		return "the `" + f + "` syntax node"
	}
	switch kind {
	case "call":
		return "a call of kind `" + name + "`"
	case "pattern":
		return "a `" + name + "` pattern"
	case "conv":
		return "an implicit `" + name + "` conversion"
	case "basic":
		return "a value of the basic type `" + name + "`"
	}
	return "the `" + name + "` form of the `" + kind + "` node"
}

// supportTable is docs/spec/support.md, generated from the lowering's family
// inventory (implementedFamilies, refusedFamilies; accepted_test.go) and the
// open owners (openOwners; stage4_refusals_test.go).
func supportTable() string {
	var b strings.Builder
	b.WriteString("# Support\n\n")
	b.WriteString("<!-- Generated by TestSupportTableIsCurrent (internal/sketch/lower); do not edit. Rewrite it with: go test ./internal/sketch/lower -run TestSupportTableIsCurrent -update-support -->\n\n")
	b.WriteString("This page lists what `ergo build`, `ergo run` and `ergo test` do with each construct that the checker accepts. A **family** is a kind of construct: a syntax node, a call kind, a pattern kind, an implicit conversion or a basic type. The page is generated from the lowering's inventory, and a test fails when the two differ.\n\n")
	b.WriteString("- **" + statusRuns + "**: the lowering emits Go for it. `TestAcceptedNodesLower` lowers, vets, builds and runs a witness of each such family. A test and its asserts are in the test build of `ergo test` only.\n")
	b.WriteString("- **" + statusRefused + "**: the build stops at the construct with S109, and the message names the open owner. `TestRefusedFamiliesHaveWitnesses` keeps a checked program that reaches each refusal.\n")
	b.WriteString("- **" + statusOmitted + "**: the checker checks it, and every build leaves it out. A law is checked and not run.\n\n")
	b.WriteString("A construct that the checker refuses never reaches the build. Its diagnostic is in [diagnostics.md](diagnostics.md). The status of each construct of the language, the designed ones included, is in the [specification's status table](README.md#status-per-construct).\n\n")
	b.WriteString("| Family | What it is | Status | Owner |\n| --- | --- | --- | --- |\n")
	type row struct{ family, status, owner string }
	var rows []row
	for _, f := range implementedFamilies {
		if o, ok := omittedFamilies[f]; ok {
			rows = append(rows, row{f, statusOmitted, o})
			continue
		}
		rows = append(rows, row{f, statusRuns, ""})
	}
	for f, o := range refusedFamilies {
		rows = append(rows, row{f, statusRefused, o})
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].family < rows[j].family })
	for _, r := range rows {
		owner := r.owner
		if owner != "" {
			owner = ownerLink(owner)
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", r.family, familyText(r.family), r.status, owner)
	}
	b.WriteString("\n## Open owners\n\nA refusal names one of these owners.\n\n")
	for _, o := range openOwners {
		fmt.Fprintf(&b, "- %s: %s.\n", ownerLink(o), ownerText[o])
	}
	return b.String()
}

// ownerLink is an owner as a Markdown link to its issue. 196b is a part of
// #196.
func ownerLink(o string) string {
	if strings.HasPrefix(o, "#") {
		return "[" + o + "](https://github.com/cevr/ergo/issues/" + o[1:] + ")"
	}
	return "[" + o + "](https://github.com/cevr/ergo/issues/196)"
}

// TestSupportTableIsCurrent (lower-v1 stage 5, D-S5-7): docs/spec/support.md
// equals the table generated from the family inventory, so the published
// support cannot drift from what the lowering does. Every refused or
// omitted family names an open owner with its text.
func TestSupportTableIsCurrent(t *testing.T) {
	implemented := map[string]bool{}
	for _, f := range implementedFamilies {
		implemented[f] = true
	}
	for f, o := range omittedFamilies {
		if !implemented[f] {
			t.Errorf("the omitted family %s is not an implemented family", f)
		}
		if ownerText[o] == "" {
			t.Errorf("the omitted family %s names %q, which is not an open owner with a text", f, o)
		}
	}
	for f, o := range refusedFamilies {
		if ownerText[o] == "" {
			t.Errorf("the refused family %s names %q, which is not an open owner with a text", f, o)
		}
	}
	for _, o := range openOwners {
		if ownerText[o] == "" {
			t.Errorf("the open owner %s has no text", o)
		}
	}
	if len(ownerText) != len(openOwners) {
		t.Errorf("ownerText has %d owners, openOwners %d: a closed owner keeps a text", len(ownerText), len(openOwners))
	}
	want := supportTable()
	if *updateSupport {
		if err := os.WriteFile(supportPath, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(supportPath)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != want {
		t.Errorf("%s is not the table the inventory generates; rewrite it with -update-support\n%s", supportPath, supportFirstDiff(string(got), want))
	}
}

// supportFirstDiff names the first line where got and want differ.
func supportFirstDiff(got, want string) string {
	g, w := strings.Split(got, "\n"), strings.Split(want, "\n")
	for i := 0; i < len(g) || i < len(w); i++ {
		var a, b string
		if i < len(g) {
			a = g[i]
		}
		if i < len(w) {
			b = w[i]
		}
		if a != b {
			return fmt.Sprintf("line %d:\n  have %q\n  want %q", i+1, a, b)
		}
	}
	return ""
}
