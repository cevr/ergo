var updateMembers = flag.Bool("update-members", false, "rewrite members_gen.go from the toolchain's source")

// TestPureGoFactsHold is the determinism guard of v1.PureImports: every
// member it can call gives the same results under two host states; a
// planted member that reads the working directory (filepath.Abs, which
// v1.PureImportsExcept() names) is refuted.
//
// Mutants it alone catches: ffi-pure-guard-one-state (the two states are
// one).
func TestPureGoFactsHold(t *testing.T) {
	callable := Callable(members)
	t.Logf("the guard calls %d of %d members", callable, len(members))
	if callable*2 < len(members) {
		t.Errorf("the guard draws the arguments of %d of %d members: most go unchecked", callable, len(members))
	}
	for _, d := range Pure(members) {
		t.Errorf("a member of v1.PureImports reads host state: %v", d)
	}
	if d := Pure(map[string]any{"path/filepath.Abs": filepath.Abs}); len(d) == 0 {
		t.Errorf("filepath.Abs, which reads the working directory, passes the determinism guard")
	}
}

// TestMembersCurrent: members_gen.go is the generator's output for the
// pinned toolchain and the current v1.PureImports and v1.PureImportsExcept()
// (go test ./internal/gofacts/hostguard -run TestMembersCurrent -args
// -update-members rewrites it).
//
// Mutant it alone catches: ffi-pure-except-dropped (filepath.Abs joins
// the members).
func TestMembersCurrent(t *testing.T) {
	out, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		t.Fatal(err)
	}
	src, err := membersSource(strings.TrimSpace(string(out)))
	if err != nil {
		t.Fatal(err)
	}
	if *updateMembers {
		if err := os.WriteFile("members_gen.go", src, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	have, err := os.ReadFile("members_gen.go")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(have, src) {
		t.Errorf("members_gen.go is stale: run go test ./internal/gofacts/hostguard -run TestMembersCurrent -args -update-members")
	}
}

// membersSource is the text of members_gen.go: every exported function
// with no type parameter of each package of v1.PureImports, in the files
// the build of this platform reads, minus v1.PureImportsExcept().
func membersSource(goroot string) ([]byte, error) {
	var b, imports bytes.Buffer
	pkgs := slices.Sorted(slices.Values(v1.PureImports))
	ctx := build.Default
	for _, p := range pkgs {
		dir := filepath.Join(goroot, "src", filepath.FromSlash(p))
		entries, err := os.ReadDir(dir)
		if err != nil {
			return nil, err
		}
		names := map[string]bool{}
		for _, e := range entries {
			n := e.Name()
			if e.IsDir() || !strings.HasSuffix(n, ".go") || strings.HasSuffix(n, "_test.go") {
				continue
			}
			if ok, err := ctx.MatchFile(dir, n); err != nil || !ok {
				continue
			}
			f, err := parser.ParseFile(token.NewFileSet(), filepath.Join(dir, n), nil, parser.SkipObjectResolution)
			if err != nil {
				return nil, err
			}
			if f.Name.Name != path.Base(p) {
				continue
			}
			for _, d := range f.Decls {
				fd, ok := d.(*ast.FuncDecl)
				if ok && fd.Recv == nil && fd.Type.TypeParams == nil && ast.IsExported(fd.Name.Name) && !slices.Contains(v1.PureImportsExcept()[p], fd.Name.Name) {
					names[fd.Name.Name] = true
				}
			}
		}
		if len(names) > 0 {
			// A package of generic functions only (slices) has none.
			fmt.Fprintf(&imports, "\t%q\n", p)
		}
		for _, n := range slices.Sorted(maps.Keys(names)) {
			fmt.Fprintf(&b, "\t%q: %s.%s,\n", p+"."+n, path.Base(p), n)
		}
	}
	src := "// Code generated by TestMembersCurrent -update-members. DO NOT EDIT.\n\npackage hostguard\n\nimport (\n" + imports.String() +
		")\n\n// members are the guarded members of v1.PureImports (pure.go).\nvar members = map[string]any{\n" + b.String() + "}\n"
	return format.Source([]byte(src))
}
