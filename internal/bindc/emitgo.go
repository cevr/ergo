package bindc

import (
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"
)

// GoPackage emits the Go package of a binding (the go/<package>.go
// golden): one gofmt-clean file over purego v0.11.3, built for linux and
// darwin on amd64 and arm64.
//
// The raw layer has one unexported function variable per function, with
// the exact C shape (a pointer to a handle type, a callback and a token key
// are uintptr, every other pointer is unsafe.Pointer, a struct by value is
// its call form of abi.go). The callbacks are emitcb.go. Load opens the
// library, looks up
// every symbol with purego.Dlsym (an error names a missing symbol), calls
// the ABI-version function first, and registers the raw functions with
// purego.RegisterFunc only when the ABI matches; RegisterLibFunc, which
// panics on a missing symbol, is never used.
//
// The typed layer has one exported function per typed function. Each
// returns an error last: ErrNotLoaded before a successful Load (no C call),
// ErrDestroyed for a nil or destroyed handle (no C call), ErrTooLong for a
// slice longer than its length type holds (no C call), or the Status of a
// status result. A Go value passed by address stays alive until C returns
// through runtime.KeepAlive after the call.
func GoPackage(b *Binding) (name string, src []byte, err error) {
	e := &goEmitter{b: b, imports: map[string]bool{}}
	body := e.file()
	if e.err != nil {
		return "", nil, e.err
	}
	var w strings.Builder
	fmt.Fprintf(&w, "// Code generated by ergo bind c (internal/bindc); DO NOT EDIT.\n")
	fmt.Fprintf(&w, "//\n// header %s sha256 %s\n// contract sha256 %s\n\n", b.Contract.Header, b.HeaderSHA256, b.ContractSHA256)
	w.WriteString("//go:build (linux || darwin) && (amd64 || arm64)\n\n")
	fmt.Fprintf(&w, "// Package %s binds %s over purego. The raw layer is unexported; the\n// typed layer is the exported functions. Call Load first.\npackage %s\n\n", b.Contract.Go.Package, b.Contract.Header, b.Contract.Go.Package)
	var imps []string
	for p := range e.imports {
		imps = append(imps, p)
	}
	sort.Strings(imps)
	w.WriteString("import (\n")
	for _, p := range imps {
		fmt.Fprintf(&w, "\t%q\n", p)
	}
	w.WriteString(")\n\n")
	w.WriteString(body)
	out, err := format.Source([]byte(w.String()))
	if err != nil {
		return "", nil, fmt.Errorf("bindc: the generated Go does not format: %v", err)
	}
	return b.Contract.Go.Package + ".go", out, nil
}

type goEmitter struct {
	b       *Binding
	w       strings.Builder
	imports map[string]bool
	// err is the first fact the emitter cannot write as Go; GoPackage
	// returns it and no source.
	err error
}

func (e *goEmitter) p(format string, args ...any) { fmt.Fprintf(&e.w, format, args...) }

func (e *goEmitter) use(pkg string) string {
	e.imports[pkg] = true
	if i := strings.LastIndexByte(pkg, '/'); i >= 0 {
		return pkg[i+1:]
	}
	return pkg
}

func (e *goEmitter) file() string {
	b := e.b
	k := b.k
	pkg := b.Contract.Go.Package
	e.use("unsafe")

	// Constants.
	e.p("// The constants of %s.\nconst (\n", b.Contract.Header)
	for _, x := range b.Constants {
		e.p("\t%s %s = %s\n", x.Name, goScalar[x.Type], x.Value())
	}
	e.p(")\n\n")

	// Status.
	st := k.types[b.Contract.Status.Type]
	e.p("// Status is a status code of %s other than %s; a typed function\n// returns it as its error.\ntype Status %s\n\n", b.Contract.Status.Type, b.Contract.Status.Success, goScalar[st.Scalar])
	e.p("// The status codes.\nconst (\n")
	for _, x := range b.Codes {
		e.p("\t%s Status = %s\n", b.CodeGoName(x), x.Value())
	}
	e.p(")\n\n")
	e.p("func (s Status) Error() string {\n\tswitch s {\n")
	for _, x := range b.Codes {
		e.p("\tcase %s:\n\t\treturn %q\n", b.CodeGoName(x), pkg+": "+x.Name+" ("+x.Value()+")")
	}
	e.p("\t}\n\treturn %q + %s.FormatInt(int64(s), 10)\n}\n\n", pkg+": status ", e.use("strconv"))
	e.p("// statusError maps a status result to nil for %s, else to its Status.\nfunc statusError(s %s) error {\n\tif s == %s {\n\t\treturn nil\n\t}\n\treturn Status(s)\n}\n\n",
		b.Contract.Status.Success, goScalar[st.Scalar], b.Success.Value())

	// Errors and Load.
	abiF := k.m.Functions[0]
	for _, f := range k.m.Functions {
		if f.Name == b.Contract.ABI.Function {
			abiF = f
		}
	}
	abiT := goScalar[mustScalar(k, abiF.Result)]
	errs := e.use("errors")
	e.p("// ABIMismatchError is the error of Load when %s() is not %s.\ntype ABIMismatchError struct {\n\tWant, Got %s\n}\n\n", b.Contract.ABI.Function, b.Contract.ABI.Macro, abiT)
	e.p("func (e *ABIMismatchError) Error() string {\n\treturn %s.Sprintf(%q, e.Got, e.Want)\n}\n\n", e.use("fmt"), pkg+": the library's ABI version is %d, the binding's is %d")
	e.p("var (\n")
	e.p("\t// ErrNotLoaded is the error of a call before a successful Load.\n\tErrNotLoaded = %s.New(%q)\n", errs, pkg+": Load has not succeeded")
	e.p("\t// ErrDestroyed is the error of a call on a nil or destroyed handle.\n\tErrDestroyed = %s.New(%q)\n", errs, pkg+": the handle is nil or destroyed")
	e.p("\t// ErrTooLong is the error of a call with a slice longer than its C length holds.\n\tErrTooLong = %s.New(%q)\n", errs, pkg+": a slice is longer than its C length holds")
	e.p(")\n\n")
	e.p("var (\n\tloadMu sync.Mutex\n\tloaded %s.Bool\n)\n\n", e.use("sync/atomic"))
	e.use("sync")
	e.p("func ready() error {\n\tif !loaded.Load() {\n\t\treturn ErrNotLoaded\n\t}\n\treturn nil\n}\n\n")
	e.p("// sliceData is the address of the first element of s, or nil when s is empty.\nfunc sliceData[T any](s []T) unsafe.Pointer {\n\tif len(s) == 0 {\n\t\treturn nil\n\t}\n\treturn unsafe.Pointer(unsafe.SliceData(s))\n}\n\n")
	pg := e.use("github.com/ebitengine/purego")
	abiIndex := 0
	e.p("// symbols are the raw functions, in header order.\nvar symbols = [...]struct {\n\tname string\n\tfn   any\n}{\n")
	for i, f := range b.Funcs {
		if f.C.Name == b.Contract.ABI.Function {
			abiIndex = i
		}
		e.p("\t{%q, &%s},\n", f.C.Name, rawName(f.C.Name))
	}
	e.p("}\n\n")
	cbDoc, cbMake := "", ""
	if len(e.boundCbs()) > 0 {
		cbDoc = `
// Before it opens the library it makes the C pointer of each callback
// trampoline that has none yet (once per process); when purego has no
// callback slot left it returns *CallbackSlotsError and reaches no C code.`
		cbMake = "\tif err := cbMake(); err != nil {\n\t\treturn err\n\t}\n"
	}
	e.p(`// Load opens the library at path and binds every function of %[1]s.
// It looks up every symbol first (an error names a missing one), then calls
// %[2]s and returns *ABIMismatchError unless it returns %[3]s (%[4]d),
// and only then registers the functions. A failed Load leaves the package
// unloaded: no C function was called but %[2]s, and every typed function
// returns ErrNotLoaded.%[13]s
func Load(path string) error {
	loadMu.Lock()
	defer loadMu.Unlock()
	if loaded.Load() {
		return %[5]s.New(%[6]q)
	}
%[14]s	lib, err := %[7]s.Dlopen(path, %[7]s.RTLD_NOW|%[7]s.RTLD_LOCAL)
	if err != nil {
		return %[8]s.Errorf(%[9]q, path, err)
	}
	addrs := make([]uintptr, len(symbols))
	for i, s := range symbols {
		addr, err := %[7]s.Dlsym(lib, s.name)
		if err != nil || addr == 0 {
			_ = %[7]s.Dlclose(lib)
			return %[8]s.Errorf(%[10]q, path, s.name, err)
		}
		addrs[i] = addr
	}
	var abi func() %[11]s
	%[7]s.RegisterFunc(&abi, addrs[%[12]d])
	if got := abi(); got != %[4]d {
		_ = %[7]s.Dlclose(lib)
		return &ABIMismatchError{Want: %[4]d, Got: got}
	}
	for i, s := range symbols {
		%[7]s.RegisterFunc(s.fn, addrs[i])
	}
	loaded.Store(true)
	return nil
}

`, b.Contract.Header, b.Contract.ABI.Function, b.Contract.ABI.Macro, b.ABIWant, errs, pkg+": Load: already loaded",
		pg, e.use("fmt"), pkg+": Load %s: %w", pkg+": Load %s: missing symbol %s (%v)", abiT, abiIndex, cbDoc, cbMake)

	// Types.
	for _, d := range k.m.Types {
		gn := b.GoTypes[d.Name]
		switch d.Kind {
		case DeclScalar:
			if d.Name == b.Contract.Status.Type {
				continue
			}
			e.p("// %s is %s.\ntype %s %s\n\n", gn, d.Name, gn, goScalar[d.Scalar])
		case DeclOpaque:
			if h := k.handles[d.Name]; h != nil {
				e.p("// %s is a %s handle. %s destroys it and sets it to nil; a later\n// call on it returns ErrDestroyed. Thread affinity: %s.\ntype %s struct{ p uintptr }\n\n",
					gn, d.Name, goCamel(strings.TrimPrefix(h.Destroy, b.Contract.Prefixes.Function)), h.Thread, gn)
			}
		case DeclStruct:
			e.structDecl(d)
		case DeclCallback:
			if cb := k.cbs[d.Name]; cb != nil && cb.Bound() {
				e.cbFuncType(cb)
			}
		}
	}

	// Call forms (abi.go).
	if structs := e.byValueStructs(); len(structs) > 0 {
		e.p("// The call forms: a struct passed or returned by value crosses purego as\n// the plainest Go struct that purego marshals as C passes the struct.\n")
		seen := map[string]bool{}
		for _, s := range structs {
			if fm := k.form(s); !seen[fm.GoName()] {
				seen[fm.GoName()] = true
				e.p("%s\n", fm.GoDecl())
			}
		}
		e.p("\n// toABI copies the Go struct v into its call form W, byte for byte.\nfunc toABI[W, T any](v T) (w W) {\n\t*(*T)(unsafe.Pointer(&w)) = v\n\treturn w\n}\n\n")
		e.p("// fromABI copies the call form w back into its Go struct T.\nfunc fromABI[T, W any](w W) T {\n\treturn *(*T)(unsafe.Pointer(&w))\n}\n\n")
		e.p("// Each call form holds its struct: it is no smaller and no less aligned.\nvar (\n")
		for _, s := range structs {
			gn, fn := b.GoTypes[s], k.form(s).GoName()
			e.p("\t_ = [unsafe.Sizeof(%s{}) - unsafe.Sizeof(%s{})]struct{}{}\n", fn, gn)
			e.p("\t_ = [unsafe.Alignof(%s{}) - unsafe.Alignof(%s{})]struct{}{}\n", fn, gn)
		}
		e.p(")\n\n")
	}

	// Callbacks: the trampolines and the registry (emitcb.go), the panic
	// containment, the thread id and the Owner (emitthread.go).
	e.callbacks()
	e.threadHelper()
	e.ownerRunner()

	// Raw layer.
	e.p("// The raw layer: the exact C shape of every function, with a struct by\n// value in its call form, a callback as uintptr, and a token key as uintptr.\nvar (\n")
	for _, f := range b.Funcs {
		e.p("\t%s func(%s)%s\n", rawName(f.C.Name), e.rawParams(f), e.rawResult(f.C.Result))
	}
	e.p(")\n\n")

	// Typed layer.
	for _, f := range b.Funcs {
		if f.goTyped() {
			e.typedFunc(f)
		}
	}
	return e.w.String()
}

// byValueStructs are the structs that a function passes
// or returns by value, sorted.
func (e *goEmitter) byValueStructs() []string {
	k := e.b.k
	set := map[string]bool{}
	for _, f := range e.b.Funcs {
		ts := []Type{f.C.Result}
		for _, p := range f.C.Params {
			ts = append(ts, p.Type)
		}
		for _, t := range ts {
			if k.isByValueStruct(t) {
				set[t.Name] = true
			}
		}
	}
	var out []string
	for s := range set {
		out = append(out, s)
	}
	sort.Strings(out)
	return out
}

func mustScalar(k *classifier, t Type) Scalar {
	s, _ := k.scalarOf(t)
	return s
}

func rawName(c string) string { return "c_" + c }

// fieldName is the Go name of field i of struct d (Binding.FieldNames):
// CamelCase, or an unexported name for an autofill field, which the
// binding sets and the caller cannot.
func (e *goEmitter) fieldName(d TypeDecl, i int) string { return e.b.FieldNames[d.Name][i] }

// fieldType is the Go type of a field: a pointer or a callback is uintptr.
func (e *goEmitter) fieldType(t Type) string {
	switch t.Kind {
	case TypeArray:
		return "[" + strconv.FormatInt(t.Len, 10) + "]" + e.fieldType(*t.Elem)
	case TypePointer:
		return "uintptr"
	case TypeNamed:
		if d := e.b.k.types[t.Name]; d.Kind == DeclCallback {
			return "uintptr"
		}
	}
	return e.b.GoType(t)
}

// needsFill reports whether a struct holds an autofill field, directly or
// in a nested struct or array.
func (e *goEmitter) needsFill(name string) bool {
	d := e.b.k.types[name]
	if d == nil || d.Kind != DeclStruct {
		return false
	}
	for _, f := range d.Fields {
		t := f.Type
		for t.Kind == TypeArray {
			t = *t.Elem
		}
		if e.b.Autofill[f.Name] != "" || t.Kind == TypeNamed && e.needsFill(t.Name) {
			return true
		}
	}
	return false
}

func (e *goEmitter) structDecl(d TypeDecl) {
	gn := e.b.GoTypes[d.Name]
	e.p("// %s is %s (%d bytes, alignment %d).\ntype %s struct {\n", gn, d.Name, d.Size, d.Align, gn)
	for i, f := range d.Fields {
		e.p("\t%s %s\n", e.fieldName(d, i), e.fieldType(f.Type))
	}
	e.p("}\n\n")
	e.p("// The layout of %s: each line fails to compile when Go's layout differs.\nvar (\n", gn)
	e.p("\t_ [1]struct{} = [unsafe.Sizeof(%s{}) - %d + 1]struct{}{}\n", gn, d.Size)
	e.p("\t_ [1]struct{} = [unsafe.Alignof(%s{}) - %d + 1]struct{}{}\n", gn, d.Align)
	for i, f := range d.Fields {
		e.p("\t_ [1]struct{} = [unsafe.Offsetof(%s{}.%s) - %d + 1]struct{}{}\n", gn, e.fieldName(d, i), f.Offset)
		e.p("\t_ [1]struct{} = [unsafe.Sizeof(%s{}.%s) - %d + 1]struct{}{}\n", gn, e.fieldName(d, i), f.Size)
	}
	e.p(")\n\n")
	if !e.needsFill(d.Name) {
		return
	}
	e.p("// fill sets the autofill fields of s.\nfunc (s *%s) fill() {\n", gn)
	for i, f := range d.Fields {
		fn := e.fieldName(d, i)
		switch e.b.Autofill[f.Name] {
		case "size":
			e.p("\ts.%s = %d\n", fn, d.Size)
			continue
		case "abi":
			e.p("\ts.%s = %d\n", fn, e.b.ABIWant)
			continue
		}
		e.fill("s."+fn, f.Type, 0)
	}
	e.p("}\n\n")
}

// needsFillType reports whether a value of type t holds an autofill
// field: a struct that holds one, or an array of them.
func (e *goEmitter) needsFillType(t Type) bool {
	for t.Kind == TypeArray {
		t = *t.Elem
	}
	return t.Kind == TypeNamed && e.needsFill(t.Name)
}

// fill emits the statements that set the autofill fields of the Go value
// x of C type t: x.fill() for a struct that holds one, and a loop for an
// array of them (or a slice: an array type with no length). Each loop
// variable is _i<depth>.
func (e *goEmitter) fill(x string, t Type, depth int) {
	switch {
	case t.Kind == TypeArray && e.needsFillType(*t.Elem):
		v := "_i" + strconv.Itoa(depth)
		e.p("\tfor %s := range %s {\n", v, x)
		e.fill(x+"["+v+"]", *t.Elem, depth+1)
		e.p("\t}\n")
	case t.Kind == TypeNamed && e.needsFill(t.Name):
		e.p("\t%s.fill()\n", x)
	}
}

// rawType is the Go type of a C parameter or result in the raw layer.
func (e *goEmitter) rawType(t Type) string {
	k := e.b.k
	switch t.Kind {
	case TypePointer:
		if t.LenExpr == "" && k.isHandleType(*t.Elem) {
			return "uintptr"
		}
		return "unsafe.Pointer"
	case TypeNamed:
		d := k.types[t.Name]
		switch d.Kind {
		case DeclCallback:
			return "uintptr"
		case DeclScalar:
			return goScalar[d.Scalar]
		case DeclStruct:
			return k.form(t.Name).GoName()
		}
		return e.b.GoTypes[t.Name]
	case TypeScalar:
		return goScalar[t.Scalar]
	}
	return "?"
}

// rawParams are the Go types of the raw function of f: rawType, except a
// token key of a typed function, which is uintptr (the binding passes an
// integer there, never a pointer).
func (e *goEmitter) rawParams(f *BoundFunc) string {
	keys := map[int]bool{}
	if f.RawOnly == "" {
		for _, q := range f.Positions {
			if q.Class == ClassKey {
				keys[q.Param] = true
			}
		}
	}
	var s []string
	for i, p := range f.C.Params {
		if keys[i] {
			s = append(s, "uintptr")
			continue
		}
		s = append(s, e.rawType(p.Type))
	}
	return strings.Join(s, ", ")
}

func (e *goEmitter) rawResult(t Type) string {
	if t.Kind == TypeVoid {
		return ""
	}
	return " " + e.rawType(t)
}

// typedFunc emits the adapter of one typed function.
func (e *goEmitter) typedFunc(f *BoundFunc) {
	b, k, s := e.b, e.b.k, f.Sig
	c := f.C
	var params []string
	for _, p := range s.Params {
		params = append(params, p.Name+" "+p.Type)
	}
	res := s.ResultTypes()
	resList := strings.Join(res, ", ")
	if len(res) > 1 {
		resList = "(" + resList + ")"
	}
	e.p("// %s calls %s.\n", f.GoName, c.Name)
	if f.Destroys != nil {
		e.p("// On success it sets the handle to nil; a later call on it returns ErrDestroyed.\n")
	}
	for _, p := range s.Params {
		if t := c.Params[p.C].Type; (p.Class == ClassInBuffer || p.Class == ClassOutBuffer) && e.needsFillType(*t.Elem) {
			e.p("// It sets the autofill fields of each element of %s.\n", p.Name)
		}
		if p.Class == ClassCallback {
			e.cbParamDoc(c, p)
		}
	}
	e.p("func %s(%s) %s {\n", f.GoName, strings.Join(params, ", "), resList)

	// The zero results, for an early return.
	zeros := make([]string, 0, len(s.Results)+1)
	for _, r := range s.Results {
		t := c.Result
		if r.C >= 0 {
			t = *c.Params[r.C].Type.Elem
		}
		zeros = append(zeros, e.zero(t, r.Type))
	}
	ret := func(err string) string { return "return " + strings.Join(append(slicesClone(zeros), err), ", ") }
	e.p("\tif err := ready(); err != nil {\n\t\t%s\n\t}\n", ret("err"))

	goParam := map[int]GoParam{}
	for _, p := range s.Params {
		goParam[p.C] = p
	}
	pos := map[int]Position{}
	lengthOf := map[int]Position{} // length or capacity param -> its buffer
	for _, q := range f.Positions {
		pos[q.Param] = q
		if q.Class == ClassInBuffer || q.Class == ClassOutBuffer {
			lengthOf[q.Length] = q
		}
	}
	// Checks before C: handles, then slice lengths.
	for _, p := range s.Params {
		if p.Class == ClassHandle {
			e.p("\tif %s == nil || %s.p == 0 {\n\t\t%s\n\t}\n", p.Name, p.Name, ret("ErrDestroyed"))
		}
	}
	for i := range c.Params {
		q, ok := lengthOf[i]
		if !ok {
			continue
		}
		lt := mustScalar(k, c.Params[i].Type)
		limit := uint64(1)<<(8*scalarSize[lt]) - 1
		if scalarSize[lt] == 8 {
			limit = ^uint64(0)
		}
		sl := goParam[q.Param].Name
		elem := *c.Params[q.Param].Type.Elem
		if q.Bytes {
			es := e.elemSize(elem)
			e.p("\tif uint64(len(%s)) > %d {\n\t\t%s\n\t}\n", sl, limit/uint64(es), ret("ErrTooLong"))
		} else if limit != ^uint64(0) {
			e.p("\tif uint64(len(%s)) > %d {\n\t\t%s\n\t}\n", sl, limit, ret("ErrTooLong"))
		}
	}
	// Autofill and out-parameters.
	var args, keep []string
	outVar := map[int]string{}
	for i, p := range c.Params {
		q, isPos := pos[i]
		gp := goParam[i]
		switch {
		case isPos && (q.Class == ClassOut || q.Class == ClassOutCount):
			v := "_o" + strconv.Itoa(i)
			outVar[i] = v
			t := *p.Type.Elem
			if q.By == ruleCreate {
				e.p("\tvar %s uintptr\n", v)
			} else {
				e.p("\tvar %s %s\n", v, b.GoType(t))
				e.fill(v, t, 0)
			}
			args = append(args, "unsafe.Pointer(&"+v+")")
			keep = append(keep, "&"+v)
		case isPos && q.Class == ClassHandle:
			args = append(args, gp.Name+".p")
		case isPos && q.Class == ClassCallback:
			args = append(args, "_c"+strconv.Itoa(i))
		case isPos && q.Class == ClassKey:
			args = append(args, "_k"+strconv.Itoa(k.tokenOf(c, i)))
		case isPos && q.Class == ClassValue:
			t := *p.Type.Elem
			if p.Type.LenExpr != "" {
				// const T name[N]: the Go parameter is a [N]T.
				t = Type{Kind: TypeArray, Elem: p.Type.Elem, Len: p.Type.Len}
			}
			e.fill(gp.Name, t, 0)
			args = append(args, "unsafe.Pointer(&"+gp.Name+")")
			keep = append(keep, "&"+gp.Name)
		case isPos && (q.Class == ClassInBuffer || q.Class == ClassOutBuffer):
			e.fill(gp.Name, Type{Kind: TypeArray, Elem: p.Type.Elem}, 0)
			args = append(args, "sliceData("+gp.Name+")")
			keep = append(keep, gp.Name)
		default:
			if q, ok := lengthOf[i]; ok {
				lt := e.rawType(p.Type)
				n := "len(" + goParam[q.Param].Name + ")"
				if q.Bytes {
					es := e.elemSize(*c.Params[q.Param].Type.Elem)
					if es != 1 {
						n += "*" + strconv.FormatInt(es, 10)
					}
				}
				args = append(args, lt+"("+n+")")
				continue
			}
			rt := e.rawType(p.Type)
			if k.isByValueStruct(p.Type) {
				// A struct by value: its autofill fields, then its call form.
				e.fill(gp.Name, p.Type, 0)
				args = append(args, "toABI["+rt+"]("+gp.Name+")")
			} else if gp.Type != rt {
				args = append(args, rt+"("+gp.Name+")")
			} else {
				args = append(args, gp.Name)
			}
		}
	}
	// Callbacks: the registry entries before the C call (emitcb.go).
	uses := e.cbUses(f, goParam)
	for _, u := range uses {
		e.cbBefore(u, s.Status)
	}
	// With bound callbacks, the typed call takes the panic pending on its OS
	// thread right after the C call (_p, emitthread.go): a callback that
	// panicked during the C call ran on this goroutine and locked it to the
	// thread, so it is still there. It panics with it after the registry
	// follows the status, before a result is converted.
	guard := e.guardsCalls()
	call := rawName(c.Name) + "(" + strings.Join(args, ", ") + ")"
	switch {
	case c.Result.Kind == TypeVoid:
		e.p("\t%s\n", call)
	default:
		e.p("\t_r := %s\n", call)
	}
	if guard {
		e.p("\t_p := cbTake()\n")
	}
	raise := func(indent string) {
		if guard {
			e.p("%sif _p != nil {\n%s\tpanic(_p)\n%s}\n", indent, indent, indent)
		}
	}
	for _, v := range keep {
		// Only a function that passes Go memory imports runtime.
		e.p("\t%s.KeepAlive(%s)\n", e.use("runtime"), v)
	}
	if s.Status {
		e.p("\tif err := statusError(_r); err != nil {\n")
		for _, u := range uses {
			e.cbFailed(u)
		}
		raise("\t\t")
		e.p("\t\t%s\n\t}\n", ret("err"))
	}
	// After a successful return: clears, ends and the owner's destroy
	// release their entries, before a destroyed handle loses its address.
	for _, u := range uses {
		e.cbSucceeded(u)
	}
	e.cbEnds(f, goParam)
	if f.Destroys != nil {
		for _, p := range s.Params {
			if p.Class == ClassHandle {
				e.cbOwnerDestroyed(f.Destroys.Type, p.Name+".p")
				e.p("\t%s.p = 0\n", p.Name)
			}
		}
	}
	raise("\t")
	var outs []string
	for _, r := range s.Results {
		switch {
		case r.C < 0 && k.isByValueStruct(c.Result):
			outs = append(outs, "fromABI["+r.Type+"](_r)")
		case r.C < 0 && r.Type == e.rawType(c.Result):
			outs = append(outs, "_r")
		case r.C < 0:
			outs = append(outs, r.Type+"(_r)")
		case pos[r.C].By == ruleCreate:
			outs = append(outs, "&"+strings.TrimPrefix(r.Type, "*")+"{p: "+outVar[r.C]+"}")
		default:
			outs = append(outs, outVar[r.C])
		}
	}
	e.p("\treturn %s\n}\n\n", strings.Join(append(outs, "nil"), ", "))
}

// zero is the zero value of a Go result of C type t and Go type gt.
func (e *goEmitter) zero(t Type, gt string) string {
	if strings.HasPrefix(gt, "*") {
		return "nil"
	}
	if s, ok := e.b.k.scalarOf(t); ok {
		if s == Bool {
			return "false"
		}
		return "0"
	}
	return gt + "{}"
}

// elemSize is the size of a buffer element.
func (e *goEmitter) elemSize(t Type) int64 {
	if s, ok := e.b.k.scalarOf(t); ok {
		return scalarSize[s]
	}
	return e.b.k.types[t.Name].Size
}

func slicesClone(s []string) []string { return append([]string(nil), s...) }
