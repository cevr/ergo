package bindc

import (
	"fmt"
	"go/format"
)

// GoGuardFile emits the optional -tags ergocguard companion file for a bound Go
// package. When compiled with -tags ergocguard on Linux or Darwin, its init
// installs runtime/v1.GuardCReadPtr and runtime/v1.GuardCWritePtr via
// SetCGuardHooks so every typed in_buffer and out_buffer C call executes over
// mmap/mprotect guard pages.
func GoGuardFile(pkg string) (name string, src []byte, err error) {
	raw := fmt.Sprintf(`// Code generated by ergo bind c (internal/bindc); DO NOT EDIT.

//go:build ergocguard && (linux || darwin)

package %s

import v1 "ergo.local/prototype/runtime/v1"

func init() {
	SetCGuardHooks(v1.GuardCReadPtr, v1.GuardCWritePtr)
}
`, pkg)
	out, err := format.Source([]byte(raw))
	if err != nil {
		return "", nil, fmt.Errorf("bindc: guard file does not format: %v", err)
	}
	return pkg + "_cguard.go", out, nil
}
