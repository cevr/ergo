package bindc

import (
	"fmt"
	"strings"

	format "ergo.local/prototype/internal/hostsyntax"
	"ergo.local/prototype/internal/sketch/syntax"
)

// ErgoText emits the checked Ergo C binding of a binding (the <header>.ergo
// golden and ergo.bind/<import_path>/<pkg>.ergo). It parses with
// internal/sketch/syntax, formats cleanly with internal/hostsyntax, and checks
// cleanly with internal/sketch/check's C-binding verifier (cbind.go):
//
//   - a `// ergo:bind c <import_path> <header_sha256> <contract_sha256> <platforms...>`
//     provenance header;
//   - `Load(path string) fails go.Error needs go.Foreign`, exported C constants,
//     `Status` + status constants + sentinel error vars, and scalar typedefs;
//   - opaque handle types with `implements Closer` and `Close()` for every
//     destroyable handle;
//   - `// ergo:cdata` flat record structs with `[N]T` fixed arrays and no
//     autofill fields;
//   - record-kind interfaces with `Is<RecordType>()` markers;
//   - one `extern go <path>.<GoName> func <GoName>(...) ... fails go.Error
//     needs go.Foreign` per typed function without a callback, with
//     `// ergo:reads` on input buffers, `// ergo:writes` on output buffers,
//     `own *<Handle>` on destroy functions, `go.Ref[<Handle>]` on create
//     results, and `Option[go.Ref[T]]` on optional parameters;
//   - a `// not bound: <name> (<reason>)` line per raw-only or callback-taking
//     function (callbacks into Ergo are CFFI-3 / bind-c-7).
//
// Bind gives every name of the text (Binding.ergoNames, names.go).
func ErgoText(b *Binding) ([]byte, error) {
	e := &ergoEmitter{b: b}
	src := e.file()
	if _, err := syntax.Parse(src); err != nil {
		return nil, fmt.Errorf("bindc: the generated Ergo does not parse: %v", err)
	}
	out, err := format.Source(src)
	if err != nil {
		return nil, fmt.Errorf("bindc: the generated Ergo does not format: %v", err)
	}
	return []byte(out), nil
}

// cBindPlatforms matches the build constraint of the generated Go package
// (`//go:build (linux || darwin) && (amd64 || arm64)`).
const cBindPlatforms = "darwin/amd64 darwin/arm64 linux/amd64 linux/arm64"

type ergoEmitter struct {
	b *Binding
	w strings.Builder
}

func (e *ergoEmitter) p(format string, args ...any) { fmt.Fprintf(&e.w, format, args...) }

// ergoType is the Ergo type of a C value type inside the binding package:
// scalars by their Go name, fixed arrays as [N]T, handle pointers as *H (or
// go.Ref[H] on create results), and named types unqualified (this file IS the
// binding of the package).
func (e *ergoEmitter) ergoType(t Type) string {
	k := e.b.k
	switch t.Kind {
	case TypeScalar:
		return goScalar[t.Scalar]
	case TypeArray:
		return fmt.Sprintf("[%d]%s", t.Len, e.ergoType(*t.Elem))
	case TypePointer:
		if t.LenExpr == "" && k.isHandleType(*t.Elem) {
			return "*" + e.b.GoTypes[t.Elem.Name]
		}
	case TypeNamed:
		return e.b.GoTypes[t.Name]
	}
	return "?"
}

func (e *ergoEmitter) recordHeader(d TypeDecl) string {
	if e.b.kinds[d.Name] != nil {
		return d.Name
	}
	if len(d.Fields) > 0 && d.Fields[0].Type.Kind == TypeNamed && containsString(e.b.kinds[d.Fields[0].Type.Name], d.Name) {
		return d.Fields[0].Type.Name
	}
	return ""
}

func containsString(xs []string, target string) bool {
	for _, x := range xs {
		if x == target {
			return true
		}
	}
	return false
}

func (e *ergoEmitter) file() string {
	b := e.b
	k := b.k
	c := b.Contract
	ip := c.Go.ImportPath

	e.p("// Code generated by ergo bind c (internal/bindc); DO NOT EDIT.\n")
	e.p("// ergo:bind c %s %s %s %s\n\n", ip, b.HeaderSHA256, b.ContractSHA256, cBindPlatforms)

	e.p("extern go %s.Load func Load(path string) fails go.Error needs go.Foreign\n", ip)
	if e.hasBoundCbs() {
		e.p("extern go %s.LiveCallbacks func LiveCallbacks() int needs go.Foreign\n", ip)
	}
	e.p("\n")

	// Exported C constants.
	for _, x := range b.Constants {
		e.p("extern go %s.%s let %s %s\n", ip, x.Name, x.Name, goScalar[x.Type])
	}
	if len(b.Constants) > 0 {
		e.p("\n")
	}

	// Status type, Error method, status codes, and sentinel errors.
	st := k.types[c.Status.Type]
	e.p("extern go %s.Status type Status %s\n", ip, goScalar[st.Scalar])
	e.p("extern go %s.Status.Error func (s Status) Error() string needs go.Foreign\n", ip)
	for _, x := range b.Codes {
		gn := b.CodeGoName(x)
		e.p("extern go %s.%s let %s Status\n", ip, gn, gn)
	}
	e.p("extern go %s.ErrNotLoaded let ErrNotLoaded go.Error\n", ip)
	e.p("extern go %s.ErrDestroyed let ErrDestroyed go.Error\n", ip)
	e.p("extern go %s.ErrTooLong let ErrTooLong go.Error\n\n", ip)

	// Scalar typedefs.
	wroteScalar := false
	for _, d := range k.m.Types {
		if d.Kind != DeclScalar || d.Name == c.Status.Type {
			continue
		}
		gn := b.GoTypes[d.Name]
		e.p("extern go %s.%s type %s %s\n", ip, gn, gn, goScalar[d.Scalar])
		wroteScalar = true
	}
	if wroteScalar {
		e.p("\n")
	}

	// Opaque handle types (with implements Closer + Close() for destroyable handles).
	for _, d := range k.m.Types {
		if d.Kind != DeclOpaque {
			continue
		}
		h := k.handles[d.Name]
		if h == nil {
			continue
		}
		gn := b.GoTypes[d.Name]
		if h.Destroy != "" {
			e.p("extern go %s.%s type %s {} implements Closer\n", ip, gn, gn)
			e.p("extern go %s.%s.Close func (h own *%s) Close() fails go.Error needs go.Foreign\n\n", ip, gn, gn)
		} else {
			e.p("extern go %s.%s type %s {}\n\n", ip, gn, gn)
		}
	}

	// Flat C data structs (marked // ergo:cdata, with [N]T fixed arrays and no autofill fields).
	for _, d := range k.m.Types {
		if d.Kind != DeclStruct || !b.records[d.Name] {
			continue
		}
		gn := b.GoTypes[d.Name]
		e.p("// ergo:cdata\nextern go %s.%s type %s {\n", ip, gn, gn)
		for i, f := range d.Fields {
			if b.Autofill[f.Name] != "" {
				continue
			}
			e.p("\t%s %s,\n", b.FieldNames[d.Name][i], e.ergoType(f.Type))
		}
		e.p("}\n")
		if h := e.recordHeader(d); h != "" && b.unions[h] {
			rt := b.RecordType(h)
			e.p("extern go %s.%s.Is%s func (s %s) Is%s() needs go.Foreign\n", ip, gn, rt, gn, rt)
		}
		e.p("\n")
	}

	// Record-kind interfaces (one per record header union).
	for _, d := range k.m.Types {
		if !b.unions[d.Name] {
			continue
		}
		rt := b.RecordType(d.Name)
		e.p("extern go %s.%s type %s {\n\tIs%s() needs go.Foreign,\n}\n\n", ip, rt, rt, rt)
	}

	// Typed C functions (including ScopeCall and ScopeRegistered callbacks).
	for _, f := range b.Funcs {
		if why := f.ErgoUnbound(); why != "" {
			e.p("// not bound: %s (%s)\n", f.C.Name, why)
			continue
		}
		pos := map[int]Position{}
		for _, q := range f.Positions {
			pos[q.Param] = q
		}

		var params []string
		var reads []string
		var scoped []string
		var cbTypes []string
		hasCallScopeCb := false
		writesParam := ""
		writesType := ""
		for i, p := range f.Sig.Params {
			t := f.C.Params[p.C].Type
			pname := f.ErgoParams[i]
			var et string
			switch p.Class {
			case ClassHandle:
				if f.Destroys != nil {
					et = "own *" + b.GoTypes[t.Elem.Name]
				} else {
					et = "*" + b.GoTypes[t.Elem.Name]
				}
			case ClassValue:
				et = e.ergoType(*t.Elem)
				if t.LenExpr != "" {
					et = fmt.Sprintf("[%d]%s", t.Len, et)
				} else if b.unions[t.Elem.Name] {
					et = b.RecordType(t.Elem.Name)
				}
			case ClassOptional:
				et = "Option[go.Ref[" + e.ergoType(*t.Elem) + "]]"
			case ClassInBuffer:
				et = "[]" + e.ergoType(*t.Elem)
				if et == "[]uint8" {
					et = "[]byte"
				}
				reads = append(reads, pname)
			case ClassOutBuffer:
				et = "[]" + e.ergoType(*t.Elem)
				if et == "[]uint8" {
					et = "[]byte"
				}
				if writesParam == "" {
					writesParam = pname
					writesType = et
				}
			case ClassCallback:
				cb := k.cbs[t.Name]
				isCallScope := cb.Rule.Scope == ScopeCall
				if isCallScope {
					hasCallScopeCb = true
				}
				cbType, cbScoped := e.ergoCallbackType(cb, pname, isCallScope)
				et = cbType
				scoped = append(scoped, cbScoped...)
				cbTypes = append(cbTypes, pname+" "+cb.GoName)
			default:
				et = e.ergoType(t)
			}
			params = append(params, pname+" "+et)
		}

		var res []string
		if writesType != "" {
			res = append(res, writesType)
		}
		for _, r := range f.Sig.Results {
			if r.C < 0 {
				res = append(res, e.ergoType(f.C.Result))
				continue
			}
			if pos[r.C].By == ruleCreate {
				res = append(res, "go.Ref["+b.GoTypes[f.C.Params[r.C].Type.Elem.Elem.Name]+"]")
				continue
			}
			res = append(res, e.ergoType(*f.C.Params[r.C].Type.Elem))
		}
		result := ""
		switch len(res) {
		case 0:
		case 1:
			result = " " + res[0]
		default:
			result = " (" + strings.Join(res, ", ") + ")"
		}
		for _, ct := range cbTypes {
			e.p("// ergo:cbtype %s\n", ct)
		}
		if len(scoped) > 0 {
			e.p("// ergo:scoped %s\n", strings.Join(scoped, " "))
		}
		if len(reads) > 0 {
			e.p("// ergo:reads %s\n", strings.Join(reads, " "))
		}
		if writesParam != "" {
			e.p("// ergo:writes %s\n", writesParam)
		}
		tparams := ""
		failsRow := " fails go.Error"
		foreignRow := " needs go.Foreign"
		if hasCallScopeCb {
			tparams = "[CE, CR]"
			failsRow = " fails CE | go.Error"
			foreignRow = " needs CR | go.Foreign"
		}
		e.p("extern go %s.%s func %s%s(%s)%s%s%s\n", ip, f.GoName, f.GoName, tparams, strings.Join(params, ", "), result, failsRow, foreignRow)
	}
	return e.w.String()
}

func (e *ergoEmitter) hasBoundCbs() bool {
	for _, cb := range e.b.Callbacks {
		if cb.Bound() {
			return true
		}
	}
	return false
}

// ergoCallbackType formats the Ergo function type for a bound C callback and
// returns any `cbParam.sliceParam` entries for C-borrowed in_buffer slices.
func (e *ergoEmitter) ergoCallbackType(cb *BoundCallback, paramName string, isCallScope bool) (string, []string) {
	cf := callbackFunc(cb.Decl)
	pos := map[int]Position{}
	for _, q := range cb.Positions {
		pos[q.Param] = q
	}
	sc := ergoFuncScope(nil)
	var cparams []string
	var scoped []string
	for _, cp := range cb.Sig.Params {
		q := pos[cp.C]
		ct := cf.Params[cp.C].Type
		cname := sc.alloc(cp.Name, "callback parameter "+cp.Name)
		var et string
		switch q.Class {
		case ClassValue:
			et = e.ergoType(*ct.Elem)
			if ct.LenExpr != "" {
				et = fmt.Sprintf("[%d]%s", ct.Len, et)
			}
		case ClassInBuffer:
			et = "[]" + e.ergoType(*ct.Elem)
			if et == "[]uint8" {
				et = "[]byte"
			}
			scoped = append(scoped, paramName+"."+cname)
		default:
			et = e.ergoType(ct)
		}
		cparams = append(cparams, cname+" "+et)
	}
	var cres []string
	for _, cr := range cb.Sig.Results {
		if cr.C < 0 {
			cres = append(cres, e.ergoType(cf.Result))
			continue
		}
		q := pos[cr.C]
		if q.Class == ClassOutArray {
			cres = append(cres, fmt.Sprintf("[%d]%s", q.Array, e.ergoType(*cf.Params[cr.C].Type.Elem)))
			continue
		}
		cres = append(cres, e.ergoType(*cf.Params[cr.C].Type.Elem))
	}
	resText := ""
	switch len(cres) {
	case 0:
	case 1:
		resText = " " + cres[0]
	default:
		resText = " (" + strings.Join(cres, ", ") + ")"
	}
	if isCallScope {
		return "func(" + strings.Join(cparams, ", ") + ")" + resText + " fails CE needs CR", scoped
	}
	return "own func(" + strings.Join(cparams, ", ") + ")" + resText, scoped
}
