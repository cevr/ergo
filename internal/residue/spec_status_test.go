var updateStatus = flag.Bool("update-status", false, "rewrite the Status paragraphs of docs/spec and its README status table from docs/spec/status.json")

// statusLedger is docs/spec/status.json: the one source of the status of
// each part of the specification. A rule's status is never written by
// hand: TestSpecStatusIsGenerated writes it from here.
type statusLedger struct {
	// Paragraphs are the Status paragraphs of the spec files, each keyed
	// by its file and the heading it stands under.
	Paragraphs []statusParagraph `json:"paragraphs"`
	// Constructs are the rows of the README's status table, in order.
	Constructs []statusConstruct `json:"constructs"`
}

type statusParagraph struct {
	File      string   `json:"file"`
	Heading   string   `json:"heading"`
	Status    string   `json:"status"`
	Text      string   `json:"text"`
	Witnesses []string `json:"witnesses"`
}

type statusConstruct struct {
	Construct string   `json:"construct"`
	Status    string   `json:"status"`
	Cell      string   `json:"cell"`
	Section   string   `json:"section"`
	Witnesses []string `json:"witnesses"`
}

// statusWords are the statuses a ledger entry may have.
var statusWords = map[string]bool{"implemented": true, "partly implemented": true, "designed": true}

const statusTableMark = "<!-- Generated by TestSpecStatusIsGenerated (internal/residue) from status.json; do not edit. Rewrite it with: go test ./internal/residue -run TestSpecStatusIsGenerated -update-status -->"

const statusTableHead = "| Construct | Status | Section |\n| --- | --- | --- |"

// render is the Status paragraph a ledger entry writes.
func (p statusParagraph) render() string {
	return "Status: **" + p.Status + "**" + p.Text
}

// witnessProblems checks an entry's status against its witnesses: a
// designed part names no witness test (one that exists says it is
// built), and any other part names at least one test that exists.
func witnessProblems(where, status string, witnesses []string, exists func(dir, name string) bool) []string {
	var out []string
	if !statusWords[status] {
		out = append(out, fmt.Sprintf("%s: status %q is none of implemented, partly implemented, designed", where, status))
	}
	if status == "designed" && len(witnesses) > 0 {
		out = append(out, fmt.Sprintf("%s: designed, yet it names the witness %v: say what is built", where, witnesses))
	}
	if status != "designed" && len(witnesses) == 0 {
		out = append(out, fmt.Sprintf("%s: %s, yet it names no witness test", where, status))
	}
	for _, w := range witnesses {
		dir, name, ok := strings.Cut(w, ":")
		if !ok || !exists(dir, name) {
			out = append(out, fmt.Sprintf("%s: witness %q is no test (want dir:TestName)", where, w))
		}
	}
	return out
}

// generateStatus writes a spec file's Status paragraphs and, for the
// README, its status table from the ledger. A paragraph is generated when
// its file is not on the allowlist, or when it stands before the file's
// first section. It returns the generated text and the problems found.
func generateStatus(name, text string, ledger statusLedger, handWritten bool) (string, []string) {
	var problems []string
	byHeading := map[string]statusParagraph{}
	for _, p := range ledger.Paragraphs {
		if p.File == name {
			byHeading[p.Heading] = p
		}
	}
	used := map[string]bool{}
	lines := strings.Split(text, "\n")
	var out []string
	heading, section, fence := "", false, false
	for i := 0; i < len(lines); i++ {
		line := lines[i]
		if strings.HasPrefix(strings.TrimSpace(line), "```") {
			fence = !fence
		}
		if !fence && strings.HasPrefix(line, "#") {
			heading = strings.TrimSpace(strings.TrimLeft(line, "#"))
			section = section || strings.HasPrefix(line, "## ")
		}
		if fence || !strings.HasPrefix(line, "Status") || (handWritten && section) {
			out = append(out, line)
			continue
		}
		end := i
		for end+1 < len(lines) && strings.TrimSpace(lines[end+1]) != "" {
			end++
		}
		p, ok := byHeading[heading]
		switch {
		case !ok:
			problems = append(problems, fmt.Sprintf("docs/spec/%s:%d: a Status paragraph under %q written by hand: give it an entry in status.json", name, i+1, heading))
			out = append(out, lines[i:end+1]...)
		case used[heading]:
			problems = append(problems, fmt.Sprintf("docs/spec/%s:%d: a second Status paragraph under %q", name, i+1, heading))
			out = append(out, lines[i:end+1]...)
		default:
			used[heading] = true
			out = append(out, p.render())
		}
		i = end
	}
	for h := range byHeading {
		if !used[h] {
			problems = append(problems, fmt.Sprintf("status.json: no Status paragraph in docs/spec/%s under %q", name, h))
		}
	}
	got := strings.Join(out, "\n")
	if name == "README.md" {
		var table strings.Builder
		table.WriteString(statusTableMark + "\n\n" + statusTableHead + "\n")
		for _, c := range ledger.Constructs {
			fmt.Fprintf(&table, "| %s | %s | %s |\n", c.Construct, c.Cell, c.Section)
		}
		at := strings.Index(got, statusTableHead)
		if at < 0 {
			return got, append(problems, "docs/spec/README.md: no status table")
		}
		start := at
		if m := strings.LastIndex(got[:at], statusTableMark+"\n\n"); m >= 0 && m+len(statusTableMark)+2 == at {
			start = m
		}
		end := at
		for end < len(got) {
			nl := strings.IndexByte(got[end:], '\n')
			if nl < 0 {
				end = len(got)
				break
			}
			if !strings.HasPrefix(got[end:], "|") {
				break
			}
			end += nl + 1
		}
		got = got[:start] + table.String() + got[end:]
	}
	return got, problems
}

// testExists reports whether dir (from the root) declares the test name.
func testExists(repo string) func(dir, name string) bool {
	cache := map[string]string{}
	return func(dir, name string) bool {
		src, ok := cache[dir]
		if !ok {
			paths, _ := filepath.Glob(filepath.Join(repo, filepath.FromSlash(dir), "*_test.go"))
			var b strings.Builder
			for _, p := range paths {
				data, err := os.ReadFile(p)
				if err == nil {
					b.Write(data)
				}
			}
			src = b.String()
			cache[dir] = src
		}
		return regexp.MustCompile(`(?m)^func ` + regexp.QuoteMeta(name) + `\(`).MatchString(src)
	}
}

// statusProblems checks the ledger and every spec file's generated text.
func statusProblems(ledger statusLedger, files map[string]string, allow map[string]string, exists func(dir, name string) bool) (map[string]string, []string) {
	var problems []string
	for _, p := range ledger.Paragraphs {
		problems = append(problems, witnessProblems(fmt.Sprintf("status.json %s %q", p.File, p.Heading), p.Status, p.Witnesses, exists)...)
		if _, ok := files[p.File]; !ok {
			problems = append(problems, fmt.Sprintf("status.json: %s is not a spec file", p.File))
		}
	}
	for _, c := range ledger.Constructs {
		where := fmt.Sprintf("status.json construct %q", c.Construct)
		problems = append(problems, witnessProblems(where, c.Status, c.Witnesses, exists)...)
		if designed := strings.HasPrefix(c.Cell, "Designed"); designed != (c.Status == "designed") {
			problems = append(problems, fmt.Sprintf("%s: status %s, cell %q", where, c.Status, c.Cell))
		}
	}
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	want := map[string]string{}
	for _, name := range names {
		_, listed := allow[name]
		got, ps := generateStatus(name, files[name], ledger, listed)
		problems = append(problems, ps...)
		if got != files[name] {
			want[name] = got
		}
		if listed {
			if _, all := generateStatus(name, files[name], ledger, false); len(all) == 0 {
				problems = append(problems, fmt.Sprintf("docs/spec/%s: every Status paragraph is generated: delete its row from the status allowlist", name))
			}
		}
	}
	return want, problems
}

// TestSpecStatusIsGenerated: the Status paragraphs of docs/spec and the
// README's status table are written from docs/spec/status.json, and each
// status agrees with its witness tests. A file on the allowlist keeps its
// sections' paragraphs by hand until its unit converts it; its opening
// Status paragraph is generated already.
func TestSpecStatusIsGenerated(t *testing.T) {
	repo := specRoot(t)
	data, err := os.ReadFile(filepath.Join(repo, "docs/spec/status.json"))
	if err != nil {
		t.Fatal(err)
	}
	var ledger statusLedger
	if err := json.Unmarshal(data, &ledger); err != nil {
		t.Fatalf("docs/spec/status.json: %v", err)
	}
	files := specFiles(t, repo)
	allow := readSpecAllow(t, "testdata/spec-status-allow.txt")
	want, problems := statusProblems(ledger, files, allow, testExists(repo))
	for _, p := range problems {
		t.Error(p)
	}
	for name, text := range want {
		if *updateStatus {
			if err := os.WriteFile(filepath.Join(repo, "docs/spec", name), []byte(text), 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		t.Errorf("docs/spec/%s differs from status.json at line %d: rerun with -update-status", name, firstDiff(files[name], text))
	}
}

func firstDiff(a, b string) int {
	al, bl := strings.Split(a, "\n"), strings.Split(b, "\n")
	for i := range min(len(al), len(bl)) {
		if al[i] != bl[i] {
			return i + 1
		}
	}
	return min(len(al), len(bl)) + 1
}

// TestSpecStatusRules pins the generator on fixed text.
func TestSpecStatusRules(t *testing.T) {
	ledger := statusLedger{
		Paragraphs: []statusParagraph{{File: "a.md", Heading: "A", Status: "implemented", Text: ": the rule runs.", Witnesses: []string{"p:TestA"}}},
		Constructs: []statusConstruct{{Construct: "X", Status: "designed", Cell: "Designed", Section: "[a](a.md)"}},
	}
	exists := func(dir, name string) bool { return dir == "p" && name == "TestA" }
	for _, c := range []struct {
		name, text string
		listed     bool
		problems   int
		changed    bool
	}{
		{"generated", "# A\n\nStatus: **implemented**: the rule runs.\n", false, 0, false},
		{"edited by hand", "# A\n\nStatus: **implemented**: the rule runs, and more.\n", false, 0, true},
		{"a paragraph of two lines", "# A\n\nStatus: **implemented**: the rule\nruns.\n", false, 0, true},
		{"a section paragraph with no entry", "# A\n\nStatus: **implemented**: the rule runs.\n\n## B\n\nStatus: built.\n", false, 1, false},
		{"the same on the allowlist", "# A\n\nStatus: **implemented**: the rule runs.\n\n## B\n\nStatus: built.\n", true, 0, false},
		{"an opening paragraph by hand on the allowlist", "# A\n\nStatus: built.\n", true, 0, true},
		{"a paragraph in a fence", "# A\n\nStatus: **implemented**: the rule runs.\n\n## B\n\n```\nStatus: built.\n```\n", false, 0, false},
	} {
		got, ps := generateStatus("a.md", c.text, ledger, c.listed)
		if len(ps) != c.problems {
			t.Errorf("%s: problems %v, want %d", c.name, ps, c.problems)
		}
		if (got != c.text) != c.changed {
			t.Errorf("%s: generated %q", c.name, got)
		}
	}
	for _, c := range []struct {
		status    string
		witnesses []string
		problems  int
	}{
		{"designed", nil, 0},
		{"designed", []string{"p:TestA"}, 1},
		{"implemented", nil, 1},
		{"implemented", []string{"p:TestB"}, 1},
		{"partly implemented", []string{"p:TestA"}, 0},
		{"checked", []string{"p:TestA"}, 1},
	} {
		if got := witnessProblems("w", c.status, c.witnesses, exists); len(got) != c.problems {
			t.Errorf("%s %v: %v, want %d problems", c.status, c.witnesses, got, c.problems)
		}
	}
	readme := "# R\n\n" + statusTableHead + "\n| X | Implemented | [a](a.md) |\n\nAfter.\n"
	got, _ := generateStatus("README.md", readme, ledger, false)
	if want := "# R\n\n" + statusTableMark + "\n\n" + statusTableHead + "\n| X | Designed | [a](a.md) |\n\nAfter.\n"; got != want {
		t.Errorf("README table:\n%s\nwant\n%s", got, want)
	}
	if again, _ := generateStatus("README.md", got, ledger, false); again != got {
		t.Errorf("README table is not stable:\n%s", again)
	}
}
