// wire.ts generates @cvr/tn1-lint's wire module (tools/npm/tn1-lint/wire.js
// and wire.d.ts) from tn1-lint's Ergo types: `ergo tsmap --emit-js` of
// cmd/tn1-lint gives Request, Reply and Report as Effect schemas, and
// their JSON Schemas are embedded in a zero-dependency CommonJS module
// with a small checker. lint.js, worker.js and effect-oxlint's tn1Lint
// rule read serve's lines and lint's report through it, so the shapes are
// declared once, in cmd/tn1-lint.
//
//   bun ts/wire.ts --write DIR [--source FILE]   write DIR/wire.js and DIR/wire.d.ts
//   bun ts/wire.ts --check DIR [--source FILE]   exit 1 when they are not what it writes
//
// FILE is a file of the cmd/tn1-lint package (default
// cmd/tn1-lint/serve.ergo), or --source-file F names a file that holds
// its path (the wire-current case: its copy of the program cannot resolve
// go.mod's replace of ergo.dev/tn1, so tsmap reads the checkout's).
// ERGO is the ergo binary (default: ergo).
import { Schema } from "effect"
import { readFileSync, unlinkSync, writeFileSync } from "node:fs"
import { join, resolve } from "node:path"

const args = process.argv.slice(2)
const flag = (name: string) => {
  const at = args.indexOf(name)
  return at < 0 ? undefined : args[at + 1]
}
const write = flag("--write")
const check = flag("--check")
const dir = write ?? check
if (dir === undefined) throw new Error("usage: bun ts/wire.ts --write DIR | --check DIR [--source FILE]")
const sourceFile = flag("--source-file")
const source = resolve(sourceFile === undefined ? (flag("--source") ?? "cmd/tn1-lint/serve.ergo") : readFileSync(sourceFile, "utf8").trim())

const tsmap = Bun.spawnSync([process.env.ERGO || "ergo", "tsmap", "--emit-js", source])
if (tsmap.exitCode !== 0) throw new Error(`ergo tsmap --emit-js ${source}: exit ${tsmap.exitCode}: ${tsmap.stderr}`)
// tsmap's module, imported from beside the program so its "effect" resolves; then removed.
const projected = resolve(".wire-tsmap.mjs")
writeFileSync(projected, tsmap.stdout)
const types = await import(projected).finally(() => unlinkSync(projected))

type Json = { readonly [key: string]: any }
const known = new Set(["type", "properties", "required", "additionalProperties", "items", "anyOf", "enum", "$ref", "description", "minimum", "maximum"])
const defs: Record<string, Json> = {}
const refName = (ref: string) => ref.replace(/^#\/\$defs\//, "")

function walk(s: Json, visit: (s: Json) => void, seen = new Set<string>()): void {
  visit(s)
  if (s.$ref) {
    const name = refName(s.$ref)
    if (seen.has(name)) return
    seen.add(name)
    walk(defs[name]!, visit, seen)
  }
  for (const p of Object.values((s.properties ?? {}) as Record<string, Json>)) walk(p, visit, seen)
  if (s.items) walk(s.items, visit, seen)
  for (const a of s.anyOf ?? []) walk(a, visit, seen)
}

/** The wire (encoded) JSON Schema of `name`, its definitions merged into defs. */
function wire(name: string): Json {
  const schema = types[name]
  if (!Schema.isSchema(schema)) throw new Error(`ergo tsmap of ${source} has no type ${name}`)
  const document = Schema.toJsonSchemaDocument(schema)
  const root = document.schema.$ref ? document.schema : { $ref: `#/$defs/${name}` }
  if (!document.schema.$ref) defs[name] = document.schema
  for (const [n, def] of Object.entries(document.definitions as Record<string, Json>)) {
    if (n in defs && JSON.stringify(defs[n]) !== JSON.stringify(def)) throw new Error(`${n} is defined twice, differently`)
    defs[n] = def
  }
  walk(root, (s) => {
    for (const key of Object.keys(s)) if (!known.has(key)) throw new Error(`the JSON Schema keyword ${key} (in ${name}) is not one wire.js checks`)
  })
  return root
}

const roots = { Request: wire("Request"), Reply: wire("Reply"), Report: wire("Report") }
const request = defs[refName(roots.Request.$ref)]!
const requestFields = Object.keys(request.properties)
for (const k of requestFields) if (request.properties[k].type !== "string") throw new Error(`Request.${k} is not a string; encodeRequest writes each field as one`)

/** The schema without descriptions: what the checker reads. */
function bare(s: Json): Json {
  if (Array.isArray(s)) return s.map(bare)
  if (typeof s !== "object" || s === null) return s
  const out: Record<string, Json> = {}
  for (const [k, v] of Object.entries(s)) {
    if (k === "description") continue
    out[k] = k === "properties" ? Object.fromEntries(Object.entries(v as Json).map(([p, ps]) => [p, bare(ps)])) : bare(v)
  }
  return out
}

const lines = (o: Record<string, unknown>) =>
  `{\n${Object.entries(o)
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},\n`)
    .join("")}}`

const header = `// Generated by examples/tn1-lint/ts/wire.ts from tn1-lint's Ergo types
// (cmd/tn1-lint: Request, Reply, Report), through ergo tsmap: do not edit.`

const js = `"use strict";
${header}
//
// The lines of \`tn1-lint serve\` and the report of \`tn1-lint lint\`, checked
// against those types: encodeRequest(request) is a request line,
// decodeReply(line) a reply, decodeReport(text) a report. A line or report
// that is not the declared JSON throws UnreadableReply, naming where.

const defs = ${lines(Object.fromEntries(Object.entries(defs).map(([n, d]) => [n, bare(d)])))};

/** The text is not the JSON tn1-lint declares (a binary this wrapper was not built for). */
class UnreadableReply extends Error {
  constructor(message) {
    super(message);
    this.name = "UnreadableReply";
    this._tag = "UnreadableReply";
  }
}

/** Where \`value\` breaks \`schema\` (a path and why), or undefined when it does not. */
function mismatch(schema, value, at) {
  if (schema.$ref) return mismatch(defs[schema.$ref.slice(8)], value, at);
  if (schema.anyOf) {
    const why = schema.anyOf.map((s) => mismatch(s, value, at));
    return why.includes(undefined) ? undefined : why.join("; or ");
  }
  if (schema.enum && !schema.enum.includes(value)) return \`\${at} is \${JSON.stringify(value)}, not one of \${schema.enum.join(", ")}\`;
  switch (schema.type) {
    case "string":
      return typeof value === "string" ? undefined : \`\${at} is not a string\`;
    case "boolean":
      return typeof value === "boolean" ? undefined : \`\${at} is not a boolean\`;
    case "integer":
      if (!Number.isInteger(value)) return \`\${at} is not an integer\`;
      if (value < schema.minimum || value > schema.maximum) return \`\${at} is out of range\`;
      return undefined;
    case "array":
      if (!Array.isArray(value)) return \`\${at} is not a list\`;
      for (let i = 0; i < value.length; i++) {
        const why = mismatch(schema.items, value[i], \`\${at}[\${i}]\`);
        if (why) return why;
      }
      return undefined;
    case "object":
      if (typeof value !== "object" || value === null || Array.isArray(value)) return \`\${at} is not an object\`;
      for (const key of schema.required) if (!(key in value)) return \`\${at} has no \${key}\`;
      for (const key of Object.keys(schema.properties)) {
        if (!(key in value)) continue;
        const why = mismatch(schema.properties[key], value[key], \`\${at}.\${key}\`);
        if (why) return why;
      }
      return undefined;
  }
  return undefined;
}

/** \`text\` parsed and checked against \`schema\`, or UnreadableReply naming \`what\`. */
function decode(schema, text, what) {
  let value;
  try {
    value = JSON.parse(text);
  } catch (e) {
    throw new UnreadableReply(\`tn1-lint: \${what} is not JSON: \${String(text).slice(0, 200)}\`);
  }
  const why = mismatch(schema, value, what);
  if (why) throw new UnreadableReply(\`tn1-lint: \${why}\`);
  return value;
}

/** The line serve reads for \`request\` (each field as a string). */
function encodeRequest(request) {
  return JSON.stringify({ ${requestFields.map((k) => `${JSON.stringify(k)}: String(request.${k})`).join(", ")} });
}

/**
 * One reply line of serve: its diagnostics, or an error and none. Until
 * P6 makes a failure a refusal of its own, Reply holds both fields: one
 * with an error and diagnostics is no reply serve writes.
 */
function decodeReply(line) {
  const reply = decode(${JSON.stringify(roots.Reply)}, line, "reply");
  if (reply.error !== "" && reply.diagnostics.length > 0) throw new UnreadableReply("tn1-lint: reply has an error and diagnostics");
  return reply;
}

/** The oxlint JSON report \`tn1-lint lint\` prints. */
function decodeReport(text) {
  return decode(${JSON.stringify(roots.Report)}, text, "report");
}

module.exports = { encodeRequest, decodeReply, decodeReport, UnreadableReply };
`

/** The JSON Schema text of each other type tsmap projects: an inline schema equal to one is printed by its name. */
const named = new Map<string, string>()
for (const [n, s] of Object.entries(types)) {
  if (n in defs || !Schema.isSchema(s)) continue
  const document = Schema.toJsonSchemaDocument(s as Schema.Top)
  if (!document.schema.$ref && Object.keys(document.definitions).length === 0) named.set(JSON.stringify(document.schema), n)
}
const used = new Set<string>()

function doc(text: string | undefined, indent: string): string {
  return text ? `${indent}/** ${text.trim().replace(/\s*\n\s*/g, " ")} */\n` : ""
}

function type(s: Json, indent: string): string {
  if (s.$ref) return refName(s.$ref)
  const name = named.get(JSON.stringify(s))
  if (name !== undefined) {
    used.add(name)
    return name
  }
  if (s.anyOf) return s.anyOf.map((a: Json) => type(a, indent)).join(" | ")
  if (s.enum) return (s.enum as unknown[]).map((v) => JSON.stringify(v)).join(" | ")
  switch (s.type) {
    case "string":
      return "string"
    case "boolean":
      return "boolean"
    case "integer":
    case "number":
      return "number"
    case "array": {
      const item = type(s.items, indent)
      return /[| ]/.test(item) ? `Array<${item}>` : `${item}[]`
    }
    case "object":
      return `{\n${fields(s, `${indent}  `)}${indent}}`
  }
  throw new Error(`no TypeScript type for ${JSON.stringify(s)}`)
}

function fields(s: Json, indent: string): string {
  return Object.entries(s.properties as Record<string, Json>)
    .map(([k, p]) => `${doc(p.description, indent)}${indent}${JSON.stringify(k).slice(1, -1) === k && /^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k)}${(s.required as string[]).includes(k) ? "" : "?"}: ${type(p, indent)};\n`)
    .join("")
}

const declaration = (n: string, s: Json) =>
  s.type === "object"
    ? `${doc(s.description, "")}export interface ${n} {\n${fields(s, "  ")}}\n`
    : `${doc(s.description, "")}export type ${n} = ${type(s, "")};\n`

/** The roots' declarations, then each named type they use, in the order first used. */
function declarations(): string {
  const out = Object.entries(defs).map(([n, s]) => declaration(n, s))
  const printed = new Set<string>()
  for (let more = true; more; ) {
    more = false
    for (const n of [...used]) {
      if (printed.has(n)) continue
      printed.add(n)
      more = true
      const s = [...named].find(([, name]) => name === n)![0]
      out.push(declaration(n, JSON.parse(s)))
    }
  }
  return out.join("\n")
}

const dts = `${header}

${declarations()}
/** The text is not the JSON tn1-lint declares (a binary this wrapper was not built for). */
export class UnreadableReply extends Error {
  readonly _tag: "UnreadableReply";
}

/** The line serve reads for \`request\` (each field as a string). */
export function encodeRequest(request: Request): string;

/** One reply line of serve: its diagnostics, or an error and none; throws UnreadableReply. */
export function decodeReply(line: string): Reply;

/** The oxlint JSON report \`tn1-lint lint\` prints; throws UnreadableReply. */
export function decodeReport(text: string): Report;
`

let stale = 0
for (const [name, text] of [["wire.js", js], ["wire.d.ts", dts]] as const) {
  const path = join(dir, name)
  if (write !== undefined) {
    writeFileSync(path, text)
    continue
  }
  let before = ""
  try {
    before = readFileSync(path, "utf8")
  } catch {}
  if (before !== text) {
    console.log(`stale ${name}: run bun ts/wire.ts --write ${dir}`)
    stale++
  }
}
if (stale > 0) process.exit(1)
console.log(write !== undefined ? `wrote wire.js and wire.d.ts in ${dir}` : "current")
