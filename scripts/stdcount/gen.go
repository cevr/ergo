package main

import (
	"fmt"
	"slices"
	"strings"
)

// The generated programs. Both take `<case> <n>` and print the checksum of
// n operations as their last line. The Ergo program names a case c<i>; the
// Go program names the Go form g<i> and the hand form h<i>.

// kindsOf is the input kinds a case reads: its own, and each kind whose
// function its set-up calls.
func kindsOf(c Case) []string {
	kinds := []string{c.Input}
	for kind, name := range inputKinds {
		if strings.Contains(c.ErgoSetup+c.GoSetup+c.HandSetup, name+"()") {
			kinds = append(kinds, kind)
		}
	}
	return kinds
}

func usedKinds(cs []Case) []string {
	var kinds []string
	for _, c := range cs {
		for _, k := range kindsOf(c) {
			if !slices.Contains(kinds, k) {
				kinds = append(kinds, k)
			}
		}
	}
	// A blob is built from the lines: the line function comes with it.
	if slices.Contains(kinds, "blob") {
		kinds = slices.DeleteFunc(kinds, func(k string) bool { return k == "line" })
	}
	slices.Sort(kinds)
	return kinds
}

func union(sets ...[]string) []string {
	var out []string
	for _, s := range sets {
		for _, x := range s {
			if !slices.Contains(out, x) {
				out = append(out, x)
			}
		}
	}
	slices.Sort(out)
	return out
}

// ergoProgram is main.ergo for the cases.
func ergoProgram(cs []Case) string {
	kinds := usedKinds(cs)
	imports := [][]string{{"os", "strconv"}}
	for _, c := range cs {
		imports = append(imports, c.ErgoImports)
	}
	if slices.Contains(kinds, "blob") {
		imports = append(imports, []string{"strings"})
	}
	var b strings.Builder
	b.WriteString("// Generated by scripts/stdcount. Each case runs n operations and folds\n// their results into the checksum it prints.\n\n")
	for _, imp := range union(imports...) {
		fmt.Fprintf(&b, "import %s\n", imp)
	}
	b.WriteString("\n")
	for _, k := range kinds {
		b.WriteString(ergoInputFunc(k))
		b.WriteString("\n")
	}
	for i, c := range cs {
		needs := ""
		if strings.Contains(c.Ergo, "Console.") {
			needs = " needs Console"
		}
		fmt.Fprintf(&b, "// c%d: %s %s\nfunc c%d(n int) int%s {\n\tlet xs = %s()\n", i, c.Pkg, c.Name, i, needs, inputKinds[c.Input])
		if c.ErgoSetup != "" {
			fmt.Fprintf(&b, "\t%s\n", c.ErgoSetup)
		}
		fmt.Fprintf(&b, "\tlet mut acc = 0\n\tfor i in 0..n {\n\t\tlet x = xs[i %% 64]\n\t\t%s\n\t\tacc += r\n\t}\n\tacc\n}\n\n", c.Ergo)
	}
	b.WriteString("func main() fails os.Exit needs Console | Ambient {\n\twith context { os.Process: os.NewHost() } {\n\t\tlet args = os.Process.Args()\n")
	b.WriteString("\t\tif len(args) != 2 {\n\t\t\treturn os.Exit{Code: 2, Message: \"usage: stdcount-ergo CASE N\"}\n\t\t}\n")
	b.WriteString("\t\tlet n = strconv.Atoi(args[1]) catch {\n\t\tcase strconv.Malformed, strconv.OutOfRange:\n\t\t\treturn os.Exit{Code: 2, Message: \"stdcount-ergo: N is not a count\"}\n\t\t}\n")
	b.WriteString("\t\tlet acc = match args[0] {\n")
	for i := range cs {
		fmt.Fprintf(&b, "\t\tcase \"c%d\":\n\t\t\tc%d(n)\n", i, i)
	}
	b.WriteString("\t\tcase _:\n\t\t\t-1\n\t\t}\n\t\tif acc == -1 {\n\t\t\treturn os.Exit{Code: 2, Message: \"stdcount-ergo: no such case\"}\n\t\t}\n")
	b.WriteString("\t\tConsole.Println(\"\\(acc)\")\n\t}\n}\n")
	return b.String()
}

// goProgram is main.go for the Go and hand forms of the cases.
func goProgram(cs []Case) string {
	kinds := usedKinds(cs)
	imports := [][]string{{"fmt", "os", "strconv"}}
	for _, c := range cs {
		imports = append(imports, c.GoImports)
		if c.Hand != "" {
			imports = append(imports, c.HandImports)
		}
	}
	if slices.Contains(kinds, "blob") {
		imports = append(imports, []string{"strings"})
	}
	var b strings.Builder
	b.WriteString("// Generated by scripts/stdcount. The Go form (g) and the hand form (h)\n// of each case.\n\npackage main\n\nimport (\n")
	for _, imp := range union(imports...) {
		fmt.Fprintf(&b, "\t%q\n", imp)
	}
	b.WriteString(")\n\nfunc b2i(b bool) int {\n\tif b {\n\t\treturn 1\n\t}\n\treturn 0\n}\n\n")
	for _, k := range kinds {
		b.WriteString(goInputFunc(k))
		b.WriteString("\n")
	}
	form := func(prefix string, i int, c Case, setup, body string) {
		fmt.Fprintf(&b, "// %s%d: %s %s\nfunc %s%d(n int) int {\n\txs := %s()\n", prefix, i, c.Pkg, c.Name, prefix, i, inputKinds[c.Input])
		if setup != "" {
			fmt.Fprintf(&b, "\t%s\n", setup)
		}
		fmt.Fprintf(&b, "\tacc := 0\n\tfor i := 0; i < n; i++ {\n\t\tx := xs[i%%64]\n\t\t_ = x\n\t\t%s\n\t\tacc += r\n\t}\n\treturn acc\n}\n\n", body)
	}
	for i, c := range cs {
		form("g", i, c, c.GoSetup, c.Go)
		if c.Hand != "" {
			form("h", i, c, c.HandSetup, c.Hand)
		}
	}
	b.WriteString("func main() {\n\tif len(os.Args) != 3 {\n\t\tfmt.Fprintln(os.Stderr, \"usage: stdcount-go CASE N\")\n\t\tos.Exit(2)\n\t}\n")
	b.WriteString("\tn, err := strconv.Atoi(os.Args[2])\n\tif err != nil {\n\t\tfmt.Fprintln(os.Stderr, \"stdcount-go: N is not a count\")\n\t\tos.Exit(2)\n\t}\n\tvar acc int\n\tswitch os.Args[1] {\n")
	for i, c := range cs {
		fmt.Fprintf(&b, "\tcase \"g%d\":\n\t\tacc = g%d(n)\n", i, i)
		if c.Hand != "" {
			fmt.Fprintf(&b, "\tcase \"h%d\":\n\t\tacc = h%d(n)\n", i, i)
		}
	}
	b.WriteString("\tdefault:\n\t\tfmt.Fprintln(os.Stderr, \"stdcount-go: no such case\")\n\t\tos.Exit(2)\n\t}\n\tfmt.Println(acc)\n}\n")
	return b.String()
}

// allocHook is added to both programs' modules: at exit (main returns or
// os.Exit) it prints the heap allocations and the write system calls of
// the process on stderr. Build with -ldflags=-checklinkname=0. It changes
// no hot path.
const allocHook = `package main

// Added by scripts/stdcount (a receipt tool): print the allocation count
// and bytes, and the write system calls, at process exit.

import (
	"fmt"
	"os"
	"runtime"
	"strings"
	_ "unsafe"
)

type stdcountExitHook struct {
	F            func()
	RunOnFailure bool
}

//go:linkname stdcountExithookAdd internal/runtime/exithook.Add
func stdcountExithookAdd(h stdcountExitHook)

func init() {
	stdcountExithookAdd(stdcountExitHook{F: func() {
		var m runtime.MemStats
		runtime.ReadMemStats(&m)
		syscw := "0"
		if io, err := os.ReadFile("/proc/self/io"); err == nil {
			for _, line := range strings.Split(string(io), "\n") {
				if v, ok := strings.CutPrefix(line, "syscw: "); ok {
					syscw = v
				}
			}
		}
		fmt.Fprintf(os.Stderr, "ALLOCS mallocs=%d bytes=%d syscw=%s\n", m.Mallocs, m.TotalAlloc, syscw)
	}, RunOnFailure: true})
}
`
