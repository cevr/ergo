// Command drawgen writes the packages under drawing: for each package of
// MyGo's drawing layer under internal/, a package of the same name whose
// files mirror the internal package's files, with their build constraints,
// and declare each exported type as an alias, each exported constant as
// itself and each exported function as a function that calls it. Exported
// variables are left out (a copy would not see later writes), and so are
// functions whose signatures name an unexported type of their package. A
// generic declaration or a variadic function is an error: the layer has
// none today.
//
// Run it with go generate in the drawing module's root; -check reports the
// files that differ from what it would write and writes nothing.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/build/constraint"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"go/types"
	"os"
	"os/exec"
	"path"
	"path/filepath"
	"sort"
	"strings"
)

// Packages are the packages of the drawing layer, relative to
// github.com/egoist/mygo/internal.
var Packages = []string{
	"surface",  // the window-to-content seam: Conn
	"platform", // Surface, its events, keys, cursors, text input, access tree
	"scene",    // the display list
	"text",     // shaping, line breaking, measuring, glyphs
	"vec",      // paths
	"raster",   // the CPU renderer
	"gpu",      // what the GPU renderers share
	"gpu/gl",   // OpenGL (Linux, browsers)
	"gpu/metal",
	"gpu/d3d11",
	"fake", // the backend of tests: no window, no display
}

// Internal is the import path the packages are under.
const Internal = "github.com/egoist/mygo/internal/"

// Marker starts the comment that marks a generated file.
const Marker = "// Code generated by drawgen"

func main() {
	check := flag.Bool("check", false, "report stale files and write nothing")
	listSkipped := flag.Bool("skipped", false, "list the exported names left out, with the reason")
	flag.Parse()
	dirs, err := SourceDirs()
	if err != nil {
		fail(err)
	}
	stale := 0
	for _, p := range Packages {
		files, skipped, err := Generate(p, dirs[p])
		if err != nil {
			fail(err)
		}
		if *listSkipped {
			for _, s := range skipped {
				fmt.Println("skipped", s)
			}
			continue
		}
		changes, err := Sync(p, files, !*check)
		if err != nil {
			fail(err)
		}
		for _, c := range changes {
			fmt.Println(c)
		}
		stale += len(changes)
	}
	strays, err := Strays(!*check)
	if err != nil {
		fail(err)
	}
	for _, s := range strays {
		fmt.Println("stale", s)
	}
	stale += len(strays)
	if *check && stale > 0 {
		os.Exit(1)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "drawgen:", err)
	os.Exit(1)
}

// SourceDirs returns the directory of each package of Packages, as the
// go command resolves it from the working directory's module.
func SourceDirs() (map[string]string, error) {
	args := []string{"list", "-e", "-json=ImportPath,Dir,Error", "--"}
	for _, p := range Packages {
		args = append(args, Internal+p)
	}
	out, err := exec.Command("go", args...).Output()
	if err != nil {
		return nil, fmt.Errorf("go list: %w", err)
	}
	dirs := map[string]string{}
	dec := json.NewDecoder(bytes.NewReader(out))
	for dec.More() {
		var p struct {
			ImportPath, Dir string
		}
		if err := dec.Decode(&p); err != nil {
			return nil, err
		}
		dirs[strings.TrimPrefix(p.ImportPath, Internal)] = p.Dir
	}
	for _, p := range Packages {
		if dirs[p] == "" {
			return nil, fmt.Errorf("go list found no directory for %s", Internal+p)
		}
	}
	return dirs, nil
}

// Strays returns the generated files outside the directories of Packages,
// as a package dropped from the list leaves them, and with write removes
// them.
func Strays(write bool) ([]string, error) {
	var strays []string
	err := filepath.WalkDir(".", func(f string, e os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if e.IsDir() && f == "internal" {
			return filepath.SkipDir // drawgen itself
		}
		if e.IsDir() || filepath.Ext(f) != ".go" {
			return nil
		}
		for _, p := range Packages {
			if filepath.Dir(f) == filepath.FromSlash(p) {
				return nil
			}
		}
		b, err := os.ReadFile(f)
		if err != nil || !generated(b) {
			return err
		}
		strays = append(strays, f)
		if write {
			return os.Remove(f)
		}
		return nil
	})
	return strays, err
}

// generated reports whether a file's text has a line that starts with
// Marker, as drawgen's files do.
func generated(b []byte) bool {
	return bytes.HasPrefix(b, []byte(Marker+" ")) || bytes.Contains(b, []byte("\n"+Marker+" "))
}

// Sync makes the directory of package p hold files and no other generated
// file, or with write false only reports what differs.
func Sync(p string, files map[string][]byte, write bool) ([]string, error) {
	dir := filepath.FromSlash(p)
	var changes []string
	old, _ := filepath.Glob(filepath.Join(dir, "*.go"))
	for _, f := range old {
		if _, ok := files[filepath.Base(f)]; ok {
			continue
		}
		b, err := os.ReadFile(f)
		if err != nil {
			return nil, err
		}
		if !generated(b) {
			continue
		}
		changes = append(changes, "stale "+f)
		if write {
			if err := os.Remove(f); err != nil {
				return nil, err
			}
		}
	}
	names := make([]string, 0, len(files))
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		f := filepath.Join(dir, n)
		b, err := os.ReadFile(f)
		if err == nil && bytes.Equal(b, files[n]) {
			continue
		}
		changes = append(changes, "write "+f)
		if write {
			if err := os.MkdirAll(dir, 0o755); err != nil {
				return nil, err
			}
			if err := os.WriteFile(f, files[n], 0o644); err != nil {
				return nil, err
			}
		}
	}
	return changes, nil
}

// Generate returns the files of the package that mirrors internal package
// p, whose sources are in dir, by name, and the exported names it left out
// with the reason.
func Generate(p, dir string) (map[string][]byte, []string, error) {
	paths, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, nil, err
	}
	sort.Strings(paths)
	name := path.Base(p)
	files := map[string][]byte{}
	var skipped []string
	for _, src := range paths {
		base := filepath.Base(src)
		if strings.HasSuffix(base, "_test.go") {
			continue
		}
		fset := token.NewFileSet()
		f, err := parser.ParseFile(fset, src, nil, parser.ParseComments)
		if err != nil {
			return nil, nil, err
		}
		if f.Name.Name != name {
			continue // a generator's package main
		}
		out, skip, err := mirror(fset, f, p, base)
		if err != nil {
			return nil, nil, fmt.Errorf("%s: %w", src, err)
		}
		skipped = append(skipped, skip...)
		if out != nil {
			files[base] = out
		}
	}
	return files, skipped, nil
}

// impl is the name the generated files give the internal package.
const impl = "impl"

// file collects what one generated file declares.
type file struct {
	fset *token.FileSet
	src  *ast.File
	used map[string]bool // import names the declarations use
	body bytes.Buffer
}

// mirror returns the generated file for src, nil when src exports
// nothing that can be mirrored.
func mirror(fset *token.FileSet, src *ast.File, p, base string) ([]byte, []string, error) {
	g := &file{fset: fset, src: src, used: map[string]bool{}}
	var skipped []string
	n := 0
	for _, d := range src.Decls {
		switch d := d.(type) {
		case *ast.GenDecl:
			switch d.Tok {
			case token.TYPE:
				for _, s := range d.Specs {
					s := s.(*ast.TypeSpec)
					if !s.Name.IsExported() {
						continue
					}
					if s.TypeParams != nil {
						return nil, nil, fmt.Errorf("generic type %s: drawgen writes no generic alias yet", s.Name.Name)
					}
					fmt.Fprintf(&g.body, "type %s = %s.%s\n\n", s.Name.Name, impl, s.Name.Name)
					n++
				}
			case token.CONST:
				var names []string
				for _, s := range d.Specs {
					for _, id := range s.(*ast.ValueSpec).Names {
						if id.IsExported() {
							names = append(names, id.Name)
						}
					}
				}
				if len(names) == 0 {
					continue
				}
				g.body.WriteString("const (\n")
				for _, id := range names {
					fmt.Fprintf(&g.body, "\t%s = %s.%s\n", id, impl, id)
				}
				g.body.WriteString(")\n\n")
				n += len(names)
			case token.VAR:
				for _, s := range d.Specs {
					for _, id := range s.(*ast.ValueSpec).Names {
						if id.IsExported() {
							skipped = append(skipped, fmt.Sprintf("%s.%s: a variable", p, id.Name))
						}
					}
				}
			}
		case *ast.FuncDecl:
			if d.Recv != nil || !d.Name.IsExported() {
				continue
			}
			// Generic and variadic functions are not in the drawing layer
			// today; a generator that wrote them would hold code no input
			// reaches.
			if d.Type.TypeParams != nil {
				return nil, nil, fmt.Errorf("generic function %s: drawgen writes no generic wrapper yet", d.Name.Name)
			}
			if bad := unexported(d.Type); bad != "" {
				skipped = append(skipped, fmt.Sprintf("%s.%s: its signature names %s", p, d.Name.Name, bad))
				continue
			}
			if err := g.wrapper(d); err != nil {
				return nil, nil, err
			}
			n++
		}
	}
	if n == 0 {
		return nil, skipped, nil
	}
	var out bytes.Buffer
	if c := buildConstraint(src); c != "" {
		fmt.Fprintf(&out, "%s\n\n", c)
	}
	fmt.Fprintf(&out, "%s from internal/%s/%s. DO NOT EDIT.\n\n", Marker, p, base)
	fmt.Fprintf(&out, "package %s\n\nimport (\n", src.Name.Name)
	fmt.Fprintf(&out, "\t%s %q\n", impl, Internal+p)
	imports, err := g.imports()
	if err != nil {
		return nil, nil, err
	}
	for _, i := range imports {
		fmt.Fprintf(&out, "\t%s\n", i)
	}
	out.WriteString(")\n\n")
	out.Write(g.body.Bytes())
	b, err := format.Source(out.Bytes())
	if err != nil {
		return nil, nil, fmt.Errorf("format: %w\n%s", err, out.Bytes())
	}
	return b, skipped, nil
}

// buildConstraint returns the //go:build line of f, or "".
func buildConstraint(f *ast.File) string {
	for _, cg := range f.Comments {
		if cg.Pos() > f.Package {
			break
		}
		for _, c := range cg.List {
			if constraint.IsGoBuild(c.Text) {
				return c.Text
			}
		}
	}
	return ""
}

// unexported returns the first unexported, non-predeclared type name the
// signature t names, or "".
func unexported(t *ast.FuncType) string {
	bad := ""
	var visit func(n ast.Node) bool
	visit = func(n ast.Node) bool {
		switch n := n.(type) {
		case *ast.SelectorExpr:
			return false // another package's name: exported
		case *ast.Field:
			// A parameter, field or method: its names are not types.
			if n.Type != nil {
				ast.Inspect(n.Type, visit)
			}
			return false
		case *ast.Ident:
			if bad == "" && !n.IsExported() && types.Universe.Lookup(n.Name) == nil {
				bad = n.Name
			}
		}
		return bad == ""
	}
	for _, l := range []*ast.FieldList{t.Params, t.Results} {
		if l != nil {
			ast.Inspect(l, visit)
		}
	}
	return bad
}

// expr prints a type of the source file, noting the imports it uses.
func (g *file) expr(e ast.Expr) string {
	ast.Inspect(e, func(n ast.Node) bool {
		if s, ok := n.(*ast.SelectorExpr); ok {
			if id, ok := s.X.(*ast.Ident); ok {
				g.used[id.Name] = true
			}
		}
		return true
	})
	var b bytes.Buffer
	if err := printer.Fprint(&b, g.fset, e); err != nil {
		panic(err)
	}
	return b.String()
}

// wrapper writes a function that calls the internal function d with its
// own parameters, in order.
func (g *file) wrapper(d *ast.FuncDecl) error {
	reserved := map[string]bool{impl: true}
	for _, s := range g.src.Imports {
		reserved[importName(s)] = true
	}
	var params, args []string
	i := 0
	for _, f := range d.Type.Params.List {
		if _, ok := f.Type.(*ast.Ellipsis); ok {
			return fmt.Errorf("variadic function %s: drawgen writes no variadic wrapper yet", d.Name.Name)
		}
		typ := g.expr(f.Type)
		names := f.Names
		if len(names) == 0 {
			names = []*ast.Ident{nil}
		}
		var ns []string
		for _, n := range names {
			name := fmt.Sprintf("p%d", i)
			if n != nil && n.Name != "_" {
				name = n.Name
				for reserved[name] {
					name += "_"
				}
			}
			ns = append(ns, name)
			args = append(args, name)
			i++
		}
		params = append(params, strings.Join(ns, ", ")+" "+typ)
	}
	call := fmt.Sprintf("%s.%s(%s)", impl, d.Name.Name, strings.Join(args, ", "))
	var results []string
	if d.Type.Results != nil {
		for _, f := range d.Type.Results.List {
			typ := g.expr(f.Type)
			for range max(1, len(f.Names)) {
				results = append(results, typ)
			}
		}
	}
	res := ""
	switch len(results) {
	case 0:
	case 1:
		res = " " + results[0]
	default:
		res = " (" + strings.Join(results, ", ") + ")"
	}
	stmt := call
	if len(results) > 0 {
		stmt = "return " + call
	}
	fmt.Fprintf(&g.body, "func %s(%s)%s {\n\t%s\n}\n\n", d.Name.Name, strings.Join(params, ", "), res, stmt)
	return nil
}

// importName returns the name an import binds: its explicit name, else
// the last element of its path without a major version.
func importName(s *ast.ImportSpec) string {
	if s.Name != nil {
		return s.Name.Name
	}
	p := strings.Trim(s.Path.Value, `"`)
	base := path.Base(p)
	if len(base) > 1 && base[0] == 'v' && strings.Trim(base[1:], "0123456789") == "" {
		base = path.Base(path.Dir(p))
	}
	return base
}

// imports returns the import specs of the source file that the generated
// declarations use, as the source wrote them.
func (g *file) imports() ([]string, error) {
	var out []string
	found := map[string]bool{}
	for _, s := range g.src.Imports {
		n := importName(s)
		if !g.used[n] {
			continue
		}
		found[n] = true
		if s.Name != nil {
			out = append(out, s.Name.Name+" "+s.Path.Value)
		} else {
			out = append(out, s.Path.Value)
		}
	}
	for n := range g.used {
		if !found[n] {
			return nil, fmt.Errorf("no import binds %s", n)
		}
	}
	sort.Strings(out)
	return out, nil
}
